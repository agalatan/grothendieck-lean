#!/usr/bin/env python3
"""Generate Grothe/Cert240/Data.lean from the exact handoff exports (no floats involved).

Boxes for radial indices 0..119 are the interval sums of the source tables
(origin-0-25 + origin-25-36); indices 120..239 come from the added table.
Row 3 of the scalar preprocessors is stored negated upstream; we emit the
positively weighted (negated back) orientation.
"""
import json
from fractions import Fraction as Q
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
D = ROOT / "handoff" / "data" / "npz-exact-rationals"

def arr(j, k):
    return [Q(int(v["numerator"]), int(v["denominator"])) for v in j["arrays"][k]["values"]]

t1 = json.load(open(D / "origin-0-25.json"))
t2 = json.load(open(D / "origin-25-36.json"))
t3 = json.load(open(D / "origin-modes-120-239.json"))
assert t3["arrays"]["start"]["values"][0]["numerator"] == "120"

def box(side, part, which):
    k = f"{side}_{part}_{which}"
    a = [x + y for x, y in zip(arr(t1, k), arr(t2, k))]
    return a + arr(t3, k)

eta = [Q(s) for s in json.load(open(ROOT / "handoff" / "upper" / "inverse_eta.json"))]
assert len(eta) == 120 and eta[0] > 0 and sum(abs(e) for e in eta) == 1

def q(x: Q) -> str:
    return f"({x.numerator} : ℚ) / {x.denominator}" if x.denominator != 1 else f"({x.numerator} : ℚ)"

def lst(name, doc, xs):
    body = ",\n   ".join(q(x) for x in xs)
    return f"/-- {doc} -/\ndef {name} : List ℚ :=\n  [{body}]\n\n"

rows = {
 "row1": {0: "0.906231648312", 1: "-0.093651693922", 4: "-0.000116657762"},
 "row2": {0: "0.910377315558", 1: "-0.063651630829", 3: "-0.025971053610"},
 "row3": {0: "0.912512978184", 1: "-0.035570362029", 3: "-0.050646289677", 4: "-0.001270370107"},
 "row4": {0: "0.901913867354", 1: "-0.037111896010", 3: "-0.026391249065", 5: "-0.033420629518", 7: "-0.001162358049"},
 "row5": {0: "0.094626045381", 1: "-0.856254413568", 10: "0.001274576105", 13: "0.008312996734",
          14: "0.001885453067", 15: "0.001662844635", 16: "0.009295485863", 17: "0.009399425108",
          18: "0.008540450681", 19: "0.000847985940", 20: "0.003771690693", 21: "0.000873880329",
          27: "-0.000419180236", 29: "-0.000311954497", 30: "-0.000455650279", 31: "-0.000996284704",
          35: "-0.000865568525", 37: "0.000206113648"},
}
out = ["import Mathlib\n\n/-!\n# Exact certificate data for the 240-mode upper certificate\n\n"
       "Generated by `tools/gen_cert240_data.py` from `handoff/` (exact rationals; no floats).\n"
       "`aReLo n ≤ Re A_n ≤ aReHi n` etc. are the *claimed* enclosures of the truncated radial\n"
       "coefficient integrals `A_n(0,36)` of the left phase, `B` of the right phase (source tables\n"
       "for `n < 120`, added table for `120 ≤ n < 240`).  Containment is a hypothesis, not a theorem.\n-/\n\nnamespace Grothe.Cert240\n\n"]
out.append(lst("etaCoeffs", "The frozen common preprocessor `η(t) = t·E(t²)`: the 120 radial coefficients of `E`.", eta))
for side, nm in (("left", "a"), ("right", "b")):
    for part, pn in (("real", "Re"), ("imag", "Im")):
        for which, wn in (("lower", "Lo"), ("upper", "Hi")):
            out.append(lst(f"{nm}{pn}{wn}", f"{which} endpoints of the {part} part of the {side} coefficient boxes, indices 0..239.", box(side, part, which)))
for name, dat in rows.items():
    n = max(dat) + 1
    xs = [Q(dat.get(i, "0")) for i in range(n)]
    out.append(lst(name, f"Scalar preprocessor `{name}` (coefficients of `P` in `ρ(t) = t·P(t²)`), positive orientation.", xs))
out.append("end Grothe.Cert240\n")
(ROOT / "Grothe" / "Cert240" / "Data.lean").write_text("".join(out))
print("wrote Data.lean", sum(len(s) for s in out), "chars")
