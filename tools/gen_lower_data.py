for row in rows:
    ell, beta, C = Q(row["ell"]), Q(row["beta"]), Q(row["C"]); assert Q(row["q2"]) == 1
    if row["origin"] == "received":
        rr = env_rcv["profiles"][row["reference"]]
        assert Q(env_rcv["epsilon"]) == EPS
        if rr["provenance"] == "v2":
            k = next(k for k, b in enumerate(base_rows) if b[0] == rr["id"])
            b = base_rows[k]
            assert b[1] == ell and b[2] == beta
            exact = transfer(b[3], beta, EPS0, EPS)
            assert Q(rr["C"]) == exact and C == ceilq(exact)
            prov.append((0, k))
        else:
            k = pw_by_file[rr["provenance"]]; m = pw_meta[k]
            s = m[3]; assert s == EPS / EPS0
            assert s * m[4] == ell and s * m[5] == beta
            exact = transfer(s * m[6], beta, s * EPS0, EPS)
            assert exact == s * m[6] and Q(rr["C"]) == exact and C == ceilq(exact)
            prov.append((1, k))
    else:
        k = pw_by_file[row["reference"]]; m = pw_meta[k]; s = Q(row["scale"]); assert s == m[3]
        assert s * m[4] == ell and s * m[5] == beta
        exact = transfer(s * m[6], beta, s * EPS0, EPS)
        assert C == ceilq(exact)
        prov.append((1, k))
