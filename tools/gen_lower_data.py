    assert prev == tail
    polys = [[Q(x) for x in pl["coefficients"]] for pl in g["polynomials"]]
    for pl in polys:
        assert len(pl) == 7 and pl[3] == pl[5] == 0 and pl[1] >= 0 and pl[6] >= 0
