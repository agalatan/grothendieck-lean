    E = sym3(p["M_E"]); R = sym2(p["M_R"]); assert p["M_R"] == p["M_I"]
    assert Q(p["epsilon"]) == EPS0
    src_profiles.append((p["id"], Q(p["ell"]), Q(p["beta"]), Q(p["delta"]), E, R))
    items.append(f"  ⟨\"{p['id']}\", {q(p['ell'])}, {q(p['beta'])}, {q(p['delta'])},\n    {fmt_sym3(E)},\n    {fmt_sym2(R)}⟩")
