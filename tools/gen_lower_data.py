def fam_upper(coeffs, de, db, r):
    mono = [Q(1), de, db, r, de*de, de*db, db*db, de*r, db*r, r*r]
    return sum(max(lo*m, hi*m) for (lo, hi), m in zip(coeffs, mono))

src_pts = [[(Q(p["r"]), Q(p["cap"]) + LIFT) for p in g["points"]] for g in src]
pw_files = [("pointwise", H / "next-lower-received" / f) for f in sorted(p.name for p in (H / "next-lower-received").glob("pointwise-*.json") if not p.name.endswith(".cap.json"))]
