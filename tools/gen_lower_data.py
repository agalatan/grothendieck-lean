#!/usr/bin/env python3
"""Generate the Stein side of the lower-bound certificate (exact rationals only).

usage: python3 tools/gen_lower_data.py [--check]

Witness T = P₁,₀ − εP₂,₁ + ν(Id − P₁,₀ − P₂,₁) with (ε, ν) = (191/250, 47/2000); the rows are stated at its hat weight
ε̂ = 25/31 (`Grothe.Lower.ε`) and the node caps of their potentials are those of the hat tail ν̂ = 47/1953.

Inputs (committed): data/tail-caps/row_set.json (the row set: per cap row its θ, δ, κ, smax, the row constant C; the mass
row's λ and S), data/tail-caps/<t>/table.json (the cap tables), and data/tail-rows/ (the law certificates of the rows, the
mass row and the envelope env_final_clean.json, with their sha256 in data/tail-rows/SHA256SUMS).

Outputs (Grothe/Lower/):
  RowDataSS.lean       row SS = K + 1 (K the index of row_set.json): header (ℓ, β, δ, κ, smax, cap), even block, coupling,
                       node caps, mesh and the x-cells (the 12 plain rows: Stein cells for `checkRow`; rows 0.4 and 0.6:
                       spectral cells `xlo#xhi#rects#nodes` for `checkSpecRow`)
  RowData.lean         the list `rowData`
  MassRow.lean         the mass row λ = 1/2 (`massRow`: the table of Ψ(s) = φ_c(s/δ), c = 2ν̂ + λ, its spectral cells; cap
                       S − capPad)
  RowGateData.lean     `rowGates` (ℓ, β, δ, R) and `rowR`;  RowGates.lean: their exact checks
  EnvelopeData.lean    the envelope: `envB` and the cells `lo,hi,i,j,θ` of [0, 9/10] (scalar row 0 the mass row's tangent,
                       k + 1 the row k)
  Cert/RowSS.lean, Cert/MassRow.lean   the native row checks
  Cert/Envelope.lean   the kernel-checked envelope
  Cert/Rows.lean       `RowFacts` of every row
Before writing, the data are checked with exact fractions: the gates of every row at ε̂ (E ≻ 0, E ⪰ diag(−1, ε̂, ε̂),
N = E − diag(ε̂ − δ, 0, 0) ≻ 0, R ≻ 0, R ⪰ diag(−1, ε̂), R ⪰ diag(ε̂, 0)), κ ≤ 1/δ − bᵀN⁻¹b, the Lipschitz header, the node
caps of every row against its cap table, the mass row's table against φ_c, and every cell of the envelope against `envB`.
The row cap is ⌈C − capPad − 2β²/ε̂⌉ at 10⁻¹⁵ (C of `row_set.json`), so the scalar row of a row is (ℓ, β, C') with
C ≤ C' ≤ C + 10⁻¹⁵; the mass row's cap is S − capPad.
"""
import hashlib
import json
from fractions import Fraction as Q
from math import isqrt
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
EPSH = Q(25, 31)
NUH = Q(47, 1953)
ENV_B = Q(7064131, 10**7)        # the cap of the hat value checked by the envelope (its maximum is 0.7064129749…)

RHO = Q(973612157, 10**9)
PAD = Q(1, 10**11)

def qs(x) -> str:
    x = Q(x)
    return f"{x.numerator}/{x.denominator}" if x.denominator != 1 else f"{x.numerator}"

def q(x) -> str:
    x = Q(x)
    return f"({x.numerator} : ℚ) / {x.denominator}" if x.denominator != 1 else f"({x.numerator} : ℚ)"

def ldl3(m, strict):
    m11, m12, m13, m22, m23, m33 = m
    d1 = m11
    assert d1 > 0 if strict else d1 >= 0, (m, strict)
    if d1 == 0:
        assert m12 == 0 and m13 == 0; l21 = l31 = Q(0)
    else:
        l21, l31 = m12 / d1, m13 / d1
    d2 = m22 - d1 * l21 * l21
    assert d2 > 0 if strict else d2 >= 0, (m, strict)
    r = m23 - d1 * l21 * l31
    if d2 == 0:
        assert r == 0; l32 = Q(0)
    else:
        l32 = r / d2
    d3 = m33 - d1 * l31 * l31 - d2 * l32 * l32
    assert d3 > 0 if strict else d3 >= 0, (m, strict)
    return (d1, d2, d3, l21, l31, l32)

def ldl2(m, strict):
    m11, m12, m22 = m
    d1 = m11
    assert d1 > 0 if strict else d1 >= 0, (m, strict)
    l21 = Q(0) if d1 == 0 else m12 / d1
    d2 = m22 - d1 * l21 * l21
    assert d2 > 0 if strict else d2 >= 0, (m, strict)
    return (d1, d2, l21)

def solve3(M, b):
    A = [list(M[i]) + [b[i]] for i in range(3)]
    for i in range(3):
        p = next(r for r in range(i, 3) if A[r][i] != 0); A[i], A[p] = A[p], A[i]
        A[i] = [v / A[i][i] for v in A[i]]
        for r in range(3):
            if r != i: A[r] = [v - A[r][i] * w for v, w in zip(A[r], A[i])]
    return [A[i][3] for i in range(3)]

def fmt(c): return "⟨" + ", ".join(q(v) for v in c) + "⟩"

def rsqrt(x):
    a, b = isqrt(x.numerator), isqrt(x.denominator)
    assert a * a == x.numerator and b * b == x.denominator
    return Q(a, b)

def lean_str(s): return '"' + s + '"'


HEADER = "(generated by `tools/gen_lower_data.py`; do not edit)"


def main(check=False):
    src = ROOT / "data" / "tail-rows"
    capdir = ROOT / "data" / "tail-caps"
    out = ROOT / "Grothe" / "Lower"
    for line in open(src / "SHA256SUMS"):
        h, fn = line.split(None, 1)
        assert hashlib.sha256(open(src / fn.strip(), "rb").read()).hexdigest() == h, fn
    S = json.load(open(capdir / "row_set.json"))
    files = {}

    def law_of(P):
        name = P["law"]["file"] if isinstance(P["law"], dict) else None
        sub = "spectral" if P["cuts"] == "spectral" else "plain"
        path = src / sub / name.split("/")[-1]
        assert hashlib.sha256(open(path, "rb").read()).hexdigest() == P["law"]["sha256"], path
        return json.load(open(path))

    def mesh_vs(R):
        mesh = [Q(v) for v in R["mesh"]]
        assert mesh and mesh[0] == 0 and all(mesh[i] < mesh[i + 1] for i in range(len(mesh) - 1))
        return ",".join(qs(rsqrt(t)) for t in mesh[1:])

    def spec_cells(R, delta):
        cells, prev = [], Q(0)
        for cell in R["cells"]:
            xlo, xhi = Q(cell["x"][0]), Q(cell["x"][1])
            assert xlo == prev and set(cell) <= {"x", "nodes"}
            prev = xhi
            ws = []
            for n in cell["nodes"]:
                y = n["y"]
                assert len(y) == 5 and len(n["z"]) == len(R["mesh"]) - 1
                ws.append(f"{qs(n['sigma'])}:" + ",".join(qs(v) for v in (y[0], y[4], y[1], y[2], y[3])) + ":" +
                          ",".join(qs(n[k]) for k in ("lam", "mu", "t", "be", "nu")) + "|" + ",".join(qs(v) for v in n["z"]))
            sig = [Q(n["sigma"]) for n in cell["nodes"]]
            assert all(0 < sig[i] < sig[i + 1] for i in range(len(sig) - 1)) and sig[-1] >= delta * RHO
            cells.append(f"{qs(xlo)}#{qs(xhi)}##" + ";".join(["0"] + ws))
        assert prev >= Q(31, 4)
        return cells, sum(len(c["nodes"]) for c in R["cells"])

    def plain_cells(R):
        cells = []
        for cell in R["cells"]:
            rects = cell["rects"] if cell["kind"] == "moment" else cell["small"]
            rs = ";".join(f"{qs(r['s'][0])}:{qs(r['s'][1])}:" + ",".join(qs(v) for v in r["P"]) for r in rects)
            bank = ";".join(",".join(str(int(v)) for v in z) for z in cell.get("bank", []))
            ns = []
            for n in cell.get("nodes", []):
                y = n["y"]
                assert len(n["mu"]) == len(n["cuts"])
                ns.append(f"{qs(n['sigma'])}:" + ",".join(qs(v) for v in (y[0], y[4], y[1], y[2], y[3])) + ":" +
                          ",".join(f"{int(m)},{int(k)}" for m, k in zip(n["mu"], n["cuts"])))
            cells.append(f"{qs(cell['x'][0])}|{qs(cell['x'][1])}|{rs}|{bank}|" + ";".join(ns))
        return cells, sum(len(c.get("nodes", [])) for c in R["cells"])

    def row_module(name, doc, header, E, b, nodes, vs, cells):
        return ("import Grothe.Lower.RowDataTypes\n\n/-!\n# " + doc + " " + HEADER + "\n-/\n\n"
                "namespace Grothe.Lower\n\nset_option maxRecDepth 100000\n\n"
                f"/-- {doc}. -/\ndef {name} : Row :=\n  ⟨" + ", ".join(map(q, header)) + ",\n   " + fmt(E) + ",\n   " +
                ", ".join(map(q, b)) + ",\n   " + lean_str(nodes) + ",\n   " + lean_str(vs) + ",\n   [" +
                ",\n    ".join(lean_str(c) for c in cells) + "]⟩\n\nend Grothe.Lower\n")

    rows, gates, scal = [], [], {}
    for P in sorted((P for P in S["pieces"] if P.get("kind") == "caprow"), key=lambda P: P["index"]):
        K, t = P["index"], P["name"]
        assert K == len(rows)
        SS = f"{K + 1:02d}"
        spectral = P["cuts"] == "spectral"
        R = law_of(P)
        th = [Q(v) for v in R["theta"]]
        assert th == [Q(v) for v in P["theta"]] and Q(R["eps"]) == EPSH
        E = tuple(th[0:6]); Rm = tuple(th[6:9]); delta = th[9]; b = th[10:13]; ell, beta = th[13], th[14]
        assert 0 < delta < EPSH and ell >= 2 * beta >= 0
        _gates = (ldl3(E, True), ldl3((E[0] + 1, E[1], E[2], E[3] - EPSH, E[4], E[5] - EPSH), False),
                  ldl3((E[0] - (EPSH - delta), E[1], E[2], E[3], E[4], E[5]), False), ldl2(Rm, True),
                  ldl2((Rm[0] + 1, Rm[1], Rm[2] - EPSH), False), ldl2((Rm[0] - EPSH, Rm[1], Rm[2]), False))
        N = (E[0] - (EPSH - delta), E[1], E[2], E[3], E[4], E[5])
        ldl3(N, True)
        c = solve3([[N[0], N[1], N[2]], [N[1], N[3], N[4]], [N[2], N[4], N[5]]], b)
        kappa, smax = Q(R["kappa"]), Q(R["smax"])
        assert kappa == Q(P["kappa"]) and smax == Q(P["smax"])
        assert 0 < kappa <= 1 / delta - sum(x * y for x, y in zip(b, c))
        assert smax >= 2 * (abs(1 + b[0]) + Q(7358, 10000) * abs(b[1]) + Q(707107, 10**6) * abs(b[2]))
        cap_exact = Q(P["C"]) - PAD - 2 * beta * beta / EPSH
        cap = Q(-((-cap_exact.numerator * 10**15) // cap_exact.denominator), 10**15)
        T = json.load(open(capdir / t / "table.json"))
        assert [Q(v) for v in R["nodes"]] == [Q(v) for v in T["nodes"]] and [Q(v) for v in R["caps"]] == [Q(v) for v in T["caps"]]
        nodes = ";".join(f"{qs(r)}:{qs(cc)}" for r, cc in zip(R["nodes"], R["caps"]))
        cells, nst = spec_cells(R, delta) if spectral else plain_cells(R)
        doc = (f"Row `{t}` of the certificate: header, node caps, mesh and its {len(cells)} `x`-cells "
               f"({nst} {'spectral' if spectral else 'Stein'} nodes)")
        files[f"RowData{SS}.lean"] = row_module(f"row{SS}", doc, (ell, beta, delta, kappa, smax, cap), E, b, nodes, mesh_vs(R), cells)
        chk = "checkSpecRow" if spectral else "checkRow"
        files[f"Cert/Row{SS}.lean"] = (
            ("import Grothe.Lower.SpecRows\n" if spectral else "import Grothe.Lower.Rows\n") +
            f"import Grothe.Lower.RowData{SS}\n\n/-! # The check of row `{t}` {HEADER} -/\n\nnamespace Grothe.Lower\n\n"
            f"theorem certRow{SS} : {chk} row{SS} = true := by native_decide\n\nend Grothe.Lower\n")
        rows.append(dict(t=t, SS=SS, spectral=spectral))
        gates.append((ell, beta, delta, Rm))
        scal[t] = (ell, beta, 2 * beta * beta / EPSH + cap + PAD)
    n = len(rows)
    files["RowData.lean"] = ("".join(f"import Grothe.Lower.RowData{r['SS']}\n" for r in rows) +
        "\n/-!\n# The rows " + HEADER + "\n\n" +
        f"The {n} rows at the weight `ε = 25/31`, sorted by their nominal `t`: " + ", ".join(r["t"] for r in rows) + ".\n-/\n\n"
        "namespace Grothe.Lower\n\n/-- The rows of the certificate, sorted by their nominal `t`. -/\ndef rowData : List Row :=\n  [" +
        ", ".join(f"row{r['SS']}" for r in rows) + "]\n\nend Grothe.Lower\n")
    # the facts of every row
    alts = " | ".join("rfl" for _ in rows)
    files["Cert/Rows.lean"] = ("".join(f"import Grothe.Lower.Cert.Row{r['SS']}\n" for r in rows) +
        "import Grothe.Lower.RowData\n\n/-! # The rows hold: `RowFacts` of every row of `rowData` " + HEADER + " -/\n\n"
        "namespace Grothe.Lower\n\n/-- **Every row of `rowData` is certified** (the plain rows by `checkRow`, the spectral rows by "
        "`checkSpecRow`). -/\ntheorem rowData_facts : ∀ r ∈ rowData, RowFacts r := by\n"
        "  intro r hr\n  simp only [rowData, List.mem_cons, List.not_mem_nil, or_false] at hr\n"
        f"  rcases hr with {alts}\n" +
        "\n".join(f"  · exact rowFacts_of_{'checkSpecRow' if r['spectral'] else 'checkRow'} _ certRow{r['SS']}" for r in rows) +
        "\n\nend Grothe.Lower\n")
    # the gates
    files["RowGateData.lean"] = ("import Grothe.Lower.RowDataTypes\n\n/-!\n# The `R`-gates of the rows " + HEADER + "\n\n"
        "For each row, in the order of `rowData`: `(ℓ, β, δ)` and the `2×2` gate matrix `R` of the fibre potential (the block of\n"
        "`M = diag(E, E, R, R, ε I₂)` acting on the coefficients `ζ = (c_z, c_H)`). `rowGates_consistent` ties the entries to\n"
        "`rowData`, `rowGates_ok` checks `R ≻ 0`, `R ⪰ diag(−1, ε)`, `R ⪰ diag(ε, 0)`, and `rowData_smaxOK` checks the Lipschitz\n"
        "header of every row, `smax ≥ 2(|1 + b₁| + 0.7358|b₂| + 0.707107|b₃|)` (with `2/e ≤ 0.7358`, `1/√2 ≤ 0.707107`).\n-/\n\n"
        f"namespace Grothe.Lower\n\n/-- `(ℓ, β, δ, R)` of the {n} rows. -/\ndef rowGates : List (ℚ × ℚ × ℚ × Sym2) := [\n" +
        ",\n".join(f"  ({q(l)}, {q(bb)}, {q(d)}, {fmt(Rm)})" for l, bb, d, Rm in gates) + "]\n\n"
        "/-- The `R` gate of the `k`-th row. -/\ndef rowR (k : ℕ) : Sym2 := ((rowGates.getD k (0, 0, 0, ⟨0, 0, 0⟩)).2.2.2)\n\n"
        "end Grothe.Lower\n")
    files["RowGates.lean"] = ("import Grothe.Lower.RowReduction\nimport Grothe.Lower.RowGateData\n\n/-! # Exact checks of the row "
        "gates " + HEADER + " -/\n\nnamespace Grothe.Lower\n\n"
        "/-- The entries of `rowGates` agree with `rowData`. -/\ntheorem rowGates_consistent :\n"
        "    rowGates.length = rowData.length ∧\n"
        "      (rowData.zip rowGates).all (fun p => decide (p.1.ell = p.2.1 ∧ p.1.beta = p.2.2.1 ∧\n"
        "        p.1.delta = p.2.2.2.1)) = true := by\n  decide +kernel\n\n"
        "/-- **The `R`-gates of all rows**: `R ≻ 0`, `R ⪰ diag(−1, ε)`, `R ⪰ diag(ε, 0)`. -/\ntheorem rowGates_ok :\n"
        "    rowGates.all (fun g => g.2.2.2.psdOK && (g.2.2.2.subDiag (-1) ε).psdOK &&\n"
        "      (g.2.2.2.subDiag ε 0).psdOK) = true := by\n  decide +kernel\n\n"
        "/-- **The Lipschitz header of all rows**: `smax ≥ 2(|1 + b₁| + 0.7358|b₂| + 0.707107|b₃|)`. -/\n"
        "theorem rowData_smaxOK :\n    rowData.all (fun r => decide (2 * (|1 + r.b1| + 7358 / 10000 * |r.b2|\n"
        "      + 707107 / 1000000 * |r.b3|) ≤ r.smax)) = true := by\n  decide +kernel\n\nend Grothe.Lower\n")
    # the mass row
    P = next(P for P in S["pieces"] if P.get("kind") == "mass")
    R = law_of(P)
    lam, Sval = Q(P["lam"]), Q(P["S"])
    delta, kappa, smax = Q(R["delta"]), Q(R["kappa"]), Q(R["smax"])
    assert (Q(R["mass"]), delta, kappa, smax) == (lam, Q(P["delta"]), Q(P["kappa"]), Q(P["smax"])) and Q(R["eps"]) == EPSH
    cc = 2 * Q(R["nu_hat"]) + lam
    assert Q(R["nu_hat"]) == NUH and 0 < kappa <= EPSH / delta**2 and smax >= 2 * EPSH / delta

    def phi(r):
        return EPSH**2 * r * r / cc if r <= cc / EPSH else 2 * EPSH * r - cc
    rs, cs = [Q(v) for v in R["nodes"]], [Q(v) for v in R["caps"]]
    assert rs[0] == 0 and all(cs[k] >= phi(rs[k] / delta) for k in range(len(rs)))
    nodes = ";".join(f"{qs(r)}:{qs(c)}" for r, c in zip(rs, cs))
    cells, nst = spec_cells(R, delta)
    doc = (f"The mass row λ = {qs(lam)} of the certificate: the table of `Ψ(s) = φ_c(s/δ)`, `c = 2ν̂ + λ`, mesh and its "
           f"{len(cells)} `x`-cells ({nst} spectral nodes); cap S − capPad")
    files["MassRow.lean"] = row_module("massRow", doc, (Q(0), Q(0), delta, kappa, smax, Sval - PAD),
                                       (Q(0),) * 6, (Q(0),) * 3, nodes, mesh_vs(R), cells)
    files["Cert/MassRow.lean"] = ("import Grothe.Lower.SpecRows\nimport Grothe.Lower.MassNodes\n\n/-! # The cell check of the mass "
                                  "row " + HEADER + " -/\n\nnamespace Grothe.Lower\n\n"
                                  "theorem certMassRow : checkSpecCells massRow massNodes = true := by native_decide\n\nend Grothe.Lower\n")
    # the envelope
    env = json.load(open(src / "env_final_clean.json"))
    assert Q(env["eps"]) == EPSH and Q(env["step"]) == Q(1, 2000) and len(env["cells"]) == 1800
    assert Q(env["target"]) > ENV_B and env["mass"] == {"mass_0.5": {"lam": qs(lam), "S": qs(Sval)}}
    index = {r["t"]: k + 1 for k, r in enumerate(rows)}
    index["mass_0.5"] = 0
    for t, (l, bb, C) in scal.items():
        e = env["rows"][t]
        assert Q(e["ell"]) == l and Q(e["beta"]) == bb and Q(e["C"]) <= C <= Q(e["C"]) + Q(1, 10**15), t

    step = Q(env["step"])
    size = len(env["cells"])
    assert lam == Q(1, 2) and step * size == Q(9, 10)

    def scalar_row(i, midpoint):
        if i == 0:
            return lam * midpoint, Q(0), lam + Sval + lam * midpoint**2
        return scal[rows[i - 1]["t"]]

    def cell_max(mixture, start, end):
        lo, hi = start * step, end * step
        mid = (lo + hi) / 2
        i, j, theta = mixture
        la, ba, ca = scalar_row(i, mid)
        lb, bb, cb = scalar_row(j, mid)
        ell = (1 - theta) * la + theta * lb
        cap = (1 - theta) * ca + theta * cb - 2 * (1 - theta) * theta * (ba - bb)**2 / EPSH
        return cap + max(lo * (lo - 2 * ell), hi * (hi - 2 * ell))

    mixtures = set()
    fine_max = Q(0)
    for k, (a, b, weight, val) in enumerate(env["cells"]):
        i, j, theta = index[a], index[b], Q(weight)
        assert 0 <= theta <= 1 and (i != 0 or (j == 0 and theta == 0))
        mixture = (i, j, theta)
        value = cell_max(mixture, k, k + 1)
        assert value <= Q(val) + Q(1, 10**15) and value <= ENV_B, (k, value)
        mixtures.add(mixture)
        fine_max = max(fine_max, value)

    def reach(start, mixture):
        # For a fixed mixture the underlying quadratic is convex. At either endpoint a
        # midpoint mass tangent adds the same nonnegative multiple of (hi - lo)^2.
        # Thus the maximum on [start, end] is nondecreasing as end grows.
        lo, hi = start, size + 1
        while lo + 1 < hi:
            mid = (lo + hi) // 2
            if cell_max(mixture, start, mid) <= fine_max:
                lo = mid
            else:
                hi = mid
        return lo

    ecells, worst = [], Q(0)
    start = 0
    while start < size:
        end, mixture = max((reach(start, mix), mix) for mix in mixtures)
        assert end > start, ("uncovered grid point", start)
        value = cell_max(mixture, start, end)
        assert value <= fine_max
        worst = max(worst, value)
        i, j, theta = mixture
        ecells.append(f"  ⟨{q(start * step)}, {q(end * step)}, {i}, {j}, {q(theta)}⟩")
        start = end
    files["EnvelopeData.lean"] = ("import Grothe.Lower.Envelope\n\n/-!\n# The envelope of the rows " + HEADER + "\n\n"
        f"From `data/tail-rows/env_final_clean.json`: a cover of `[0, 9/10]` by {len(ecells)} intervals, each with "
        "the scalar rows `i`, `j` and the weight `θ` of\nits mixture (`0` the tangent of the mass row at the midpoint of the "
        f"cell, `k + 1` the row `k`). Its maximum is {float(worst):.10f}.\n-/\n\n"
        "namespace Grothe.Lower\n\n"
        f"/-- The cap of the hat value checked by the envelope. -/\ndef envB : ℚ := {ENV_B.numerator} / {ENV_B.denominator}\n\n"
        "/-- The cells `lo,hi,i,j,θ` of the envelope. -/\ndef envCells : List EnvCell := [\n" +
        ",\n".join(ecells) + "]\n\nend Grothe.Lower\n")
    files["Cert/Envelope.lean"] = ("import Grothe.Lower.EnvelopeData\nimport Grothe.Lower.MassNodes\n"
        "import Grothe.Lower.RowData\n\n/-! # The check of the envelope " + HEADER + " -/\n\nnamespace Grothe.Lower\n\n"
        "theorem certEnvelope : checkEnvCells rowData massS envB envCells = true := by\n  decide +kernel\n\nend Grothe.Lower\n")
    if check:
        bad = [k for k, v in files.items() if not (out / k).exists() or (out / k).read_text() != v]
        if bad:
            raise SystemExit("gen_lower_data --check: differs: " + ", ".join(bad))
        print(f"gen_lower_data --check: {len(files)} files of Grothe/Lower reproduce byte for byte")
        return
    for k, v in files.items():
        (out / k).parent.mkdir(parents=True, exist_ok=True)
        (out / k).write_text(v)
    print(f"gen_lower_data: wrote {len(files)} files to Grothe/Lower (envelope maximum {float(worst):.12f} <= envB = {float(ENV_B)})")


if __name__ == "__main__":
    args = sys.argv[1:]
    if any(a != "--check" for a in args):
        raise SystemExit("usage: gen_lower_data.py [--check]")
    main(check="--check" in args)
