    beta = w * Q(pi["beta"]) + (1 - w) * Q(pj["beta"]) + db
    assert Q(p["ell"]) == ell and Q(p["beta"]) == beta and Q(p["epsilon"]) == EPS0
    E = sym3([[w * Q(x) + (1 - w) * Q(y) for x, y in zip(a, b)] for a, b in zip(pi["M_E"], pj["M_E"])])
    R = sym2([[w * Q(x) + (1 - w) * Q(y) for x, y in zip(a, b)] for a, b in zip(pi["M_R"], pj["M_R"])])
    assert sym3(p["M_E"]) == E and sym2(p["M_R"]) == R and p["M_R"] == p["M_I"]
    delta = Q(p["delta"])
    gain = 2 * w * (1 - w) * (Q(pi["beta"]) - Q(pj["beta"])) ** 2 / EPS0
    assert Q(g["variance_gain"]) == gain
    # nodes
    nodes, prov = [], []
    kcode = {"pointwise": 0, "dense": 1, "shifted": 2}[kind]
    if kind == "shifted":
        assert Q(g["node_reserve"]) == LIFT and not g.get("conditional_moments")
        for n in g["points"]:
            a, b = n["source_nodes"]
            assert a["source_index"] == i and b["source_index"] == j
