out.append("/-- The nine source profiles `(id, ℓ, β, δ, M_E, M_R)`. -/\ndef srcProfiles : List SrcProfile :=\n[" + ",\n".join(items) + "]\n\n")
out.append("/-- LDL certificates for the gates of the nine source profiles (at `ε₀`). -/\ndef srcGates : List GateCert :=\n[" + ",\n".join("  " + s for s in src_gates) + "]\n\n")
groups = []
for g in src:
    rows = [[Q(c) for c in rec["coefficients"]] for rec in g["polynomials"]] + \
           [[Q(c) for c in rec["coefficients"]] for rec in extra.get(g["profile"]["id"], [])]
    for r in rows:
        assert len(r) == 7 and r[3] == 0 and r[5] == 0 and r[1] >= 0 and r[6] >= 0
    groups.append(rows)
