def transfer(C, beta, ea, eb): return C + (eb - ea) * RHO ** 2 + 2 * beta ** 2 * (1 / eb - 1 / ea)
rows = env_new["profiles"]; assert len(rows) == 47 and Q(env_new["epsilon"]) == EPS
