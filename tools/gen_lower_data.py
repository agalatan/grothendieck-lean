import sys
ROOT = Path(__file__).resolve().parent.parent
HANDOFF = Path(os.environ.get("GROTHE_HANDOFF", ROOT / "handoff"))   # the (git-ignored) data folder; set it when running from a worktree


def replay_canonical(check=False):
    """Render the exact stored constructors without the archived discovery package."""
    source = ROOT / "data" / "lower-rows"
    out = ROOT / "Grothe" / "Lower"
    paths = sorted(source.glob("row*.json"))
    if [p.name for p in paths] != [f"row{k:02d}.json" for k in range(1, 20)]:
        raise ValueError("The canonical source must contain exactly rows 01 through 19")

    def rational(value):
        x = Q(value)
        return f"({x.numerator} : ℚ) / {x.denominator}" if x.denominator != 1 else f"({x.numerator} : ℚ)"

    def lean_string(value):
        if not isinstance(value, str) or any(c in value for c in ('"', '\\', '\n', '\r')):
            raise ValueError("Expected an unescaped constructor string")
        return '"' + value + '"'

    rendered = {}
    for k, path in enumerate(paths, 1):
        data = json.loads(path.read_text())
        header, matrix, coupling = data["header"], data["even_matrix"], data["coupling"]
        cells, name = data["cells"], data["name"]
        if (len(header), len(matrix), len(coupling)) != (6, 6, 3):
            raise ValueError(f"Wrong constructor dimensions in {path}")
        body = (f"/-- The row `{name}`. -/\ndef row{k:02d} : Row :=\n  ⟨" +
                ", ".join(map(rational, header)) + ",\n   ⟨" + ", ".join(map(rational, matrix)) + "⟩,\n   " +
                ", ".join(map(rational, coupling)) + ",\n   " + lean_string(data["nodes"]) + ",\n   " +
                lean_string(data["mesh"]) + ",\n   [" + ",\n    ".join(map(lean_string, cells)) + "]⟩\n\n")
        rendered[f"RowData{k:02d}.lean"] = (
            "import Grothe.Lower.RowDataTypes\n\n/-!\n# Row `" + name +
            "` (generated by `tools/gen_lower_data.py`; do not edit)\n\n" +
            f"Header, node caps, mesh and the {len(cells)} `x`-cells ({data['source_cell_nodes']} nodes) " +
            f"of the row with nominal point `t = {name}`.\n-/\n\n" +
            "namespace Grothe.Lower\n\n" + body + "end Grothe.Lower\n")
    defs = ("/-- The rows of the certificate, sorted by their nominal `t`. -/\ndef rowData : List Row :=\n  [" +
            ", ".join(f"row{k:02d}" for k in range(1, 20)) + "]\n\n")
    rendered["RowData.lean"] = (
        "".join(f"import Grothe.Lower.RowData{k:02d}\n" for k in range(1, 20)) +
        "\n/-!\n# The rows (generated by `tools/gen_lower_data.py`; do not edit)\n\n" +
        "The 19 rows at the witness parameter `ε = 149/200`.\n-/\n\n" +
        "namespace Grothe.Lower\n\n" + defs + "end Grothe.Lower\n")
    for filename, text in rendered.items():
        target = out / filename
        if check:
            if target.read_text() != text:
                raise ValueError(f"Canonical inputs do not reproduce {target}")
        else:
            target.write_text(text)
    print(f"{'checked' if check else 'wrote'} 19 row modules and RowData.lean from {source}")


RHO = Q(973612157, 10**9)
PAD = Q(1, 10**11)

def qs(x) -> str:
    x = Q(x)
    return f"{x.numerator}/{x.denominator}" if x.denominator != 1 else f"{x.numerator}"

def q(x) -> str:
    x = Q(x)
    return f"({x.numerator} : ℚ) / {x.denominator}" if x.denominator != 1 else f"({x.numerator} : ℚ)"

def ldl3(m, strict):
    m11, m12, m13, m22, m23, m33 = m
    d1 = m11
    assert d1 > 0 if strict else d1 >= 0, (m, strict)
    if d1 == 0:
        assert m12 == 0 and m13 == 0; l21 = l31 = Q(0)
    else:
        l21, l31 = m12 / d1, m13 / d1
    d2 = m22 - d1 * l21 * l21
    assert d2 > 0 if strict else d2 >= 0, (m, strict)
    r = m23 - d1 * l21 * l31
    if d2 == 0:
        assert r == 0; l32 = Q(0)
    else:
        l32 = r / d2
    d3 = m33 - d1 * l31 * l31 - d2 * l32 * l32
    assert d3 > 0 if strict else d3 >= 0, (m, strict)
    return (d1, d2, d3, l21, l31, l32)

def ldl2(m, strict):
    m11, m12, m22 = m
    d1 = m11
    assert d1 > 0 if strict else d1 >= 0, (m, strict)
    l21 = Q(0) if d1 == 0 else m12 / d1
    d2 = m22 - d1 * l21 * l21
    assert d2 > 0 if strict else d2 >= 0, (m, strict)
    return (d1, d2, l21)

def solve3(M, b):
    A = [list(M[i]) + [b[i]] for i in range(3)]
    for i in range(3):
        p = next(r for r in range(i, 3) if A[r][i] != 0); A[i], A[p] = A[p], A[i]
        A[i] = [v / A[i][i] for v in A[i]]
        for r in range(3):
            if r != i: A[r] = [v - A[r][i] * w for v, w in zip(A[r], A[i])]
    return [A[i][3] for i in range(3)]

def fmt(c): return "⟨" + ", ".join(q(v) for v in c) + "⟩"

def rsqrt(x):
    a, b = isqrt(x.numerator), isqrt(x.denominator)
    assert a * a == x.numerator and b * b == x.denominator
    return Q(a, b)

def lean_str(s): return '"' + s + '"'


def archive_mode(SOURCE):
    """Explicit archived-source mode: SOURCE = cert-0745e | cert-0745d | cert-0745c."""
    CERT = HANDOFF / "lower-stein" / SOURCE
    ROWS = CERT / {"cert-0745e": "rows_final_e.json", "cert-0745d": "rows_final_d.json", "cert-0745c": "rows_final_c.json"}[SOURCE]
    OUT = ROOT / "Grothe" / "Lower"

    man = json.load(open(CERT / "manifest.json"))
    EPS = Q(man["eps"]); B = Q(man["B"])
    assert EPS == Q(149, 200) and B == {"cert-0745e": Q(713440973, 10**9), "cert-0745d": Q(713443719, 10**9), "cert-0745c": Q(356727549, 500000000)}[SOURCE]
    for fn, h in man["files"].items():
        assert hashlib.sha256(open(CERT / fn, "rb").read()).hexdigest() == h, fn
    consts = json.load(open(ROWS))
    rowfiles = sorted((f for f in man["files"] if f.startswith("row_")), key=lambda f: Q(json.load(open(CERT / f))["t"]))
    rows = []
    for idx, fn in enumerate(rowfiles, 1):
        R = json.load(open(CERT / fn))
        th = [Q(v) for v in R["theta"]]
        E = tuple(th[0:6]); Rm = tuple(th[6:9]); delta = th[9]; b = th[10:13]; ell, beta = th[13], th[14]
        assert 0 < delta < EPS and ell >= 2 * beta >= 0
        # sanity checks of the reduction data (not used by the Lean theorem): the six matrix gates,
        # N ≻ 0 and the per-row price κ ≤ 1/δ − bᵀN⁻¹b
        _gates = (ldl3(E, True), ldl3((E[0] + 1, E[1], E[2], E[3] - EPS, E[4], E[5] - EPS), False),
             ldl3((E[0] - (EPS - delta), E[1], E[2], E[3], E[4], E[5]), False), ldl2(Rm, True),
             ldl2((Rm[0] + 1, Rm[1], Rm[2] - EPS), False), ldl2((Rm[0] - EPS, Rm[1], Rm[2]), False))
        N = (E[0] - (EPS - delta), E[1], E[2], E[3], E[4], E[5])
        ldl3(N, True)
        c = solve3([[N[0], N[1], N[2]], [N[1], N[3], N[4]], [N[2], N[4], N[5]]], b)
        kappa = Q(R["kappa"]); assert 0 < kappa <= 1 / delta - sum(x * y for x, y in zip(b, c))
        smax = Q(R["smax"])
        assert smax >= 2 * (abs(1 + b[0]) + Q(7358, 10000) * abs(b[1]) + Q(707107, 10**6) * abs(b[2]))
        K = consts[R["name"]]
        assert Q(K["ell"]) == ell and Q(K["beta"]) == beta
        cap_exact = Q(K["C"]) - PAD - 2 * beta * beta / EPS
        cap = Q(-((-cap_exact.numerator * 10**15) // cap_exact.denominator), 10**15)   # rounded up
        assert cap_exact <= cap < cap_exact + Q(1, 10**15)
        # cap nodes and caps are exact rationals read from their strings (no rounding: cert-0745e has k/800 nodes)
        assert all(isinstance(v, str) for v in R["nodes"] + R["caps"]) and all(Q(qs(v)) == Q(v) for v in R["nodes"] + R["caps"])
        nodes = ";".join(f"{qs(r)}:{qs(cc)}" for r, cc in zip(R["nodes"], R["caps"]))
        mesh = [Q(v) for v in R["mesh"]]
        assert not mesh or mesh[0] == 0
        vs = ",".join(qs(rsqrt(t)) for t in mesh[1:])
        cells = []
        for cell in R["cells"]:
            rects = cell["rects"] if cell["kind"] == "moment" else cell["small"]
            rs = ";".join(f"{qs(r['s'][0])}:{qs(r['s'][1])}:" + ",".join(qs(v) for v in r["P"]) for r in rects)
            bank = ";".join(",".join(str(int(v)) for v in z) for z in cell.get("bank", []))
            ns = []
            for n in cell.get("nodes", []):
                y = n["y"]
                assert len(n["mu"]) == len(n["cuts"])
                ns.append(f"{qs(n['sigma'])}:" + ",".join(qs(v) for v in (y[0], y[4], y[1], y[2], y[3])) + ":" +
                          ",".join(f"{int(m)},{int(k)}" for m, k in zip(n["mu"], n["cuts"])))
            cells.append(f"{qs(cell['x'][0])}|{qs(cell['x'][1])}|{rs}|{bank}|" + ";".join(ns))
        name = f"row{idx:02d}"
        body = (f"/-- The row `{R['name']}`. -/\ndef {name} : Row :=\n  ⟨{q(ell)}, {q(beta)}, {q(delta)}, {q(kappa)}, {q(smax)}, {q(cap)},\n"
                f"   {fmt(E)},\n   {q(b[0])}, {q(b[1])}, {q(b[2])},\n   {lean_str(nodes)},\n   {lean_str(vs)},\n   [" +
                ",\n    ".join(lean_str(s) for s in cells) + "]⟩\n\n")
        nst = sum(len(c.get("nodes", [])) for c in R["cells"])
        canonical = ROOT / "data" / "lower-rows"
        canonical.mkdir(exist_ok=True)
        (canonical / f"row{idx:02d}.json").write_text(json.dumps({
            "name": R["name"],
            "header": list(map(qs, (ell, beta, delta, kappa, smax, cap))),
            "even_matrix": list(map(qs, E)), "coupling": list(map(qs, b)),
            "nodes": nodes, "mesh": vs, "cells": cells, "source_cell_nodes": nst,
        }, indent=2, ensure_ascii=False) + "\n")
        text = ("import Grothe.Lower.RowDataTypes\n\n/-!\n# Row `" + R["name"] + "` (generated by `tools/gen_lower_data.py`; do not edit)\n\n"
                f"Header, node caps, mesh and the {len(cells)} `x`-cells ({nst} nodes) of the row with nominal point `t = {R['name']}`.\n-/\n\n"
                "namespace Grothe.Lower\n\n" + body + "end Grothe.Lower\n")
        (OUT / f"RowData{idx:02d}.lean").write_text(text)
        rows.append(dict(name=R["name"], lean=name))

    defs = "/-- The rows of the certificate, sorted by their nominal `t`. -/\ndef rowData : List Row :=\n  [" + ", ".join(r["lean"] for r in rows) + "]\n\n"
    text = ("".join(f"import Grothe.Lower.RowData{i:02d}\n" for i in range(1, len(rows) + 1)) + "\n/-!\n"
            "# The rows (generated by `tools/gen_lower_data.py`; do not edit)\n\n"
            f"The {len(rows)} rows at the witness parameter `ε = 149/200`.\n-/\n\n"
            "namespace Grothe.Lower\n\n" + defs + "end Grothe.Lower\n")
    (OUT / "RowData.lean").write_text(text)
    print("ok", json.dumps(dict(rows=len(rows), bytes=sum((OUT / f"RowData{i:02d}.lean").stat().st_size for i in range(1, len(rows) + 1)))))


def tail_mode(check=False):
    """The rows of the identity-tail certificate at ε̂ = 25/31 (claude-b9ee, issue #183), as separate modules beside the rows of
    today's certificate: `Grothe/Lower/TailRows/RowKK.lean` (`tailSteinRowKK`, the 14 cap rows numbered as in
    `data/tail-caps/row_set.json`), `MassRow.lean` (`tailMassRow`, the mass row λ = 1/2) and the checks `CheckKK.lean`,
    `CheckMass.lean`. Inputs: the law certificates in `data/tail-rows/` (copied byte for byte from the certificate's lean-data/
    folder; sha256 in `data/tail-rows/SHA256SUMS` and in `row_set.json`), the row constants of `row_set.json`, the cap tables of
    `data/tail-caps/<t>/table.json`. The 12 plain rows keep today's cell format (`checkRow`); the spectral rows 0.4 and 0.6 and the
    mass row get the cells of `SpecRows.lean` (`xlo#xhi#rects#nodes`, a node `0` or a spectral witness `τ:y₀,y₄,y₁,y₂,y₃:λ,μ,t,β,ν|z…`;
    `checkSpecRow`, `checkSpecCells`). The sanity checks of the archive mode are made at ε̂ (gates, κ, smax), and the node caps
    of every row must equal its cap table. The row cap is ⌈C − capPad − 2β²/ε̂⌉ at 10⁻¹⁵ (C of `row_set.json`); the mass row's
    cap is S − capPad (S of `row_set.json`)."""
    EPSH = Q(25, 31)
    src = ROOT / "data" / "tail-rows"
    capdir = ROOT / "data" / "tail-caps"
    out = ROOT / "Grothe" / "Lower" / "TailRows"
    for line in open(src / "SHA256SUMS"):
        h, fn = line.split(None, 1)
        assert hashlib.sha256(open(src / fn.strip(), "rb").read()).hexdigest() == h, fn
    S = json.load(open(capdir / "row_set.json"))
    files = {}

    def law_of(P):
        name = P["law"]["file"] if isinstance(P["law"], dict) else None
        sub = "spectral" if P["cuts"] == "spectral" else "plain"
        path = src / sub / name.split("/")[-1]
        assert hashlib.sha256(open(path, "rb").read()).hexdigest() == P["law"]["sha256"], path
        return json.load(open(path))

    def mesh_vs(R):
        mesh = [Q(v) for v in R["mesh"]]
        assert mesh and mesh[0] == 0 and all(mesh[i] < mesh[i + 1] for i in range(len(mesh) - 1))
        return ",".join(qs(rsqrt(t)) for t in mesh[1:])

    def spec_cells(R, delta):
        cells, prev = [], Q(0)
        for cell in R["cells"]:
            xlo, xhi = Q(cell["x"][0]), Q(cell["x"][1])
            assert xlo == prev and set(cell) <= {"x", "nodes"}
            prev = xhi
            ws = []
            for n in cell["nodes"]:
                y = n["y"]
                assert len(y) == 5 and len(n["z"]) == len(R["mesh"]) - 1
                ws.append(f"{qs(n['sigma'])}:" + ",".join(qs(v) for v in (y[0], y[4], y[1], y[2], y[3])) + ":" +
                          ",".join(qs(n[k]) for k in ("lam", "mu", "t", "be", "nu")) + "|" + ",".join(qs(v) for v in n["z"]))
            sig = [Q(n["sigma"]) for n in cell["nodes"]]
            assert all(0 < sig[i] < sig[i + 1] for i in range(len(sig) - 1)) and sig[-1] >= delta * RHO
            cells.append(f"{qs(xlo)}#{qs(xhi)}##" + ";".join(["0"] + ws))
        assert prev >= Q(31, 4)
        return cells, sum(len(c["nodes"]) for c in R["cells"])

    def plain_cells(R):
        cells = []
        for cell in R["cells"]:
            rects = cell["rects"] if cell["kind"] == "moment" else cell["small"]
            rs = ";".join(f"{qs(r['s'][0])}:{qs(r['s'][1])}:" + ",".join(qs(v) for v in r["P"]) for r in rects)
            bank = ";".join(",".join(str(int(v)) for v in z) for z in cell.get("bank", []))
            ns = []
            for n in cell.get("nodes", []):
                y = n["y"]
                assert len(n["mu"]) == len(n["cuts"])
                ns.append(f"{qs(n['sigma'])}:" + ",".join(qs(v) for v in (y[0], y[4], y[1], y[2], y[3])) + ":" +
                          ",".join(f"{int(m)},{int(k)}" for m, k in zip(n["mu"], n["cuts"])))
            cells.append(f"{qs(cell['x'][0])}|{qs(cell['x'][1])}|{rs}|{bank}|" + ";".join(ns))
        return cells, sum(len(c.get("nodes", [])) for c in R["cells"])

    def row_module(name, doc, header, E, b, nodes, vs, cells, imports):
        return ("import Grothe.Lower.RowDataTypes\n\n/-!\n# " + doc + " (generated by `tools/gen_lower_data.py --tail`; do not edit)\n-/\n\n"
                "namespace Grothe.Lower\n\nset_option maxRecDepth 100000\n\n"
                f"/-- {doc}. -/\ndef {name} : Row :=\n  ⟨" + ", ".join(map(q, header)) + ",\n   " + fmt(E) + ",\n   " +
                ", ".join(map(q, b)) + ",\n   " + lean_str(nodes) + ",\n   " + lean_str(vs) + ",\n   [" +
                ",\n    ".join(lean_str(c) for c in cells) + "]⟩\n\nend Grothe.Lower\n")

    for P in sorted((P for P in S["pieces"] if P.get("kind") == "caprow"), key=lambda P: P["index"]):
        K, t = P["index"], P["name"]
        spectral = P["cuts"] == "spectral"
        R = law_of(P)
        th = [Q(v) for v in R["theta"]]
        assert th == [Q(v) for v in P["theta"]] and Q(R["eps"]) == EPSH
        E = tuple(th[0:6]); Rm = tuple(th[6:9]); delta = th[9]; b = th[10:13]; ell, beta = th[13], th[14]
        assert 0 < delta < EPSH and ell >= 2 * beta >= 0
        _gates = (ldl3(E, True), ldl3((E[0] + 1, E[1], E[2], E[3] - EPSH, E[4], E[5] - EPSH), False),
                  ldl3((E[0] - (EPSH - delta), E[1], E[2], E[3], E[4], E[5]), False), ldl2(Rm, True),
                  ldl2((Rm[0] + 1, Rm[1], Rm[2] - EPSH), False), ldl2((Rm[0] - EPSH, Rm[1], Rm[2]), False))
        N = (E[0] - (EPSH - delta), E[1], E[2], E[3], E[4], E[5])
        ldl3(N, True)
        c = solve3([[N[0], N[1], N[2]], [N[1], N[3], N[4]], [N[2], N[4], N[5]]], b)
        kappa, smax = Q(R["kappa"]), Q(R["smax"])
        assert kappa == Q(P["kappa"]) and smax == Q(P["smax"])
        assert 0 < kappa <= 1 / delta - sum(x * y for x, y in zip(b, c))
        assert smax >= 2 * (abs(1 + b[0]) + Q(7358, 10000) * abs(b[1]) + Q(707107, 10**6) * abs(b[2]))
        cap_exact = Q(P["C"]) - PAD - 2 * beta * beta / EPSH
        cap = Q(-((-cap_exact.numerator * 10**15) // cap_exact.denominator), 10**15)
        T = json.load(open(capdir / t / "table.json"))
        assert [Q(v) for v in R["nodes"]] == [Q(v) for v in T["nodes"]] and [Q(v) for v in R["caps"]] == [Q(v) for v in T["caps"]]
        nodes = ";".join(f"{qs(r)}:{qs(cc)}" for r, cc in zip(R["nodes"], R["caps"]))
        cells, nst = spec_cells(R, delta) if spectral else plain_cells(R)
        nm = f"tailSteinRow{K:02d}"
        doc = (f"Row {K} (`t = {t}`) of the identity-tail certificate: header, node caps, mesh and its {len(cells)} `x`-cells "
               f"({nst} {'spectral' if spectral else 'Stein'} nodes)")
        files[f"Row{K:02d}.lean"] = row_module(nm, doc, (ell, beta, delta, kappa, smax, cap), E, b, nodes, mesh_vs(R), cells, [])
        chk = "checkSpecRow" if spectral else "checkRow"
        files[f"Check{K:02d}.lean"] = (
            ("import Grothe.Lower.SpecRows\n" if spectral else "import Grothe.Lower.Rows\n") +
            f"import Grothe.Lower.TailRows.Row{K:02d}\n\n/-! # The row check of row {K} (`t = {t}`) of the identity-tail certificate "
            "(generated by `tools/gen_lower_data.py --tail`; do not edit) -/\n\nnamespace Grothe.Lower\n\n"
            f"theorem {nm}_check : {chk} {nm} = true := by native_decide\n\nend Grothe.Lower\n")
    # the mass row
    P = next(P for P in S["pieces"] if P.get("kind") == "mass")
    R = law_of(P)
    lam, Sval = Q(P["lam"]), Q(P["S"])
    delta, kappa, smax = Q(R["delta"]), Q(R["kappa"]), Q(R["smax"])
    assert (Q(R["mass"]), delta, kappa, smax) == (lam, Q(P["delta"]), Q(P["kappa"]), Q(P["smax"])) and Q(R["eps"]) == EPSH
    cc = 2 * Q(R["nu_hat"]) + lam
    assert Q(R["nu_hat"]) == Q(47, 1953) and 0 < kappa <= EPSH / delta**2 and smax >= 2 * EPSH / delta

    def phi(r):
        return EPSH**2 * r * r / cc if r <= cc / EPSH else 2 * EPSH * r - cc
    rs, cs = [Q(v) for v in R["nodes"]], [Q(v) for v in R["caps"]]
    assert rs[0] == 0 and all(cs[k] >= phi(rs[k] / delta) for k in range(len(rs)))
    nodes = ";".join(f"{qs(r)}:{qs(c)}" for r, c in zip(rs, cs))
    cells, nst = spec_cells(R, delta)
    doc = (f"The mass row λ = {qs(lam)} of the identity-tail certificate: the table of `Ψ(s) = φ_c(s/δ)`, `c = 2ν̂ + λ`, mesh and its "
           f"{len(cells)} `x`-cells ({nst} spectral nodes); cap S − capPad")
    files["MassRow.lean"] = row_module("tailMassRow", doc, (Q(0), Q(0), delta, kappa, smax, Sval - PAD),
                                       (Q(0),) * 6, (Q(0),) * 3, nodes, mesh_vs(R), cells, [])
