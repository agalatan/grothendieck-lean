#!/usr/bin/env python3
"""Generate the lower-bound row data modules (exact rationals only):

  Grothe/Lower/RowData01.lean …   one module per row: header (ℓ, β, δ, κ, smax, cap, M_E, b), node
                                  caps, mesh, and the x-cells (moment rectangles, bank of cut
                                  vectors, nodes) as strings
  Grothe/Lower/RowData.lean       the list of rows

Inputs: `handoff/lower-stein/<SOURCE>/` (default `cert-0745e`; manifest.json, row_<t>.json) and the exact
row constants `<SOURCE>/rows_final_<e|d|c>.json` written by the reference verifier
(`verify_cert.py <SOURCE> --rows ...`).  The row cap is the exact row maximum rounded up
to a multiple of 10⁻¹⁵.  The matrix gates of the rows (M_E ≻ 0, M_R ≻ 0 and the four
domination gates at ε, by exact LDLᵀ factorizations) and the per-row price κ ≤ 1/δ − bᵀN⁻¹b are
asserted here as sanity checks of the data of the Gaussian reduction; the Lean theorem does
not use them (it checks κδ² ≤ δ + gatePrice(N, δb) and the positivity of the trailing gate
block, `checkRow`).  The scalar envelope and the cover are generated by `gen_lower_mixed.py`.
"""
import hashlib
import json
from fractions import Fraction as Q
from math import isqrt
from pathlib import Path

import os
import sys
ROOT = Path(__file__).resolve().parent.parent
HANDOFF = Path(os.environ.get("GROTHE_HANDOFF", ROOT / "handoff"))   # the (git-ignored) data folder; set it when running from a worktree
# usage: tools/gen_lower_data.py [SOURCE]   SOURCE = cert-0745e (default) | cert-0745d | cert-0745c (folder in handoff/lower-stein)
SOURCE = sys.argv[1] if len(sys.argv) > 1 else "cert-0745e"
CERT = HANDOFF / "lower-stein" / SOURCE
ROWS = CERT / {"cert-0745e": "rows_final_e.json", "cert-0745d": "rows_final_d.json", "cert-0745c": "rows_final_c.json"}[SOURCE]
OUT = ROOT / "Grothe" / "Lower"
RHO = Q(973612157, 10**9)
PAD = Q(1, 10**11)

def qs(x) -> str:
    x = Q(x)
    return f"{x.numerator}/{x.denominator}" if x.denominator != 1 else f"{x.numerator}"

def q(x) -> str:
    x = Q(x)
    return f"({x.numerator} : ℚ) / {x.denominator}" if x.denominator != 1 else f"({x.numerator} : ℚ)"

def ldl3(m, strict):
    m11, m12, m13, m22, m23, m33 = m
    d1 = m11
    assert d1 > 0 if strict else d1 >= 0, (m, strict)
    if d1 == 0:
        assert m12 == 0 and m13 == 0; l21 = l31 = Q(0)
    else:
        l21, l31 = m12 / d1, m13 / d1
    d2 = m22 - d1 * l21 * l21
    assert d2 > 0 if strict else d2 >= 0, (m, strict)
    r = m23 - d1 * l21 * l31
    if d2 == 0:
        assert r == 0; l32 = Q(0)
    else:
        l32 = r / d2
    d3 = m33 - d1 * l31 * l31 - d2 * l32 * l32
    assert d3 > 0 if strict else d3 >= 0, (m, strict)
    return (d1, d2, d3, l21, l31, l32)

def ldl2(m, strict):
    m11, m12, m22 = m
    d1 = m11
    assert d1 > 0 if strict else d1 >= 0, (m, strict)
    l21 = Q(0) if d1 == 0 else m12 / d1
    d2 = m22 - d1 * l21 * l21
    assert d2 > 0 if strict else d2 >= 0, (m, strict)
    return (d1, d2, l21)

def solve3(M, b):
    A = [list(M[i]) + [b[i]] for i in range(3)]
    for i in range(3):
        p = next(r for r in range(i, 3) if A[r][i] != 0); A[i], A[p] = A[p], A[i]
        A[i] = [v / A[i][i] for v in A[i]]
        for r in range(3):
            if r != i: A[r] = [v - A[r][i] * w for v, w in zip(A[r], A[i])]
    return [A[i][3] for i in range(3)]

def fmt(c): return "⟨" + ", ".join(q(v) for v in c) + "⟩"

def rsqrt(x):
    a, b = isqrt(x.numerator), isqrt(x.denominator)
    assert a * a == x.numerator and b * b == x.denominator
    return Q(a, b)

def lean_str(s): return '"' + s + '"'

man = json.load(open(CERT / "manifest.json"))
EPS = Q(man["eps"]); B = Q(man["B"])
assert EPS == Q(149, 200) and B == {"cert-0745e": Q(713440973, 10**9), "cert-0745d": Q(713443719, 10**9), "cert-0745c": Q(356727549, 500000000)}[SOURCE]
for fn, h in man["files"].items():
    assert hashlib.sha256(open(CERT / fn, "rb").read()).hexdigest() == h, fn
consts = json.load(open(ROWS))
rowfiles = sorted((f for f in man["files"] if f.startswith("row_")), key=lambda f: Q(json.load(open(CERT / f))["t"]))
rows = []
for idx, fn in enumerate(rowfiles, 1):
    R = json.load(open(CERT / fn))
    th = [Q(v) for v in R["theta"]]
    E = tuple(th[0:6]); Rm = tuple(th[6:9]); delta = th[9]; b = th[10:13]; ell, beta = th[13], th[14]
    assert 0 < delta < EPS and ell >= 2 * beta >= 0
    # sanity checks of the reduction data (not used by the Lean theorem): the six matrix gates,
    # N ≻ 0 and the per-row price κ ≤ 1/δ − bᵀN⁻¹b
    _gates = (ldl3(E, True), ldl3((E[0] + 1, E[1], E[2], E[3] - EPS, E[4], E[5] - EPS), False),
         ldl3((E[0] - (EPS - delta), E[1], E[2], E[3], E[4], E[5]), False), ldl2(Rm, True),
         ldl2((Rm[0] + 1, Rm[1], Rm[2] - EPS), False), ldl2((Rm[0] - EPS, Rm[1], Rm[2]), False))
    N = (E[0] - (EPS - delta), E[1], E[2], E[3], E[4], E[5])
    ldl3(N, True)
    c = solve3([[N[0], N[1], N[2]], [N[1], N[3], N[4]], [N[2], N[4], N[5]]], b)
    kappa = Q(R["kappa"]); assert 0 < kappa <= 1 / delta - sum(x * y for x, y in zip(b, c))
    smax = Q(R["smax"])
    assert smax >= 2 * (abs(1 + b[0]) + Q(7358, 10000) * abs(b[1]) + Q(707107, 10**6) * abs(b[2]))
    K = consts[R["name"]]
    assert Q(K["ell"]) == ell and Q(K["beta"]) == beta
    cap_exact = Q(K["C"]) - PAD - 2 * beta * beta / EPS
    cap = Q(-((-cap_exact.numerator * 10**15) // cap_exact.denominator), 10**15)   # rounded up
    assert cap_exact <= cap < cap_exact + Q(1, 10**15)
    # cap nodes and caps are exact rationals read from their strings (no rounding: cert-0745e has k/800 nodes)
    assert all(isinstance(v, str) for v in R["nodes"] + R["caps"]) and all(Q(qs(v)) == Q(v) for v in R["nodes"] + R["caps"])
    nodes = ";".join(f"{qs(r)}:{qs(cc)}" for r, cc in zip(R["nodes"], R["caps"]))
    mesh = [Q(v) for v in R["mesh"]]
    assert not mesh or mesh[0] == 0
    vs = ",".join(qs(rsqrt(t)) for t in mesh[1:])
    cells = []
    for cell in R["cells"]:
        rects = cell["rects"] if cell["kind"] == "moment" else cell["small"]
        rs = ";".join(f"{qs(r['s'][0])}:{qs(r['s'][1])}:" + ",".join(qs(v) for v in r["P"]) for r in rects)
        bank = ";".join(",".join(str(int(v)) for v in z) for z in cell.get("bank", []))
        ns = []
        for n in cell.get("nodes", []):
            y = n["y"]
            assert len(n["mu"]) == len(n["cuts"])
            ns.append(f"{qs(n['sigma'])}:" + ",".join(qs(v) for v in (y[0], y[4], y[1], y[2], y[3])) + ":" +
                      ",".join(f"{int(m)},{int(k)}" for m, k in zip(n["mu"], n["cuts"])))
        cells.append(f"{qs(cell['x'][0])}|{qs(cell['x'][1])}|{rs}|{bank}|" + ";".join(ns))
    name = f"row{idx:02d}"
    body = (f"/-- The row `{R['name']}`. -/\ndef {name} : Row :=\n  ⟨{q(ell)}, {q(beta)}, {q(delta)}, {q(kappa)}, {q(smax)}, {q(cap)},\n"
            f"   {fmt(E)},\n   {q(b[0])}, {q(b[1])}, {q(b[2])},\n   {lean_str(nodes)},\n   {lean_str(vs)},\n   [" +
            ",\n    ".join(lean_str(s) for s in cells) + "]⟩\n\n")
    nst = sum(len(c.get("nodes", [])) for c in R["cells"])
    text = ("import Grothe.Lower.Rows\n\n/-!\n# Row `" + R["name"] + "` (generated by `tools/gen_lower_data.py`; do not edit)\n\n"
            f"Header, node caps, mesh and the {len(cells)} `x`-cells ({nst} nodes) of the row with nominal point `t = {R['name']}`.\n-/\n\n"
            "namespace Grothe.Lower\n\n" + body + "end Grothe.Lower\n")
    (OUT / f"RowData{idx:02d}.lean").write_text(text)
    rows.append(dict(name=R["name"], lean=name))

defs = "/-- The rows of the certificate, sorted by their nominal `t`. -/\ndef rowData : List Row :=\n  [" + ", ".join(r["lean"] for r in rows) + "]\n\n"
text = ("".join(f"import Grothe.Lower.RowData{i:02d}\n" for i in range(1, len(rows) + 1)) + "\n/-!\n"
        "# The rows (generated by `tools/gen_lower_data.py`; do not edit)\n\n"
        f"The {len(rows)} rows at the witness parameter `ε = 149/200`.\n-/\n\n"
        "namespace Grothe.Lower\n\n" + defs + "end Grothe.Lower\n")
(OUT / "RowData.lean").write_text(text)
print("ok", json.dumps(dict(rows=len(rows), bytes=sum((OUT / f"RowData{i:02d}.lean").stat().st_size for i in range(1, len(rows) + 1)))))
