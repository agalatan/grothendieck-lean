#!/usr/bin/env python3
"""Generate Grothe/Lower/ProfileData.lean and Grothe/Lower/EnvelopeData.lean from handoff/lower.

Exact rationals only.  LDL certificates for the matrix gates are computed here with
fractions.Fraction; Lean re-checks the factorization identities exactly.
"""
import json
from fractions import Fraction as Q
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOW = ROOT / "handoff" / "lower"
EPS = Q(37, 50)

src = json.load(open(ROOT / "handoff" / "data" / "lower-source-profiles.json"))["groups"]
extra = json.load(open(LOW / "base" / "certificates" / "additional-polynomials.json"))
records = json.load(open(LOW / "coupled-profiles.json"))
env = json.load(open(LOW / "envelope.json"))

def q(x: Q) -> str:
    x = Q(x)
    return f"({x.numerator} : ℚ) / {x.denominator}" if x.denominator != 1 else f"({x.numerator} : ℚ)"

def qs(x: Q) -> str:
    x = Q(x)
    return f"{x.numerator}/{x.denominator}" if x.denominator != 1 else f"{x.numerator}"

def sym3(M):
    M = [[Q(v) for v in row] for row in M]
    assert all(M[i][j] == M[j][i] for i in range(3) for j in range(3))
    return (M[0][0], M[0][1], M[0][2], M[1][1], M[1][2], M[2][2])

def sym2(M):
    M = [[Q(v) for v in row] for row in M]
    assert M[0][1] == M[1][0]
    return (M[0][0], M[0][1], M[1][1])

def ldl3(m, strict):
    m11, m12, m13, m22, m23, m33 = m
    d1 = m11
    assert d1 > 0 if strict else d1 >= 0, (m, strict)
    if d1 == 0:
        assert m12 == 0 and m13 == 0; l21 = l31 = Q(0)
    else:
        l21, l31 = m12 / d1, m13 / d1
    d2 = m22 - d1 * l21 * l21
    assert d2 > 0 if strict else d2 >= 0, (m, strict)
    r = m23 - d1 * l21 * l31
    if d2 == 0:
        assert r == 0; l32 = Q(0)
    else:
        l32 = r / d2
    d3 = m33 - d1 * l31 * l31 - d2 * l32 * l32
    assert d3 > 0 if strict else d3 >= 0, (m, strict)
    # re-check identity
    assert (d1, d1*l21, d1*l31, d1*l21*l21 + d2, d1*l21*l31 + d2*l32, d1*l31*l31 + d2*l32*l32 + d3) == m
    return (d1, d2, d3, l21, l31, l32)

def ldl2(m, strict):
    m11, m12, m22 = m
    d1 = m11
    assert d1 > 0 if strict else d1 >= 0, (m, strict)
    if d1 == 0:
        assert m12 == 0; l21 = Q(0)
    else:
        l21 = m12 / d1
    d2 = m22 - d1 * l21 * l21
    assert d2 > 0 if strict else d2 >= 0, (m, strict)
    assert (d1, d1*l21, d1*l21*l21 + d2) == m
    return (d1, d2, l21)

def gates(E, R, delta):
    e_pd = ldl3(E, True)
    e_dom1 = ldl3((E[0] + 1, E[1], E[2], E[3] - EPS, E[4], E[5] - EPS), False)
    e_dom2 = ldl3((E[0] - (EPS - delta), E[1], E[2], E[3], E[4], E[5]), False)
    r_pd = ldl2(R, True)
    r_dom1 = ldl2((R[0] + 1, R[1], R[2] - EPS), False)
    r_dom2 = ldl2((R[0] - EPS, R[1], R[2]), False)
    return (e_pd, e_dom1, e_dom2, r_pd, r_dom1, r_dom2)

def fmt_ldl3(c): return "⟨" + ", ".join(q(v) for v in c) + "⟩"
def fmt_ldl2(c): return "⟨" + ", ".join(q(v) for v in c) + "⟩"
def fmt_gates(g):
    return "⟨" + ", ".join([fmt_ldl3(g[0]), fmt_ldl3(g[1]), fmt_ldl3(g[2]), fmt_ldl2(g[3]), fmt_ldl2(g[4]), fmt_ldl2(g[5])]) + "⟩"

out = ["import Grothe.Lower.Profiles\n\n/-!\n# Lower-bound certificate data (generated by `tools/gen_lower_data.py`; do not edit)\n\n"
       "Source profiles and polynomials come from the pinned upstream `check_complex_lower.py`\n"
       "(exported as `handoff/data/lower-source-profiles.json`) plus the 48 additional polynomials;\n"
       "the 21 coupled profiles come from `handoff/lower/coupled-profiles.json`.  Polynomial\n"
       "coefficients are the raw (unlifted) source values; the lift `1/10⁸` is applied in Lean.\n-/\n\nnamespace Grothe.Lower\n\n"]

# source profiles
items = []
src_gates = []
for g in src:
    p = g["profile"]
    E = sym3(p["M_E"]); R = sym2(p["M_R"]); assert p["M_R"] == p["M_I"]
    assert Q(p["epsilon"]) == EPS
    items.append(f"  ⟨\"{p['id']}\", {q(p['ell'])}, {q(p['beta'])}, {q(p['delta'])},\n    ⟨{', '.join(q(v) for v in E)}⟩,\n    ⟨{', '.join(q(v) for v in R)}⟩⟩")
    src_gates.append(fmt_gates(gates(E, R, Q(p["delta"]))))
out.append("/-- The nine source profiles `(id, ℓ, β, δ, M_E, M_R)`. -/\ndef srcProfiles : List SrcProfile :=\n[" + ",\n".join(items) + "]\n\n")
out.append("/-- LDL certificates for the gates of the nine source profiles. -/\ndef srcGates : List GateCert :=\n[" + ",\n".join("  " + s for s in src_gates) + "]\n\n")

# polynomials per group (source + extra), raw coefficients
groups = []
for g in src:
    rows = [[Q(c) for c in rec["coefficients"]] for rec in g["polynomials"]] + \
           [[Q(c) for c in rec["coefficients"]] for rec in extra.get(g["profile"]["id"], [])]
    for r in rows:
        assert len(r) == 7 and r[3] == 0 and r[5] == 0 and r[1] >= 0 and r[6] >= 0
    groups.append(rows)
for gi, rows in enumerate(groups):
    body = ",\n".join("  [" + ", ".join(q(c) for c in r) + "]" for r in rows)
    out.append(f"/-- Physical polynomials of source group {gi} (`{src[gi]['profile']['id']}`), raw coefficients. -/\ndef polyGroup{gi} : List (List ℚ) :=\n[{body}]\n\n")
out.append("/-- All polynomial groups. -/\ndef polyGroups : List (List (List ℚ)) :=\n  [" + ", ".join(f"polyGroup{i}" for i in range(len(groups))) + "]\n\n")

# virtual records
recs = []
for k, r in enumerate(records):
    i, j = r["indices"]; pi, pj = src[i]["profile"], src[j]["profile"]
    assert r["profiles"] == [pi["id"], pj["id"]]
    w = Q(r["weight"]); di, dj = Q(pi["delta"]), Q(pj["delta"])
    d = w * di + (1 - w) * dj
    assert Q(r["ell"]) == w * Q(pi["ell"]) + (1 - w) * Q(pj["ell"])
    assert Q(r["beta"]) == w * Q(pi["beta"]) + (1 - w) * Q(pj["beta"])
    scales = tuple(map(Q, r.get("argument_scales", [str(di), str(dj)])))
    assert w * scales[0] + (1 - w) * scales[1] == d
    dprime = Q(r["delta"])
    assert 0 < dprime <= d
    gain = 2 * w * (1 - w) * (Q(pi["beta"]) - Q(pj["beta"])) ** 2 / EPS
    assert Q(r["gain"]) == gain
    E = sym3([[w * Q(x) + (1 - w) * Q(y) for x, y in zip(a, b)] for a, b in zip(pi["M_E"], pj["M_E"])])
    R = sym2([[w * Q(x) + (1 - w) * Q(y) for x, y in zip(a, b)] for a, b in zip(pi["M_R"], pj["M_R"])])
    if "tightening" in r:
        tp = r["tightening"]["profile"]
        assert sym3(tp["M_E"]) == E and sym2(tp["M_R"]) == R and Q(tp["delta"]) == dprime
    else:
        assert dprime == d
    g = gates(E, R, dprime)
    leaves = []
    for leaf in r["leaves"]:
        s = f"{leaf['path']}:{leaf['polynomials'][0]}:{leaf['polynomials'][1]}"
        if "argument_scales" in leaf:
            a, b = map(Q, leaf["argument_scales"])
            s += f":{qs(a)}:{qs(b)}"
        leaves.append(s)
    recs.append(f"  ⟨{i}, {j}, {q(w)}, {q(r['ell'])}, {q(r['beta'])}, {q(d)}, {q(dprime)}, {q(gain)}, {q(r['cap'])},\n    {q(scales[0])}, {q(scales[1])},\n    {fmt_gates(g)},\n    \"{';'.join(leaves)}\"⟩")
out.append("/-- The 21 coupled (virtual) profiles. -/\ndef vrecords : List VRecord :=\n[" + ",\n".join(recs) + "]\n\nend Grothe.Lower\n")
(ROOT / "Grothe" / "Lower" / "ProfileData.lean").write_text("".join(out))

# envelope
rows = env["rows"]
eo = ["import Grothe.Lower.Envelope\n\n/-!\n# Scalar envelope data (generated by `tools/gen_lower_data.py`; do not edit)\n\n"
      "Rows `(ℓ, β, C)` sorted by `ℓ`, with provenance names, from `handoff/lower/envelope.json`; the\n"
      "20 scalar leaves select one or two rows each.\n-/\n\nnamespace Grothe.Lower\n\n"]
eo.append("/-- Provenance of each envelope row. -/\ndef envRowNames : List String :=\n  [" + ", ".join(f"\"{r[0]}\"" for r in rows) + "]\n\n")
eo.append("/-- Envelope rows `(ℓ, β, C)`. -/\ndef envRows : List EnvRow :=\n[" + ",\n".join(f"  ⟨{q(r[1])}, {q(r[2])}, {q(r[3])}⟩" for r in rows) + "]\n\n")
eo.append("/-- Scalar cover leaves: path and selected row indices. -/\ndef envLeaves : List EnvLeaf :=\n[" + ",\n".join(f"  ⟨\"{l['path']}\", [{', '.join(map(str, l['profiles']))}]⟩" for l in env["leaves"]) + "]\n\nend Grothe.Lower\n")
(ROOT / "Grothe" / "Lower" / "EnvelopeData.lean").write_text("".join(eo))
print("ok", len(records), sum(len(r["leaves"]) for r in records), "leaves;", sum(len(g) for g in groups), "polys;", len(rows), "rows;", len(env["leaves"]), "env leaves")
