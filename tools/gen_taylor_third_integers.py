#!/usr/bin/env python3
"""Regenerate exact authoritative third-center integer grades from pinned NPZ.

The source is the pinned binary64 archive used by gen_taylor_band_data.py.
When the original thirdCenterPacked literal is still present, also replay all
6,552 records and check exact equality to the newly generated integer arrays.
These data define the finite center; they do not prove Gaussian error bounds.
"""
from __future__ import annotations
import argparse
from fractions import Fraction
from hashlib import sha256
import json
from pathlib import Path
import re
import sys
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'data/taylor-approximants'
INPUT_MANIFEST = DATA / 'manifest.json'
LEGACY_SOURCE = ROOT / 'Grothe/UpperChaos/TaylorBandData.lean'
OUTPUT = ROOT / 'Grothe/UpperChaos/TaylorThirdIntegerData.lean'
SQUARE = ROOT / 'Grothe/UpperChaos/ArraySquareEnergy.lean'
MANIFEST = DATA / 'third-integer-manifest.json'
EXPONENT = 105
BANDS = [(0,11),(11,21),(21,31),(31,51)]


def count_through(degree):
    n=(degree+1)//2
    return n*(n+1)*(n+2)//3


def legacy_records_if_present():
    src=LEGACY_SOURCE.read_text(encoding='utf-8')
    marker='def thirdCenterPacked : String := String.intercalate "," ['
    if marker not in src:
        return None
    body=src.split(marker,1)[1].split('\n]',1)[0]
    rows=re.findall(r'"([^"\\]*)"',body)
    if len(rows)!=26:
        raise ValueError(f'original literal has {len(rows)} grades, expected 26')
    return [r for row in rows for r in row.split(',')]


def generated():
    manifest=json.loads(INPUT_MANIFEST.read_text(encoding='utf-8'))
    candidates=[entry for entry in manifest['inputs'] if Path(entry['path']).name=='arb_phase_power3_D51.npz']
    if len(candidates)!=1:
        raise ValueError('missing or duplicate pinned third-center input')
    info=candidates[0]
    source=DATA/info['path']
    raw=source.read_bytes()
    if len(raw)!=info['size_bytes'] or sha256(raw).hexdigest()!=info['sha256']:
        raise ValueError('pinned NPZ size or hash mismatch')
    with np.load(source,allow_pickle=False) as archive:
        arr=archive['center']
        if arr.dtype!=np.dtype('<f8') or arr.shape!=(6552,) or not np.isfinite(arr).all():
            raise ValueError('unexpected or nonfinite binary64 source')
        rationals=[Fraction.from_float(float(v)) for v in arr]
    exponents=[x.denominator.bit_length()-1 for x in rationals]
    if max(exponents)!=EXPONENT:
        raise ValueError('third center common exponent changed')
    for x,e in zip(rationals,exponents):
        if x.denominator!=2**e or abs(x.numerator)>=2**53:
            raise ValueError('invalid binary64 dyadic')
    records=[f'{x.numerator}:{e}' for x,e in zip(rationals,exponents)]
    decoded=[x.numerator*2**(EXPONENT-e) for x,e in zip(rationals,exponents)]
    if [Fraction(v,2**EXPONENT) for v in decoded]!=rationals:
        raise ValueError('integer-scaled round trip differs from original binary64')
    legacy=legacy_records_if_present()
    if legacy is not None and legacy!=records:
        raise ValueError('legacy source records differ from pinned NPZ, including ordering')
    total=sum(x*x for x in rationals)
    band_energies=[sum(x*x for x in rationals[count_through(lo):count_through(hi)]) for lo,hi in BANDS]
    if sum(band_energies)!=total:
        raise ValueError('band energies do not sum to total')
    old_cert=json.loads((DATA/'third-center.json').read_text(encoding='utf-8'))
    if Fraction(old_cert['energy'])!=total or [Fraction(b['energy']) for b in old_cert['bands']]!=band_energies:
        raise ValueError('existing checked generator targets differ from pinned NPZ')
    grades=[]
    for q in range(26):
        start=q*(q+1)*(q+2)//3
        end=(q+1)*(q+2)*(q+3)//3
        values=decoded[start:end]
        if len(values)!=(q+1)*(q+2):
            raise ValueError(f'wrong grade length {q}')
        grades.append(values)
    if sum(map(len,grades))!=6552 or len(grades[-1])!=702:
        raise ValueError('wrong graded index geometry')
    lines=['import Mathlib.Data.Int.Basic','',
           '/-! Generated by tools/gen_taylor_third_integers.py from the pinned',
           'third-center binary64 input. Integer values have common denominator 2^105,',
           'in exact grade / row / column order. These data do not establish Gaussian',
           'approximation or numerical error bounds. Agent-ID: codex-8c4d. -/', '',
           'namespace Grothe.UpperChaos','']
    for q,values in enumerate(grades):
        parts=[]
        for off in range(0,len(values),64):
            part=f'thirdCenterIntegerGrade{q:02d}Part{off:03d}'
            parts.append(part)
            lines.append(f'def {part} : Array ℤ := #['+', '.join(map(str,values[off:off+64]))+']')
        lines.append(f'def thirdCenterIntegerGrade{q:02d} : Array ℤ := ' + ' ++ '.join(parts))
        lines.append('')
    lines.extend(['/-- All 26 grades in their exact original ordering. -/',
                  'def thirdCenterIntegerValues : List ℤ :=',
                  '  '+' ++\n  '.join(f'thirdCenterIntegerGrade{q:02d}.toList' for q in range(26)),
                  '', 'end Grothe.UpperChaos', ''])
    # Generic algebra splits every array fold across its actual named subarrays.
    square = """import Mathlib.Data.Int.Basic

/-! Generic exact addition of integer array square energies. -/
namespace Grothe.UpperChaos.ArraySquareEnergy

def energy (xs : Array ℤ) : ℤ := xs.foldl (fun acc x => acc + x ^ 2) 0

private theorem list_fold_add (xs : List ℤ) (a : ℤ) :
    xs.foldl (fun acc x => acc + x ^ 2) a =
      a + xs.foldl (fun acc x => acc + x ^ 2) 0 := by
  induction xs generalizing a with
  | nil => simp
  | cons x xs ih =>
    simp only [List.foldl_cons]
    rw [ih (a + x ^ 2), ih (0 + x ^ 2)]
    simp only [Int.zero_add, Int.add_assoc]

theorem fold_add (xs : Array ℤ) (a : ℤ) :
    xs.foldl (fun acc x => acc + x ^ 2) a = a + energy xs := by
  unfold energy
  rw [← Array.foldl_toList, ← Array.foldl_toList]
  exact list_fold_add xs.toList a

theorem energy_append (xs ys : Array ℤ) : energy (xs ++ ys) = energy xs + energy ys := by
  unfold energy
  rw [Array.foldl_append, fold_add]
  rfl
end Grothe.UpperChaos.ArraySquareEnergy
"""
    part_outputs={}
    grade_outputs={}
    for q,grade_values in enumerate(grades):
        grade_parts=[]
        for off in range(0,len(grade_values),64):
            part=f'thirdCenterIntegerGrade{q:02d}Part{off:03d}'
            mod=f'TaylorThirdIntegerGrade{q:02d}Part{off:03d}Check'
            xs=grade_values[off:off+64]
            part_outputs[ROOT/f'Grothe/UpperChaos/{mod}.lean']=f"""import Grothe.UpperChaos.TaylorThirdIntegerData
import Grothe.UpperChaos.ArraySquareEnergy
import Lean.Util.CollectAxioms
import Lean.Elab.Command
/-! Exact actual source subarray, at most 64 integers. Generated by
 tools/gen_taylor_third_integers.py. Agent-ID: codex-8c4d. -/
namespace Grothe.UpperChaos.{mod}
open ArraySquareEnergy

theorem part_length : {part}.size = {len(xs)} := by decide +kernel

theorem part_energy : energy {part} = {sum(v*v for v in xs)} := by decide +kernel

end Grothe.UpperChaos.{mod}
open Lean Elab Command
run_cmd do
  for target in #[``Grothe.UpperChaos.{mod}.part_length,
      ``Grothe.UpperChaos.{mod}.part_energy] do
    for ax in ← Lean.collectAxioms target do
      unless #[`propext, `Classical.choice, `Quot.sound].contains ax do
        throwError m!"{{target}} has forbidden axiom {{ax}}"
"""
            grade_parts.append((part,mod))
        imports='\n'.join(f'import Grothe.UpperChaos.{mod}' for _,mod in grade_parts)
        size_lemmas=', '.join(f'{mod}.part_length' for _,mod in grade_parts)
        energy_lemmas=', '.join(f'{mod}.part_energy' for _,mod in grade_parts)
        size_append='Array.size_append, ' if len(grade_parts)>1 else ''
        energy_append='energy_append, ' if len(grade_parts)>1 else ''
        energy_finish='\n  decide +kernel' if len(grade_parts)>1 else ''
        gmod=f'TaylorThirdIntegerGrade{q:02d}Check'
        gname=f'thirdCenterIntegerGrade{q:02d}'
        grade_outputs[ROOT/f'Grothe/UpperChaos/{gmod}.lean']=f"""{imports}
import Lean.Util.CollectAxioms
import Lean.Elab.Command

/-! Exact source-grade array length and integer squared energy, composed
from bounded actual subarrays. No Gaussian error is asserted. Generated by
 tools/gen_taylor_third_integers.py. Agent-ID: codex-8c4d. -/
namespace Grothe.UpperChaos.{gmod}
open ArraySquareEnergy

theorem grade_length : {gname}.size = {len(grade_values)} := by
  simp only [{gname}, {size_append}{size_lemmas}]

theorem grade_energy : {gname}.foldl (fun acc x => acc + x ^ 2) (0 : ℤ) =
    {sum(v*v for v in grade_values)} := by
  change energy {gname} = _
  simp only [{gname}, {energy_append}{energy_lemmas}]{energy_finish}

end Grothe.UpperChaos.{gmod}
open Lean Elab Command
run_cmd do
  for target in #[``Grothe.UpperChaos.{gmod}.grade_length,
      ``Grothe.UpperChaos.{gmod}.grade_energy] do
    for ax in ← Lean.collectAxioms target do
      unless #[`propext, `Classical.choice, `Quot.sound].contains ax do
        throwError m!"{{target}} has forbidden axiom {{ax}}"
"""
    meta={'status':'authoritative exact finite center; no Gaussian error claim',
          'input':info['path'],'input_sha256':info['sha256'],'records':6552,
          'grades':26,'denominator_exponent':EXPONENT,
          'original_records_sha256':sha256(','.join(records).encode()).hexdigest(),
          'total_integer_square_sum':str(sum(v*v for v in decoded)),
          'target_total_energy':str(total),
          'target_band_energies':[str(v) for v in band_energies],
          'grade_details':[{'grade':q,'length':len(v),
                            'integer_square_sum':str(sum(x*x for x in v)),
                            'integer_values_sha256':sha256(','.join(map(str,v)).encode()).hexdigest()}
                           for q,v in enumerate(grades)]}
    return {OUTPUT:'\n'.join(lines), SQUARE:square, MANIFEST:json.dumps(meta,indent=2)+'\n', **part_outputs, **grade_outputs}


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check',action='store_true',help='compare generated bytes without writing')
    args=p.parse_args()
    files=generated(); mismatches=[]
    for path,text in files.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8')!=text:
                mismatches.append(str(path.relative_to(ROOT)))
        else:
            if path.exists() and path.read_text(encoding='utf-8')!=text:
                raise FileExistsError(f'refusing to overwrite changed generated file: {path}')
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(text,encoding='utf-8')
    if mismatches:
        print('\n'.join(mismatches),file=sys.stderr)
        raise SystemExit(1)
    print(f'{"verified" if args.check else "wrote"} 26 integer grades, 6552 exact values, 116 part checks, grade checks and manifest')

if __name__=='__main__':
    main()
