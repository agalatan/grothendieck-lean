#!/usr/bin/env python3
"""Render the two actual degree-one energyTable targets. Agent-ID: codex-7c2e.

Only the target literals come from JSON. The Lean statements consume the
unchanged energyRows/parseRow/parseEntry/tabVal definitions, and retain every
row and matching entry. No decoder, source bytes or numerical allowance changes.
"""
import argparse
from fractions import Fraction
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'data/upper-preprocess/certificate.json'
OUTPUT = ROOT / 'Grothe/Upper/EnergyDegreeOneLookup.lean'
TEMPLATE = 'import Grothe.Upper.Final\nimport Lean.Util.CollectAxioms\n\n/-! Actual current stored degree-one energy lookups. The complete energyRows\nparser and tabVal remain the targets; no replacement parser or source axiom.\nGenerated by tools/gen_energy_degree_one_lookup.py from the tracked\nupper-preprocess certificate. Agent-ID: codex-7c2e. -/\n\nnamespace Grothe.Upper.EnergyDegreeOneLookup\n\nprivate def rowValue (n m : ℕ) (row : GrotheKernel.RowQ) : ℚ :=\n  if row.1 = m then\n    (row.2.map fun entry => if entry.1 = n then entry.2 else 0).sum\n  else 0\n\n/-- Preserve every row and every matching entry, including duplicates.\nThis changes only evaluation order, so nonmatching rows need no entry decoding. -/\nprivate theorem tabVal_rows (rows : List GrotheKernel.RowQ) (n m : ℕ) :\n    tabVal rows (n, m) = (rows.map (rowValue n m)).sum := by\n  induction rows with\n  | nil => rfl\n  | cons row rows ih =>\n    have hr : (row.2.map fun entry =>\n        if (entry.1, row.1) = (n, m) then entry.2 else 0).sum = rowValue n m row := by\n      by_cases h : row.1 = m <;> simp [rowValue, h, Prod.mk.injEq]\n    calc\n      tabVal (row :: rows) (n, m) =\n          (row.2.map fun entry =>\n            if (entry.1, row.1) = (n, m) then entry.2 else 0).sum + tabVal rows (n, m) := by\n        simp only [tabVal, flat, List.flatMap_cons, List.map_append, List.sum_append,\n          List.map_map, Function.comp_def]\n      _ = ((row :: rows).map (rowValue n m)).sum := by\n        rw [hr, ih]\n        rfl\n\ntheorem one_zero : energyTable (1, 0) =\n    (@FIRST@ : ℚ) := by\n  unfold energyTable\n  rw [tabVal_rows]\n  decide +kernel\n\ntheorem zero_one : energyTable (0, 1) =\n    (@SECOND@ : ℚ) := by\n  unfold energyTable\n  rw [tabVal_rows]\n  decide +kernel\n\nend Grothe.Upper.EnergyDegreeOneLookup\n\nrun_cmd do\n  let allowed : Array Lean.Name := #[`propext, `Classical.choice, `Quot.sound]\n  for target in #[``Grothe.Upper.EnergyDegreeOneLookup.one_zero,\n      ``Grothe.Upper.EnergyDegreeOneLookup.zero_one] do\n    let dependencies ← Lean.collectAxioms target\n    let unexpected := dependencies.filter fun n => !allowed.contains n\n    unless unexpected.isEmpty do\n      throwError m!"Unexpected degree-one table lookup axioms: {unexpected}"\n'


def render():
    values = {}
    for n, m, value in json.loads(SOURCE.read_text())['energies']:
        if (n, m) in {(1, 0), (0, 1)}:
            if (n, m) in values:
                raise ValueError('duplicate degree-one input target')
            q = Fraction(value)
            values[n, m] = f'{q.numerator} / {q.denominator}'
    if values.keys() != {(1, 0), (0, 1)}:
        raise ValueError('missing actual degree-one target')
    return TEMPLATE.replace('@FIRST@', values[1, 0]).replace('@SECOND@', values[0, 1])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != result:
            raise SystemExit('actual degree-one lookup source differs from canonical render')
        print('actual degree-one lookup source is up to date')
    else:
        OUTPUT.write_text(result)
        print(OUTPUT.relative_to(ROOT))


if __name__ == '__main__':
    main()
