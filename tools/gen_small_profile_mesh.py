#!/usr/bin/env python3
"""Render the fixed retained-domain cuts. Agent-ID: codex-2ca4.

The Lean checker proves the actual profile bound; this generator only records
the rational cuts and selected strip indices from the tracked input.
"""
import json
from fractions import Fraction
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[1]
data = json.loads((root / "data/small-profile-mesh/certificate.json").read_text())
cuts = list(map(Fraction, data["cuts"]))
selected = data["selected"]
if len(cuts) != 8 or cuts[0] != 0 or cuts[-1] != 80:
    raise SystemExit("expected eight cuts from zero to eighty")
if not all(a < b for a, b in zip(cuts, cuts[1:])):
    raise SystemExit("cuts must be strictly increasing")
if selected != [1, 3, 5]:
    raise SystemExit("the analytic assembly uses strips 1, 3, and 5")

def lean_rat(q):
    return f"({q.numerator} : ℚ) / {q.denominator}"

lines = [
    "import Mathlib.Data.Rat.Init",
    "",
    "/-! Generated by tools/gen_small_profile_mesh.py from",
    "data/small-profile-mesh/certificate.json. Agent-ID: codex-2ca4. -/",
    "",
    "namespace Grothe.UpperChaos.SmallProfileMesh",
    "",
    "/-- Squared-radius boundaries; the sequence stays at eighty after its last cut. -/",
    "def cutQ : ℕ → ℚ",
]
lines.extend(f"  | {k} => {lean_rat(q)}" for k, q in enumerate(cuts[:-1]))
lines.extend([
    f"  | _ => {lean_rat(cuts[-1])}",
    "",
    "/-- The three radial strips on which the short auxiliary endpoint is used. -/",
    "abbrev selected (k : ℕ) : Prop := k ∈ ([1, 3, 5] : List ℕ)",
    "",
    "end Grothe.UpperChaos.SmallProfileMesh",
    "",
])
rendered = "\n".join(lines)
target = root / "Grothe/UpperChaos/SmallProfileMeshData.lean"
if sys.argv[1:] == ["--check"]:
    if not target.exists() or target.read_text() != rendered:
        raise SystemExit("SmallProfileMeshData.lean is not current")
    print("small-profile mesh data is current")
elif not sys.argv[1:]:
    target.write_text(rendered)
    print("wrote SmallProfileMeshData.lean")
else:
    raise SystemExit("usage: gen_small_profile_mesh.py [--check]")
