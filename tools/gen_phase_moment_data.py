#!/usr/bin/env python3
"""Generate exact phase-moment targets, bound to the production phase data.

The stored fractions are targets, not certificates. Each numerical Lean leaf
must compute the corresponding moment from the production phase and prove the
equality. This generator performs only source and formatting checks.
"""

import argparse
import json
import math
from fractions import Fraction as Q
from pathlib import Path

from needle_phase_moments import read_phase


ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "data/phase-moments/targets.json"
OUTPUT = ROOT / "Grothe/UpperChaos/PhaseMomentData.lean"


def generate():
    data = json.loads(INPUT.read_text())
    terms, epsilon, metadata = read_phase(ROOT / "Grothe/Upper/Data.lean")
    for key in ("phase_payload_sha256", "phase_terms", "phase_total_degree"):
        if data[key] != metadata[key]:
            raise ValueError(f"production phase mismatch: {key}")
    if Q(data["epsilon"]) != epsilon:
        raise ValueError("production phase damping mismatch")
    denominator = math.lcm(*(q.denominator for q in terms.values()))
    if denominator != int(data["common_denominator"]):
        raise ValueError("production phase denominator mismatch")
    if set(data["targets"]) != {"2", "4", "6"}:
        raise ValueError("expected the second, fourth and sixth moment targets")
    lines = [
        "import Mathlib.Data.Rat.Defs", "",
        "/-! Generated by tools/gen_phase_moment_data.py from data/phase-moments/targets.json.",
        "Exact targets for the production phase moments; numerical leaf proofs check them. -/", "",
        "namespace Grothe.UpperChaos", "",
    ]
    for power in (2, 4, 6):
        q = Q(data["targets"][str(power)])
        if q <= 0:
            raise ValueError(f"expected a positive moment target at power {power}")
        lines += [
            f"/-- Exact target for the phase moment of order `{power}`. -/",
            f"def phaseMoment{power}Q : ℚ := {q.numerator} / {q.denominator}", "",
        ]
    lines += ["end Grothe.UpperChaos", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    wanted = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != wanted:
            raise SystemExit("PhaseMomentData.lean is stale; run tools/gen_phase_moment_data.py")
        print("phase moment targets match the production phase and generated Lean data")
    else:
        OUTPUT.write_text(wanted)
        print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
