#!/usr/bin/env python3
"""Reproduce first/second candidate grade energies and checked band arithmetic.

Agent-ID: codex-8c4d. The existing pinned NPZ reader preserves the source
binary64 values exactly. Generated per-grade numbers remain candidates until
actual-source grade certificates are bound to them. Lean independently checks
the filtered arithmetic against the actual stored band target definitions.
"""
from __future__ import annotations

import argparse
from hashlib import sha256
import json
from pathlib import Path
import re
import sys
import zipfile

sys.dont_write_bytecode = True
from gen_taylor_rounding_data import COMMON_EXPONENT, count_levels, read_f64, scaled

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'Grothe/UpperChaos/FirstSecondGradeEnergyTargets.lean'
E = 206
CONFIG = (
    ('first', 'arb_first_phase_D181.npz', 91, 91, 6),
    ('second', 'arb_phase_power2_D151.npz', 76, 46, 4),
)


def read_target_function(text: str, name: str, count: int) -> list[int]:
    marker = re.search(rf'^def {name} : Fin {count} → [ℕℤ]\n(.*?)(?=\n\n)', text, re.M | re.S)
    if marker is None:
        raise ValueError(f'cannot find actual band target function: {name}')
    items = re.findall(r'^  \| (\d+|_) => (-?\d+)$', marker[1], re.M)
    if len(items) != count or [p for p, _ in items] != [str(k) for k in range(count - 1)] + ['_']:
        raise ValueError(f'unexpected actual target cases: {name}')
    return [int(value) for _, value in items]


def inputs() -> list[dict]:
    if COMMON_EXPONENT != E:
        raise ValueError('source helper changed its common denominator exponent')
    data = ROOT / 'data/taylor-approximants'
    manifest = json.loads((data / 'manifest.json').read_text())
    band_path = ROOT / 'Grothe/UpperChaos/TaylorCenterBandData.lean'
    band_text = band_path.read_text()
    results = []
    for label, filename, original_n, retain_n, bands in CONFIG:
        found = [item for item in manifest['inputs'] if Path(item['path']).name == filename]
        if len(found) != 1:
            raise ValueError(f'missing or duplicate pinned source: {filename}')
        info = found[0]
        path = data / info['path']
        raw = path.read_bytes()
        if len(raw) != info['size_bytes'] or sha256(raw).hexdigest() != info['sha256']:
            raise ValueError(f'pinned source hash/size mismatch: {filename}')
        with zipfile.ZipFile(path) as archive:
            original = read_f64(archive, 'center.npy', (count_levels(original_n),))
        retained = scaled(original[:count_levels(retain_n)])
        if len(retained) != count_levels(retain_n):
            raise ValueError(f'wrong retained coefficient count: {label}')
        energies = []
        for q in range(retain_n):
            start, stop = count_levels(q), count_levels(q + 1)
            values = retained[start:stop]
            if len(values) != (q + 1) * (q + 2):
                raise ValueError(f'wrong grade geometry: {label},{q}')
            energies.append(sum(value * value for value in values))
        prefix = label + 'CenterBand'
        lo = read_target_function(band_text, prefix + 'Lo', bands)
        hi = read_target_function(band_text, prefix + 'Hi', bands)
        expected = read_target_function(band_text, prefix + 'IntegerEnergy', bands)
        for k in range(bands):
            actual = sum(value for q, value in enumerate(energies) if lo[k] < 2 * q + 1 <= hi[k])
            if actual != expected[k]:
                raise ValueError(f'candidate arithmetic differs from actual stored band target: {label},{k}')
        results.append({'label': label, 'original_n': original_n, 'retained_n': retain_n,
                        'source': str(Path('data/taylor-approximants') / info['path']),
                        'source_sha256': info['sha256'], 'energies': energies,
                        'bands': bands, 'target_sha256': sha256(band_path.read_bytes()).hexdigest()})
    return results


def band_statement(label: str, levels: int, k: str) -> list[str]:
    return [
        f'    (∑ q ∈ Finset.range {levels},',
        f'      if {label}CenterBandLo {k} < 2*q+1 ∧ 2*q+1 ≤ {label}CenterBandHi {k}',
        f'        then {label}GradeEnergy q else 0) = {label}CenterBandIntegerEnergy {k}',
    ]


def generated() -> str:
    source = inputs()
    lines = [
        'import Mathlib.Algebra.BigOperators.Ring.Finset',
        'import Mathlib.Tactic.FinCases',
        'import Grothe.UpperChaos.TaylorCenterBandData',
        'import Lean.Util.CollectAxioms',
        'import Lean.Elab.Command', '',
        '/-! Generated by tools/gen_first_second_grade_energy_targets.py.',
        'Candidate integer grade energies at coefficient scale 2^206. They must',
        'still be bound to the actual source arrays by separate grade certificates.',
        'The arithmetic below checks the six and four filtered sums against the',
        'actual TaylorCenterBandData targets, not copied target literals.',
        'No Gaussian comparison error or final upper bound is asserted.',
        'Agent-ID: codex-8c4d.',
    ]
    for item in source:
        lines += [f"{item['label']} source: {item['source']}",
                  f"source SHA256: {item['source_sha256']}",
                  f"retained grades: {item['retained_n']} of {item['original_n']}"]
    lines += [f"band-definition SHA256: {source[0]['target_sha256']}", '-/', '',
              'namespace Grothe.UpperChaos.FirstSecondGradeEnergyTargets', '',
              'set_option maxRecDepth 8192', 'set_option maxHeartbeats 2000000', '']
    audit = []
    for item in source:
        label, levels = item['label'], item['retained_n']
        values = ', '.join(map(str, item['energies']))
        lines += [f'/-- Candidate exact squared integer energy of each retained {label}-center grade. -/',
                  f'def {label}GradeEnergyCandidates : List ℤ := [{values}]', '',
                  f'def {label}GradeEnergy (q : ℕ) : ℤ := {label}GradeEnergyCandidates[q]?.getD 0', '']
        for k in range(item['bands']):
            name = f'{label}_band{k}_arithmetic'
            audit.append(name)
            lines += [f'theorem {name} :'] + band_statement(label, levels, str(k))[:-1]
            lines += [band_statement(label, levels, str(k))[-1] + ' := by', '  decide +kernel', '']
        name = f'{label}_band_arithmetic'
        audit.append(name)
        lines += [f'theorem {name} (k : Fin {item["bands"]}) :'] + band_statement(label, levels, 'k')[:-1]
        lines += [band_statement(label, levels, 'k')[-1] + ' := by', '  fin_cases k']
        lines += [f'  · exact {label}_band{k}_arithmetic' for k in range(item['bands'])]
        lines.append('')
    lines += ['end Grothe.UpperChaos.FirstSecondGradeEnergyTargets', '',
              'open Lean Elab Command', 'run_cmd do',
              '  let allowed : Array Name := #[`propext, `Classical.choice, `Quot.sound]',
              '  let targets : Array Name := #[']
    lines += [f'    ``Grothe.UpperChaos.FirstSecondGradeEnergyTargets.{name}' +
              (',' if i + 1 < len(audit) else ']') for i, name in enumerate(audit)]
    lines += ['  for target in targets do', '    let axs ← Lean.collectAxioms target',
              '    logInfo m!"Exact stored-band arithmetic audit {target}: {axs.qsort Name.lt}"',
              '    for ax in axs do', '      unless allowed.contains ax do',
              '        throwError m!"{target} has forbidden axiom {ax}"', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='compare generated bytes without writing')
    args = parser.parse_args()
    expected = generated()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text() != expected:
            raise SystemExit('missing or changed: ' + str(TARGET))
    else:
        TARGET.write_text(expected)
    print(f'{"verified" if args.check else "generated"} candidate grade energies (91 + 46) and ten actual-target band identities; source-grade binding remains separate')


if __name__ == '__main__':
    main()
