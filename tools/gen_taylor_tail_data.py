#!/usr/bin/env python3
"""Generate exact Taylor tail-cap data and its arithmetic receipt.

Agent-ID: codex-44c5. Inputs are tracked recipes, original comparison allowances,
exact phase moments and exact finite-center norm enclosures. The resulting
Gaussian error caps remain hypotheses; no integration or endpoint is proved.
"""
import argparse
import hashlib
import json
import math
from fractions import Fraction as Q
from pathlib import Path

ROOT = next(p for p in Path(__file__).resolve().parents if (p / "lean-toolchain").is_file())


def read_json(path):
    raw = path.read_bytes()
    return json.loads(raw), hashlib.sha256(raw).hexdigest()


def path_label(path, root):
    try:
        return str(path.resolve().relative_to(root.resolve()))
    except ValueError:
        return str(path.resolve())


def generated(repo, recipe_path, first_second_path=None, third_path=None):
    recipe, recipe_sha = read_json(recipe_path)
    if recipe["schema_version"] != 1:
        raise ValueError("unsupported Taylor tail recipe")
    comparison_path = repo / recipe["comparison_source"]
    comparison, comparison_sha = read_json(comparison_path)
    if comparison_sha != recipe["comparison_source_sha256"]:
        raise ValueError("original comparison source hash mismatch")
    public_path = repo / recipe["public_comparison_recipe"]
    public, public_sha = read_json(public_path)
    if public["source_sha256"] != comparison_sha:
        raise ValueError("public comparison recipe belongs to another source")
    moment_path = repo / recipe["phase_moment_targets"]
    moments, moment_sha = read_json(moment_path)
    first_second_path = first_second_path or repo / recipe["first_second_center_norms"]
    first_second, first_second_sha = read_json(first_second_path)
    if first_second["comparison_source_sha256"] != comparison_sha:
        raise ValueError("first/second norm data belong to another comparison source")
    third_path = third_path or repo / recipe["third_center_norms"]
    third, third_sha = read_json(third_path)
    manifest_path = repo / "data/taylor-approximants/manifest.json"
    manifest, manifest_sha = read_json(manifest_path)
    hashes = {Path(s["path"]).name: s["sha256"] for s in manifest["inputs"]}
    inherited_hashes = comparison["source_sha256"].values()
    if any(h not in inherited_hashes for h in hashes.values()):
        raise ValueError("a coefficient manifest hash is absent from the original comparison")
    source_hashes = {
        1: hashes["arb_first_phase_D181.npz"],
        2: hashes["arb_phase_power2_D151.npz"],
        3: hashes["arb_phase_power3_D51.npz"],
    }
    sources = {s["power"]: s for s in first_second["sources"]}
    sources[3] = third
    for power, source in sources.items():
        if source["source_sha256"] != source_hashes[power]:
            raise ValueError("center norm source hash mismatch")
    records = []
    lines = [
        "import Mathlib.Data.Rat.Defs", "",
        "/-! Generated by tools/gen_taylor_tail_data.py from the tracked tail recipe.",
        "Exact finite scalar budgets; Gaussian band-error inequalities remain hypotheses.",
        "Agent-ID: codex-44c5 -/", "", "namespace Grothe.UpperChaos", "",
    ]
    if sorted(t["power"] for t in recipe["tails"]) != [1, 2, 3]:
        raise ValueError("the recipe must specify each of the three Taylor powers once")
    for tail in recipe["tails"]:
        power, factor = tail["power"], tail["factorial"]
        if factor != math.factorial(power):
            raise ValueError("incorrect factorial scaling")
        precision = tail["decimal_precision"]
        if not isinstance(precision, int) or not 0 <= precision <= 100:
            raise ValueError("invalid decimal precision")
        denominator = 10 ** precision
        original = next(x for x in comparison["details"] if x["power"] == power)
        finite = original["bands"]
        norm_bands = sources[power]["bands"]
        indices = tail["public_finite_indices"]
        if len(finite) != len(norm_bands) or len(finite) != len(indices):
            raise ValueError("finite-band lengths differ")
        moment = Q(moments["targets"][str(2 * power)])
        lowers, original_errors, caps, public_caps, band_records = [], [], [], [], []
        last_hi = 0
        for band, norm, idx in zip(finite, norm_bands, indices):
            production = public["bands"][idx]
            limits = (band["lo"], band["hi"])
            if limits != (norm["lo"], norm["hi"]) or limits != (production["lo"], production["hi"]):
                raise ValueError("total-degree band endpoints differ")
            if band["lo"] != last_hi or band["hi"] <= band["lo"]:
                raise ValueError("finite degree bands are not a contiguous partition")
            last_hi = band["hi"]
            lower, upper, energy = Q(norm["norm_lower"]), Q(norm["norm_upper"]), Q(norm["energy"])
            if not 0 < lower <= upper or not lower ** 2 <= energy <= upper ** 2:
                raise ValueError("invalid finite-center norm enclosure")
            error = Q(band["coefficient_error_cap"])
            numerator = (error.numerator * denominator + error.denominator - 1) // error.denominator
            cap = Q(numerator, denominator)
            public_cap = factor * Q(production["error"])
            if not 0 <= error <= cap <= public_cap:
                raise ValueError("rounded error fails source/public cap containment")
            lowers.append(lower)
            original_errors.append(error)
            caps.append(cap)
            public_caps.append(public_cap)
            band_records.append({
                "lo": band["lo"], "hi": band["hi"], "public_index": idx,
                "center_norm_lower": str(lower), "original_unscaled_error": str(error),
                "decimal_numerator": str(numerator), "proposed_unscaled_error": str(cap),
                "public_unscaled_error": str(public_cap),
            })
        production_tail = public["bands"][tail["public_tail_index"]]
        if production_tail["lo"] != last_hi or production_tail["hi"] != 0 or original["cutoff"] != last_hi:
            raise ValueError("omitted-tail cutoff mismatch")
        cap = factor * Q(production_tail["error"])
        captured = sum((max(Q(), lo - err) ** 2 for lo, err in zip(lowers, caps)), Q())
        budget = moment - captured
        slack = cap ** 2 - budget
        if slack < 0:
            raise ValueError("rounded error caps do not fit the public tail budget")
        records.append({
            "power": power, "factorial": factor, "decimal_precision": precision,
            "decimal_denominator": str(denominator), "lean_name": tail["lean_name"],
            "coefficient_source_sha256": source_hashes[power], "phase_moment": str(moment),
            "bands": band_records, "public_tail_index": tail["public_tail_index"],
            "unscaled_tail_cap": str(cap), "captured_energy_lower": str(captured),
            "tail_energy_budget": str(budget), "squared_tail_slack": str(slack),
            "checks": {"source_errors_enclosed": True, "finite_public_caps_implied": True,
                       "tail_budget_fits": True},
        })
        lines += [
            f"/-- Unscaled power-{power} Gaussian error allowances, rounded upward at `10^-{precision}`. -/",
            f"def {tail['lean_name']} : Fin {len(caps)} → ℚ",
        ]
        for k, band in enumerate(band_records):
            pattern = str(k) if k + 1 < len(caps) else "_"
            lines.append(f"  | {pattern} => {band['decimal_numerator']} / {denominator}")
        lines.append("")
    lines += ["end Grothe.UpperChaos", ""]
    inputs = [
        ("recipe", recipe_path, recipe_sha), ("original_comparison", comparison_path, comparison_sha),
        ("public_comparison", public_path, public_sha), ("phase_moments", moment_path, moment_sha),
        ("coefficient_manifest", manifest_path, manifest_sha),
        ("first_second_norms", first_second_path, first_second_sha), ("third_norms", third_path, third_sha),
    ]
    receipt = {
        "agent_id": "codex-44c5", "schema_version": 1,
        "scope": "Finite rational arithmetic and provenance only; Gaussian band-error caps remain hypotheses",
        "sources": {name: {"path": path_label(path, repo), "sha256": digest} for name, path, digest in inputs},
        "tails": records,
    }
    return "\n".join(lines), json.dumps(receipt, indent=2) + "\n", records


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=ROOT)
    parser.add_argument("--recipe", type=Path)
    parser.add_argument("--first-second-norms", type=Path)
    parser.add_argument("--third-norms", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--receipt", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    repo = args.repo.resolve()
    recipe_path = args.recipe or repo / "data/taylor-approximants/tail-recipe.json"
    output = args.output or repo / "Grothe/UpperChaos/TaylorTailData.lean"
    receipt = args.receipt or repo / "data/taylor-approximants/tail-caps.json"
    lean, summary, records = generated(repo, recipe_path, args.first_second_norms, args.third_norms)
    for path, wanted in [(output, lean), (receipt, summary)]:
        if args.check:
            if not path.exists() or path.read_text() != wanted:
                raise SystemExit(f"stale generated Taylor tail data: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(wanted)
    print(json.dumps({"agent_id": "codex-44c5", "checked" if args.check else "generated": str(output),
        "tails": [{"power": r["power"], "decimal_precision": r["decimal_precision"],
                   "squared_tail_slack": float(Q(r["squared_tail_slack"]))} for r in records]}, indent=2))

if __name__ == "__main__":
    main()
