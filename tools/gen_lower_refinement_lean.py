# tools/gen_lower_refinement_lean.py
"""Export the exact lower-refinement law bank to the existing Lean checker.

Acceptance inputs live in data/lower-refinement. The ordered registry fixes
the appended batch indices. No solver, ignored archive, or network is used.
"""
import argparse
from fractions import Fraction as Q
import json
from pathlib import Path

from lower_refinement import ROOT, batches, new_certificates
from verify_lower_refinement import new_node_check, source_check, source_of_batch
import rankone_law as law


def qs(value):
    return str(Q(value))


def qterm(value):
    value = Q(value)
    return f'({value.numerator} : ℚ) / {value.denominator}'


def batch_term(doc):
    parent = batches[doc['batch']]
    witness = doc['witness']
    source = source_of_batch(doc['batch'])
    nodes = ';'.join(qs(x) + ':' + qs(law.value(source.at(x), x))
                     for x in source.knots)
    mesh = ','.join(map(qs, witness['rv'][1:]))
    parameters = ','.join(qs(witness[key]) for key in ('lam', 'mu', 't', 'beta', 'nu'))
    node = qs(witness['tau']) + ':' + ','.join(map(qs, witness['P'])) + ':' + parameters
    if 'tensor_budget' in witness:
        gram = witness['tensor_budget']
        fields = [gram['A'], gram['B']] + gram['M0'] + gram['M1']
        fields += [gram['alpha'], gram['beta']]
        if 'sixth_joint' in witness:
            joint = witness['sixth_joint']
            kind = joint.get('kind', 'triangle')
            if kind not in ('triangle', 'young'):
                raise ValueError('Unsupported joint certificate')
            tag = ['j', '1' if kind == 'young' else '0']
            tag += [qs(joint[key]) for key in ('alpha', 'xmax', 'weight')]
        else:
            tag = ['g']
        node += ':' + ','.join(tag + list(map(qs, fields)))
    node += '|' + ','.join(map(qs, witness['phi']))
    return (f"⟨{parent['i']}, {parent['j']}, {qterm(parent['w'])}, "
            f"{qterm(source.pieces[-1][1][1])},\n"
            f'    {json.dumps(nodes)},\n'
            f'    {json.dumps(mesh)}, true,\n'
            f'    [{json.dumps(node)}]⟩')


def render():
    source_check()
    pieces = [
        '-- Grothe/Research/LowerRefinementData.lean\n'
        'import Grothe.Lower.RowData\n'
        'import Grothe.Lower.MixedData\n'
        'import Grothe.Research.LawNodeData\n\n'
        '/-! Generated by `tools/gen_lower_refinement_lean.py` from the exact law bank. -/\n\n'
        'namespace Grothe.Research.LowerRefinementData\n\n'
        'open Grothe.Lower\n\n'
    ]
    names = []
    for index, (path, doc) in enumerate(new_certificates):
        new_node_check(doc)
        name = f'refinementBatch{index:02d}'
        names.append(name)
        pieces.append(f'/-- Acceptance input: `data/lower-refinement/nodes/{path.name}`. -/\n')
        pieces.append(f'def {name} : JBatch :=\n  {batch_term(doc)}\n\n')
    pieces.append('def refinementExtraBatches : List JBatch :=\n  [' + ', '.join(names) + ']\n\n')
    pieces.append('def refinementBatches : List JBatch :=\n'
                  '  mixedBatches ++ LawNodeData.extraBatches ++ refinementExtraBatches\n\n'
                  'end Grothe.Research.LowerRefinementData\n')
    return ''.join(pieces)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'Grothe/Research/LowerRefinementData.lean'
    text = render()
    if args.check:
        if output.read_text() != text:
            raise ValueError('Generated lower-refinement law data differ')
    else:
        output.write_text(text)
    print(f'PASS exact Lean law-bank export: {len(new_certificates)} batches')


if __name__ == '__main__':
    main()
