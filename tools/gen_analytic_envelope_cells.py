# Both frozen cover/finish recipes used this fixed degree; it must not be
# inferred from polynomial support, whose highest rounded coefficients may vanish.
PROFILE_DEGREE = 10
PROFILE_BITS = 160
LANES = 4
PROFILE_COUNT = 104
EXPONENTIAL_COUNT = 83
CELL_COUNT = 183
PARENT_RECIPE = "7730edf3b65ba2a27a7c65f7c26ef98a2b0fd4614ea1cd8e83390ba8d8ff3e90"
FINISH_RECIPE = "c6cc4cce8c71c0ac4278bdea7c02b3abe545e3d42242139c8cb64af3daa240fa"


def require(condition, message):
    if not condition:
        raise ValueError(message)


def model_value(m):
    return {k: m[k] for k in ("bits", "coefficients", "remainder")}


def interval(lo, hi):
    require(Q(lo) <= Q(hi), "reversed interval")
    return f"⟨{rat(lo)}, {rat(hi)}, by decide +kernel⟩"


def header(certificate_hash, detail):
    return f'''/-!
Generated by tools/gen_analytic_envelope_cells.py.
Certificate SHA256: {certificate_hash}
{detail}
All finite facts require Lean kernel checking. Agent-ID: codex-2ca4.
-/
'''


def regenerate_profile(source, context, index):
    lo, hi = map(Q, context["radial_bounds"])
    require(lo < hi, f"profile {index}: nonpositive width")
    require(context["model"]["bits"] == PROFILE_BITS, f"profile {index}: unexpected precision")
    coordinate = rp.coordinate(lo, hi, 0, PROFILE_DEGREE, PROFILE_BITS)
    denominator = int(source["profileDen"])
    rp.HORNER_RECORDS = []
    try:
        result = rp.horner(source["profileCoefficients"], coordinate,
            lambda pair: rp.Model.from_interval(rp.Interval.rational(
                Q(int(pair[0]), denominator), Q(int(pair[1]), denominator), PROFILE_BITS),
                PROFILE_DEGREE))
        trace = rp.HORNER_RECORDS[0]
    finally:
        rp.HORNER_RECORDS = None
    require(model_value(rp.model_json(result)) == model_value(context["model"]),
            f"profile {index}: regenerated model differs from pinned candidate")
    require(result.range().max_abs() == Q(context["profile_abs_upper"]),
            f"profile {index}: absolute bound differs from pinned model range")
    return coordinate, trace


def replay_leancert_exp_upper(q, precision=256, depth=64):
    """Exact replay of the specific LeanCert expression check emitted below.

    This is a generation sanity check only: LeanCert's proved checker still
    establishes the real inequality independently in each generated module.
    """
    unit = 1 << precision

    def ceil(x):
        return -((-x.numerator) // x.denominator)

    def endpoint_upper(x):
        scale = 1 << ((ceil(abs(x)) + 1).bit_length() - 1)
        reduced = x / scale
        polynomial = Q(0)
        for n in reversed(range(depth + 1)):
            polynomial = Q(1, factorial(n)) + reduced * polynomial
        radius = abs(reduced)
        remainder = Q(3 ** (ceil(radius) + 1)) * radius ** (depth + 1) / factorial(depth + 1)
        # All frozen inputs have a strictly positive Taylor lower endpoint,
        # so interval powering is exactly powering the two endpoints.
        require(polynomial - remainder > 0, "LeanCert replay: nonpositive Taylor lower endpoint")
        return (polynomial + remainder) ** scale

    rounded_lo = Q((q * unit).__floor__(), unit)
    rounded_hi = Q(ceil(q * unit), unit)
    upper = max(endpoint_upper(rounded_lo), endpoint_upper(rounded_hi))
    return Q(ceil(upper * unit), unit)


def render_profile(index, context, coordinate, trace, digest):
    lo, hi = map(Q, context["radial_bounds"])
    center, width = (lo + hi) / 2, (hi - lo) / 2
    name = f"AnalyticEnvelopeProfiles{index:03d}"
    predecessor = (f"import Grothe.UpperChaos.AnalyticEnvelopeProfiles{index - LANES:03d}\n"
                   if index >= LANES else "")
    return f'''import Grothe.UpperChaos.Q0ProfileRectangleModel
import Grothe.UpperChaos.RectangleCoordinates
{predecessor}

{header(digest, f"Shared actual profile enclosure {index}; degree {PROFILE_DEGREE}, precision {PROFILE_BITS} bits.")}
namespace Grothe.UpperChaos.{name}

open LeanCert.Core RectangleModelCheck RectangleHornerTrace
open PointwiseGeometricEnclosure LeanCertProductionProfile

set_option maxHeartbeats 0
set_option maxRecDepth 100000

def radialLo : ℚ := {rat(lo)}
def radialHi : ℚ := {rat(hi)}
def center : ℚ := {rat(center)}
def halfwidth : ℚ := {rat(width)}
def profileAbsUpper : ℚ := {rat(context['profile_abs_upper'])}

private def coordinate : Model := {model(rp.model_json(coordinate))}
{trace_defs(trace)}

private theorem coordinate_checked :
    RectangleCoordinates.checkX center halfwidth coordinate = true := by decide +kernel

private theorem profile_checked :
    trace.check coordinate Q0ProfileRectangleModel.inputs = true := by decide +kernel

private theorem profileAbsUpper_nonneg : 0 ≤ profileAbsUpper := by decide +kernel

private theorem range_checked :
    intervalSubset (range trace.output)
      (errorInterval profileAbsUpper profileAbsUpper_nonneg) = true := by decide +kernel

/-- The actual profile is bounded throughout this complete closed radial interval. -/
theorem profile_bound {{s : ℝ}} (hs : s ∈ Set.Icc (radialLo : ℝ) radialHi) :
    |q0Kappa s| ≤ (profileAbsUpper : ℝ) := by
  let x := (s - (center : ℝ)) / (halfwidth : ℝ)
  have hx : |x| ≤ 1 := by
    have hs' := hs
    norm_num [radialLo, radialHi, Set.mem_Icc] at hs'
    apply abs_le.mpr
    dsimp [x, center, halfwidth]
    norm_num
    constructor <;> linarith [hs'.1, hs'.2]
  have hy : |(0 : ℝ)| ≤ 1 := by norm_num
  have hc := RectangleCoordinates.x_sound center halfwidth coordinate coordinate_checked hx hy
  have he : (center : ℝ) + (halfwidth : ℝ) * x = s := by
    dsimp [x, center, halfwidth]
    norm_num
    ring
  rw [he] at hc
  have hp := Q0ProfileRectangleModel.profile_of_trace coordinate trace profile_checked hx hy hc
  have hb := mem_of_intervalSubset range_checked (mem_range hx hy hp)
  exact abs_le.mpr (by
    simpa only [errorInterval, IntervalRat.mem_def, Rat.cast_neg] using hb)

end Grothe.UpperChaos.{name}
'''


def render_exponential(index, entry, digest):
    radial = -Q(entry["input"])
    require(radial >= 0, f"exponential {index}: positive exponent")
    scalar = rp.exp_rational(-radial, PROFILE_BITS)
    require(Q(entry["upper"]) == Q(scalar.hi + 2, scalar.unit),
            f"exponential {index}: upper differs from original candidate recipe")
    require(replay_leancert_exp_upper(-radial) <= Q(entry["upper"]),
            f"exponential {index}: LeanCert dyadic upper check would fail")
    name = f"AnalyticEnvelopeExponentials{index:03d}"
    if index < LANES:
        tail = max(i for i in range(PROFILE_COUNT) if i % LANES == index)
        predecessor = f"AnalyticEnvelopeProfiles{tail:03d}"
    else:
        predecessor = f"AnalyticEnvelopeExponentials{index - LANES:03d}"
    return f'''import LeanCert.Validity.Dyadic
import Grothe.UpperChaos.{predecessor}

{header(digest, f"Shared scalar exponential upper certificate {index}.")}
namespace Grothe.UpperChaos.{name}

open LeanCert.Core LeanCert.Validity

set_option maxHeartbeats 0
set_option maxRecDepth 100000

def radialLo : ℚ := {rat(radial)}
def expUpper : ℚ := {rat(entry['upper'])}

private theorem exp_upper_checked :
    checkUpperBoundDyadicChecked (.exp (.const (-radialLo))) 0 0 (by norm_num)
      expUpper (-256) 64 = true := by decide +kernel

/-- The actual exponential lies below the original outward-rounded scalar bound. -/
theorem exp_upper : Real.exp (-(radialLo : ℝ)) ≤ (expUpper : ℝ) := by
  have hu := verify_upper_bound_dyadic_checked (.exp (.const (-radialLo)))
    0 0 (by norm_num) expUpper (-256) 64 (by norm_num)
    exp_upper_checked 0 (by norm_num)
  simpa only [Expr.eval, Rat.cast_neg] using hu

end Grothe.UpperChaos.{name}
'''


def validate_cell(row, profiles, exponentials, index):
    geometry = row["cell"]
    profile = profiles[row["profile_context"]]
    exponential = exponentials[row["exponential_input"]]
    slo, shi = map(Q, geometry["s"])
    alo, ahi = map(Q, geometry["aux"])
    require([slo, shi] == list(map(Q, profile["radial_bounds"])), f"cell {index}: radial mismatch")
    require(slo == -Q(exponential["input"]), f"cell {index}: exponential input mismatch")
    require(0 <= slo < shi and 0 <= alo < ahi, f"cell {index}: invalid geometry")
    x = Q(row["parameters"]["aux_abs_upper"])
    require(x == max(abs(alo), abs(ahi)), f"cell {index}: auxiliary bound mismatch")
    k = Q(profile["profile_abs_upper"])
    e = Q(exponential["upper"])
    chart = geometry["chart"]
    require(chart in ("direct", "reciprocal"), f"cell {index}: invalid chart")
    if chart == "direct":
        require(row["parameters"]["rule"] ==
                "GaussianDenominatorEnvelope.direct_core/direct_companion",
                f"cell {index}: unexpected direct envelope rule")
        a, b = 2 * shi * e, 4 * k * e
    else:
        require(row["parameters"]["rule"] ==
                "GaussianDenominatorEnvelope.inverse_sq_box/companion_inverse_sq_box",
                f"cell {index}: unexpected reciprocal envelope rule")
        require(slo > 0, f"cell {index}: zero reciprocal radial lower endpoint")
        n = row["parameters"]["power"]
        require(isinstance(n, int) and 0 <= n <= 32, f"cell {index}: invalid envelope power")
        d = x * x + k * k
        require(Q(row["parameters"]["denominator_upper"]) == d, f"cell {index}: denominator mismatch")
        a = 2 * shi * x * x * (e * factorial(n + 2) * d ** n / slo ** (n + 2))
        b = 2 * k * x * x * (e * (factorial(n + 2) + factorial(n + 3)) * d ** n / slo ** (n + 2))
    for component, (lower, upper) in enumerate(((Q(0), a), (-b, b))):
        regenerated = rp.Model.from_interval(
            rp.Interval.rational(lower, upper, PROFILE_BITS), PROFILE_DEGREE)
        require(model_value(rp.model_json(regenerated)) == model_value(row["models"][component]),
                f"cell {index}: analytic formula does not reproduce candidate model {component}")
        require(regenerated.integral((shi - slo) / 2, (ahi - alo) / 2) ==
                tuple(map(Q, row["integrals"][component])),
                f"cell {index}: original integral endpoints do not reproduce")
    area = (shi - slo) * (ahi - alo)
    ilo, ihi = map(Q, row["integrals"][0])
    jlo, jhi = map(Q, row["integrals"][1])
    require(ilo == 0 and area * a <= ihi, f"cell {index}: first integral does not fit")
    require(jlo == -jhi and jlo <= -area * b and area * b <= jhi,
            f"cell {index}: companion integral does not fit")


def render_cell(index, row, profiles, exponentials, digest):
    validate_cell(row, profiles, exponentials, index)
    pi, ei = row["profile_context"], row["exponential_input"]
    pn, en = f"AnalyticEnvelopeProfiles{pi:03d}", f"AnalyticEnvelopeExponentials{ei:03d}"
    name = f"AnalyticEnvelopeCell{index:03d}"
    if index < LANES:
        # All contexts finish before finite-integral checking begins. Together
        # with each stage's fixed lanes this bounds certificate concurrency.
        predecessors = [f"AnalyticEnvelopeExponentials{max(i for i in range(EXPONENTIAL_COUNT) if i % LANES == lane):03d}"
                        for lane in range(LANES)]
    else:
        predecessors = [f"AnalyticEnvelopeCell{index - LANES:03d}"]
    chain_imports = "\n".join(f"import Grothe.UpperChaos.{p}" for p in predecessors if p != en)
    direct = row["cell"]["chart"] == "direct"
    first_fn = "first" if direct else "reciprocalFirst"
    companion_fn = "companion" if direct else "reciprocalCompanion"
    slo, shi = row["cell"]["s"]
    alo, ahi = row["cell"]["aux"]
    if direct:
        bounds = '''def firstUpper : ℚ := 2 * radialHi * expUpper
def companionAbsUpper : ℚ := 4 * profileAbsUpper * expUpper'''
        pointwise = f'''theorem first_bound (η s u : ℝ) (hp : (s, u) ∈ cell.domain) :
    0 ≤ firstKernel η s u ∧ firstKernel η s u ≤ (firstUpper : ℝ) := by
  have hs : s ∈ Set.Icc (radialLo : ℝ) radialHi := hp.1
  have hs0 : 0 ≤ s :=
    (show (0 : ℝ) ≤ radialLo by exact_mod_cast radial_nonneg).trans hs.1
  have hb := Q0BasePairEnvelope.direct_first η s (q0Kappa s) u
    radialLo radialHi expUpper hs0 hs.1 hs.2 {en}.exp_upper
  simpa only [firstKernel, firstUpper, Rat.cast_mul, Rat.cast_ofNat] using hb

theorem companion_bound (η s u : ℝ) (hp : (s, u) ∈ cell.domain) :
    |companionKernel η s u| ≤ (companionAbsUpper : ℝ) := by
  have hs : s ∈ Set.Icc (radialLo : ℝ) radialHi := hp.1
  have hs0 : 0 ≤ s :=
    (show (0 : ℝ) ≤ radialLo by exact_mod_cast radial_nonneg).trans hs.1
  have hb := Q0BasePairEnvelope.direct_companion η s (q0Kappa s) u
    radialLo profileAbsUpper expUpper hs0 hs.1 ({pn}.profile_bound hs) {en}.exp_upper
  simpa only [companionKernel, companionAbsUpper, Rat.cast_mul, Rat.cast_ofNat] using hb
'''
    else:
        bounds = f'''def power : ℕ := {row['parameters']['power']}
def auxAbsUpper : ℚ := {rat(row['parameters']['aux_abs_upper'])}
def denominatorUpper : ℚ := auxAbsUpper ^ 2 + profileAbsUpper ^ 2
def firstUpper : ℚ := 2 * radialHi * auxAbsUpper ^ 2 *
  (expUpper * ((power + 2).factorial : ℚ) * denominatorUpper ^ power / radialLo ^ (power + 2))
def companionAbsUpper : ℚ := 2 * profileAbsUpper * auxAbsUpper ^ 2 *
  (expUpper * ((power + 2).factorial + (power + 3).factorial : ℚ) *
    denominatorUpper ^ power / radialLo ^ (power + 2))

private theorem radial_pos : 0 < radialLo := by decide +kernel

private theorem auxiliary_bounds : -auxAbsUpper ≤ auxLo ∧ auxHi ≤ auxAbsUpper := by
  decide +kernel

private theorem auxiliary_bound {{x : ℝ}} (hx : x ∈ Set.Icc (auxLo : ℝ) auxHi) :
    |x| ≤ (auxAbsUpper : ℝ) := by
  have hlo : -(auxAbsUpper : ℝ) ≤ (auxLo : ℝ) := by
    exact_mod_cast auxiliary_bounds.1
  have hhi : (auxHi : ℝ) ≤ (auxAbsUpper : ℝ) := by
    exact_mod_cast auxiliary_bounds.2
  exact abs_le.mpr ⟨hlo.trans hx.1, hx.2.trans hhi⟩

private theorem denominator_bound {{s x : ℝ}} (hp : (s, x) ∈ cell.domain) :
    x ^ 2 + (q0Kappa s) ^ 2 ≤ (denominatorUpper : ℝ) := by
  have hx2 : x ^ 2 ≤ (auxAbsUpper : ℝ) ^ 2 := by
    simpa only [sq_abs] using pow_le_pow_left₀ (abs_nonneg x) (auxiliary_bound hp.2) 2
  have hk2 : (q0Kappa s) ^ 2 ≤ (profileAbsUpper : ℝ) ^ 2 := by
    simpa only [sq_abs] using pow_le_pow_left₀ (abs_nonneg (q0Kappa s))
      ({pn}.profile_bound hp.1) 2
  simpa only [denominatorUpper, Rat.cast_add, Rat.cast_pow] using add_le_add hx2 hk2
'''
        pointwise = f'''theorem first_bound (η s x : ℝ) (hp : (s, x) ∈ cell.domain) :
    0 ≤ firstKernel η s x ∧ firstKernel η s x ≤ (firstUpper : ℝ) := by
  have hs : s ∈ Set.Icc (radialLo : ℝ) radialHi := hp.1
  have hb := Q0BasePairEnvelope.reciprocal_first power η s (q0Kappa s) x
    radialLo radialHi auxAbsUpper denominatorUpper expUpper
    (by exact_mod_cast radial_pos) hs.1 hs.2 (auxiliary_bound hp.2)
    (denominator_bound hp) {en}.exp_upper
  simpa only [firstKernel, firstUpper, Rat.cast_mul, Rat.cast_div, Rat.cast_pow,
    Rat.cast_natCast, Rat.cast_ofNat] using hb

theorem companion_bound (η s x : ℝ) (hp : (s, x) ∈ cell.domain) :
    |companionKernel η s x| ≤ (companionAbsUpper : ℝ) := by
  have hs : s ∈ Set.Icc (radialLo : ℝ) radialHi := hp.1
  have hb := Q0BasePairEnvelope.reciprocal_companion power η s (q0Kappa s) x
    radialLo auxAbsUpper profileAbsUpper denominatorUpper expUpper
    (by exact_mod_cast radial_pos) hs.1 (auxiliary_bound hp.2)
    ({pn}.profile_bound hs) (denominator_bound hp) {en}.exp_upper
  simpa only [companionKernel, companionAbsUpper, Rat.cast_mul, Rat.cast_div, Rat.cast_pow,
    Rat.cast_add, Rat.cast_natCast, Rat.cast_ofNat] using hb
'''
    return f'''import Grothe.UpperChaos.AdaptiveRectangleEnvelope
import Grothe.UpperChaos.Q0BasePairEnvelope
import Grothe.UpperChaos.{pn}
import Grothe.UpperChaos.{en}
{chain_imports}

{header(digest, f"Actual {row['cell']['chart']} envelope cell {index}: retained root {row['root']}, path {row['path']!r}. Original integral intervals preserved.")}
namespace Grothe.UpperChaos.{name}

open LeanCert.Core LeanCertProductionProfile AdaptiveRectanglePartition

set_option maxHeartbeats 0
set_option maxRecDepth 100000

abbrev radialLo : ℚ := {pn}.radialLo
abbrev radialHi : ℚ := {pn}.radialHi
abbrev profileAbsUpper : ℚ := {pn}.profileAbsUpper
abbrev expUpper : ℚ := {en}.expUpper
def auxLo : ℚ := {rat(alo)}
def auxHi : ℚ := {rat(ahi)}
def cell : Rect := ⟨radialLo, radialHi, auxLo, auxHi⟩

theorem cell_valid : cell.Valid := by decide +kernel

private theorem radial_nonneg : 0 ≤ radialLo := by decide +kernel

noncomputable def firstKernel (η s u : ℝ) : ℝ :=
  Q0BasePairKernel.{first_fn} η s (q0Kappa s) u

noncomputable def companionKernel (η s u : ℝ) : ℝ :=
  Q0BasePairKernel.{companion_fn} η s (q0Kappa s) u

{bounds}

{pointwise}

def firstInterval : IntervalRat := {interval(*row['integrals'][0])}
def companionInterval : IntervalRat := {interval(*row['integrals'][1])}

private theorem first_interval_fit :
    firstInterval.lo ≤ 0 ∧ cell.area * firstUpper ≤ firstInterval.hi := by decide +kernel

private theorem companion_interval_fit :
    companionInterval.lo ≤ -(cell.area * companionAbsUpper) ∧
      cell.area * companionAbsUpper ≤ companionInterval.hi := by decide +kernel

/-- The actual first kernel integral lies in its original nonnegative interval. -/
theorem first_integral_mem (η : ℝ) : cell.integral (firstKernel η) ∈ firstInterval := by
  exact cell.integral_mem_of_nonneg_envelope cell_valid (firstKernel η) firstUpper firstInterval
    (fun p hp => first_bound η p.1 p.2 hp) first_interval_fit.1 first_interval_fit.2

/-- The actual companion integral lies in its original symmetric interval. -/
theorem companion_integral_mem (η : ℝ) :
    cell.integral (companionKernel η) ∈ companionInterval := by
  exact cell.integral_mem_of_abs_envelope cell_valid (companionKernel η)
    companionAbsUpper companionInterval (fun p hp => companion_bound η p.1 p.2 hp)
    companion_interval_fit.1 companion_interval_fit.2

/-- Both complete cell integrals are certified, with no numerical or model premises. -/
theorem integrals_mem (η : ℝ) :
    cell.integral (firstKernel η) ∈ firstInterval ∧
      cell.integral (companionKernel η) ∈ companionInterval :=
  ⟨first_integral_mem η, companion_integral_mem η⟩

end Grothe.UpperChaos.{name}
'''


def generate():
    raw = DATA.read_bytes()
    data = json.loads(raw)
    source_raw = (DATA.parent / data["source_polynomial"]).read_bytes()
    require(hashlib.sha256(source_raw).hexdigest() == data["provenance"]["profile_source_sha256"],
            "profile source hash mismatch")
    require(data["provenance"]["parent_recorded_recipe_sha256"] == PARENT_RECIPE,
            "unexpected frozen parent recipe")
    require(data["provenance"]["finish_recorded_recipe_sha256"] == FINISH_RECIPE,
            "unexpected frozen finish recipe")
    require(len(data["cells"]) == CELL_COUNT and len(data["profile_contexts"]) == PROFILE_COUNT and
            len(data["exponential_inputs"]) == EXPONENTIAL_COUNT, "unexpected complete family cardinalities")
    digest = hashlib.sha256(raw).hexdigest()
    source = json.loads(source_raw)
    cells = list(range(CELL_COUNT))
    profiles = sorted({data["cells"][i]["profile_context"] for i in cells})
    exponentials = sorted({data["cells"][i]["exponential_input"] for i in cells})
    require(profiles == list(range(PROFILE_COUNT)) and exponentials == list(range(EXPONENTIAL_COUNT)),
            "shared context indexes are not the complete contiguous families")
    outputs = {}
    for i in profiles:
        context = data["profile_contexts"][i]
        coordinate, trace = regenerate_profile(source, context, i)
        outputs[f"AnalyticEnvelopeProfiles{i:03d}.lean"] = render_profile(i, context, coordinate, trace, digest)
    for i in exponentials:
        outputs[f"AnalyticEnvelopeExponentials{i:03d}.lean"] = render_exponential(
            i, data["exponential_inputs"][i], digest)
    for i in cells:
        outputs[f"AnalyticEnvelopeCell{i:03d}.lean"] = render_cell(i, data["cells"][i],
            data["profile_contexts"], data["exponential_inputs"], digest)
    # Verify that every generated dependency is present and the fixed proof
    # lanes are acyclic. No generated check runs earlier in a partial batch.
    graph = {}
    for name, content in outputs.items():
        dependencies = set()
        for line in content.splitlines():
            if line.startswith("import Grothe.UpperChaos.AnalyticEnvelope"):
                dependency = line.removeprefix("import Grothe.UpperChaos.") + ".lean"
                require(dependency in outputs, f"missing generated import {dependency}")
                dependencies.add(dependency)
        graph[name] = dependencies
    remaining = dict(graph)
    while remaining:
        ready = {name for name, deps in remaining.items() if not deps}
        require(ready, "cycle in generated proof lanes")
        require(len(ready) <= LANES, "generated proof lane width exceeded")
        remaining = {name: deps - ready for name, deps in remaining.items() if name not in ready}
    return outputs, {"cells": len(cells), "profiles": len(profiles), "exponentials": len(exponentials)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--verify-only", action="store_true", help="replay and render without writing Lean files")
    args = parser.parse_args()
    outputs, counts = generate()
    if args.check:
        for name, content in outputs.items():
            path = OUT / name
            require(path.exists() and path.read_text() == content, f"generated output differs: {path}")
    elif not args.verify_only:
        for name, content in outputs.items():
            (OUT / name).write_text(content)
    print(json.dumps({**counts, "modules": len(outputs),
                      "source_bytes": sum(len(x.encode()) for x in outputs.values()),
                      "mode": "check" if args.check else "verify-only" if args.verify_only else "write"}))


if __name__ == "__main__":
    main()
