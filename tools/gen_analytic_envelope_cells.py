#!/usr/bin/env python3
"""Render complete Lean certificates for the frozen analytic envelope cells.

The Python replay only validates the pinned candidate recipe. Every profile
operation, scalar exponential upper bound, rational fit, and actual finite
integral bound is proved again in the generated Lean sources.

Agent-ID: codex-2ca4.
"""

