#!/usr/bin/env python3
"""Small kernel receipts for the actual degree-zero/one smoothing matrices.
Agent-ID: codex-7c2e. Natural square-root inequalities avoid evaluating the
large square-root algorithm in proof reduction.
"""
import argparse
import json
from math import isqrt
from pathlib import Path


def render(data):
    S,D,U,V,W=(data[k] for k in ['scale','denominator','u','v','w'])
    entries=[('zero',0,0,0,1),('one00',1,0,0,U),('one01',1,0,1,V),
             ('one10',1,1,0,V),('one11',1,1,1,W)]
    lines=['import Grothe.UpperChaos.ProductionSmoothingApprox','import Lean.Util.CollectAxioms','',
           '/-! Generated by tools/gen_degree_one_matrix.py from',
           'data/retained-f0/degree-one-rounding.json. Agent-ID: codex-7c2e. -/',
           'set_option warningAsError true',
           'namespace Grothe.UpperChaos.FixedChaosSmoothing.PolynomialEntries',
           'namespace DegreeOneMatrix','']
    for name,n,c,e,x in entries:
        scalar = '1' if name == 'zero' else {'one00':'smoothingU', 'one01':'smoothingV',
                                            'one10':'smoothingV', 'one11':'smoothingW'}[name]
        moment = f'matrixMomentNumerator U V W {n-c} {c} {n-e} {e}'
        value_expr = '1' if name == 'zero' else {'one00':'U','one01':'V','one10':'V','one11':'W'}[name]
        lines += [f'private theorem {name}_moment (U V W : ℕ) :',
                  f'    {moment} = {value_expr} := by',
                  '  norm_num [matrixMomentNumerator, matrixMomentSummand,',
                  '    ← Nat.choose_eq_fast_choose]', '']
        radicand=S*S*x*x//(D**(2*n))
        value=isqrt(radicand)
        lines += [f'private theorem {name}_sqrt : Nat.sqrt {radicand} = {value} := by',
                  '  apply Eq.symm','  apply Nat.eq_sqrt\'.mpr',
                  '  constructor <;> norm_num','',
                  f'theorem {name} : productionSavedEntryQ {n} {c} {e} =',
                  f'    ({value} / {S} : ℚ) := by',
                  '  unfold productionSavedEntryQ savedEntryQ RationalSqrtFloor.sqrtFloor',
                  '  change ((Nat.sqrt (smoothingEntryScale ^ 2 *',
                  '    matrixMomentNumerator smoothingU smoothingV smoothingW',
                  f'      {n-c} {c} {n-e} {e} ^ 2 / (smoothingScalarDen ^ {2*n} * 1)) : ℚ) /',
                  f'      (smoothingEntryScale : ℚ)) = ({value} / {S} : ℚ)',
                  f'  rw [{name}_moment]',
                  f'  have hr : smoothingEntryScale ^ 2 * {scalar} ^ 2 /',
                  f'      (smoothingScalarDen ^ {2*n} * 1) =',
                  f'        {radicand} := by',
                  f'    norm_num [smoothingScalarDen, smoothingEntryScale{", " + scalar if scalar != "1" else ""}]',
                  f'  rw [hr, {name}_sqrt]','  norm_num [smoothingEntryScale]','']
    lines += ['end DegreeOneMatrix',
              'end Grothe.UpperChaos.FixedChaosSmoothing.PolynomialEntries','']
    targets = ', '.join('``Grothe.UpperChaos.FixedChaosSmoothing.PolynomialEntries.DegreeOneMatrix.' + entry[0] for entry in entries)
    lines += ['run_cmd do', '  let allowed : Array Lean.Name := #[`propext, `Classical.choice, `Quot.sound]',
              '  for target in #[' + targets + '] do',
              '    let dependencies ← Lean.collectAxioms target',
              '    Lean.logInfo m!\"Degree-one matrix audit {target}: {dependencies}\"',
              '    let unexpected := dependencies.filter fun n => !allowed.contains n',
              '    unless unexpected.isEmpty do throwError m!\"Unexpected matrix axioms: {unexpected}\"', '']
    return '\n'.join(lines)


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo',type=Path,default=Path(__file__).resolve().parents[1])
    parser.add_argument('--check', action='store_true')
    args=parser.parse_args()
    data=json.loads((args.repo/'data/retained-f0/degree-one-rounding.json').read_text())
    path=args.repo/'Grothe/UpperChaos/ProductionDegreeOneMatrix.lean'
    text = render(data)
    if args.check:
        if path.read_text() != text:
            raise SystemExit(f'Generated file differs: {path}')
    else:
        path.write_text(text)
    print(path)
