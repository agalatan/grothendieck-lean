#!/usr/bin/env python3
"""Encode exact cell-head pilot outputs; Lean replays each group. Agent-ID: codex-a7c4."""

import argparse
import hashlib
import re
from pathlib import Path


def render(input_dir: Path, group: int) -> str:
    arrays = []
    digest = hashlib.sha256()
    for residue in range(8 * group, 8 * group + 8):
        content = (input_dir / f"head125-residue-{residue}.txt").read_bytes()
        digest.update(content)
        entries = []
        for line in content.decode().splitlines():
            match = re.fullmatch(r"(-?\d+),(-?\d+)", line)
            if match is None:
                raise ValueError(f"Malformed exact interval for residue {residue}")
            lo, hi = map(int, match.groups())
            if lo > hi:
                raise ValueError(f"Reversed interval for residue {residue}")
            entries.append(f"    ⟨{lo}, {hi}⟩")
        if len(entries) != 126:
            raise ValueError(f"Residue {residue}: expected 126 grades, got {len(entries)}")
        arrays.append("  #[\n" + ",\n".join(entries) + "\n  ]")
    name = f"group{group:02d}"
    return (
        "import Grothe.UpperReplacement.HeadWitness\n"
        "import Lean.Elab.Tactic.Decide\n\n"
        "/-! Exact saved intervals with a complete replay. Agent-ID: codex-a7c4.\n"
        f"Input SHA256: {digest.hexdigest()}. -/\n\n"
        "namespace Grothe.UpperReplacement.HeadWitnessFacts\n\n"
        "set_option maxRecDepth 10000\n\n"
        f"def {name} : Array (Array GrotheKernel.Ival) := #[\n"
        + ",\n".join(arrays)
        + "\n]\n\n"
        "set_option maxHeartbeats 0 in\n"
        f"theorem {name}_checked : HeadWitness.groupOK {8 * group} {name} = true := by\n"
        "  native_decide\n\n"
        "end Grothe.UpperReplacement.HeadWitnessFacts\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--group", type=int, choices=range(8))
    mode.add_argument("--aggregate", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.aggregate:
        text = render_aggregate()
        output = args.output_dir.parent / "HeadWitnessFacts.lean"
    else:
        text = render(args.input_dir, args.group)
        output = args.output_dir / f"Group{args.group:02d}.lean"
    if args.check:
        if output.read_text() != text:
            raise SystemExit(f"Generated witness differs: {output}")
    else:
        args.output_dir.mkdir(parents=True, exist_ok=True)
        output.write_text(text)


def render_aggregate() -> str:
    imports = "".join(
        f"import Grothe.UpperReplacement.HeadWitnessFacts.Group{g:02d}\n"
        for g in range(8)
    )
    cases = "\n  ".join(
        [f"Fin.cases group{g:02d}_checked <|" for g in range(8)] + ["fun i ↦ Fin.elim0 i"]
    )
    return imports + """import Grothe.UpperReplacement.HeadCompute
import Grothe.Upper.Data
import Lean.Elab.Tactic.Decide

/-! Complete signed head and closed numerical bounds. Agent-ID: codex-a7c4.
Generated by tools/gen_private_upper_head_witness.py --aggregate. -/

namespace Grothe.UpperReplacement.HeadWitnessFacts

def groups : Array (Array (Array GrotheKernel.Ival)) := #[
  group00, group01, group02, group03, group04, group05, group06, group07]

def grades : Array GrotheKernel.Ival := HeadWitness.savedGrades groups

theorem all_groups : ∀ g : Fin 8,
    HeadWitness.groupOK (g.val * 8) (groups[g.val]?.getD #[]) = true :=
  """ + cases + """

set_option maxRecDepth 10000 in
set_option maxHeartbeats 0 in
theorem head_checked :
    HeadCompute.headOK 251 Upper.energyRows grades RootData.piI
      (711964618746086 / 10 ^ 15) (873503595 / 10 ^ 15) = true := by
  native_decide

end Grothe.UpperReplacement.HeadWitnessFacts
"""


if __name__ == "__main__":
    main()
