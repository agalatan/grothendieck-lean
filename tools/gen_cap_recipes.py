#!/usr/bin/env python3
"""Generate `Grothe/LowerAnalytic/CapRecipeData.lean`: the price recipes of the vertex-node caps.

usage: tools/gen_cap_recipes.py ROWINDEX:recipes.json [ROWINDEX:recipes.json ...]
recipes.json: list of {k, g, v0 (12 rationals), var (list of 12-vectors), scale} (k = node index in
`Row.nodeList`, g = grid index of the row's grid list), as written by the recipe search (anchored proposal, AF proposal_m.py; search only:
the Lean check `nodeOK` certifies every cap from the recipe, whatever its quality).
"""
import json, sys
from fractions import Fraction as F
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Grothe" / "LowerAnalytic" / "CapRecipeData.lean"

def q(x):
    x = F(x)
    return f"({x.numerator} : Rat)" if x.denominator == 1 else f"({x.numerator} : Rat) / {x.denominator}"

def recipe(r):
    v0 = ", ".join(q(x) for x in r["v0"])
    var = ", ".join("[" + ", ".join(q(x) for x in f) + "]" for f in r["var"])
    return f"⟨[{v0}], [{var}], {q(r['scale'])}⟩"

rows = {}
for arg in sys.argv[1:]:
    k, path = arg.split(":", 1)
    rows[int(k)] = json.load(open(path))
lines = ["import GrotheKernel.CapCheck", "", "/-!",
         "# Price recipes of the vertex-node caps (generated by `tools/gen_cap_recipes.py`; do not edit)",
         "", "For each certified row (index in `rowData`), the recipes `(node index, recipe)`.", "-/", "",
         "namespace Grothe.LowerAnalytic", "", "open GrotheKernel", ""]
for k in sorted(rows):
    lines.append(f"/-- The recipes of row {k}. -/")
    lines.append(f"def capRecipes{k:02d} : List (Nat × Nat × Recipe) := [")
    body = [f"  ({r['k']}, {r.get('g', 0)}, {recipe(r)})" for r in rows[k]]
    lines.append(",\n".join(body))
    lines.append("]")
    lines.append("")
lines += ["end Grothe.LowerAnalytic", ""]
OUT.write_text("\n".join(lines))
print(f"wrote {OUT}: rows {sorted(rows)}, {sum(len(v) for v in rows.values())} recipes")
