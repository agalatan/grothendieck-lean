#!/usr/bin/env python3
"""Generate `Grothe/LowerAnalytic/CapRecipeData.lean`: the price recipes of the vertex-node caps.

usage: tools/gen_cap_recipes.py ROWINDEX:recipes.json[:EXCL] [...]
EXCL: comma-separated node indices whose caps are left to certify (excluded from the row check).
recipes.json: list of {k, g, v0 (12 rationals), var (list of 12-vectors), scale} (k = node index in
`Row.nodeList`, g = grid index of the row's grid list), as written by the recipe search (anchored proposal, AF proposal_m.py; search only:
the Lean check `nodeOK` certifies every cap from the recipe, whatever its quality).
"""
import json, sys
from fractions import Fraction as F
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Grothe" / "LowerAnalytic" / "CapRecipeData.lean"

def q(x):
    x = F(x)
    return f"({x.numerator} : Rat)" if x.denominator == 1 else f"({x.numerator} : Rat) / {x.denominator}"

def qs(x):
    x = F(x)
    return f"{x.numerator}" if x.denominator == 1 else f"{x.numerator}/{x.denominator}"

def recipe(r):
    parts = [",".join(qs(x) for x in r["v0"])] + [",".join(qs(x) for x in f) for f in r["var"]] + [qs(r["scale"])]
    return '"' + "|".join(parts) + '"'

rows = {}
excl = {}
for arg in sys.argv[1:]:
    parts = arg.split(":")
    k, path = int(parts[0]), parts[1]
    rows[k] = json.load(open(path))
    excl[k] = [int(x) for x in parts[2].split(",")] if len(parts) > 2 and parts[2] else []
lines = ["import GrotheKernel.CapCheck", "", "/-!",
         "# Price recipes of the vertex-node caps (generated by `tools/gen_cap_recipes.py`; do not edit)",
         "", "For each certified row (index in `rowData`), the recipes `(node index, recipe)`.", "-/", "",
         "namespace Grothe.LowerAnalytic", "", "open GrotheKernel", "", "set_option maxRecDepth 100000", ""]
for k in sorted(rows):
    lines.append(f"/-- The recipes of row {k}. -/")
    lines.append(f"def capRecipes{k:02d} : List (Nat × Nat × String) := [")
    body = [f"  ({r['k']}, {r.get('g', 0)}, {recipe(r)})" for r in rows[k]]
    lines.append(",\n".join(body))
    lines.append("]")
    lines.append("")
lines.append("/-- The certified rows: `(row index, recipes, excluded nodes)`. -/")
lines.append("def capRowsData : List (Nat × List (Nat × Nat × String) × List Nat) := [")
lines.append(",\n".join(f"  ({k}, capRecipes{k:02d}, [{', '.join(map(str, excl[k]))}])" for k in sorted(rows)))
lines.append("]")
lines.append("")
lines += ["end Grothe.LowerAnalytic", ""]
OUT.write_text("\n".join(lines))
print(f"wrote {OUT}: rows {sorted(rows)}, {sum(len(v) for v in rows.values())} recipes")
