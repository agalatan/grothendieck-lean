"""Generate the exact Haagerup resolvent certificate from repository data."""
from pathlib import Path
from fractions import Fraction
import argparse, json
ROOT=Path(__file__).resolve().parents[1]
DATA=ROOT/'data/haagerup-resolvent/certificate.json'
OUTPUT=ROOT/'Grothe/Haagerup/PowerCheck.lean'
def trim_trailing_zeros(xs):
    """Canonical coefficient list of the same exact rational polynomial."""
    end=len(xs)
    while end and Fraction(xs[end-1])==0:end-=1
    return xs[:end]
def render(c):
    def rat(x):
        x=Fraction(x)
        return str(x.numerator) if x.denominator==1 else f'{x.numerator}/{x.denominator}'
    def entries(xs):return ',\n  '.join(rat(x) for x in xs)
    return f'''import Mathlib.Tactic
import GrotheKernel.ResolventTail

/-! Generated by tools/gen_haagerup_power.py from data/haagerup-resolvent/certificate.json.
Do not edit this file by hand. All checks use sequential outward integer arithmetic. -/
set_option maxRecDepth 100000
set_option maxHeartbeats 4000000
namespace Grothe.HaagerupPower
open GrotheKernel

def pl : List ℚ := [{entries(c['P'])}]
def rl : List ℚ := [{entries(trim_trailing_zeros(c['R']))}]
def terms : ℕ := {c['K']}
def cutoff : ℕ := {c['M']}
def seedPower : ℕ := {c['seed_power']}
def headCap : ℚ := {rat(c['head'])}
def tailCap : ℚ := {rat(c['tail'])}
def gamma : ℚ := {rat(c['gamma'])}
def ratio : ℚ := {rat(c['q'])}
def seedCap : ℚ := {rat(c['seed_cap'])}
def defectCap : ℚ := {rat(c['defect_cap'])}
def slope : ℚ := {rat(c['P'][0])}

def checks : Bool :=
  haagCheck cutoff pl terms slope headCap gamma && powerNormOK pl 4 ratio &&
    resolventNormOK pl rl defectCap && seedNormOK pl rl seedPower seedCap &&
    resolventTailOK terms seedPower ratio seedCap gamma defectCap tailCap

/-- Complete finite residual, power contraction, inverse defect, combined seed,
and Abel-tail budget. No floating arithmetic or parallel evaluation is used. -/
theorem check : checks = true := by native_decide

end Grothe.HaagerupPower
'''
def main():
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args()
    out=render(json.loads(DATA.read_text()))
    if a.check:
        if OUTPUT.read_text()!=out:raise SystemExit('generated Lean data is stale')
        print('PASS byte-for-byte generated Lean data')
    else:OUTPUT.write_text(out)
if __name__=='__main__':main()
