#!/usr/bin/env python3
"""Render the complete root-11 integral proof from pinned candidate endpoints.

The generated Lean theorem uses the already proved actual reciprocal envelope.
Python only selects and renders the original finite integral intervals; Lean
checks the root identity and every area-weighted arithmetic comparison.

Agent-ID: codex-2ca4
"""

from __future__ import annotations

import argparse
from fractions import Fraction
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = ROOT / "data/analytic-envelope-cells/certificate.json"
DEFAULT_OUTPUT = ROOT / "Grothe/UpperChaos/Q0BasePairRoot11Integral.lean"


def rational(value: str) -> str:
    q = Fraction(value)
    return f"({q.numerator} / {q.denominator})"


def render(raw: bytes) -> str:
    certificate = json.loads(raw)
    rows = [row for row in certificate["cells"] if row["root"] == 11 and row["path"] == ""]
    if len(rows) != 1:
        raise ValueError("expected exactly one complete root-11 envelope cell")
    row = rows[0]
    cell = row["cell"]
    if (cell["chart"], cell["strip"]) != ("reciprocal", 5):
        raise ValueError("root 11 is not the reciprocal root of radial strip 5")
    expected = [Fraction(25203679, 1000000), Fraction(25204191, 1000000), Fraction(1, 100), Fraction(1)]
    if list(map(Fraction, cell["s"] + cell["aux"])) != expected:
        raise ValueError("root 11 no longer matches the accepted reciprocal envelope domain")
    intervals = row["integrals"]
    if len(intervals) != 2 or any(len(pair) != 2 or Fraction(pair[0]) > Fraction(pair[1]) for pair in intervals):
        raise ValueError("invalid original integral intervals")
    if Fraction(intervals[0][0]) != 0 or Fraction(intervals[1][0]) != -Fraction(intervals[1][1]):
        raise ValueError("expected the original one-sided first and symmetric companion intervals")
    slo, shi, alo, ahi = map(rational, cell["s"] + cell["aux"])
    flo, fhi = map(rational, intervals[0])
    clo, chi = map(rational, intervals[1])
    certificate_sha = hashlib.sha256(raw).hexdigest()
    profile_sha = certificate["provenance"]["profile_source_sha256"]
    return f'''import Grothe.UpperChaos.AdaptiveRectangleEnvelope
import Grothe.UpperChaos.AdaptiveRetainedCoefficient
import Grothe.UpperChaos.Q0BasePairReciprocalEnvelope

/-!
# Complete actual base-pair integral on retained root 11

Generated by tools/gen_analytic_envelope_root11.py.
Certificate SHA256: {certificate_sha}
Profile-source SHA256: {profile_sha}

The literal rectangle is the entire reciprocal root of radial strip 5.
The previously proved actual-kernel envelope fits inside the original stored
integral intervals after multiplication by the exact area. The first lower
endpoint remains zero; no source-omission or normalization error is added.

Agent-ID: codex-2ca4
-/

open LeanCert.Core Set

namespace Grothe.UpperChaos.Q0BasePairRoot11Integral

open AdaptiveRectanglePartition LeanCertProductionProfile

def root : Rect := ⟨{slo}, {shi}, {alo}, {ahi}⟩

theorem root_eq_fixed : root = AdaptiveRetainedCoefficient.reciprocalRoot 5 := by
  decide +kernel

theorem root_valid : root.Valid := by
  decide +kernel

/-- The original first-component candidate interval, with its zero lower endpoint. -/
def firstInterval : IntervalRat :=
  ⟨{flo},
    {fhi}, by decide +kernel⟩

/-- The original signed companion candidate interval. -/
def companionInterval : IntervalRat :=
  ⟨{clo},
    {chi}, by decide +kernel⟩

set_option maxRecDepth 100000 in
set_option maxHeartbeats 0 in
private theorem first_budget :
    firstInterval.lo ≤ 0 ∧
      root.area * Q0BasePairReciprocalEnvelope.firstUpper ≤ firstInterval.hi := by
  decide +kernel

set_option maxRecDepth 100000 in
set_option maxHeartbeats 0 in
private theorem companion_budget :
    companionInterval.lo ≤ -(root.area * Q0BasePairReciprocalEnvelope.companionAbsUpper) ∧
      root.area * Q0BasePairReciprocalEnvelope.companionAbsUpper ≤ companionInterval.hi := by
  decide +kernel

private theorem radial_mem {{p : ℝ × ℝ}} (hp : p ∈ root.domain) :
    p.1 ∈ Icc (Q0BasePairReciprocalEnvelope.radialLo : ℝ)
      Q0BasePairReciprocalEnvelope.radialHi :=
  hp.1

private theorem auxiliary_abs_le {{p : ℝ × ℝ}} (hp : p ∈ root.domain) :
    |p.2| ≤ (Q0BasePairReciprocalEnvelope.auxAbsUpper : ℝ) := by
  have hlo : (0 : ℝ) ≤ (root.auxLo : ℝ) := by norm_num [root]
  rw [abs_of_nonneg (hlo.trans hp.2.1)]
  exact hp.2.2

/-- The whole first reciprocal integral satisfies its original candidate
interval, for every damping parameter, with no numerical premises. -/
theorem first_integral_mem (η : ℝ) :
    root.integral (fun s x => Q0BasePairKernel.reciprocalFirst η s (q0Kappa s) x) ∈
      firstInterval := by
  apply Rect.integral_mem_of_nonneg_envelope root root_valid
    (fun s x => Q0BasePairKernel.reciprocalFirst η s (q0Kappa s) x)
    Q0BasePairReciprocalEnvelope.firstUpper firstInterval
  · intro p hp
    exact Q0BasePairReciprocalEnvelope.first_bound η p.1 p.2
      (radial_mem hp) (auxiliary_abs_le hp)
  · exact first_budget.1
  · exact first_budget.2

/-- The whole signed companion reciprocal integral satisfies its original
candidate interval, for every damping parameter, with no numerical premises. -/
theorem companion_integral_mem (η : ℝ) :
    root.integral (fun s x => Q0BasePairKernel.reciprocalCompanion η s (q0Kappa s) x) ∈
      companionInterval := by
  apply Rect.integral_mem_of_abs_envelope root root_valid
    (fun s x => Q0BasePairKernel.reciprocalCompanion η s (q0Kappa s) x)
    Q0BasePairReciprocalEnvelope.companionAbsUpper companionInterval
  · intro p hp
    exact Q0BasePairReciprocalEnvelope.companion_bound η p.1 p.2
      (radial_mem hp) (auxiliary_abs_le hp)
  · exact companion_budget.1
  · exact companion_budget.2

/-- Both actual base-pair integrals on the complete fixed reciprocal root. -/
theorem integrals_mem (η : ℝ) :
    root.integral (fun s x => Q0BasePairKernel.reciprocalFirst η s (q0Kappa s) x) ∈
        firstInterval ∧
      root.integral (fun s x => Q0BasePairKernel.reciprocalCompanion η s (q0Kappa s) x) ∈
        companionInterval :=
  ⟨first_integral_mem η, companion_integral_mem η⟩

end Grothe.UpperChaos.Q0BasePairRoot11Integral
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render(args.input.read_bytes()).encode()
    if args.check:
        if args.output.read_bytes() != rendered:
            raise ValueError("generated root-11 integral module differs from existing output")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(rendered)
    print(json.dumps({"check": args.check, "output_bytes": len(rendered),
                      "output_sha256": hashlib.sha256(rendered).hexdigest()}, sort_keys=True))


if __name__ == "__main__":
    main()
