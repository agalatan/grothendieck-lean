#!/usr/bin/env python3
"""Generate source-coordinate and selected source-row replay, Agent-ID: codex-aa04.

Uses the canonical source export and the committed actual-coordinate models.
Each generated row refers to codex-8c4d's canonical Q0LiteralSourceData. This
checks numerical evaluation, not the separate source-to-literal equality.
"""
import argparse
from fractions import Fraction as Q
import hashlib
import json
from pathlib import Path
import rectangle_probe as rp
from gen_profile_model import model, rat
from gen_exponential_model import load_model
from check_horner_trace import check as preflight_trace

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / 'data/q0_quadrature'
OUT = ROOT / 'Grothe/UpperChaos'


def trace_defs(trace, prefix=''):
    out = []
    for i, step in enumerate(trace['steps']):
        out.append(f'private def {prefix}product{i} : Model := {model(step["product"])}\n'
                   f'private def {prefix}result{i} : Model := {model(step["result"])}\n')
    tail = 'Trace.nil'
    for i in reversed(range(len(trace['steps']))):
        step = trace['steps'][i]
        tail = f'(Trace.cons {prefix}product{i} {prefix}result{i} {rat(step["mulBudget"])} 0 {tail})'
    out.append(f'private def {prefix}trace : Trace := {tail}\n')
    return '\n'.join(out)


def generate():
    profile = json.loads((DATA/'profile-model-trace.json').read_bytes())
    rate = json.loads((DATA/'rate-model-trace.json').read_bytes())
    reciprocal = json.loads((DATA/'reciprocal-model-trace.json').read_bytes())
    source_bytes = (DATA/'source-polynomial.json').read_bytes()
    source = json.loads(source_bytes)
    recipe = json.loads((DATA/'source-model-recipe.json').read_bytes())
    assert recipe['degree'] == 6 and recipe['bits'] == 160
    k = load_model(profile['trace']['output'])
    t = load_model(rate['nodes']['t'])
    z = load_model(reciprocal['nodes']['reciprocal'])
    kt = k*t
    v = kt*z
    outputs = {}
    outputs['Q0SourceCoordinateModel.lean'] = f'''import Grothe.UpperChaos.Q0ReciprocalRectangleModel

/-! Generated by tools/q0_quadrature/gen_source_row_models.py.
Actual shifted source coordinate on the normalized square. Agent-ID: codex-aa04. -/
namespace Grothe.UpperChaos.Q0SourceCoordinateModel
open LeanCert.Core RectangleCoefficientArithmetic RectangleModelCheck
open Q0RateRectangleModel Q0ReciprocalRectangleModel LeanCertProductionProfile
set_option maxRecDepth 100000
set_option maxHeartbeats 0
private def ktModel : Model := {model(rp.model_json(kt))}
def vModel : Model := {model(rp.model_json(v))}
private theorem kt_checked :
    mulOK Q0ProfileRectangleModel.profileModel tModel ktModel {rat(kt.product_budget)} = true := by
  decide +kernel
private theorem v_checked :
    mulOK ktModel reciprocalModel vModel {rat(v.product_budget)} = true := by decide +kernel
noncomputable def actualV (x y : ℝ) : ℝ :=
  q0Kappa ((2001/2000 : ℝ) + (1/2000) * x) *
    (((2001/2000 : ℝ) + (1/2000) * y) ^ 2) * (actualRate x y)⁻¹
/-- Actual source argument, with every product and rounding remainder checked. -/
theorem actual_v_model (x y : ℝ) (hx : |x| ≤ 1) (hy : |y| ≤ 1) :
    Contains vModel x y (actualV x y) := by
  have hkt := mul_sound Q0ProfileRectangleModel.profileModel tModel ktModel
    {rat(kt.product_budget)} kt_checked hx hy
    (Q0ProfileRectangleModel.actual_profile_model x y hx hy) (actual_t_model x y hx hy)
  exact mul_sound ktModel reciprocalModel vModel {rat(v.product_budget)} v_checked hx hy hkt
    (actual_reciprocal_model x y hx hy)
end Grothe.UpperChaos.Q0SourceCoordinateModel
'''
    row_models = {}
    for row_index in recipe['rows']:
        row = source['sourceCoefficients'][row_index]
        rp.HORNER_RECORDS = []
        result = rp.horner(row, z, lambda col: rp.horner(col, v,
            lambda a: rp.Model.constant(int(a), 6, v.bits)))
        row_models[row_index] = result
        records = rp.HORNER_RECORDS
        assert all(preflight_trace(r) for r in records), 'external arithmetic preflight rejected a row'
        outer = records[-1]
        # Recursion generates columns from high to low order.
        columns = list(reversed(records[:-1]))
        assert len(columns)==len(row)
        text = [f'''import Grothe.UpperChaos.Q0SourceCoordinateModel
import Grothe.UpperChaos.RectangleIntegerHornerTrace
import Grothe.UpperChaos.Q0LiteralSourceData

/-! Generated by tools/q0_quadrature/gen_source_row_models.py.
Source-export SHA256: {hashlib.sha256(source_bytes).hexdigest()}
Numerical replay of canonical literal source row {row_index}. The actual-source
binding is proved separately by the source compiler. Agent-ID: codex-aa04. -/
namespace Grothe.UpperChaos.Q0SourceRow{row_index}Model
open LeanCert.Core RectangleCoefficientArithmetic RectangleModelCheck RectangleHornerTrace
open Q0RateRectangleModel Q0ReciprocalRectangleModel Q0SourceCoordinateModel
set_option maxRecDepth 100000
set_option maxHeartbeats 0
private def row : List (List ℤ) := Q0LiteralSourceData.sourceCoefficients.getD {row_index} []
''']
        for j, tr in enumerate(columns):
            text.append(f'\nnamespace Column{j}\n')
            text.append(trace_defs(tr))
            text.append(f'''
def output : Model := trace.output
private theorem checked :
    trace.check vModel ((row.getD {j} []).map (fun c : ℤ => constant (c : ℚ))) = true := by
  decide +kernel
 theorem contains (x y : ℝ) (hx : |x| ≤ 1) (hy : |y| ≤ 1) :
    Contains output x y (he1 (row.getD {j} []) (actualV x y)) :=
  trace.integer_sound vModel (row.getD {j} []) checked hx hy (actual_v_model x y hx hy)
end Column{j}
''')
        text.append(trace_defs(outer))
        inputs = '['+', '.join(f'Column{j}.output' for j in range(len(row)))+']'
        values = '['+', '.join(f'he1 (row.getD {j} []) (actualV x y)' for j in range(len(row)))+']'
        pairproof = 'List.Forall₂.nil'
        for j in reversed(range(len(row))):
            pairproof=f'(List.Forall₂.cons (Column{j}.contains x y hx hy) {pairproof})'
        text.append(f'''
private def inputs : List Model := {inputs}
private theorem checked : trace.check reciprocalModel inputs = true := by decide +kernel

def rowModel : Model := trace.output

/-- Enclosure of an entire canonical source row, including cancellation before
all rounding and truncation reserves are accumulated. -/
theorem row_model (x y : ℝ) (hx : |x| ≤ 1) (hy : |y| ≤ 1) :
    Contains rowModel x y
      (he2 (Q0LiteralSourceData.sourceCoefficients.getD {row_index} [])
        ((actualRate x y)⁻¹) (actualV x y)) := by
  have hi : List.Forall₂ (fun m a => Contains m x y a) inputs
      (row.map (fun col => he1 col (actualV x y))) := by
    change List.Forall₂ _ {inputs} {values}
    exact {pairproof}
  have h := trace.sound reciprocalModel hx hy (actual_reciprocal_model x y hx hy)
    inputs _ hi checked
  rw [evalG_map (fun col => he1 col (actualV x y)) id
    (fun col => he1 col (actualV x y)) (fun _ => rfl)] at h
  exact h
end Grothe.UpperChaos.Q0SourceRow{row_index}Model
''')
        outputs[f'Q0SourceRow{row_index}Model.lean'] = '\n'.join(text)
    if recipe['rows'] == list(range(len(source['sourceCoefficients']))):
        from gen_source_assembly import render_assembly
        outputs.update(render_assembly(source, profile, row_models))
    rp.HORNER_RECORDS = None
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args=parser.parse_args()
    for name, text in generate().items():
        path = OUT/name
        if args.check:
            if path.read_text()!=text:
                raise SystemExit(f'{name} differs from generated output')
        else:
            path.write_text(text)
            print(name, len(text), 'bytes')


if __name__=='__main__':
    main()
