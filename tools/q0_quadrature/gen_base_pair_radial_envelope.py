#!/usr/bin/env python3
"""Generate a concrete actual-kernel radial envelope, not a whole integral.

The recipe and source coefficients are committed; generated checks replay all
profile coefficients, Horner arithmetic and the scalar exponential in Lean.
Agent-ID: codex-aa04.
"""
import argparse
from fractions import Fraction as Q
import hashlib
import json
from pathlib import Path

import rectangle_probe as rp
from gen_profile_model import model, rat
from gen_source_row_models import trace_defs

ROOT = Path(__file__).resolve().parents[2]
RECIPE = ROOT / 'data/q0_quadrature/base-pair-radial-envelope-recipe.json'
OUTPUT = ROOT / 'Grothe/UpperChaos/Q0BasePairRadialEnvelope.lean'


def direct_conclusions():
    return '''/-- All numerical profile and exponential inputs are discharged. -/
theorem first_bound (η s u : ℝ) (hs : s ∈ Set.Icc (radialLo : ℝ) radialHi) :
    0 ≤ Q0BasePairKernel.first η s (q0Kappa s) u ∧
      Q0BasePairKernel.first η s (q0Kappa s) u ≤ (firstUpper : ℝ) := by
  have hs0 : 0 ≤ s := le_trans (by norm_num [radialLo]) hs.1
  have hb := Q0BasePairEnvelope.direct_first η s (q0Kappa s) u radialLo radialHi expUpper
    hs0 hs.1 hs.2 exp_upper
  simpa only [firstUpper, Rat.cast_mul, Rat.cast_ofNat] using hb

theorem companion_bound (η s u : ℝ) (hs : s ∈ Set.Icc (radialLo : ℝ) radialHi) :
    |Q0BasePairKernel.companion η s (q0Kappa s) u| ≤ (companionAbsUpper : ℝ) := by
  have hs0 : 0 ≤ s := le_trans (by norm_num [radialLo]) hs.1
  have hb := Q0BasePairEnvelope.direct_companion η s (q0Kappa s) u radialLo profileAbsUpper expUpper
    hs0 hs.1 (profile_bound hs) exp_upper
  simpa only [companionAbsUpper, Rat.cast_mul, Rat.cast_ofNat] using hb

theorem first_small : firstUpper < (1/10^27 : ℚ) := by decide +kernel

theorem companion_small : companionAbsUpper < (1/10^19 : ℚ) := by decide +kernel
'''


def render(reciprocal=False):
    path = ROOT / 'data/q0_quadrature/base-pair-reciprocal-envelope-recipe.json' if reciprocal else RECIPE
    raw = path.read_bytes()
    recipe = json.loads(raw)
    source_raw = (ROOT / recipe['profile_input']).read_bytes()
    source = json.loads(source_raw)
    lo, hi = map(Q, recipe['s'])
    assert 0 < lo < hi and recipe['bits'] == 160
    c, h = (lo+hi)/2, (hi-lo)/2
    coordinate = rp.coordinate(lo, hi, 0, recipe['degree'], recipe['bits'])
    den = int(source['profileDen'])
    rp.HORNER_RECORDS = []
    profile = rp.horner(source['profileCoefficients'], coordinate,
                       lambda pair: rp.Model.from_interval(rp.Interval.rational(
                           Q(int(pair[0]), den), Q(int(pair[1]), den), recipe['bits']),
                           recipe['degree']))
    trace = rp.HORNER_RECORDS[0]
    rp.HORNER_RECORDS = None
    bound = profile.range().max_abs()
    rounding_den = int(recipe.get('profile_rounding_den', 1))
    K = Q(rp.ceildiv(bound.numerator*rounding_den, bound.denominator), rounding_den)
    E = Q(recipe['exp_upper'])
    namespace = 'Q0BasePairReciprocalEnvelope' if reciprocal else 'Q0BasePairRadialEnvelope'
    description = ('The reciprocal coordinate has modulus at most one; damping is arbitrary.\nThis is not a full Gaussian coefficient enclosure.' if reciprocal else\
                   'The auxiliary variable and damping parameter remain arbitrary. This is not\na full Gaussian coefficient enclosure.')
    conclusions = reciprocal_conclusions() if reciprocal else direct_conclusions()
    upper_definitions = reciprocal_definitions(recipe) if reciprocal else '''def firstUpper : ℚ := 2*radialHi*expUpper
def companionAbsUpper : ℚ := 4*profileAbsUpper*expUpper'''
    return f'''import Grothe.UpperChaos.Q0BasePairEnvelope
import Grothe.UpperChaos.Q0ProfileRectangleModel
import Grothe.UpperChaos.RectangleCoordinates
import LeanCert.Validity.Dyadic

/-! Generated by tools/q0_quadrature/gen_base_pair_radial_envelope.py.
Recipe SHA256: {hashlib.sha256(raw).hexdigest()}
Profile-input SHA256: {hashlib.sha256(source_raw).hexdigest()}
Concrete bounds for both actual j0 kernels on a retained radial interval.
{description} Agent-ID: codex-aa04. -/

namespace Grothe.UpperChaos.{namespace}
open LeanCert.Core LeanCert.Validity RectangleModelCheck RectangleHornerTrace
open PointwiseGeometricEnclosure LeanCertProductionProfile

set_option maxHeartbeats 0
set_option maxRecDepth 100000

def radialLo : ℚ := {rat(lo)}
def radialHi : ℚ := {rat(hi)}
def center : ℚ := {rat(c)}
def halfwidth : ℚ := {rat(h)}
def profileAbsUpper : ℚ := {rat(K)}
def expUpper : ℚ := {rat(E)}
{upper_definitions}

private def coordinate : Model := {model(rp.model_json(coordinate))}
{trace_defs(trace)}

private theorem coordinate_checked :
    RectangleCoordinates.checkX center halfwidth coordinate = true := by decide +kernel

private theorem profile_checked :
    trace.check coordinate Q0ProfileRectangleModel.inputs = true := by decide +kernel

private theorem profileAbsUpper_nonneg : 0 ≤ profileAbsUpper := by decide +kernel

private theorem range_checked :
    intervalSubset (range trace.output)
      (errorInterval profileAbsUpper profileAbsUpper_nonneg) = true := by decide +kernel

theorem profile_bound {{s : ℝ}} (hs : s ∈ Set.Icc (radialLo : ℝ) radialHi) :
    |q0Kappa s| ≤ (profileAbsUpper : ℝ) := by
  let x := (s-(center : ℝ))/(halfwidth : ℝ)
  have hx : |x| ≤ 1 := by
    have hs' := hs
    norm_num [radialLo, radialHi, Set.mem_Icc] at hs'
    apply abs_le.mpr
    dsimp [x, center, halfwidth]
    norm_num
    constructor <;> linarith [hs'.1, hs'.2]
  have hy : |(0 : ℝ)| ≤ 1 := by norm_num
  have hc := RectangleCoordinates.x_sound center halfwidth coordinate coordinate_checked hx hy
  have he : (center : ℝ)+(halfwidth : ℝ)*x = s := by
    dsimp [x, center, halfwidth]
    norm_num
    ring
  rw [he] at hc
  have hp := Q0ProfileRectangleModel.profile_of_trace coordinate trace profile_checked hx hy hc
  have hb := mem_of_intervalSubset range_checked (mem_range hx hy hp)
  exact abs_le.mpr (by
    simpa only [errorInterval, IntervalRat.mem_def, Rat.cast_neg] using hb)

private theorem exp_upper_checked :
    checkUpperBoundDyadicChecked (.exp (.const (-radialLo))) 0 0 (by norm_num)
      expUpper (-256) 64 = true := by decide +kernel

theorem exp_upper : Real.exp (-(radialLo : ℝ)) ≤ (expUpper : ℝ) := by
  have hu := verify_upper_bound_dyadic_checked (.exp (.const (-radialLo)))
    0 0 (by norm_num) expUpper (-256) 64 (by norm_num)
    exp_upper_checked 0 (by norm_num)
  simpa only [Expr.eval, Rat.cast_neg] using hu

{conclusions}
end Grothe.UpperChaos.{namespace}
'''


def reciprocal_definitions(recipe):
    return f'''def power : ℕ := {int(recipe['power'])}
def auxAbsUpper : ℚ := {rat(recipe['aux_abs_upper'])}
def denominatorUpper : ℚ := auxAbsUpper^2 + profileAbsUpper^2
def firstUpper : ℚ := 2*radialHi*auxAbsUpper^2 *
  (expUpper*((power+2).factorial : ℚ)*denominatorUpper^power/radialLo^(power+2))
def companionAbsUpper : ℚ := 2*profileAbsUpper*auxAbsUpper^2 *
  (expUpper*((power+2).factorial+(power+3).factorial : ℚ)*denominatorUpper^power/radialLo^(power+2))'''


def reciprocal_conclusions():
    return '''private theorem denominator_bound {s x : ℝ}
    (hs : s ∈ Set.Icc (radialLo : ℝ) radialHi) (hx : |x| ≤ (auxAbsUpper : ℝ)) :
    x^2 + (q0Kappa s)^2 ≤ (denominatorUpper : ℝ) := by
  have hx2 : x^2 ≤ (auxAbsUpper : ℝ)^2 := by
    simpa only [sq_abs] using pow_le_pow_left₀ (abs_nonneg x) hx 2
  have hk2 : (q0Kappa s)^2 ≤ (profileAbsUpper : ℝ)^2 := by
    simpa only [sq_abs] using pow_le_pow_left₀ (abs_nonneg (q0Kappa s)) (profile_bound hs) 2
  simpa only [denominatorUpper, Rat.cast_add, Rat.cast_pow] using add_le_add hx2 hk2

/-- The whole retained reciprocal strip is covered; all numerical profile
and scalar exponential hypotheses have been proved. -/
theorem first_bound (η s x : ℝ) (hs : s ∈ Set.Icc (radialLo : ℝ) radialHi)
    (hx : |x| ≤ (auxAbsUpper : ℝ)) :
    0 ≤ Q0BasePairKernel.reciprocalFirst η s (q0Kappa s) x ∧
      Q0BasePairKernel.reciprocalFirst η s (q0Kappa s) x ≤ (firstUpper : ℝ) := by
  have hb := Q0BasePairEnvelope.reciprocal_first power η s (q0Kappa s) x
    radialLo radialHi auxAbsUpper denominatorUpper expUpper
    (by norm_num [radialLo]) hs.1 hs.2 hx (denominator_bound hs hx) exp_upper
  simpa only [firstUpper, Rat.cast_mul, Rat.cast_div, Rat.cast_pow,
    Rat.cast_natCast, Rat.cast_ofNat] using hb

theorem companion_bound (η s x : ℝ) (hs : s ∈ Set.Icc (radialLo : ℝ) radialHi)
    (hx : |x| ≤ (auxAbsUpper : ℝ)) :
    |Q0BasePairKernel.reciprocalCompanion η s (q0Kappa s) x| ≤ (companionAbsUpper : ℝ) := by
  have hb := Q0BasePairEnvelope.reciprocal_companion power η s (q0Kappa s) x
    radialLo auxAbsUpper profileAbsUpper denominatorUpper expUpper
    (by norm_num [radialLo]) hs.1 hx (profile_bound hs) (denominator_bound hs hx) exp_upper
  simpa only [companionAbsUpper, Rat.cast_mul, Rat.cast_div, Rat.cast_pow,
    Rat.cast_add, Rat.cast_natCast, Rat.cast_ofNat] using hb

theorem first_small : firstUpper < (1/10^17 : ℚ) := by decide +kernel

theorem companion_small : companionAbsUpper < (1/10^19 : ℚ) := by decide +kernel
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--reciprocal', action='store_true')
    args = parser.parse_args()
    text = render(args.reciprocal)
    output = ROOT / 'Grothe/UpperChaos/Q0BasePairReciprocalEnvelope.lean' if args.reciprocal else OUTPUT
    if args.check:
        if output.read_text() != text:
            raise SystemExit('radial envelope differs from generated output')
    else:
        output.write_text(text)


if __name__ == '__main__':
    main()
