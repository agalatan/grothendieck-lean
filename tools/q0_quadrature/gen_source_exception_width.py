#!/usr/bin/env python3
"""Generate independent exact checks of the three exception-panel widths.

The relation to actual Gauss weights/decay is separate. Agent-ID: codex-aa04.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'Grothe/UpperChaos'
BLOCKS = [(146, 129, 34), (557, 128, 27), (964, 124, 14)]


def generate():
    files = {}
    for i, (start, count, cap) in enumerate(BLOCKS):
        name = f'Q0SourceExceptionWidthCheck{i}'
        lines = [
            'import Grothe.UpperChaos.Q0SourceExceptionWidth', '',
            '/-! Generated exact exception-panel width candidate.',
            'Generated by tools/q0_quadrature/gen_source_exception_width.py.',
            'Agent-ID: codex-aa04. -/',
            f'namespace Grothe.UpperChaos.{name}', '',
            'open Grothe.UpperChaos.Q0SourceExceptionWidth', '',
            'set_option maxRecDepth 65536', 'set_option maxHeartbeats 0', '',
            f'theorem checked : blockWidth {start} {count} < ({cap} : ℚ) / 10^17 := by',
            '  decide +kernel', '', f'end Grothe.UpperChaos.{name}', '']
        files[name + '.lean'] = '\n'.join(lines).encode()
    lines = [f'import Grothe.UpperChaos.Q0SourceExceptionWidthCheck{i}' for i in range(3)]
    lines += [
        'import Lean.Util.CollectAxioms', 'import Lean.Elab.Command', '',
        '/-! Exact total width of all three whole-panel exceptions.',
        'Agent-ID: codex-aa04. -/',
        'namespace Grothe.UpperChaos.Q0SourceExceptionWidthAll', '',
        'open Grothe.UpperChaos.Q0SourceExceptionWidth', '',
        'theorem total_width_lt : totalWidth < (8 : ℚ) / 10^16 := by',
        '  have h0 := Q0SourceExceptionWidthCheck0.checked',
        '  have h1 := Q0SourceExceptionWidthCheck1.checked',
        '  have h2 := Q0SourceExceptionWidthCheck2.checked',
        '  unfold totalWidth',
        '  linarith', '',
        'end Grothe.UpperChaos.Q0SourceExceptionWidthAll', '',
        'open Lean Elab Command', 'run_cmd do',
        '  let dependencies ← Lean.collectAxioms',
        '    ``Grothe.UpperChaos.Q0SourceExceptionWidthAll.total_width_lt',
        '  for dependency in dependencies do',
        '    unless (#[`propext, `Classical.choice, `Quot.sound] : Array Name).contains dependency do',
        '      throwError m!"source exception width uses unexpected axiom {dependency}"', '']
    files['Q0SourceExceptionWidthAll.lean'] = '\n'.join(lines).encode()
    return files


if __name__ == '__main__':
    files = generate()
    if sys.argv[1:] == ['--check']:
        for name, data in files.items():
            if (OUT / name).read_bytes() != data:
                raise ValueError(f'generated file differs: {name}')
    elif not sys.argv[1:]:
        for name, data in files.items():
            (OUT / name).write_bytes(data)
    else:
        raise SystemExit('usage: gen_source_exception_width.py [--check]')
    print(f'{len(files)} generated modules, {sum(map(len, files.values()))} bytes')
