#!/usr/bin/env python3
"""Emit the actual profile's rectangle-model replay, Agent-ID: codex-aa04.

All input and operation checks are Lean propositions reduced by decide +kernel.
This generator makes no trusted numerical decisions.
"""
import argparse
from fractions import Fraction as Q
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
INPUT = ROOT / 'data/q0_quadrature/profile-model-trace.json'
OUTPUT = ROOT / 'Grothe/UpperChaos/Q0ProfileRectangleModel.lean'


def rat(x):
    q = Q(x)
    return f'({q.numerator} / {q.denominator})'


def model(m):
    d = 1 << m['bits']
    values = {(i, j): int(c) for i, j, c in m['coefficients']}
    rows = []
    for i in range(max((i for i, j in values), default=-1) + 1):
        cols = [rat(Q(values.get((i, j), 0), d))
                for j in range(max((j for k, j in values if k == i), default=-1) + 1)]
        rows.append('[' + ', '.join(cols) + ']')
    lo, hi = (rat(Q(int(v), d)) for v in m['remainder'])
    return '⟨[' + ', '.join(rows) + f'], ⟨{lo}, {hi}, by decide +kernel⟩⟩'


def render(raw):
    data = json.loads(raw)
    tr = data['trace']
    if len(tr['steps']) != 12 or len(tr['inputs']) != 12:
        raise ValueError('the actual profile has twelve coefficients')
    out = [f'''import Grothe.UpperChaos.RectangleHornerTrace
import Grothe.UpperChaos.LeanCertProductionProfile

/-!
Generated by tools/q0_quadrature/gen_profile_model.py.
Input SHA256: {hashlib.sha256(raw).hexdigest()}
All rounded Horner steps and actual profile-coefficient inputs are checked.
This certifies the degree-six profile model on the first normalized rectangle;
the remaining kernel operations and whole coefficient integral are separate.
Agent-ID: codex-aa04.
-/

namespace Grothe.UpperChaos.Q0ProfileRectangleModel

open GrotheKernel LeanCert.Core RectangleCoefficientArithmetic
open RectangleModelCheck RectangleHornerTrace ProfileRootScreen

set_option maxRecDepth 100000
set_option maxHeartbeats 0

private theorem actual_coeff_in_interval (k : ℕ) (hk : k < 12) (I : IntervalRat)
    (h : I.lo * (D : ℚ) ≤ (coeffs.getD k zeroI).lo ∧
      ((coeffs.getD k zeroI).hi : ℚ) ≤ I.hi * D) : profileCoeffR k ∈ I := by
  have hm := actual_coeff_mem k hk
  change ((coeffs.getD k zeroI).lo : ℝ) ≤ profileCoeffR k * D ∧
    profileCoeffR k * D ≤ ((coeffs.getD k zeroI).hi : ℝ) at hm
  have hl : (I.lo : ℝ) * D ≤ ((coeffs.getD k zeroI).lo : ℝ) := by
    exact_mod_cast h.1
  have hu : ((coeffs.getD k zeroI).hi : ℝ) ≤ (I.hi : ℝ) * D := by
    exact_mod_cast h.2
  exact ⟨(le_of_mul_le_mul_right (hl.trans hm.1) Grothe.Upper.D_pos),
    (le_of_mul_le_mul_right (hm.2.trans hu) Grothe.Upper.D_pos)⟩

def coordinate : Model := {model(tr['variable'])}

private def exactCoordinate : Coefficients := [[{rat(data['center'])}], [{rat(data['halfwidth'])}]]

private theorem coordinate_checked :
    intervalSubset (polynomialRange (sub2 exactCoordinate coordinate.coefficients))
      coordinate.remainder = true := by decide +kernel

theorem coordinate_contains (x y : ℝ) (hx : |x| ≤ 1) (hy : |y| ≤ 1) :
    Contains coordinate x y (({rat(data['center'])} : ℝ) + {rat(data['halfwidth'])} * x) := by
  have hr := eval2_mem_polynomialRange (sub2 exactCoordinate coordinate.coefficients) hx hy
  have h := mem_of_intervalSubset coordinate_checked hr
  rw [eval2_sub] at h
  have he : eval2 exactCoordinate x y =
      ({rat(data['center'])} : ℝ) + {rat(data['halfwidth'])} * x := by
    simp [exactCoordinate, eval2, eval1, mul_comm]
  rw [he] at h
  exact h
''']
    for i, (m, pair) in enumerate(zip(tr['inputs'], data['profileCoefficients'])):
        lo, hi = (rat(Q(int(v), int(data['profileDen']))) for v in pair)
        c = Q(int(next(v for a, b, v in m['coefficients'] if a == b == 0)), 1 << m['bits'])
        out.append(f'''
private def input{i} : Model := {model(m)}
private def inputInterval{i} : IntervalRat := ⟨{lo}, {hi}, by decide +kernel⟩

private theorem input{i}_checked :
    intervalInputOK inputInterval{i} {rat(c)} input{i} 0 = true := by decide +kernel

private theorem input{i}_contains (x y : ℝ) (hx : |x| ≤ 1) (hy : |y| ≤ 1) :
    Contains input{i} x y (profileCoeffR {i}) := by
  apply intervalInput_sound inputInterval{i} {rat(c)} input{i} 0 input{i}_checked hx hy
  exact actual_coeff_in_interval {i} (by decide) inputInterval{i} (by decide +kernel)
''')
    for i, step in enumerate(tr['steps']):
        out.append(f'\nprivate def product{i} : Model := {model(step["product"])}\n'
                   f'private def result{i} : Model := {model(step["result"])}\n')
    tail = 'Trace.nil'
    for i in reversed(range(12)):
        step = tr['steps'][i]
        tail = f'(Trace.cons product{i} result{i} {rat(step["mulBudget"])} {rat(step["addBudget"])} {tail})'
    inputs = '[' + ', '.join(f'input{i}' for i in range(12)) + ']'
    out.append(f'''
def inputs : List Model := {inputs}
private def trace : Trace := {tail}

private theorem trace_checked : trace.check coordinate inputs = true := by decide +kernel

def profileModel : Model := trace.output

private theorem actual_profile_horner (s : ℝ) :
    evalG id ((List.range 12).map profileCoeffR) s =
      LeanCertProductionProfile.q0Kappa s := by
  rw [evalG_range_map]
  simpa only [id_eq, profileCoeffR, gammaFactor, LeanCertProductionProfile.q0Kappa]
    using (profile_eq_coeff_expansion s).symm

/-- The actual production profile, with every coefficient interval and every
rounded/truncated Horner operation checked in the Lean kernel. -/
theorem actual_profile_model (x y : ℝ) (hx : |x| ≤ 1) (hy : |y| ≤ 1) :
    Contains profileModel x y
      (LeanCertProductionProfile.q0Kappa
        (({rat(data['center'])} : ℝ) + {rat(data['halfwidth'])} * x)) := by
  have hi : List.Forall₂ (fun m a => Contains m x y a)
      inputs ((List.range 12).map profileCoeffR) := by
    change List.Forall₂ _ {inputs}
      [{', '.join(f'profileCoeffR {i}' for i in range(12))}]
    exact ''')
    proof = 'List.Forall₂.nil'
    for i in reversed(range(12)):
        proof = f'(List.Forall₂.cons (input{i}_contains x y hx hy) {proof})'
    out[-1] += proof + '\n'
    out.append('''  have h := trace.sound coordinate hx hy (coordinate_contains x y hx hy)
    inputs _ hi trace_checked
  rw [actual_profile_horner] at h
  exact h
''')
    out.append(f'''
/-- Reuse the proved production coefficient models on any normalized cell.
Only the new coordinate model and finite Horner transcript change. -/
theorem profile_of_trace (argumentModel : Model) (witness : Trace)
    (hcheck : witness.check argumentModel inputs = true)
    {{x y s : ℝ}} (hx : |x| ≤ 1) (hy : |y| ≤ 1)
    (hs : Contains argumentModel x y s) :
    Contains witness.output x y (LeanCertProductionProfile.q0Kappa s) := by
  have hi : List.Forall₂ (fun m a => Contains m x y a)
      inputs ((List.range 12).map profileCoeffR) := by
    change List.Forall₂ _ {inputs}
      [{', '.join(f'profileCoeffR {i}' for i in range(12))}]
    exact {proof}
  have h := witness.sound argumentModel hx hy hs inputs _ hi hcheck
  rw [actual_profile_horner] at h
  exact h

end Grothe.UpperChaos.Q0ProfileRectangleModel
''')
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = render(INPUT.read_bytes())
    if args.check:
        if OUTPUT.read_text() != generated:
            raise SystemExit('profile model differs from generator output')
    else:
        OUTPUT.write_text(generated)


if __name__ == '__main__':
    main()
