#!/usr/bin/env python3
"""Replay the sole algebraic leaf of retained root 7. Agent-ID: codex-aa04.

The other three leaves are analytic envelopes, owned by codex-2ca4. This
generator binds the actual pair of integrals on path 111, not just a residual.
"""
import argparse
from fractions import Fraction as Q
import hashlib
import json
from pathlib import Path

import base_pair_trace
from gen_base_pair_leaf import generate

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / 'data/q0_quadrature'
TRACE = DATA / 'base-pair-root7-leaf-trace.json'
RECIPE = DATA / 'base-pair-root7-leaf-recipe.json'


def discover():
    recipe = json.loads(RECIPE.read_bytes())
    source = (ROOT / recipe['profile_input']).read_bytes()
    assert hashlib.sha256(source).hexdigest() == recipe['profile_input_sha256']
    raw = base_pair_trace.discover([recipe['cell']], recipe['degree'], recipe['bits'], Q(recipe['eta']))
    cell = json.loads(raw)['cells'][0]
    for name, expected in zip(('firstOutput', 'companionOutput'), recipe['expected_models']):
        assert cell['nodes'][name] == expected, f'{name} changed from the frozen candidate'
    return raw


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--discover', action='store_true')
    args = parser.parse_args()
    if args.discover:
        raw = discover()
        if args.check:
            if TRACE.read_text() != raw:
                raise SystemExit('root 7 leaf trace is not reproducible')
        else:
            TRACE.write_text(raw)
    replacements = {'Q0BasePairReciprocalLeaf': 'Q0BasePairRoot7Leaf',
                    'Q0BasePairLeafScalars': 'Q0BasePairRoot7LeafScalars'}
    for name, text in generate(TRACE.read_bytes()).items():
        for old, new in replacements.items():
            name, text = name.replace(old, new), text.replace(old, new)
        text = text.replace('Generated by tools/q0_quadrature/gen_base_pair_leaf.py',
                            'Generated by tools/q0_quadrature/gen_base_pair_root7_leaf.py')
        path = ROOT / 'Grothe/UpperChaos' / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'{path} differs from generated root 7 leaf')
        else:
            path.write_text(text)


if __name__ == '__main__':
    main()
