#!/usr/bin/env python3
"""Generate closed Lean checks of the decoded exceptional saved-row fits.

Reuse the pinned row loader and the exact existing chunk partition. The
checks refer directly to existing CentersChunk rows; no numeric payload is
copied or rounded. Lean's kernel must establish every rational inequality.
The resulting fit does not certify the actual physical profile parameter.
Agent-ID: codex-aa04.
"""
from __future__ import annotations

import argparse
import importlib.util
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'Grothe/UpperChaos'


def source_parts():
    """Apply the source generator's row loader and chunking rule verbatim."""
    source = Path(__file__).with_name('gen_source_exception_centers.py')
    spec = importlib.util.spec_from_file_location('source_exception_centers', source)
    if spec is None or spec.loader is None:
        raise ValueError('cannot load the exceptional source-row generator')
    module = importlib.util.module_from_spec(spec)
    previous = sys.dont_write_bytecode
    try:
        sys.dont_write_bytecode = True
        spec.loader.exec_module(module)
    finally:
        sys.dont_write_bytecode = previous
    rows = module.read_rows()
    parts = []
    for row in rows:
        if (not parts or len(parts[-1]) == module.ROWS_PER_MODULE or
                row[0] != parts[-1][-1][0] + 1):
            parts.append([])
        parts[-1].append(row)
    if len(rows) != 417 or len(parts) != 16:
        raise ValueError('the established exceptional row partition changed')
    return parts


def generate() -> dict[str, bytes]:
    parts = source_parts()
    files = {}
    names = []
    for chunk, part in enumerate(parts):
        name = f'Q0SourceSavedLinearCheckChunk{chunk:02}'
        source_name = f'Q0SourceExceptionCentersChunk{chunk:02}'
        names.append(name)
        lines = [
            'import Grothe.UpperChaos.Q0SourceSavedLinearCheckCore',
            f'import Grothe.UpperChaos.{source_name}',
            '',
            '/-! Generated exact saved-row linear-model check.',
            'Generated by tools/q0_quadrature/gen_source_saved_linear_checks.py.',
            f'Source ordinal interval: {part[0][0]} through {part[-1][0]}.',
            'Agent-ID: codex-aa04. -/',
            f'namespace Grothe.UpperChaos.{name}',
            '',
            'open Q0SourceSavedLinearCheckCore',
            '',
            'set_option maxRecDepth 8192',
            'set_option maxHeartbeats 4000000',
            '',
            f'theorem checked : {source_name}.rows.all rowOK = true := by',
            '  decide +kernel',
            '',
            f'end Grothe.UpperChaos.{name}',
            '',
        ]
        files[name + '.lean'] = '\n'.join(lines).encode()

    lines = [f'import Grothe.UpperChaos.{name}' for name in names]
    lines += [
        'import Grothe.UpperChaos.Q0SourceExceptionCentersAll',
        'import Lean.Util.CollectAxioms',
        'import Lean.Elab.Command',
        '',
        '/-! Closed saved-row fit checks and their actual-source interface.',
        'Generated by tools/q0_quadrature/gen_source_saved_linear_checks.py.',
        'Physical profile enclosures remain explicit. Agent-ID: codex-aa04. -/',
        'namespace Grothe.UpperChaos.Q0SourceSavedLinearChecks',
        '',
        'open Q0SourceSavedLinearCheckCore Q0SourceSavedLinearModel',
        'open Q0GaussOrdinalEquiv Q0GaussProductionMass Q0SourceExceptionGeometry',
        'open Q0SourceExceptionPayload ConditionalNodeIndices ZeroProfilePhaseStability',
        '',
        'theorem all_checked : Q0SourceExceptionCentersAll.rows.all rowOK = true := by',
        '  simp only [Q0SourceExceptionCentersAll.rows, List.all_append,',
        '    ' + ', '.join(name + '.checked' for name in names) + ', Bool.and_true]',
        '',
        '/-- Both rational inequalities hold for the decoded saved row at this address. -/',
        'theorem source_fit_checked (a : Address) (ha : exceptionalPanel a.1.val) :',
        '    |fitParameter (Q0SourceExceptionPayload.rowAt a ha)| < (1 / 10 ^ 15 : ℚ) ∧',
        '      modelErrorSq (Q0SourceExceptionPayload.rowAt a ha)',
        '        (fitParameter (Q0SourceExceptionPayload.rowAt a ha)) <',
        '          (1 / 10 ^ 31 : ℚ) ^ 2 :=',
        '  rowOK_sound (Q0SourceExceptionPayload.rowAt a ha)',
        '    ((List.all_eq_true.mp all_checked) _ (rowAt_spec a ha).1)',
        '',
        '/-- The checked rational residual is the full selected saved-model error. -/',
        'theorem source_model_error_sq_lt (a : Address) (ha : exceptionalPanel a.1.val) :',
        '    (∑ p ∈ modes, ‖linearCenter',
        '      (fitParameter (Q0SourceExceptionPayload.rowAt a ha) : ℝ) p -',
        '        sourceCenter a ha p‖ ^ 2) < (1 / 10 ^ 31 : ℝ) ^ 2 := by',
        '  rw [source_model_error_eq]',
        '  have hreal := (Rat.cast_lt (K := ℝ)).mpr (source_fit_checked a ha).2',
        '  simpa only [Rat.cast_pow, Rat.cast_div, Rat.cast_one, Rat.cast_ofNat] using hreal',
        '',
        '/-- The saved-model field is discharged by the kernel checks. Only the',
        'two actual physical parameter enclosures are supplied by the caller. -/',
        'theorem source_linearRowBounds',
        '    (a : Address) (ha : exceptionalPanel a.1.val) (ρ η : ℝ)',
        '    (hratio : |signedProfileRatio (sourceNode a)| ≤ ρ)',
        '    (hparameter : |signedProfileRatio (sourceNode a) -',
        '      (fitParameter (Q0SourceExceptionPayload.rowAt a ha) : ℝ)| ≤ η) :',
        '    Q0ConditionalSourceVector.LinearRowBounds a (sourceCenter a ha)',
        '      (fitParameter (Q0SourceExceptionPayload.rowAt a ha) : ℝ)',
        '      ρ η (1 / 10 ^ 31 : ℝ) := by',
        '  have h := Q0SourceSavedLinearModel.source_linearRowBounds a ha',
        '    (fitParameter (Q0SourceExceptionPayload.rowAt a ha)) (1 / 10 ^ 31 : ℚ)',
        '    ρ η ((abs_nonneg _).trans hratio) ((abs_nonneg _).trans hparameter)',
        '    (by norm_num) hratio hparameter (source_fit_checked a ha).2.le',
        '  simpa only [Rat.cast_div, Rat.cast_one, Rat.cast_pow, Rat.cast_ofNat] using h',
        '',
        '/-- Actual Gaussian finite-vector error against the decoded source row,',
        'with the saved-data error certified and the physical enclosures explicit. -/',
        'theorem source_actual_error_sq_le',
        '    (a : Address) (ha : exceptionalPanel a.1.val) (ρ η : ℝ)',
        '    (hratio : |signedProfileRatio (sourceNode a)| ≤ ρ)',
        '    (hparameter : |signedProfileRatio (sourceNode a) -',
        '      (fitParameter (Q0SourceExceptionPayload.rowAt a ha) : ℝ)| ≤ η) :',
        '    (∑ p ∈ modes, ‖F0ConditionalNode.coefficient (sourceNode a) p -',
        '      sourceCenter a ha p‖ ^ 2) ≤ (5 * ρ ^ 2 + η + 1 / 10 ^ 31) ^ 2 :=',
        '  Q0ConditionalSourceVector.linear_row_error_sq_le a (sourceCenter a ha)',
        '    (fitParameter (Q0SourceExceptionPayload.rowAt a ha) : ℝ)',
        '    ρ η (1 / 10 ^ 31 : ℝ) (source_linearRowBounds a ha ρ η hratio hparameter)',
        '',
        'end Grothe.UpperChaos.Q0SourceSavedLinearChecks',
        '',
        'open Lean Elab Command',
        'run_cmd do',
        '  let allowed : Array Name := #[`propext, `Classical.choice, `Quot.sound]',
        '  for target in #[``Grothe.UpperChaos.Q0SourceSavedLinearChecks.all_checked,',
        '      ``Grothe.UpperChaos.Q0SourceSavedLinearChecks.source_fit_checked,',
        '      ``Grothe.UpperChaos.Q0SourceSavedLinearChecks.source_model_error_sq_lt,',
        '      ``Grothe.UpperChaos.Q0SourceSavedLinearChecks.source_linearRowBounds,',
        '      ``Grothe.UpperChaos.Q0SourceSavedLinearChecks.source_actual_error_sq_le] do',
        '    for dependency in (← Lean.collectAxioms target) do',
        '      unless allowed.contains dependency do',
        '        throwError m!"{target} uses unexpected axiom {dependency}"',
        '',
    ]
    files['Q0SourceSavedLinearChecks.lean'] = '\n'.join(lines).encode()
    return files


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='verify generated modules byte for byte without writing')
    args = parser.parse_args()
    files = generate()
    for name, data in files.items():
        path = OUT / name
        if args.check:
            if path.read_bytes() != data:
                raise ValueError(f'generated file differs: {name}')
        else:
            path.write_bytes(data)
    print(f'{len(files)} generated modules, {sum(map(len, files.values()))} bytes')


if __name__ == '__main__':
    main()
