#!/usr/bin/env python3
"""Reproduce one original regular source row and exact algebraic replay.

Agent-ID: codex-aa04. Only the committed 24-byte slice is read. The historical
ledger's enclosure claims and full-table digest are not verification evidence.
"""
from pathlib import Path
from fractions import Fraction
from hashlib import sha256
import argparse
import ast
import json
import struct
from gen_source_profile_ratio import eval_row, D, generate as profile_source_replay

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / 'data/q0_quadrature/regular-source-row'
OUT = ROOT / 'Grothe/UpperChaos/Q0RegularSourceRowData.lean'
REPLAY = DATA / 'replay.json'


def npy_array(raw, code, expected_descr):
    if raw[:8] != b'\x93NUMPY\x01\x00':
        raise ValueError('unsupported NPY header')
    size = int.from_bytes(raw[8:10], 'little')
    header = ast.literal_eval(raw[10:10 + size].decode('ascii'))
    if header['descr'] != expected_descr or header['fortran_order']:
        raise ValueError('unexpected NPY representation')
    payload = raw[10 + size:]
    values = struct.unpack('<' + code * (len(payload) // struct.calcsize(code)), payload)
    if header['shape'] != (len(values),):
        raise ValueError('unexpected NPY shape')
    return values


def decode(word):
    exponent = (word >> 52) & 2047
    if not 1 <= exponent <= 1023:
        raise ValueError('word outside exact normal decoder range')
    value = Fraction((1 << 52) + (word & ((1 << 52) - 1)), 1 << (1075 - exponent))
    if word >> 63:
        value = -value
    if abs(value) > 1:
        raise ValueError('source word magnitude exceeds one')
    return value


def generate():
    profile_source_replay()  # Bind the screen coefficients and interval arithmetic sources.
    spec = json.loads((DATA / 'provenance.json').read_text())
    inputs = {}
    for name, digest in spec['input_sha256'].items():
        raw = (ROOT / name).read_bytes()
        if sha256(raw).hexdigest() != digest:
            raise ValueError('input hash mismatch: ' + name)
        inputs[name] = raw
    raw = (DATA / 'row.bin').read_bytes()
    ledger_raw = (DATA / 'ledger.jsonl').read_bytes()
    if sha256(raw).hexdigest() != spec['payload_sha256'] or \
            sha256(ledger_raw).hexdigest() != spec['ledger_sha256']:
        raise ValueError('row or ledger hash mismatch')
    ledger = json.loads(ledger_raw)
    if (spec['ordinal'], spec['panel'], spec['rule']) != (3818, 135, 2):
        raise ValueError('wrong representative source address')
    n = spec['ordinal']
    offsets = npy_array(inputs['data/q0_quadrature/conditional_source/conditional_offsets.npy'], 'q', '<i8')
    cutoffs = npy_array(inputs['data/q0_quadrature/conditional_source/conditional_cutoffs.npy'], 'h', '<i2')
    selection = json.loads(inputs['data/q0_quadrature/conditional_source/exception-selection.json'])
    panel = selection['panels'][spec['panel']]
    if not 0 <= spec['rule'] < panel[2] or \
            sum(p[2] for p in selection['panels'][:spec['panel']]) + spec['rule'] != n:
        raise ValueError('source address/ordinal mismatch')
    if cutoffs[n] != spec['cutoff'] or cutoffs[n] != 1 or len(raw) != 24 or \
            offsets[n:n + 2] != (spec['source_start'], spec['source_end']) or \
            offsets[n + 1] - offsets[n] != 3:
        raise ValueError('offset/cutoff mismatch')
    if (spec['byte_start'], spec['byte_end']) != (128 + 8 * offsets[n], 128 + 8 * offsets[n + 1]):
        raise ValueError('source byte span mismatch')
    if (ledger['index'], ledger['cutoff'], ledger['sha256']) != (n, 1, spec['payload_sha256']):
        raise ValueError('ledger identity mismatch')
    words = struct.unpack('<QQQ', raw)
    x00, x01, x10 = map(decode, words)
    fit = x10 - x01
    residual = (1 - x00) ** 2 + (x10 + x01) ** 2 / 2
    if residual != 0 or not abs(fit) < Fraction(1, 10**15):
        raise ValueError('saved linear model check fails')
    lo, hi = map(Fraction, panel[:2])
    interval = eval_row(lo, hi, selection['screen_coefficients'])
    if not 13 <= lo <= hi or not all(abs(v) * 10**15 <= D for v in interval):
        raise ValueError('actual panel profile cap fails')
    rho = Fraction(1, 3 * 10**15)
    radius = 5 * rho**2 + Fraction(4, 3 * 10**15)
    if not radius < Fraction(2, 10**15):
        raise ValueError('actual Gaussian row radius fails')
    source = f'''import Grothe.UpperChaos.Q0SourceSavedLinearModel

/-! Exact original regular row. Generated by tools/q0_quadrature/gen_regular_source_row.py.
Agent-ID: codex-aa04. Gaussian and metadata proofs are in Q0RegularSourceRow. -/
namespace Grothe.UpperChaos.Q0RegularSourceRowData

def row : Q0SourceExceptionCenters.Row :=
  ⟨{n}, {offsets[n]}, 1, [{', '.join(map(str, words))}]⟩

def metadata : Q0ConditionalMetadataCheck.Row :=
  ⟨{n}, {offsets[n]}, {offsets[n + 1]}, 1⟩

end Grothe.UpperChaos.Q0RegularSourceRowData
'''.encode()
    replay = {'agent_id': 'codex-aa04', 'status': 'EXACT_EXTERNAL_REPLAY_NOT_LEAN_VERIFICATION',
              'ordinal': n, 'source_words': list(words), 'fit_parameter': str(fit),
              'model_error_squared': str(residual), 'scaled_profile_interval': list(map(str, interval)),
              'interval_scale': str(D), 'profile_abs_cap': '1/1000000000000000',
              'actual_radius_upper': str(radius), 'actual_radius_target': '2/1000000000000000',
              'finite_laplace_radius_target': '7/1000000000000000'}
    return source, (json.dumps(replay, indent=2) + '\n').encode()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source, replay = generate()
    for path, data in [(OUT, source), (REPLAY, replay)]:
        if args.check:
            if path.read_bytes() != data:
                raise ValueError('generated file differs: ' + str(path))
        else:
            path.write_bytes(data)
    print('regular row3818: 24 source bytes, exact zero model residual, profile/radius replay passed')


if __name__ == '__main__':
    main()
