#!/usr/bin/env python3
"""Generate scalar LeanCert replay statements, Agent-ID: codex-aa04.

The input values are proposed enclosures, not trusted constants. Each generated
theorem checks both endpoints in the Lean kernel with the pinned LeanCert.
"""
import argparse
from fractions import Fraction
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
INPUT = ROOT / 'data/q0_quadrature/scalar-centers.json'
OUTPUT = ROOT / 'Grothe/UpperChaos/Q0RectangleScalarCertificates.lean'


def rat(value):
    q = Fraction(value)
    return f'({q.numerator} / {q.denominator})'


def render(raw):
    data = json.loads(raw)
    out = [f'''import LeanCert.Validity.Dyadic

/-!
Generated by tools/q0_quadrature/gen_scalar_cert.py.
Input SHA256: {hashlib.sha256(raw).hexdigest()}
These certify scalar exponentials used by the rectangle model. They do not
by themselves certify a rectangle integral or a whole Gaussian coefficient.
Agent-ID: codex-aa04.
-/

namespace Grothe.UpperChaos.Q0RectangleScalarCertificates

open LeanCert.Core LeanCert.Validity

set_option maxRecDepth 100000
set_option maxHeartbeats 0
''']
    for i, r in enumerate(data['centers']):
        c, lo, hi = map(rat, (r['input'], r['lo'], r['hi']))
        if Fraction(r['lo']) > Fraction(r['hi']):
            raise ValueError('unordered proposed enclosure')
        out.append(f'''
def center{i} : ℚ := {c}
def bound{i} : IntervalRat := ⟨{lo}, {hi}, by decide +kernel⟩

private theorem center{i}_lower_checked :
    checkLowerBoundDyadicChecked (.exp (.const center{i})) 0 0 (by norm_num)
      bound{i}.lo (-256) 64 = true := by
  decide +kernel

private theorem center{i}_upper_checked :
    checkUpperBoundDyadicChecked (.exp (.const center{i})) 0 0 (by norm_num)
      bound{i}.hi (-256) 64 = true := by
  decide +kernel

/-- Both rational endpoints are verified independently of the external generator. -/
theorem exp_center{i}_mem : Real.exp (center{i} : ℝ) ∈ bound{i} := by
  have hl := verify_lower_bound_dyadic_checked (.exp (.const center{i}))
    0 0 (by norm_num) bound{i}.lo (-256) 64 (by norm_num)
    center{i}_lower_checked 0 (by norm_num)
  have hu := verify_upper_bound_dyadic_checked (.exp (.const center{i}))
    0 0 (by norm_num) bound{i}.hi (-256) 64 (by norm_num)
    center{i}_upper_checked 0 (by norm_num)
  exact ⟨by simpa only [Expr.eval] using hl, by simpa only [Expr.eval] using hu⟩
''')
    out.append('\nend Grothe.UpperChaos.Q0RectangleScalarCertificates\n')
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = render(INPUT.read_bytes())
    if args.check:
        if OUTPUT.read_text() != generated:
            raise SystemExit('scalar certificates differ from generator output')
    else:
        OUTPUT.write_text(generated)


if __name__ == '__main__':
    main()
