#!/usr/bin/env python3
"""Generate all algebraic leaves of retained root 10. Agent-ID: codex-aa04.

The twelve cells share one radial coordinate and one checked profile trace.
Every integral still refers to the actual production pair and exact geometry.
"""
import argparse
from fractions import Fraction as Q
import hashlib
import json
from pathlib import Path

import base_pair_trace
from gen_base_pair_leaf import render_cell, scalar_data
from gen_profile_model import model
from gen_source_row_models import trace_defs

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / 'data/q0_quadrature'
TRACE = DATA / 'base-pair-root10-trace.json'
RECIPE = DATA / 'base-pair-root10-recipe.json'
PROFILE = 'Q0BasePairRoot10Profile'
SCALARS = 'Q0BasePairRoot10Scalars'


def discover(recipe):
    source = (ROOT / recipe['profile_input']).read_bytes()
    assert hashlib.sha256(source).hexdigest() == recipe['profile_input_sha256']
    raw = base_pair_trace.discover([r['cell'] for r in recipe['leaves']],
                                  recipe['degree'], recipe['bits'], Q(recipe['eta']))
    for cell, leaf in zip(json.loads(raw)['cells'], recipe['leaves'], strict=True):
        for name, expected in zip(('firstOutput', 'companionOutput'), leaf['expected_models']):
            assert cell['nodes'][name] == expected, f'{leaf["path"]}/{name} changed'
    return raw


def generate(raw, recipe):
    data = json.loads(raw)
    cells = data['cells']
    first = cells[0]
    for cell in cells:
        assert cell['profile'] == first['profile']
        assert cell['nodes']['s'] == first['nodes']['s']
        assert cell['nodes']['profile'] == first['nodes']['profile']
    digest = hashlib.sha256(raw).hexdigest()
    profile = f'''import Grothe.UpperChaos.Q0ProfileRectangleModel

/-! Generated by tools/q0_quadrature/gen_base_pair_root10.py.
Transcript SHA256: {digest}
One shared radial/profile proof for the complete retained root 10.
Agent-ID: codex-aa04. -/
namespace Grothe.UpperChaos.{PROFILE}
open RectangleModelCheck RectangleHornerTrace
set_option maxRecDepth 100000
set_option maxHeartbeats 0
def sModel : Model := {model(first['nodes']['s'])}
def profileModel : Model := {model(first['nodes']['profile'])}
{trace_defs(first['profile']['trace'], 'profile')}
private theorem profile_checked :
    profiletrace.check sModel Q0ProfileRectangleModel.inputs = true := by decide +kernel

theorem profile_contains {{x y s : ℝ}} (hx : |x| ≤ 1) (hy : |y| ≤ 1)
    (hs : Contains sModel x y s) :
    Contains profileModel x y (LeanCertProductionProfile.q0Kappa s) :=
  Q0ProfileRectangleModel.profile_of_trace sModel profiletrace profile_checked hx hy hs

end Grothe.UpperChaos.{PROFILE}
'''
    scalars, indices = scalar_data(data)
    scalars = scalars.replace('Q0BasePairLeafScalars', SCALARS)
    outputs = {PROFILE + '.lean': profile, SCALARS + '.lean': scalars}
    namespaces = []
    previous = None
    for cell, leaf in zip(cells, recipe['leaves'], strict=True):
        assert cell['cell'] == leaf['cell']
        namespace = 'Q0BasePairRoot10Leaf' + leaf['path']
        namespaces.append(namespace)
        _, text = render_cell(data, cell, digest, indices, shared_profile=PROFILE)
        text = text.replace('Q0BasePairDirectLeaf', namespace).replace('Q0BasePairLeafScalars', SCALARS)
        # Each file performs substantial kernel reduction. A dependency chain
        # bounds simultaneous leaf elaborations without changing their proofs.
        if previous is not None:
            text = 'import Grothe.UpperChaos.' + previous + '\n' + text
        outputs[namespace + '.lean'] = text
        previous = namespace
    imports = '\n'.join('import Grothe.UpperChaos.' + ns for ns in namespaces)
    targets = ',\n    '.join('``Grothe.UpperChaos.' + ns + '.integrals_mem' for ns in namespaces)
    outputs['Q0BasePairRoot10Audit.lean'] = f'''{imports}
import Lean.Util.CollectAxioms
import Lean.Elab.Command

/-! All twelve actual cell integrals of root 10. Generated by
tools/q0_quadrature/gen_base_pair_root10.py. Agent-ID: codex-aa04. -/
open Lean Elab Command
run_cmd do
  let allowed : Array Name := #[`propext, `Classical.choice, `Quot.sound]
  let targets : Array Name := #[{targets}]
  for target in targets do
    let dependencies ← Lean.collectAxioms target
    logInfo m!"Root 10 integral audit {{target}}: {{dependencies}}"
    for dependency in dependencies do
      unless allowed.contains dependency do
        throwError m!"{{target}} uses unexpected axiom {{dependency}}"
'''
    return {name: text.replace('Generated by tools/q0_quadrature/gen_base_pair_leaf.py',
                              'Generated by tools/q0_quadrature/gen_base_pair_root10.py')
            for name, text in outputs.items()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--discover', action='store_true')
    args = parser.parse_args()
    recipe = json.loads(RECIPE.read_bytes())
    if args.discover:
        raw = discover(recipe)
        if args.check:
            if TRACE.read_text() != raw:
                raise SystemExit('root 10 trace is not reproducible')
        else:
            TRACE.write_text(raw)
    for name, text in generate(TRACE.read_bytes(), recipe).items():
        path = ROOT / 'Grothe/UpperChaos' / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'{path} differs from generated root 10')
        else:
            path.write_text(text)


if __name__ == '__main__':
    main()
