#!/usr/bin/env python3
"""Render complete direct base-pair root assemblies.

The committed recipe supplies the exact midpoint geometry. Generated Lean
checks each physical-cell binding and combines the imported integral
certificates; no external numerical replay is trusted by the proof.

Agent-ID: codex-2ca4.
"""
from __future__ import annotations

import argparse
from fractions import Fraction
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
# Pin semantic root identity separately from external candidate metadata.
SPECS = {
    2: {"strip": 1, "radial": ["6881023/500000", "6946559/500000"],
        "count": 24, "word": "twenty-four"},
    6: {"strip": 3, "radial": ["20817949/1000000", "4164409/200000"],
        "count": 15, "word": "fifteen"},
    10: {"strip": 5, "radial": ["25203679/1000000", "25204191/1000000"],
         "count": 12, "word": "twelve"},
}


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def render(raw: bytes, *, root_id: int) -> str:
    require(root_id in SPECS, 'unsupported fixed direct root')
    spec = SPECS[root_id]
    strip = spec['strip']
    count = spec['count']
    count_word = spec['word']
    radial = spec['radial']
    radial_literals = [f'{Fraction(q).numerator} / {Fraction(q).denominator}' for q in radial]
    generator_label = ('tools/gen_base_pair_root10_integral.py' if root_id == 10 else
                       f'tools/gen_base_pair_root_integral.py --root {root_id}')
    d = json.loads(raw)
    require(d['root'] == root_id and d['eta'] == '1/1000000000000000',
            f'expected root {root_id} at damping 1/10^15')
    require(d['root_cell']['chart'] == 'direct' and d['root_cell']['strip'] == strip,
            f'expected the direct chart of radial strip {strip}')
    require(list(map(Fraction, d['root_cell']['s'])) == list(map(Fraction, radial)),
            f'radial endpoints no longer match regularRoot {strip}')
    require(d['root_cell']['aux'] == ['0', '1'], 'expected auxiliary interval [0,1]')
    require(all(s['axis'] == 'aux' and s['root'] == root_id for s in d['splits']),
            f'all splits must be auxiliary splits of root {root_id}')
    splits = {s['path'] for s in d['splits']}
    rows = {r['path']: r for r in d['leaves']}
    require(len(rows) == len(d['leaves']) == count, f'expected {count} distinct leaves')
    require(len(splits) == len(d['splits']) == count - 1, f'expected {count-1} distinct splits')
    require(all(set(p) <= {'0', '1'} for p in splits | rows.keys()),
            'paths must be finite binary strings')
    ordered = []
    visited_splits = set()

    def validate(path='', lo=Fraction(0), hi=Fraction(1)):
        if path in splits:
            require(path not in rows, f'{path}: both leaf and internal node')
            visited_splits.add(path)
            mid = (lo + hi) / 2
            validate(path + '0', lo, mid)
            validate(path + '1', mid, hi)
        else:
            require(path in rows, f'{path}: missing leaf')
            row = rows[path]
            require(row['cell']['chart'] == 'direct' and row['cell']['strip'] == strip,
                    f'{path}: wrong chart or radial strip')
            require(row['cell']['s'] == d['root_cell']['s'], f'{path}: wrong radial endpoints')
            require(list(map(Fraction, row['cell']['aux'])) == [lo, hi],
                    f'{path}: auxiliary endpoints do not match the exact midpoint tree')
            ordered.append(path)

    validate()
    require(set(ordered) == set(rows), 'unreachable leaf in recipe')
    require(visited_splits == splits, 'unreachable internal node in recipe')

    def rat(s):
        q = Fraction(s)
        return f'({q.numerator} / {q.denominator})'

    def rect(path):
        row = rows[path]
        return '⟨' + ', '.join(map(rat, row['cell']['s'] + row['cell']['aux'])) + '⟩'

    def node(path):
        return 'root' + ''.join('.leftAux' if b == '0' else '.rightAux' for b in path)

    def tree(path=''):
        if path not in splits:
            return '.leaf'
        return f'(.splitAux {tree(path+"0")} {tree(path+"1")})'

    def interval(which, path='', level=0):
        if path not in splits:
            return f'Q0BasePairRoot{root_id}Leaf{path}.{which}Interval'
        return f'(IntervalRat.add {interval(which,path+"0",level+1)}\n' + '  '*(level+2) + interval(which,path+'1',level+1) + ')'

    lines = [
        'import Grothe.UpperChaos.AdaptiveRectangleComposition',
        'import Grothe.UpperChaos.AdaptiveRetainedCoefficient',
        *[f'import Grothe.UpperChaos.Q0BasePairRoot{root_id}Leaf{p}' for p in ordered],
        '',
        '/-!',
        f'# Complete actual base-pair integral on retained root {root_id}',
        '',
        'Agent-ID: codex-2ca4.',
        f'Generated by {generator_label}.',
        'Recipe SHA256: ' + hashlib.sha256(raw).hexdigest(),
        f'The {count_word} model-integral leaf certificates are combined by exact midpoint',
        f'integration over the complete direct root of radial strip {strip}.',
        'Every original leaf model-integral interval is added once in tree order.',
        'No numerical hypothesis, source reserve, or normalization error is added.',
        '-/',
        '',
        'open MeasureTheory Set LeanCert.Core',
        '',
        f'namespace Grothe.UpperChaos.Q0BasePairRoot{root_id}Integral',
        '',
        'open AdaptiveRectanglePartition Q0BasePairKernelContinuity',
        '',
        f'def root : Rect := ⟨{radial_literals[0]}, {radial_literals[1]}, 0, 1⟩',
        '',
        f'theorem root_eq_fixed : root = AdaptiveRetainedCoefficient.regularRoot {strip} := by',
        '  decide +kernel',
        '',
        'theorem root_valid : root.Valid := by decide +kernel',
        '',
        '/-- The exact midpoint tree in the frozen recipe. -/',
        'def tree : SplitTree := ' + tree(),
        '',
        f'/-- The canonical ordered leaves equal all {count_word} supplied physical cells. -/',
        'theorem tree_leaves : tree.leaves root =',
        '    [' + ',\n     '.join(rect(p) for p in ordered) + '] := by',
        '  decide +kernel',
        '',
    ]

    for p in ordered:
        lines += [
            f'private theorem leaf{p}_eq : {node(p)} =',
            f'    ({rect(p)} : Rect) := by decide +kernel',
            '',
            f'private theorem leaf{p}_mem :',
            f'    {node(p)}.integral (directFirst (1 / 1000000000000000)) ∈',
            f'        Q0BasePairRoot{root_id}Leaf{p}.firstInterval ∧',
            f'      {node(p)}.integral (directCompanion (1 / 1000000000000000)) ∈',
            f'        Q0BasePairRoot{root_id}Leaf{p}.companionInterval := by',
            f'  rw [leaf{p}_eq]',
            '  simpa only [Rect.integral, Rat.cast_div, Rat.cast_zero, Rat.cast_one,',
            '    Rat.cast_ofNat, div_one, zero_div] using',
            f'    Q0BasePairRoot{root_id}Leaf{p}.integrals_mem',
            '',
        ]

    lines += [
        '/-- Exact addition of the checked first-component model integrals. -/',
        'def firstInterval : IntervalRat :=',
        '  ' + interval('first'),
        '',
        '/-- Exact addition of the checked signed companion model integrals. -/',
        'def companionInterval : IntervalRat :=',
        '  ' + interval('companion'),
        '',
        '/-- Global direct-kernel continuity justifies each exact midpoint split. -/',
        'private theorem combine (r : Rect) (hr : r.Valid)',
        '    {F0 F1 C0 C1 : IntervalRat}',
        '    (h0 : r.leftAux.integral (directFirst (1 / 1000000000000000)) ∈ F0 ∧',
        '      r.leftAux.integral (directCompanion (1 / 1000000000000000)) ∈ C0)',
        '    (h1 : r.rightAux.integral (directFirst (1 / 1000000000000000)) ∈ F1 ∧',
        '      r.rightAux.integral (directCompanion (1 / 1000000000000000)) ∈ C1) :',
        '    r.integral (directFirst (1 / 1000000000000000)) ∈ IntervalRat.add F0 F1 ∧',
        '      r.integral (directCompanion (1 / 1000000000000000)) ∈',
        '        IntervalRat.add C0 C1 := by',
        '  have hc := continuous_direct_pair (1 / 1000000000000000)',
        '  exact ⟨r.integral_mem_add_splitAux hr _ hc.1.continuousOn h0.1 h1.1,',
        '    r.integral_mem_add_splitAux hr _ hc.2.continuousOn h0.2 h1.2⟩',
        '',
        f'/-- All {count_word} checked leaves close the whole root, without numerical premises. -/',
        'theorem integrals_mem :',
        '    root.integral (directFirst (1 / 1000000000000000)) ∈ firstInterval ∧',
        '      root.integral (directCompanion (1 / 1000000000000000)) ∈',
        '        companionInterval := by',
    ]

    def proof(path=''):
        if path not in splits:
            return f'leaf{path}_mem'
        left, right = proof(path+'0'), proof(path+'1')
        name = 'h' + (path or 'root')
        valid = 'root_valid' if not path else '(by decide +kernel)'
        lines.extend([f'  have {name} := combine ({node(path)}) {valid} {left} {right}'])
        return name

    proof()
    lines += [
        '  exact hroot',
        '',
        'theorem first_integral_mem :',
        '    root.integral (directFirst (1 / 1000000000000000)) ∈ firstInterval :=',
        '  integrals_mem.1',
        '',
        'theorem companion_integral_mem :',
        '    root.integral (directCompanion (1 / 1000000000000000)) ∈ companionInterval :=',
        '  integrals_mem.2',
        '',
        '/-- The same completed pair attached to the canonical retained root. -/',
        'theorem fixed_root_integrals_mem :',
        f'    (AdaptiveRetainedCoefficient.regularRoot {strip}).integral',
        '        (directFirst (1 / 1000000000000000)) ∈ firstInterval ∧',
        f'      (AdaptiveRetainedCoefficient.regularRoot {strip}).integral',
        '        (directCompanion (1 / 1000000000000000)) ∈ companionInterval := by',
        '  rw [← root_eq_fixed]',
        '  exact integrals_mem',
        '',
        f'end Grothe.UpperChaos.Q0BasePairRoot{root_id}Integral',
        '',
    ]
    return '\n'.join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=int, choices=sorted(SPECS), required=True)
    parser.add_argument('--input', type=Path)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--check', action='store_true',
                        help='Check byte-for-byte reproduction without writing files.')
    args = parser.parse_args()
    input_path = args.input or ROOT / f'data/q0_quadrature/base-pair-root{args.root}-recipe.json'
    output_path = args.output or ROOT / f'Grothe/UpperChaos/Q0BasePairRoot{args.root}Integral.lean'
    expected = render(input_path.read_bytes(), root_id=args.root).encode('utf-8')
    if args.check:
        if not output_path.exists() or output_path.read_bytes() != expected:
            parser.exit(1, f'Generated output differs: {output_path}\n')
        print(f'Byte-for-byte reproduction passed: {output_path}')
    else:
        output_path.write_bytes(expected)
        print(f'Wrote {output_path}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
