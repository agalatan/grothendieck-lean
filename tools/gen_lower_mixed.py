#!/usr/bin/env python3
"""Reproduce the retained mixed-node certificate data from durable exact inputs.

The canonical data/lower-mixed/batches.json contains the 21 batches and 351
witnesses used by the refined lower certificate. This exporter emits only
mixedBatches; the retired cover is not compiled. Its source-reference strings
and cut tokens survive solely as an uncompiled replay input for the refined
cover exporters (data/lower-unshifted/inputs/source-cover-serialization.json).

Run without arguments to regenerate Grothe/Lower/MixedData.lean, or pass
--check to compare it byte for byte. No ignored handoff package is needed.
The batch declaration is hash-pinned to the declaration retained from the
original module; this change does not regenerate any numerical witness.
"""
import argparse
from fractions import Fraction
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'data/lower-mixed/batches.json'
OUT = ROOT / 'Grothe/Lower/MixedData.lean'
ORIGINAL_SHA256 = 'a529b61562c93f665403968361aabb292cc72d93c8a47b74037ea474603bf0d0'
DECLARATION_SHA256 = 'be9e3228975b3b3761f88ddecadb5514c56b4e47badda194cdcd2e6f70f351bd'


def rational(value):
    number = Fraction(value)
    term = f'({number.numerator} : ℚ)'
    return term if number.denominator == 1 else f'{term} / {number.denominator}'


def lean_string(value):
    # All retained certificate strings use the ASCII numeric grammar.
    assert isinstance(value, str) and not any(c in value for c in ('"', '\\', '\n', '\r'))
    return '"' + value + '"'


def batch_declaration(data):
    assert data['format'] == 'grothe-mixed-batches/v1'
    assert data['original_mixed_data_sha256'] == ORIGINAL_SHA256
    assert data['declaration_sha256'] == DECLARATION_SHA256
    batches = data['batches']
    assert len(batches) == 21 and sum(len(b['witnesses']) for b in batches) == 351
    terms = []
    for batch in batches:
        assert type(batch['i']) is int and type(batch['j']) is int
        assert 0 <= batch['i'] < 19 and 0 <= batch['j'] < 19
        assert type(batch['spectral']) is bool and 0 <= Fraction(batch['theta']) <= 1
        terms.append(f"  ⟨{batch['i']}, {batch['j']}, {rational(batch['theta'])}, {rational(batch['smax'])},\n"
                     f"   {lean_string(batch['nodes'])},\n   {lean_string(batch['mesh'])},\n"
                     f"   {'true' if batch['spectral'] else 'false'},\n   [" +
                     ',\n    '.join(lean_string(w) for w in batch['witnesses']) + ']⟩')
    declaration = 'def mixedBatches : List JBatch :=\n[' + ',\n'.join(terms) + ']'
    assert hashlib.sha256(declaration.encode()).hexdigest() == DECLARATION_SHA256, \
        'Retained mixed-node declaration changed'
    return declaration


def render(data):
    return ('import Grothe.Lower.Mixed\n\n/-!\n'
            '# The mixed-node certificate data (generated by `tools/gen_lower_mixed.py`; do not edit)\n\n'
            'The 21 mixed-potential batches contain 351 exact node witnesses: 45 inherited Stein\n'
            'nodes and 306 spectral nodes. Their indices and serialized witnesses are unchanged.\n'
            'Canonical input: `data/lower-mixed/batches.json`.\n'
            '-/\n\nnamespace Grothe.Lower\n\n'
            '/-- The batches: rows `(i, j)`, weight `θ`, Lipschitz constant, mixed node caps, mesh, kind (spectral or Stein) and witnesses. -/\n' +
            batch_declaration(data) + '\n\nend Grothe.Lower\n')


def main():
    if not __debug__:
        raise SystemExit('Reject -O/-OO: exact assertions required')
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = json.loads(DATA.read_text())
    output = render(data)
    if args.check:
        assert OUT.read_text() == output, 'MixedData.lean differs from deterministic export'
    else:
        OUT.write_text(output)
    print(json.dumps(dict(status='PASS_RETAINED_MIXED_BATCHES', batches=21, nodes=351,
                          declaration_sha256=DECLARATION_SHA256,
                          lean_sha256=hashlib.sha256(output.encode()).hexdigest())))


if __name__ == '__main__':
    main()
