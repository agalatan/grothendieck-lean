#!/usr/bin/env python3
"""Generate `Grothe/LowerAnalytic/CapChordData.lean`: the chord nodes of the 19 node-cap tables.

The node strings `r:c;…` are read from the generated row modules `Grothe/Lower/RowData01..19.lean`
(so the indices are those of `Row.nodeList`).  For each row the lower convex hull of the points
(r_k, c_k) is computed in exact rationals; a node strictly inside a hull edge, or on it, is a CHORD
node `(k, i, j)` supported by the adjacent hull vertices i < k < j, with c_k ≥ chord(c_i, c_j)(r_k).
Every other node is a VERTEX: its cap must be certified directly (`VertexCaps`).  Since Ψ is convex,
Ψ(r_k) − pad ≤ chord of the vertex caps ≤ c_k at every chord node (`nodeCaps_of_vertexCaps`).
"""
import re
from fractions import Fraction as Q
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOWER = ROOT / "Grothe" / "Lower"
OUT = ROOT / "Grothe" / "LowerAnalytic" / "CapChordData.lean"


def nodes_of(k):
    text = (LOWER / f"RowData{k:02d}.lean").read_text()
    strs = re.findall(r'"([^"]*)"', text)
    s = next(x for x in strs if re.match(r"^[0-9/]+:[0-9/]+(;|$)", x))
    return [tuple(Q(v) for v in item.split(":")) for item in s.split(";")]


def chords(ns):
    H = []
    for i, (r, c) in enumerate(ns):
        while len(H) >= 2:
            a, b = H[-2], H[-1]
            if (ns[b][1] - ns[a][1]) * (r - ns[a][0]) >= (c - ns[a][1]) * (ns[b][0] - ns[a][0]):
                H.pop()
            else:
                break
        H.append(i)
    out = []
    for a, b in zip(H, H[1:]):
        for k in range(a + 1, b):
            ra, ca = ns[a]; rk, ck = ns[k]; rb, cb = ns[b]
            assert ra < rk < rb and ca + (cb - ca) / (rb - ra) * (rk - ra) <= ck and ra >= 0
            out.append((k, a, b))
    return out


rows = [chords(nodes_of(k)) for k in range(1, 20)]
lines = ["import Grothe.Lower.RowData", "", "/-!",
         "# The chord nodes of the node-cap tables (generated by `tools/gen_cap_chords.py`; do not edit)",
         "",
         "For each row a list of triples `(k, i, j)`: node `k` is a chord node supported by the vertex nodes",
         f"`i < k < j`.  {sum(map(len, rows))} chord nodes in all; the other nodes are the vertices.",
         "-/", "", "namespace Grothe.LowerAnalytic", "",
         "/-- The chord nodes of the 19 rows. -/", "def capChords : List (List (ℕ × ℕ × ℕ)) := ["]
for n, ch in enumerate(rows):
    body = ", ".join(f"({k}, {a}, {b})" for k, a, b in ch)
    lines.append(f"  [{body}]" + ("," if n < 18 else ""))
lines += ["]", "", "end Grothe.LowerAnalytic", ""]
OUT.write_text("\n".join(lines))
print(f"wrote {OUT}: {sum(map(len, rows))} chord nodes, "
      f"{sum(len(nodes_of(k)) for k in range(1, 20)) - sum(map(len, rows))} vertices")
