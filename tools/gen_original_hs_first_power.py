#!/usr/bin/env python3
"""Replay the recovered D=51/101/151 first-power parameter choices.

Agent-ID: codex-2ca4. Exact Fraction replay is not a Lean verification receipt.
The original D=151 choices differ from the later 52-gate family's choices;
all twelve original choices are therefore checked separately.
"""
import argparse
import hashlib
import json
from fractions import Fraction as F
from pathlib import Path

from gen_original_hs_parameters import audit_cov, lean_rat

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'data/original-hs-parameters'
SOURCE = DATA / 'inputs/rectangular_hs_result.json'
SOURCE_SHA = 'f6c95b644e5b37778ec9abf247af0f366580282161e9fe6fb3afadd7406c22e6'
PHASE_SHA = '04d581fa45e1d879623a0f233315dcfed39e0aa91c6684d554d0524ac8a71617'


def render():
    assert hashlib.sha256(SOURCE.read_bytes()).hexdigest() == SOURCE_SHA
    data = json.loads(SOURCE.read_text())
    assert data['source_sha256'] == PHASE_SHA
    assert [b['D'] for b in data['bands']] == [51, 101, 151]
    rows, checks = [], []
    for band in data['bands']:
        assert [p['coordinate'] for p in band['parts']] == [0, 1, 2, 3]
        for part in band['parts']:
            row = {'power': 1, 'degree': band['D'],
                   **{k: part[k] for k in ('coordinate', 'cut', 'R', 'T')}}
            i = row['coordinate']
            assert row['cut'] == [500, 500, 251, 250][i]
            R, T = F(row['R']), F(row['T'])
            assert 0 < R < 1 < T
            weights = [F(1)] * 4
            weights[i] = T
            checks.append({'row': row,
                           'z': audit_cov(F(21, 20), R, *weights[:2]),
                           'w': audit_cov(F(21, 20), R, *weights[2:])})
            rows.append(row)
    text = '''import Grothe.UpperChaos.OriginalHSParameterGates

/-!
# Recovered first-power Gaussian parameters at the original three cutoffs

These are the exact D=51,101,151 choices in the hash-bound historical
`rectangular_hs_result.json`. All twelve choices are checked by kernel reduction.
The D=151 choices differ from the later expanded certificate's choices and
are preserved separately. This proves parameter positivity, not HS tail caps.

Generated by `tools/gen_original_hs_first_power.py`. Agent-ID: codex-2ca4.
-/

namespace Grothe.UpperChaos.OriginalHSFirstPowerParameters

open OriginalHSParameterGates

'''
    names = []
    for i, row in enumerate(rows):
        name = f'firstGate{i:02d}'
        names.append(name)
        text += (f'def {name} : Gate := ⟨1, {row["degree"]}, {row["coordinate"]}, '
                 f'{row["cut"]}, {lean_rat(row["R"])}, {lean_rat(row["T"])}⟩\n')
        text += f'theorem {name}_checked : gateOK {name} = true := by decide +kernel\n\n'
    text += '/-- All three recorded output cutoffs and all four exclusions. -/\n'
    text += 'def firstGates : List Gate := [\n  ' + ', '.join(names) + ']\n\n'
    text += 'theorem firstGates_length : firstGates.length = 12 := rfl\n\n'
    text += 'theorem parameters_checked : firstGates.all gateOK = true := by\n'
    text += '  simp only [firstGates, List.all_cons, List.all_nil,\n'
    text += '    ' + ', '.join(n + '_checked' for n in names) + ', Bool.true_and]\n\n'
    text += ('theorem gate_checked_of_mem (g : Gate) (hg : g ∈ firstGates) :\n'
             '    gateOK g = true :=\n'
             '  (List.all_eq_true.mp parameters_checked) g hg\n\n'
             'end Grothe.UpperChaos.OriginalHSFirstPowerParameters\n')
    receipt = {'agent_id': 'codex-2ca4', 'status': 'EXACT_FRACTION_REPLAY_ONLY',
               'source_sha256': SOURCE_SHA, 'phase_source_sha256': PHASE_SHA,
               'scope': '12 original parameter choices; all checked separately; no HS cap',
               'checks': checks, 'lean_sha256': hashlib.sha256(text.encode()).hexdigest()}
    return {ROOT / 'Grothe/UpperChaos/OriginalHSFirstPowerParameters.lean': text,
            DATA / 'receipts/first-power-parameter-replay.json': json.dumps(receipt, indent=2) + '\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in render().items():
        if args.check:
            assert path.read_text() == content, path
        else:
            path.write_text(content)
    print('PASS: 12 recovered parameter choices; exact replay and deterministic output')
