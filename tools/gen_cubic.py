import json
from fractions import Fraction as Q
from math import comb
from pathlib import Path
import random

C6 = Q(4942288923, 10**8); RHO = Q('0.977459')
ROOT = Path(__file__).resolve().parent.parent
SIXTH = json.load(open(ROOT / 'handoff' / 'lower-import' / 'sharper_c6.json'))
def add(*ps):
    out=[Q(0)]*max(map(len,ps))
    for p in ps:
        for i,v in enumerate(p): out[i]+=v
    return out
def scale(p,a): return [a*v for v in p]
def mul(p,q):
    out=[Q(0)]*(len(p)+len(q)-1)
    for i,a in enumerate(p):
        for j,b in enumerate(q): out[i+j]+=a*b
    return out
def power(p,n):
    out=[Q(1)]
    for _ in range(n): out=mul(out,p)
    return out
def transform(p,lo,hi):
    out=[Q(0)]*len(p)
    for j,a in enumerate(p):
        for k in range(j+1): out[k]+=a*comb(j,k)*lo**(j-k)*(hi-lo)**k
    return out
def bernstein(p,lo,hi):
    p=transform(p,lo,hi); n=len(p)-1
    return [sum((p[j]*Q(comb(k,j),comb(n,j)) for j in range(k+1)),Q(0)) for k in range(n+1)]
def positive(p,lo,hi):
    todo=[(lo,hi,0)]; leaves=[]
    while todo:
        l,h,d=todo.pop(); cs=bernstein(p,l,h)
        if min(cs)>0: leaves.append((l,h,cs))
        else:
            assert d<40; mid=(l+h)/2; todo.extend([(l,mid,d+1),(mid,h,d+1)])
    leaves.sort()
    assert leaves[0][0]==lo and leaves[-1][1]==hi
    assert all(a[1]==b[0] for a,b in zip(leaves,leaves[1:]))
    return leaves
def ev(p,x): return sum(c*x**i for i,c in enumerate(p))

Nc=list(map(Q,['47.5','82.5','45','67.5']))
gap6=add(scale(power([Q(1),Q(0),Q(3,2)],3),Q(50,27)*C6*C6),scale(mul(Nc,Nc),Q(-1)))
m=[Q(2),Q(0),Q(1)]; n=[Q(6),Q(0),Q(9),C6]
q1=add(n,scale(mul(m,m),Q(-1)))
U=add(scale(n,RHO*RHO-1),mul(m,m),scale(m,-RHO*RHO-1),[Q(1)])
gap8=add(mul(U,U),scale(mul(q1,add(m,[Q(-1)])),-4*(1-RHO*RHO)**2))

def q(x):
    return f"({x.numerator} : ℝ) / {x.denominator}" if x.denominator!=1 else f"({x.numerator} : ℝ)"

def leaf_lemma(name, unfold, var, deg, idx, l, h, cs):
    c=min(cs)
    # sanity: Bernstein identity at random rational points
    for _ in range(3):
        s=Q(random.randint(0,97),97); x=l+(h-l)*s
        rhs=sum(b*comb(deg,k)*s**k*(1-s)**(deg-k) for k,b in enumerate(cs))
        assert ev(POLY[name],x)==rhs
    T=[]
    for k in range(deg+1):
        if k==0: T.append(f"(1 - s) ^ {deg}")
        elif k==deg: T.append(f"s ^ {deg}")
        else:
            sk = "s" if k==1 else f"s ^ {k}"
            T.append(f"{comb(deg,k)} * {sk} * (1 - s) ^ {deg-k}")
    lines=[f"lemma {name}_leaf{idx} ({var} : ℝ) (hl : {q(l)} ≤ {var}) (hh : {var} ≤ {q(h)}) :",
           f"    {q(c)} ≤ {name} {var} := by",
           f"  have hw : (0 : ℝ) < {q(h)} - {q(l)} := by norm_num",
           f"  obtain ⟨s, hs0, hs1, hv⟩ : ∃ s : ℝ, 0 ≤ s ∧ s ≤ 1 ∧ {var} = {q(l)} + ({q(h)} - {q(l)}) * s :=",
           f"    ⟨({var} - {q(l)}) / ({q(h)} - {q(l)}), div_nonneg (by linarith) hw.le,",
           f"      by rw [div_le_one hw]; linarith, by first | (field_simp; ring) | field_simp⟩",
           f"  have h1s : (0 : ℝ) ≤ 1 - s := by linarith"]
    for k,t in enumerate(T):
        lines.append(f"  have T{k} : (0 : ℝ) ≤ {t} := by positivity")
    lines.append(f"  subst hv")
    lines.append(f"  simp only [{unfold}]")
    hints=", ".join(f"mul_nonneg (show (0 : ℝ) ≤ {q(b)} - {q(c)} by norm_num) T{k}" for k,b in enumerate(cs))
    lines.append(f"  linarith [{hints}]")
    return "\n".join(lines)+"\n\n", c

def pos_theorem(name, var, lo, hi, leaves, cs_list):
    out=[f"theorem {name}_pos ({var} : ℝ) (h0 : {q(lo)} ≤ {var}) (h1 : {var} ≤ {q(hi)}) : 0 < {name} {var} := by"]
    prev="h0"
    for i,(l,h,c) in enumerate(leaves):
        if i<len(leaves)-1:
            out.append(f"  rcases le_or_gt {var} ({q(h)}) with hA{i} | hA{i}")
            out.append(f"  · exact lt_of_lt_of_le (by norm_num) ({name}_leaf{i} {var} {prev} hA{i})")
            prev=f"hA{i}.le"
        else:
            out.append(f"  exact lt_of_lt_of_le (by norm_num) ({name}_leaf{i} {var} {prev} h1)")
    return "\n".join(out)+"\n\n"

