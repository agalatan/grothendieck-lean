#!/usr/bin/env python3
"""Generate the ratio-generator family in an explicit staging tree.

Run through tools/gen_row227_full_certificate.py. Source generation is not
Lean verification. Agent-ID: codex-aa04. Refs #293, #21.
"""

from __future__ import annotations

import argparse
from fractions import Fraction
import gzip
import hashlib
import json
import re
from pathlib import Path


from row227_paths import ROOT, workspace

BASE = workspace() / "ratio-generator"
PACKET_SHA256 = "27df67cc032cf15455eaa18da7464e4cb7c5adecf50c2a6bcdd2d7e92787ff47"
H, WIDTH, BITS, BLOCKS = 2546, 32, 768, 80
PREFIX = "Grothe.UpperChaos."
LOOKUP = "OriginalRow227RatioLookup"
HEADER = "OriginalRow227RatioHeader"
ASSEMBLY = "OriginalRow227RatioCertificate"


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def integer(n: int) -> str:
    return f"({n})" if n < 0 else str(n)


def name(kind: str, block: int) -> str:
    return f"OriginalRow227Ratio{kind}{block:02d}"


def preamble(module: str, imports: list[str], opens: list[str] = ()) -> str:
    return "\n".join("import " + item for item in imports) + f"""

/-! Generated row227 ratio certificate.
Generated by tools/gen_row227_full_certificate.py from packet
SHA256 {PACKET_SHA256}.
Agent-ID: codex-aa04. Refs #293. -/

open LeanCert.Core
namespace {PREFIX}{module}
open ConditionalNormalizedFiniteChecks ConditionalRatioBlocks
""" + "".join("open " + item + "\n" for item in opens) + "\n"


def close(module: str) -> str:
    return f"\nend {PREFIX}{module}\n"


def guard(targets: list[str]) -> str:
    quoted = ",\n      ".join("``" + PREFIX + target for target in targets)
    return f"""
open Lean Elab Command
run_cmd do
  let allowed : Array Name := #[`propext, `Classical.choice, `Quot.sound]
  for target in #[
      {quoted}] do
    for dependency in (← Lean.collectAxioms target) do
      unless allowed.contains dependency do
        throwError m!"{{target}} uses unexpected axiom {{dependency}}"
"""


def inspect_packet(packet: dict) -> dict:
    require(packet["schema"] == 1 and packet["bits"] == BITS, "packet schema/precision")
    require(packet["horizon"] == H, "packet horizon")
    rows = packet["ratios"]
    require(len(rows) == H + 1, "all 2547 checkpoint intervals")
    require(all(len(row) == 2 and all(type(x) is int for x in row) for row in rows),
            "integer checkpoint endpoints")
    require(all(lo <= hi for lo, hi in rows), "ordered checkpoint intervals")
    q = 1 << BITS
    xlo, xhi = packet["squared_shift"]
    require(0 <= xlo <= xhi, "nonnegative squared-shift interval")
    midpoint = Fraction(packet["midpoint"], 1 << 1024)
    require(Fraction(xlo, q) <= midpoint**2 <= Fraction(xhi, q), "actual squared midpoint")
    require(rows[H][0] <= 0 and q <= rows[H][1], "terminal unit enclosure")
    # Regenerate the complete rounded backward recurrence independently of
    # the production generator, then require byte-for-byte integer values.
    regenerated = [None] * (H + 1)
    regenerated[H] = [0, q]
    for k in reversed(range(H)):
        next_lower, next_upper = regenerated[k + 1]
        lower_den = (k + 2) * q * q + xhi * (q - next_lower)
        upper_den = (k + 2) * q * q + xlo * (q - next_upper)
        numerator = (2 * k + 1) * q**3
        regenerated[k] = [numerator // (2 * lower_den), -(-numerator // (2 * upper_den))]
    require(regenerated == rows, "all 2546 rounded backward steps regenerated exactly")
    for k in range(H):
        lower, upper = rows[k]
        next_lower, next_upper = rows[k + 1]
        require(next_upper <= q, f"next upper guard {k}")
        lower_den = (k + 2) * q * q + xhi * (q - next_lower)
        upper_den = (k + 2) * q * q + xlo * (q - next_upper)
        require(2 * lower * lower_den <= (2 * k + 1) * q**3,
                f"lower multiplication guard {k}")
        require((2 * k + 1) * q**3 <= 2 * upper * upper_den,
                f"upper multiplication guard {k}")
    intervals = [n for b in range(BLOCKS)
                 for n in range(b * WIDTH, min((b + 1) * WIDTH, H + 1))]
    transitions = [n for b in range(BLOCKS)
                   for n in range(b * WIDTH, min((b + 1) * WIDTH, H))]
    require(intervals == list(range(H + 1)), "exact unique checkpoint coverage")
    require(transitions == list(range(H)), "exact unique transition coverage")
    require(32 * 79 + 18 == H, "final transition block shape")
    return {
        "checkpoint_count": len(intervals),
        "transition_count": len(transitions),
        "block_count": BLOCKS,
        "width": WIDTH,
        "last_checkpoint_block_size": 19,
        "last_transition_block_size": 18,
        "integer_guard_checks": 3 * H,
        "backward_steps_recomputed_exact": H,
        "squared_midpoint": "exact rational enclosure verified",
        "coverage": "exact ranges 0..2546 and 0..2545, each once",
    }


def lookup_tree(left: int, right: int, indent: int = 2) -> str:
    pad = " " * indent
    if right - left == 1:
        module = name("Data", left)
        start = left * WIDTH
        final_bound = f"{pad}  have hn := n.isLt\n" if left == BLOCKS - 1 else ""
        return (f"{pad}{module}.checkpoints[n.val - {start}]'(by\n"
                f"{pad}  rw [{module}.checkpoints_size]\n"
                + final_bound +
                f"{pad}  omega)")
    middle = (left + right) // 2
    cutoff = middle * WIDTH
    return (f"{pad}if h{cutoff} : n.val < {cutoff} then\n"
            + lookup_tree(left, middle, indent + 2)
            + f"\n{pad}else\n" + lookup_tree(middle, right, indent + 2))


def proof_tree(left: int, right: int, indent: int = 2) -> str:
    pad = " " * indent
    if right - left == 1:
        return (f"{pad}have he : b = (⟨{left}, by decide⟩ : Fin 80) := Fin.ext (by omega)\n"
                f"{pad}subst b\n"
                f"{pad}exact {name('Check', left)}.checked\n")
    middle = (left + right) // 2
    # A nested bullet scopes each branch's bound assumptions; the leaf uses
    # only seven or fewer split bounds and b.isLt, never numerical data.
    return (f"{pad}by_cases h{middle} : b.val < {middle}\n"
            f"{pad}·\n" + proof_tree(left, middle, indent + 2)
            + f"{pad}·\n" + proof_tree(middle, right, indent + 2))


def generate(packet: dict, bridge: str) -> dict[str, str]:
    output = {"ConditionalRatioBlocks.lean": bridge}
    for b in range(BLOCKS):
        module = name("Data", b)
        rows = packet["ratios"][b * WIDTH:min((b + 1) * WIDTH, H + 1)]
        source = preamble(module, [PREFIX + "ConditionalRatioBlocks"])
        source += f"/-- Checkpoints {b * WIDTH} through {b * WIDTH + len(rows) - 1}. -/\n"
        source += "def checkpoints : Array IntervalDyadic := #[\n"
        source += ",\n".join(
            f"  commonExponentInterval {integer(lo)} {integer(hi)} (-768) (by decide +kernel)"
            for lo, hi in rows)
        source += "\n]\n\n"
        source += (f"theorem checkpoints_size : checkpoints.size = {len(rows)} := by\n"
                   "  rfl\n")
        source += close(module)
        output[module + ".lean"] = source

    imports = [PREFIX + "ConditionalRatioBlocks"]
    imports += [PREFIX + name("Data", b) for b in range(BLOCKS)]
    source = preamble(LOOKUP, imports)
    source += "/-- Balanced dispatch, with proof-bounded access to every local array. -/\n"
    source += "def boundedR (n : Fin 2547) : IntervalDyadic :=\n" + lookup_tree(0, BLOCKS) + "\n\n"
    source += """/-- Total extension for the existing natural-indexed certificate API.
The certificate uses only indices at most 2546; `R_eq_bounded` proves that
the extension has no effect on any of those indices. No array default is used. -/
def R (n : ℕ) : IntervalDyadic :=
  boundedR ⟨min n 2546, by omega⟩

theorem R_eq_bounded (n : ℕ) (hn : n ≤ 2546) :
    R n = boundedR ⟨n, by omega⟩ := by
  unfold R
  apply congrArg boundedR
  apply Fin.ext
  exact Nat.min_eq_left hn

def lo (n : ℕ) : ℚ := (R n).lo.toRat
def hi (n : ℕ) : ℚ := (R n).hi.toRat

/-- Each block covers actual successive endpoints, including the last
next-checkpoint at index 2546. The generic constructor proves this binding. -/
def blockFamily (b : Fin 80) :
    Block lo hi (32 * b.val) (min 32 (2546 - 32 * b.val)) :=
  Block.ofBounds lo hi (32 * b.val) (min 32 (2546 - 32 * b.val))
"""
    source += close(LOOKUP)
    output[LOOKUP + ".lean"] = source

    source = preamble(HEADER, [PREFIX + LOOKUP, PREFIX + "OriginalMomentSeedData"], [LOOKUP])
    xl, xh = packet["squared_shift"]
    source += ("def squaredShift : IntervalDyadic :=\n"
               f"  commonExponentInterval {integer(xl)} {integer(xh)} (-768) (by decide +kernel)\n\n")
    source += """def xlo : ℚ := squaredShift.lo.toRat
def xhi : ℚ := squaredShift.hi.toRat

theorem header_checked : headerCheck 2546 lo hi xlo xhi = true := by
  decide +kernel

theorem squared_midpoint_enclosed :
    xlo ≤ OriginalMomentSeedData.midpointQ ^ 2 ∧
      OriginalMomentSeedData.midpointQ ^ 2 ≤ xhi := by
  decide +kernel
"""
    source += close(HEADER) + guard([HEADER + ".header_checked", HEADER + ".squared_midpoint_enclosed"])
    output[HEADER + ".lean"] = source

    for b in range(BLOCKS):
        module = name("Check", b)
        start = b * WIDTH
        count = min(WIDTH, H - start)
        source = preamble(module, [PREFIX + HEADER], [LOOKUP, HEADER])
        source += (f"/-- Exactly transitions {start} through {start + count - 1}. -/\n"
                   f"def block : Block lo hi {start} {count} :=\n"
                   f"  Block.ofBounds lo hi {start} {count}\n\n"
                   "theorem checked : block.check xlo xhi = true := by\n"
                   "  decide +kernel\n")
        source += close(module) + guard([module + ".checked"])
        output[module + ".lean"] = source

    imports = [PREFIX + name("Check", b) for b in range(BLOCKS)]
    source = preamble(ASSEMBLY, imports, [LOOKUP, HEADER])
    source += """/-- Assemble the 80 opaque checked facts by bounded block index.
This proof does not evaluate any ratio arithmetic or a complete table. -/
theorem all_blocks_checked (b : Fin 80) : (blockFamily b).check xlo xhi = true := by
  have hbound := b.isLt
""" + proof_tree(0, BLOCKS)
    source += """
/-- Complete finite certificate, including all 2546 transitions and the
original terminal unit enclosure. No whole-horizon decision is evaluated. -/
theorem certificate_checked :
    OriginalMomentRatioCertificates.certificateOK 2546 lo hi xlo xhi = true :=
  certificateOK_2546_of_32_blocks lo hi xlo xhi blockFamily
    header_checked all_blocks_checked

/-- The complete certificate encloses the actual original ratios at the
single pinned midpoint. This is not a normalized triangle or row-error claim. -/
theorem ratio_mem (k : ℕ) (hk : k ≤ 2546) :
    OriginalPositiveMoment.ratio k ((OriginalMomentSeedData.midpointQ : ℝ) ^ 2) ∈ R k := by
  have hxl : (xlo : ℝ) ≤ (OriginalMomentSeedData.midpointQ : ℝ) ^ 2 := by
    exact_mod_cast squared_midpoint_enclosed.1
  have hxh : (OriginalMomentSeedData.midpointQ : ℝ) ^ 2 ≤ (xhi : ℝ) := by
    exact_mod_cast squared_midpoint_enclosed.2
  exact OriginalMomentRatioCertificates.ratio_mem_of_certificate
    2546 lo hi xlo xhi certificate_checked hxl hxh k hk
"""
    source += close(ASSEMBLY) + guard([ASSEMBLY + ".certificate_checked", ASSEMBLY + ".ratio_mem"])
    output[ASSEMBLY + ".lean"] = source
    for filename, body in list(output.items()):
        if filename == "ConditionalRatioBlocks.lean" or "Lean.collectAxioms" in body:
            continue
        targets = re.findall(r"^theorem ([\w.]+)", body, re.M)
        if targets:
            output[filename] = body + guard([filename[:-5] + "." + t for t in targets])
    return output


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--packet", type=Path, required=True)
    parser.add_argument("--packet-sha256", required=True)
    parser.add_argument("--bridge", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    out = args.output_dir.resolve()
    require(out != BASE and out.is_relative_to(BASE), "output must remain inside the staging ratio-generator")
    require(args.packet_sha256 == PACKET_SHA256, "expected production packet pin")
    packed = args.packet.read_bytes()
    require(hashlib.sha256(packed).hexdigest() == PACKET_SHA256, "production packet digest")
    packet = json.loads(gzip.decompress(packed))
    review = inspect_packet(packet)
    bridge = args.bridge.read_text()
    require("theorem certificateOK_2546_of_32_blocks" in bridge, "expected assembly bridge API")
    outputs = generate(packet, bridge)
    lean_dir = out / "Grothe/UpperChaos"
    if not args.check:
        lean_dir.mkdir(parents=True, exist_ok=True)
    for module, source in outputs.items():
        path = lean_dir / module
        if args.check:
            require(path.read_text() == source, f"byte reproduction: {module}")
        else:
            path.write_text(source)
    manifest = {
        "agent": "codex-aa04",
        "status": "GENERATED_SOURCE_NOT_VERIFICATION_EVIDENCE",
        "packet_sha256": PACKET_SHA256,
        "bridge_sha256": hashlib.sha256(bridge.encode()).hexdigest(),
        "review": review,
        "generated_modules": len(outputs),
        "files": {module: hashlib.sha256(source.encode()).hexdigest()
                  for module, source in outputs.items()},
    }
    manifest_source = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    if args.check:
        require((out / "manifest.json").read_text() == manifest_source, "manifest reproduction")
    else:
        (out / "manifest.json").write_text(manifest_source)
    print(json.dumps({"mode": "reproduced" if args.check else "generated",
                      "modules": len(outputs), **review}, sort_keys=True))


if __name__ == "__main__":
    main()
