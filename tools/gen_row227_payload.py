#!/usr/bin/env python3
"""Emit the complete original row227 payload and its actual boundary lookup.

Agent-ID: codex-aa04. Refs #293, #21.
The SHA256 check records input provenance; it is not a Lean hypothesis.
Lean checks short literal leaves, symbolic append lengths, and one lookup
through the balanced tree. No proof reduces the full 35,777-word list.
Generation and --check do not invoke Lean or establish Lean acceptance.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from fractions import Fraction
import hashlib
import json
from pathlib import Path
import struct


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "Grothe/UpperChaos"
INPUT = ROOT / "data/original-row227-certificate/row227.bin"
SHA256 = "85f6792a14d4c198979bfc9ea6c513b765bd76147cc4fe0d0a9566addae48d1c"
WORD_COUNT = 35777
SOURCE_START, SOURCE_CUTOFF, SOURCE_ORDINAL = 8121379, 532, 227
LEAF_WORDS, LEAVES_PER_MODULE = 64, 32
BOUNDARY_C, BOUNDARY_D, BOUNDARY_INDEX = 251, 250, 35536
NAMESPACE = "Grothe.UpperChaos.OriginalRow227Payload"


def require(condition, message):
    if not condition:
        raise ValueError(message)


@dataclass(frozen=True)
class Node:
    name: str
    first_leaf: int
    end_leaf: int
    start: int
    length: int

    @property
    def contains_boundary(self):
        return self.start <= BOUNDARY_INDEX < self.start + self.length


def preamble(imports, description, namespace):
    return [*(f"import {name}" for name in imports), "", "/-!",
            description,
            "Generated by `python3 tools/gen_row227_payload.py`; do not edit.",
            "Input: data/original-row227-certificate/row227.bin",
            f"SHA256: {SHA256}",
            "The digest is provenance, not a formal premise. Agent-ID: codex-aa04.",
            "-/", "", f"namespace {namespace}", ""]


def leaf(lines, index, words):
    start = index * LEAF_WORDS
    data = words[start:start + LEAF_WORDS]
    node = Node(f"leaf{index:04d}", index, index + 1, start, len(data))
    lines.extend([f"/-- Original source words [{start}, {start + len(data)}). -/",
                  f"def {node.name} : List ℕ := ["])
    for k in range(0, len(data), 4):
        values = ", ".join(str(word) for word in data[k:k + 4])
        lines.append(f"  {values}{',' if k + 4 < len(data) else ''}")
    lines.extend(["]", "", f"theorem {node.name}_length : {node.name}.length = {len(data)} := rfl", ""])
    if node.contains_boundary:
        lines.extend([
            f"theorem {node.name}_boundary :",
            f"    {node.name}[{BOUNDARY_INDEX - start}]? = some {words[BOUNDARY_INDEX]} := rfl", ""])
    return node


def join(lines, left, right, boundary_word):
    require(left.start + left.length == right.start, "adjacent append nodes")
    require(left.end_leaf == right.first_leaf, "adjacent leaf spans")
    node = Node(f"node{left.first_leaf:04d}_{right.end_leaf:04d}",
                left.first_leaf, right.end_leaf, left.start, left.length + right.length)
    lines.extend([
        f"def {node.name} : List ℕ := {left.name} ++ {right.name}", "",
        f"theorem {node.name}_length : {node.name}.length = {node.length} := by",
        f"  change ({left.name} ++ {right.name}).length = {node.length}",
        f"  rw [List.length_append, {left.name}_length, {right.name}_length]", ""])
    if node.contains_boundary:
        offset = BOUNDARY_INDEX - node.start
        lines.extend([
            f"theorem {node.name}_boundary :",
            f"    {node.name}[{offset}]? = some {boundary_word} := by"])
        if left.contains_boundary:
            lines.extend([
                f"  exact append_left_lookup (xs := {left.name}) (ys := {right.name})",
                f"    (i := {offset}) (n := {left.length}) (x := {boundary_word})",
                f"    {left.name}_length (by decide) {left.name}_boundary", ""])
        else:
            require(right.contains_boundary, "boundary descends to a child")
            lines.extend([
                f"  exact append_right_lookup (xs := {left.name}) (ys := {right.name})",
                f"    (i := {offset}) (n := {left.length}) (x := {boundary_word})",
                f"    {left.name}_length (by decide) {right.name}_boundary", ""])
    return node


def balanced_tree(lines, nodes, boundary_word):
    require(bool(nodes), "nonempty balanced tree")
    if len(nodes) == 1:
        return nodes[0]
    middle = len(nodes) // 2
    left = balanced_tree(lines, nodes[:middle], boundary_word)
    right = balanced_tree(lines, nodes[middle:], boundary_word)
    return join(lines, left, right, boundary_word)


def finish(lines, namespace):
    return ("\n".join([*lines, f"end {namespace}"]).rstrip() + "\n").encode()


def render(words):
    outputs, chunks = {}, []
    count = (len(words) + LEAF_WORDS - 1) // LEAF_WORDS
    boundary_word = words[BOUNDARY_INDEX]
    lines = preamble(["Mathlib.Tactic"],
                     "Abstract append lookup helpers keep concrete payload proofs symbolic.", NAMESPACE + ".Data")
    lines.extend([
        "/-- Specialize using the stored length, without reducing a concrete list. -/",
        "theorem append_left_lookup {α : Type*} {xs ys : List α} {i n : ℕ} {x : α}",
        "    (hlen : xs.length = n) (hi : i < n) (hlookup : xs[i]? = some x) :",
        "    (xs ++ ys)[i]? = some x := by",
        "  have hindex : i < xs.length := by omega",
        "  exact (List.getElem?_append_left hindex).trans hlookup", "",
        "/-- Right lookup subtracts a stored length rather than computing it. -/",
        "theorem append_right_lookup {α : Type*} {xs ys : List α} {i n : ℕ} {x : α}",
        "    (hlen : xs.length = n) (hi : n ≤ i) (hlookup : ys[i - n]? = some x) :",
        "    (xs ++ ys)[i]? = some x := by",
        "  have hindex : xs.length ≤ i := by omega",
        "  rw [List.getElem?_append_right hindex, hlen]",
        "  exact hlookup", ""])
    outputs["OriginalRow227PayloadLookup.lean"] = finish(lines, NAMESPACE + ".Data")
    for chunk, first in enumerate(range(0, count, LEAVES_PER_MODULE)):
        lines = preamble(["Grothe.UpperChaos.OriginalRow227PayloadLookup"],
                         "Complete original row227 payload: short literal leaves and symbolic append lengths.",
                         NAMESPACE + ".Data")
        nodes = [leaf(lines, i, words)
                 for i in range(first, min(count, first + LEAVES_PER_MODULE))]
        chunks.append(balanced_tree(lines, nodes, boundary_word))
        outputs[f"OriginalRow227PayloadChunk{chunk:02d}.lean"] = finish(lines, NAMESPACE + ".Data")

    imports = [f"Grothe.UpperChaos.OriginalRow227PayloadChunk{chunk:02d}" for chunk in range(len(chunks))]
    lines = preamble(imports, "Balanced assembly of every original row227 payload word.", NAMESPACE + ".Data")
    top = balanced_tree(lines, chunks, boundary_word)
    require(top.start == 0 and top.length == WORD_COUNT, "complete payload tree")
    outputs["OriginalRow227PayloadData.lean"] = finish(lines, NAMESPACE + ".Data")

    exponent = (boundary_word >> 52) & 2047
    mantissa = (1 << 52) + (boundary_word & ((1 << 52) - 1))
    decoded = Fraction((-1 if boundary_word >> 63 else 1) * mantissa, 1 << (1075 - exponent))
    scalar = f"({decoded.numerator} : ℚ) / {decoded.denominator}"
    lines = preamble([
        "Grothe.UpperChaos.OriginalRow227PayloadData",
        "Grothe.UpperChaos.Q0SourceSavedLinearModel"],
        "The full original row227 and its actual production-rank boundary scalar.\n"
        "Length and lookup use stored append-tree theorems, never whole-payload reduction.\n"
        "This module makes no claim about physical transport or the Gaussian error budget.", NAMESPACE)
    lines.extend([
        "open Q0SourceExceptionCenters", "",
        "/-- All retained words of the original degree-cutoff-532 source row. -/",
        "def row : Row :=",
        f"  ⟨{SOURCE_ORDINAL}, {SOURCE_START}, {SOURCE_CUTOFF}, Data.{top.name}⟩", "",
        "theorem row_header :",
        f"    row.ordinal = {SOURCE_ORDINAL} ∧ row.sourceStart = {SOURCE_START} ∧",
        f"      row.cutoff = {SOURCE_CUTOFF} := ⟨rfl, rfl, rfl⟩", "",
        "/-- Every payload word is present, including the suffix after the selected boundary. -/",
        f"theorem words_length : row.words.length = {WORD_COUNT} := Data.{top.name}_length", "",
        "theorem source_span :",
        f"    row.sourceStart + row.words.length = {SOURCE_START + WORD_COUNT} := by",
        "  rw [words_length, row_header.2.1]", "",
        "theorem boundary_rank :",
        f"    Q0ConditionalPairRankCheck.rank {BOUNDARY_C} {BOUNDARY_D} = {BOUNDARY_INDEX} := by",
        "  decide", "",
        "/-- Safe lookup at the actual production rank in the complete original payload. -/",
        "theorem boundary_word :",
        f"    row.words[Q0ConditionalPairRankCheck.rank {BOUNDARY_C} {BOUNDARY_D}]? =",
        f"      some {boundary_word} := by",
        "  exact (congrArg (fun k : ℕ => row.words[k]?) boundary_rank).trans",
        f"    Data.{top.name}_boundary", "",
        "theorem boundary_in_range :",
        f"    Q0ConditionalPairRankCheck.rank {BOUNDARY_C} {BOUNDARY_D} < row.words.length := by",
        "  rw [boundary_rank, words_length]",
        "  decide", "",
        "theorem boundary_get",
        f"    (h : Q0ConditionalPairRankCheck.rank {BOUNDARY_C} {BOUNDARY_D} < row.words.length) :",
        f"    row.words.get ⟨Q0ConditionalPairRankCheck.rank {BOUNDARY_C} {BOUNDARY_D}, h⟩ =",
        f"      {boundary_word} := by",
        "  simpa only [List.get_eq_getElem] using",
        "    (List.getElem?_eq_some_iff.mp boundary_word).choose_spec", "",
        "theorem boundary_center",
        f"    (h : Q0ConditionalPairRankCheck.rank {BOUNDARY_C} {BOUNDARY_D} < row.words.length) :",
        f"    center row ⟨Q0ConditionalPairRankCheck.rank {BOUNDARY_C} {BOUNDARY_D}, h⟩ =",
        f"      value {boundary_word} := by",
        "  exact congrArg value (boundary_get h)", "",
        "/-- Safe lookup binds the production rational decoder for an arbitrary full row. -/",
        "theorem storedScalar_eq_of_lookup (r : Row) (p : ℕ × ℕ) (word : ℕ)",
        "    (hlookup : r.words[Q0ConditionalPairRankCheck.rank p.1 p.2]? = some word) :",
        "    Q0SourceSavedLinearModel.storedScalar r p = value word := by",
        "  obtain ⟨hindex, hword⟩ := List.getElem?_eq_some_iff.mp hlookup",
        "  simp only [Q0SourceSavedLinearModel.storedScalar, dite_eq_left hindex,",
        "    center, List.get_eq_getElem, hword]", "",
        "/-- The rational production lookup decodes the saved word, with no small-row validity premise. -/",
        "theorem boundary_scalar :",
        f"    Q0SourceSavedLinearModel.storedScalar row ({BOUNDARY_C}, {BOUNDARY_D}) =",
        f"      value {boundary_word} := by",
        f"  exact storedScalar_eq_of_lookup row ({BOUNDARY_C}, {BOUNDARY_D}) {boundary_word}",
        "    boundary_word", "",
        "theorem boundary_modeCenter :",
        f"    storedModeCenter row ({BOUNDARY_C}, {BOUNDARY_D}) = (value {boundary_word} : ℂ) := by",
        "  rw [← Q0SourceSavedLinearModel.storedScalar_cast, boundary_scalar]", "",
        "/-- Exact production binary64 decoding, checked independently of the list lookup. -/",
        "theorem boundary_value :",
        f"    value {boundary_word} = {scalar} := by",
        "  norm_num [value, magnitude, exponent, fraction]", "",
        "theorem boundary_scalar_decoded :",
        f"    Q0SourceSavedLinearModel.storedScalar row ({BOUNDARY_C}, {BOUNDARY_D}) =",
        f"      {scalar} := by",
        "  rw [boundary_scalar, boundary_value]", "",
        "theorem boundary_modeCenter_decoded :",
        f"    storedModeCenter row ({BOUNDARY_C}, {BOUNDARY_D}) =",
        f"      (({scalar}) : ℂ) := by",
        "  simp only [boundary_modeCenter, boundary_value, Rat.cast_div, Rat.cast_neg,",
        "    Rat.cast_ofNat]", ""])
    outputs["OriginalRow227Payload.lean"] = finish(lines, NAMESPACE)
    return outputs


def load_words():
    raw = INPUT.read_bytes()
    require(hashlib.sha256(raw).hexdigest() == SHA256, "pinned original payload SHA256")
    require(len(raw) == WORD_COUNT * 8, "complete original payload byte count")
    words = struct.unpack(f"<{WORD_COUNT}Q", raw)
    require(all(1 <= (word >> 52) & 2047 <= 1023 for word in words),
            "normal binary64 payload in the production decoder range")
    return words


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check byte-for-byte reproduction only")
    args = parser.parse_args()
    words = load_words()
    outputs = render(words)
    for name, content in outputs.items():
        target = OUTPUT / name
        if args.check:
            require(target.read_bytes() == content, f"reproduction: {name}")
        else:
            target.write_bytes(content)
    print(json.dumps({"agent": "codex-aa04", "source_words": len(words),
                      "leaf_words": LEAF_WORDS, "modules": len(outputs),
                      "boundary_rank": BOUNDARY_INDEX, "boundary_word": words[BOUNDARY_INDEX],
                      "status": "SOURCE_GENERATION_ONLY_UNCOMPILED"}, indent=2))


if __name__ == "__main__":
    main()
