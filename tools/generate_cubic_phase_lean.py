def lit(x):
    x=Q(x)
    return f'({x.numerator} / {x.denominator} : ℝ)'


def bern_expr(bb,subtract=Q(0)):
    n=len(bb)-1;m=len(bb[0])-1
    return ' +\n    '.join(
        f'{lit((Q(bb[i][j])-subtract)*comb(n,i)*comb(m,j))} * a ^ {i} * (1-a) ^ {n-i}'
        +(f' * b ^ {j} * (1-b) ^ {m-j}' if m else '')
        for i in range(n+1) for j in range(m+1))


