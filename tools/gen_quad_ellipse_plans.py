#!/usr/bin/env python3
"""Generate Grothe/UpperQuad/QuadEllipsePlans.lean from data/quad-checker/ellipse-plans.txt
(claude-b9ee, #303).  The plans are blocks of 64 arrays (like Q0GaussAddress.panelBlockNNN).
Usage: tools/gen_quad_ellipse_plans.py [--check]"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
src = os.path.join(ROOT, 'data', 'quad-checker', 'ellipse-plans.txt')
dst = os.path.join(ROOT, 'Grothe', 'UpperQuad', 'QuadEllipsePlans.lean')
rows = []
for line in open(src):
    t = line.split()
    if t and t[0] == 'plan':
        i, rn, rd, m, Rn, Rd, tn, td = map(int, t[1:9])
        assert i == len(rows)
        rows.append((rn, rd, m, Rn, Rd, tn, td))
out = ['import Grothe.UpperQuad.QuadEllipseCheck', '',
       '/-!', '# The per-panel plans of the ellipse checker (generated)', '',
       'Generated by `tools/gen_quad_ellipse_plans.py` from `data/quad-checker/ellipse-plans.txt`',
       '(itself produced by `tools/quad_ellipse_search.py`). Do not edit by hand.', '',
       'Agent-ID: claude-b9ee. Refs #303.', '-/', '',
       'namespace Grothe.UpperQuad.EllCheck', '']
nb = (len(rows) + 63) // 64
for b in range(nb):
    out.append('/-- Plans %d–%d. -/' % (64 * b, min(len(rows), 64 * b + 64) - 1))
    out.append('def planBlock%03d : Array Plan := #[' % b)
    blk = rows[64 * b:64 * b + 64]
    for k, (rn, rd, m, Rn, Rd, tn, td) in enumerate(blk):
        sep = ',' if k + 1 < len(blk) else ']'
        ent = '  ⟨%d/%d, %d, %d/%d, %d/%d⟩%s' % (rn, rd, m, Rn, Rd, tn, td, sep)
        if len(ent) > 100:
            ent = '  ⟨%d/%d, %d, %d/%d,\n    %d/%d⟩%s' % (rn, rd, m, Rn, Rd, tn, td, sep)
        out.append(ent)
    out.append('')
out.append('/-- The %d plans, in panel order. -/' % len(rows))
out.append('def plans : List Plan :=')
parts = ['planBlock%03d.toList' % b for b in range(nb)]
cur = '  ' + parts[0]
for q in parts[1:]:
    if len(cur) + len(' ++ ' + q) > 100:
        out.append(cur + ' ++')
        cur = '  ' + q
    else:
        cur += ' ++ ' + q
out.append(cur)
out.append('')
out.append('end Grothe.UpperQuad.EllCheck')
text = '\n'.join(out) + '\n'
if '--check' in sys.argv:
    sys.exit(0 if open(dst).read() == text else 1)
open(dst, 'w').write(text)
print('wrote', dst, len(rows), 'plans')
