#!/usr/bin/env python3
"""Export the audited private upper certificate's exact channel parameters.

Agent-ID: codex-a7c4.
This exports input data only; it does not certify the Hermite integrals or the endpoint.
The source hash pins the input to the independent audit. All arithmetic here is rational.
"""

import argparse
from fractions import Fraction
import hashlib
import json
from pathlib import Path


SOURCE_SHA256 = "e3df2d3ae7765cfcae8458daa098afa2133fe4167ed3a997bb73d7f22eecbde8"


def lean_rat(value):
    q = Fraction(value)
    return str(q.numerator) if q.denominator == 1 else f"({q.numerator} / {q.denominator})"


def lean_list(values):
    return "[" + ", ".join(map(lean_rat, values)) + "]"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--check", action="store_true", help="Check byte-for-byte regeneration")
    args = parser.parse_args()
    raw = args.source.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise SystemExit("Source differs from the audited exact columns")
    columns = json.loads(raw, parse_float=Fraction)["columns"]
    if len(columns) != 18:
        raise SystemExit("Expected exactly 18 audited channels")
    if sum(Fraction(c["w_Q"]) for c in columns) != 1:
        raise SystemExit("Weights do not sum exactly to one")

    text = '''import GrotheKernel.Table

/-!
# Exact inputs of the private 18-channel certificate

Agent-ID: codex-a7c4.
Generated by `tools/gen_private_upper_certificate.py` from the audited exact columns.
Only executable exact input data live here. Admissibility is proved in `CertificateData`.
-/

namespace Grothe.UpperReplacement.Certificate

local notation "ℚ" => Rat

inductive Kind where
  | gt | phase | tiger
  deriving DecidableEq, Repr

structure Channel where
  name : String
  kind : Kind
  weight : ℚ
  primary : List ℚ
  auxiliary : List ℚ
  radius : ℚ
  schur : ℚ
  deriving DecidableEq, Repr

def channels : List Channel := [
'''
    rows = []
    for c in columns:
        weight = Fraction(c["w_Q"])
        primary = c.get("P_Q", c.get("R_Q"))
        auxiliary = c.get("Q_Q", primary)
        if weight <= 0 or any(
            sum(abs(Fraction(x)) for x in poly) > 1 for poly in (primary, auxiliary)
        ):
            raise SystemExit(f"Invalid channel: {c['name']}")
        if c["kind"] == "GT" and Fraction(auxiliary[0]) != 0:
            raise SystemExit("The GT auxiliary polynomial must have zero constant coefficient")

        # Actual successful contour parameters from the independent Arb replay,
        # not the floating-point optimiser's candidate budget in the `info` field.
        if weight < Fraction(1, 1000):
            radius, schur = Fraction(102, 100), Fraction(25, 100)
        else:
            radius = Fraction(c["info"][0])
            schur = Fraction(c["info"][1])
        kind = {"GT": "gt", "phase": "phase", "tiger": "tiger"}[c["kind"]]
        rows.append(
            f'  {{ name := "{c["name"]}", kind := .{kind}, weight := {lean_rat(weight)},\n'
            f'    primary := {lean_list(primary)},\n'
            f'    auxiliary := {lean_list(auxiliary)},\n'
            f'    radius := {lean_rat(radius)}, schur := {lean_rat(schur)} }}'
        )
    text += ",\n".join(rows)
    text += ''']

end Grothe.UpperReplacement.Certificate
'''
    proofs = '''import Grothe.UpperReplacement.CertificateInputs
import Mathlib.Tactic

/-! Parameter admissibility for the private certificate. Agent-ID: codex-a7c4.
Generated by `tools/gen_private_upper_certificate.py`. No numerical upper bound is asserted. -/

namespace Grothe.UpperReplacement.Certificate

def ValidChannel (c : Channel) : Prop :=
  0 < c.weight ∧ (c.primary.map abs).sum ≤ 1 ∧ (c.auxiliary.map abs).sum ≤ 1 ∧
    1 < c.radius ∧ 0 < c.schur ∧ (c.kind = .gt → c.auxiliary.getD 0 0 = 0)

instance (c : Channel) : Decidable (ValidChannel c) := by
  unfold ValidChannel
  infer_instance

set_option maxRecDepth 10000 in
set_option maxHeartbeats 0 in
theorem parameters_checked : ∀ c ∈ channels, ValidChannel c := by
  decide +kernel

set_option maxRecDepth 10000 in
set_option maxHeartbeats 0 in
theorem weights_sum_one : (channels.map Channel.weight).sum = 1 := by
  decide +kernel

theorem channels_length : channels.length = 18 := by decide

end Grothe.UpperReplacement.Certificate
'''
    args.output.parent.mkdir(parents=True, exist_ok=True)
    inputs = args.output.with_name("CertificateInputs.lean")
    for path, content in [(inputs, text), (args.output, proofs)]:
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f"Generated certificate differs: {path}")
        else:
            path.write_text(content)
    print(f"Exported {len(columns)} exact channels to {inputs}; checks to {args.output}")


if __name__ == "__main__":
    main()
