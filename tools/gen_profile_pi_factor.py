#!/usr/bin/env python3
"""Exact integer witnesses for the profile's common pi normalization.

No floating point or external numerical package is used. Mathlib's pi bounds
check the nested-square-root witnesses; Lean checks the remaining rational
inequalities. Agent-ID: codex-8c4d.
"""
from fractions import Fraction
import argparse
import hashlib
import json
from math import isqrt
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RECIPE = ROOT / "data/profile-pi-factor/recipe.json"
NS = "Grothe.UpperChaos.ProfilePiFactor"


def ceil_sqrt(n):
    r = isqrt(n)
    return r + (r * r < n)


def ceil_fraction(q):
    return -((-q.numerator) // q.denominator)


def witnesses(cfg):
    bits, steps, grid_bits = (cfg[k] for k in
                             ("precision_bits", "series_steps", "sqrt_grid_bits"))
    if not (bits > 0 and steps > 0 and grid_bits > 2 * steps + bits + 16):
        raise ValueError("insufficient witness grid precision")
    grid, scale = 1 << grid_bits, 1 << bits
    lower, upper = [], []
    lo = hi = 0
    for _ in range(steps):
        prev_lo, prev_hi = lo, hi
        lo = isqrt((2 * grid + prev_lo) * grid)
        hi = ceil_sqrt((2 * grid + prev_hi) * grid)
        assert lo * lo <= (2 * grid + prev_lo) * grid
        assert (2 * grid + prev_hi) * grid <= hi * hi
        lower.append(lo)
        upper.append(hi)
    assert 0 < lo <= hi < 2 * grid
    analytic_error = Fraction(1, 4 ** steps)
    p_lo = Fraction((1 << (steps + 1)) * isqrt((2 * grid - hi) * grid), grid)
    p_hi = Fraction((1 << (steps + 1)) * (isqrt((2 * grid - lo) * grid) + 1), grid)
    p_hi += analytic_error
    pi_lo = (p_lo * scale).__floor__()
    pi_hi = ceil_fraction(p_hi * scale)
    q_lo, q_hi = Fraction(pi_lo, scale), Fraction(pi_hi, scale)
    assert Fraction(hi, grid) <= 2 - (q_lo / (1 << (steps + 1))) ** 2
    assert 2 - ((q_hi - analytic_error) / (1 << (steps + 1))) ** 2 <= Fraction(lo, grid)
    assert analytic_error <= q_hi
    sqrt_lo = isqrt(pi_lo * scale)
    sqrt_hi = isqrt(pi_hi * scale) + 1
    quarter_lo = isqrt(isqrt(pi_lo * scale ** 3))
    quarter_hi = isqrt(isqrt(pi_hi * scale ** 3)) + 1
    assert Fraction(sqrt_lo, scale) ** 2 <= q_lo
    assert q_hi <= Fraction(sqrt_hi, scale) ** 2
    assert Fraction(quarter_lo, scale) ** 4 <= q_lo
    assert q_hi <= Fraction(quarter_hi, scale) ** 4
    assert pi_hi - pi_lo == 1
    assert sqrt_hi - sqrt_lo == 1
    assert quarter_hi - quarter_lo == 1
    return lower, upper, (pi_lo, pi_hi, sqrt_lo, sqrt_hi, quarter_lo, quarter_hi)


def generated_sources(cfg, digest):
    lower, upper, vals = witnesses(cfg)
    bits, grid_bits = cfg["precision_bits"], cfg["sqrt_grid_bits"]
    pi_lo, pi_hi, sqrt_lo, sqrt_hi, quarter_lo, quarter_hi = vals
    header = ("/-! Generated by tools/gen_profile_pi_factor.py from "
              f"data/profile-pi-factor/recipe.json (SHA256 {digest}).\n"
              "Agent-ID: codex-8c4d. -/\n")
    outputs = {}
    for name, units, series, claim, tactic in [
        ("Lower", pi_lo, upper, "(piLo : ℝ) < Real.pi", "pi_lower_bound"),
        ("Upper", pi_hi, lower, "Real.pi < (piHi : ℝ)", "pi_upper_bound"),
    ]:
        const = "piLo" if name == "Lower" else "piHi"
        theorem = "pi_lo_lt" if name == "Lower" else "pi_lt_hi"
        rows = ",\n".join(f"    {n} / 2^{grid_bits}" for n in series)
        text = ("import Mathlib.Analysis.Real.Pi.Bounds\n\n" + header +
                f"\nopen Real\nnamespace {NS}\n\n"
                "-- The finite witnesses use powers beyond Lean's default exponent limit.\n"
                "set_option exponentiation.threshold 4096\n\n"
                f"def {const} : ℚ := {units} / 2^{bits}\n\n"
                "set_option maxRecDepth 65536 in\n"
                "set_option maxHeartbeats 16000000 in\n"
                f"theorem {theorem} : {claim} := by\n"
                f"  simp only [{const}, Rat.cast_div, Rat.cast_pow, Rat.cast_ofNat]\n"
                f"  {tactic} [\n{rows}]\n\nend {NS}\n")
        outputs[f"Grothe/UpperChaos/ProfilePiFactor{name}.lean"] = text
    factor = f'''import Grothe.UpperChaos.ProfilePiFactorLower
import Grothe.UpperChaos.ProfilePiFactorUpper
import Mathlib.Tactic.NormNum
import Lean.Util.CollectAxioms
import Lean.Elab.Command

{header}
namespace {NS}

-- Exact evaluation of the finite 512-bit certificate constants.
set_option exponentiation.threshold 4096

def sqrtPiLo : ℚ := {sqrt_lo} / 2^{bits}
def sqrtPiHi : ℚ := {sqrt_hi} / 2^{bits}
def piQuarterLo : ℚ := {quarter_lo} / 2^{bits}
def piQuarterHi : ℚ := {quarter_hi} / 2^{bits}

set_option maxRecDepth 65536 in
set_option maxHeartbeats 16000000 in
theorem sqrt_checks :
    0 ≤ sqrtPiLo ∧ 0 ≤ sqrtPiHi ∧ sqrtPiLo ^ 2 ≤ piLo ∧ piHi ≤ sqrtPiHi ^ 2 := by
  decide +kernel

set_option maxRecDepth 65536 in
set_option maxHeartbeats 16000000 in
theorem quarter_checks :
    0 ≤ piQuarterLo ∧ 0 ≤ piQuarterHi ∧ piQuarterLo ^ 4 ≤ piLo ∧
      piHi ≤ piQuarterHi ^ 4 := by
  decide +kernel

set_option maxRecDepth 65536 in
set_option maxHeartbeats 16000000 in
theorem width_checks :
    piHi - piLo ≤ (1 : ℚ) / 2^{bits} ∧
      sqrtPiHi - sqrtPiLo ≤ (1 : ℚ) / 2^{bits} ∧
      piQuarterHi - piQuarterLo ≤ (1 : ℚ) / 2^{bits} := by
  decide +kernel

theorem sqrt_pi_bounds :
    (sqrtPiLo : ℝ) ≤ Real.sqrt Real.pi ∧ Real.sqrt Real.pi ≤ (sqrtPiHi : ℝ) := by
  rcases sqrt_checks with ⟨_, hhi, hloSq, hhiSq⟩
  have hloSqR : (sqrtPiLo : ℝ) ^ 2 ≤ (piLo : ℝ) := by exact_mod_cast hloSq
  have hhiSqR : (piHi : ℝ) ≤ (sqrtPiHi : ℝ) ^ 2 := by exact_mod_cast hhiSq
  have hhiR : (0 : ℝ) ≤ (sqrtPiHi : ℝ) := by exact_mod_cast hhi
  exact ⟨Real.le_sqrt_of_sq_le (hloSqR.trans pi_lo_lt.le),
    Real.sqrt_le_iff.mpr ⟨hhiR, pi_lt_hi.le.trans hhiSqR⟩⟩

theorem pi_quarter_bounds :
    (piQuarterLo : ℝ) ≤ Real.sqrt (Real.sqrt Real.pi) ∧
      Real.sqrt (Real.sqrt Real.pi) ≤ (piQuarterHi : ℝ) := by
  rcases quarter_checks with ⟨_, hhi, hloFourth, hhiFourth⟩
  have hloFourthR : (piQuarterLo : ℝ) ^ 4 ≤ (piLo : ℝ) := by exact_mod_cast hloFourth
  have hhiFourthR : (piHi : ℝ) ≤ (piQuarterHi : ℝ) ^ 4 := by exact_mod_cast hhiFourth
  have hlo : (piQuarterLo : ℝ) ^ 4 ≤ Real.pi := hloFourthR.trans pi_lo_lt.le
  have hhiBound : Real.pi ≤ (piQuarterHi : ℝ) ^ 4 := pi_lt_hi.le.trans hhiFourthR
  have hloRoot : (piQuarterLo : ℝ) ^ 2 ≤ Real.sqrt Real.pi := by
    apply Real.le_sqrt_of_sq_le
    simpa only [← pow_mul] using hlo
  have hhiRoot : Real.sqrt Real.pi ≤ (piQuarterHi : ℝ) ^ 2 := by
    apply Real.sqrt_le_iff.mpr
    refine ⟨sq_nonneg _, ?_⟩
    simpa only [← pow_mul] using hhiBound
  have hhiR : (0 : ℝ) ≤ (piQuarterHi : ℝ) := by exact_mod_cast hhi
  exact ⟨Real.le_sqrt_of_sq_le hloRoot, Real.sqrt_le_iff.mpr ⟨hhiR, hhiRoot⟩⟩

theorem pi_quarter_width :
    (piQuarterHi : ℝ) - (piQuarterLo : ℝ) ≤ (1 : ℝ) / 2^{bits} := by
  have h := (Rat.cast_le (K := ℝ)).mpr width_checks.2.2
  simpa only [Rat.cast_sub, Rat.cast_div, Rat.cast_one, Rat.cast_pow,
    Rat.cast_ofNat] using h

open Lean Elab Command
run_cmd do
  let allowed : Array Name := #[``propext, ``Classical.choice, ``Quot.sound]
  for target in #[``pi_lo_lt, ``pi_lt_hi, ``sqrt_pi_bounds, ``pi_quarter_bounds,
      ``pi_quarter_width] do
    let dependencies ← Lean.collectAxioms target
    for dependency in dependencies do
      unless allowed.contains dependency do
        throwError m!"{{target}} depends on nonstandard axiom {{dependency}}"

end {NS}
'''
    outputs["Grothe/UpperChaos/ProfilePiFactor.lean"] = factor
    return outputs, vals


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    recipe = RECIPE.read_bytes()
    cfg = json.loads(recipe)
    outputs, vals = generated_sources(cfg, hashlib.sha256(recipe).hexdigest())
    for name, text in outputs.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"generated source differs: {name}")
        else:
            path.write_text(text)
    sizes = sum(len(s.encode()) for s in outputs.values())
    print(f"{'Checked' if args.check else 'Wrote'} {len(outputs)} modules, {sizes} bytes; "
          f"pi/sqrt/quarter widths in 2^-{cfg['precision_bits']} units: "
          f"{vals[1]-vals[0]}/{vals[3]-vals[2]}/{vals[5]-vals[4]}")


if __name__ == "__main__":
    main()
