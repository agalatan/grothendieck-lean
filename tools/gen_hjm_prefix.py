#!/usr/bin/env python3
"""Generate the interval head tables of the five scalar HJM branches.

For branch r this replays `Grothe.HJM.headI 120 120 pList_r` (GrotheCapsKernel/Basic.lean: fixed point with
D = 2^128, outward rounding; GrotheKernel/Haagerup.lean: haagList, hornerI) exactly with Python integers and writes
  Grothe/HJM/PrefixTable.lean      the integer endpoints `headTable_r : List (Int × Int)`,
  Grothe/HJM/PrefixCheck<r>.lean   `headI 120 120 pList_r` maps to `headTable_r` (decide +kernel), and the enclosure
                                   of `(4/π)·compCoeff haagCoeff P_r n` for n < 120.
Input: data/hjm/audit_sparse6_altgroups.py through tools/gen_hjm_data.py.

Usage: python3 tools/gen_hjm_prefix.py [--check]
"""
import ast, sys
from fractions import Fraction as Q
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import gen_hjm_data  # noqa: E402

M = K = 120
D = 1 << 128
Z = (0, 0)


def floor(q):
    return q.numerator // q.denominator


def ofRatI(q):
    return (floor(q * D), -floor(-(q * D)))


def addL(l, m):
    out = []
    for i in range(max(len(l), len(m))):
        if i >= len(l):
            out.append(m[i])
        elif i >= len(m):
            out.append(l[i])
        else:
            out.append((l[i][0] + m[i][0], l[i][1] + m[i][1]))
    return out


def mulI(a, b):
    p = [a[0] * b[0], a[0] * b[1], a[1] * b[0], a[1] * b[1]]
    return (min(p) // D, -((-max(p)) // D))


def convI(l, m):
    out = []
    for a in reversed(l):  # convI (a :: l) m, built from the end
        out = [Z] + out if a == Z else addL([mulI(a, x) for x in m], [Z] + out)
    return out


def haagList(n):
    out, r = [], Q(1)
    for k in range(n):
        out.append(r)
        r = r * (2 * k + 1) ** 2 / (4 * (k + 1) * (k + 2))
    return out


def hornerI(m, Y, rs):
    acc = []
    for r in reversed(rs):
        acc = addL([ofRatI(r)], convI(Y, acc))[:m]
    return acc


def headI(m, k, pl):
    PI = [ofRatI(q) for q in pl]
    return convI(PI, hornerI(m, [Z] + convI(PI, PI), haagList(k)))[:m]


def dense(entries):
    d = max(i for i, _ in entries)
    pl = [Q(0)] * (d + 1)
    for i, c in entries:
        pl[i] = c
    return pl


HEADER = "/-! Generated by tools/gen_hjm_prefix.py from data/hjm/audit_sparse6_altgroups.py; do not edit. -/"


def generate():
    rows, _ = gen_hjm_data.literal_rows(ast.parse(gen_hjm_data.SRC.read_text()))
    files = {}
    t = ["import Init", "", HEADER, "", "namespace Grothe.HJM", ""]
    for r in range(1, 6):
        h = headI(M, K, dense(rows[r]))
        t.append(f"/-- The interval head of branch {r} (endpoints scaled by `2^128`). -/")
        t.append(f"def headTable{r} : List (Int × Int) := [")
        t.append(",\n".join(f"  ({a}, {b})" for a, b in h) + "]")
        t.append("")
    t += ["end Grothe.HJM", ""]
    files["Grothe/HJM/PrefixTable.lean"] = "\n".join(t)
    for r in range(1, 6):
        files[f"Grothe/HJM/PrefixCheck{r}.lean"] = "\n".join([
            "import Grothe.HJM.Prefix", "import Grothe.HJM.PrefixTable", "", HEADER, "",
            "namespace Grothe.HJM", "", "open Grothe.Upper GrotheKernel", "",
            f"theorem headI_check{r} : (headI 120 120 pList{r}).map (fun a => (a.lo, a.hi)) = headTable{r} := by",
            "  decide +kernel", "",
            f"/-- **The first 120 coefficients of branch {r}**, enclosed. -/",
            f"theorem mem_head{r} {{n : ℕ}} (hn : n < 120) :",
            f"    mem (compCoeff haagCoeff (P {r - 1}) n / (Real.pi / 4)) ((ofPairs headTable{r}).getD n zeroI) := by",
            f"  rw [← getD_eq_of_pairs headI_check{r}]",
            f"  exact mem_head pList{r} (l1_P {r - 1}) hn hn", "",
            "end Grothe.HJM", ""])
    return files


if __name__ == "__main__":
    files = generate()
    if "--check" in sys.argv:
        stale = [p for p, s in files.items() if not (ROOT / p).exists() or (ROOT / p).read_text() != s]
        sys.exit(f"stale: {stale}" if stale else 0)
    for p, s in files.items():
        (ROOT / p).write_text(s)
        print("wrote", p)
