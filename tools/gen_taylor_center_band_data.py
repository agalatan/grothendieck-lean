#!/usr/bin/env python3
"""Generate exact first/second center band targets. Agent-ID: codex-37fb.

Its default output is the repository coefficient-data module. No Gaussian
error or Grothendieck endpoint assertion is made. The exact source readers are
reused from the rounding generator; independent raw-IEEE754 validation is in
audit_band_intervals.py, with a separate signed receipt.
"""

import argparse
import hashlib
import importlib.util
import json
import math
import re
from fractions import Fraction
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "Grothe/UpperChaos"
E = 206
COMPARISON_HASH = "5619546626b7588ce64a2229aa58b0d161bde613dbf9a5eaad94a3ef93461915"


def generated(repo):
    spec = importlib.util.spec_from_file_location("rounding_source", repo / "tools/gen_taylor_rounding_data.py")
    source = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(source)
    data = repo / "data/taylor-approximants"
    manifest = json.loads((data / "manifest.json").read_text())
    inputs = {Path(x["path"]).name: x for x in manifest["inputs"]}
    comparison_path = repo / "data/localized-comparison/inputs/taylor_comparison_result.json"
    raw = comparison_path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != COMPARISON_HASH:
        raise ValueError("comparison provenance mismatch")
    comparison = json.loads(raw)
    result = {
        "agent_id": "codex-37fb",
        "scope": "Finite center norm data only; no Gaussian approximation error or endpoint proof",
        "common_exponent": E,
        "comparison_source": "data/localized-comparison/inputs/taylor_comparison_result.json",
        "comparison_source_sha256": COMPARISON_HASH,
        "sources": [],
    }
    for name, power, filename, source_levels, retain_levels in [
        ("firstCenter", 1, "arb_first_phase_D181.npz", 91, 91),
        ("secondCenter", 2, "arb_phase_power2_D151.npz", 76, 46),
    ]:
        item = inputs[filename]
        path = data / item["path"]
        raw = path.read_bytes()
        if len(raw) != item["size_bytes"] or hashlib.sha256(raw).hexdigest() != item["sha256"]:
            raise ValueError(f"source size/hash mismatch: {filename}")
        with zipfile.ZipFile(path) as archive:
            values = source.read_f64(archive, "center.npy", (source.count_levels(source_levels),))
        values = values[:source.count_levels(retain_levels)]
        integers = source.scaled(values)
        if source.COMMON_EXPONENT != E:
            raise ValueError("rounding source denominator exponent changed")
        detail = next(x for x in comparison["details"] if x["power"] == power)
        bands = []
        for b in detail["bands"]:
            lo, hi = b["lo"], b["hi"]
            start = source.count_levels((lo + 1) // 2)
            stop = source.count_levels((hi + 1) // 2)
            z = sum(x * x for x in integers[start:stop])
            energy = Fraction(z, 2 ** (2 * E))
            floor = math.isqrt(energy.numerator * 10 ** 60 // energy.denominator)
            lower, upper = Fraction(floor, 10 ** 30), Fraction(floor + 1, 10 ** 30)
            assert 0 < lower and lower * lower <= energy < upper * upper
            m = re.fullmatch(r"\[([^ ]+) \+/- ([^ ]+)\]", b["center_norm"])
            if not m:
                raise ValueError("unexpected inherited center norm interval")
            midpoint, radius = map(Fraction, m.groups())
            if not 0 < radius < midpoint or not (midpoint - radius) ** 2 <= energy <= (midpoint + radius) ** 2:
                raise ValueError(f"exact norm falls outside inherited interval: {power},{lo},{hi}")
            bands.append({
                "lo": lo, "hi": hi, "start": start, "stop": stop,
                "integer_energy": str(z), "energy": str(energy),
                "norm_lower": str(lower), "norm_upper": str(upper),
                "reference_interval": b["center_norm"], "inside_reference_interval": True,
            })
        result["sources"].append({"name": name, "power": power,
            "source": item["path"], "source_sha256": item["sha256"],
            "retained_levels": retain_levels, "retained_coefficient_count": len(values), "bands": bands})

    def rat(s):
        q = Fraction(s)
        return f"({q.numerator} / {q.denominator})"

    lines = ["import Mathlib.Data.Rat.Defs", "",
        "/-! Generated by tools/gen_taylor_center_band_data.py; do not edit. Agent-ID: codex-37fb.",
        "Exact energies of unscaled, normalized finite Hermite centers. -/", "",
        "namespace Grothe.UpperChaos", ""]
    for item in result["sources"]:
        name, bands = item["name"], item["bands"]
        n = len(bands)
        for suffix, typ, key, doc in [
            ("Lo", "ℕ", "lo", "Lower excluded degree of each band."),
            ("Hi", "ℕ", "hi", "Upper included degree of each band."),
            ("IntegerEnergy", "ℤ", "integer_energy", "Exact integer energy at common scale 2^206."),
            ("LowerQ", "ℚ", "norm_lower", "Rational lower enclosure of each band norm."),
            ("UpperQ", "ℚ", "norm_upper", "Rational upper enclosure of each band norm."),
        ]:
            lines += [f"/-- {doc} -/", f"def {name}Band{suffix} : Fin {n} → {typ}"]
            for k, b in enumerate(bands):
                pattern = str(k) if k + 1 < n else "_"
                value = rat(b[key]) if typ == "ℚ" else str(b[key])
                lines.append(f"  | {pattern} => {value}")
            lines.append("")
        lines += ["/-- Exact rational energy, without rounding the stored integer target. -/",
            f"def {name}BandEnergyQ (k : Fin {n}) : ℚ :=",
            f"  ({name}BandIntegerEnergy k : ℚ) / (2 : ℚ)^412", ""]
    lines += ["end Grothe.UpperChaos", ""]
    return {"TaylorCenterBandData.lean": "\n".join(lines),
            "center-band-norms.json": json.dumps(result, indent=2) + "\n"}, result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=ROOT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs, result = generated(args.repo)
    if not args.check:
        args.output.mkdir(parents=True, exist_ok=True)
    for name, wanted in outputs.items():
        path = (args.repo / "data/taylor-approximants/center-band-norms.json"
                if name.endswith(".json") and args.output == DEFAULT_OUTPUT
                else args.output / name)
        if args.check:
            if not path.exists() or path.read_text() != wanted:
                raise SystemExit(f"stale generated center band data: {path}")
        else:
            path.write_text(wanted)
    print(json.dumps({"agent_id": "codex-37fb", "bands": sum(len(x["bands"]) for x in result["sources"]),
        "all_reference_intervals_match": True, "output": str(args.output)}, indent=2))


if __name__ == "__main__":
    main()
