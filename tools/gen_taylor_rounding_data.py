#!/usr/bin/env python3
"""Generate exact dyadic data for the Taylor rounding certificate; Agent-ID: codex-2ca4.

Writes reproducible Lean coefficient data and an exact arithmetic receipt. Reads pinned NPZ files with the
standard library, never executing pickle or numpy object data. Source binary64
centers are preserved exactly. Gaussian integration errors are outside scope.

Three new packed-data modules are emitted. The third center is reused from the
production TaylorBandData module, rather than copied into another large vector.
"""

import argparse
import ast
import hashlib
import json
import math
import struct
import zipfile
from fractions import Fraction
from pathlib import Path


COMMON_EXPONENT = 206
CHUNK_SIZE = 1024
REPO = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = REPO / "Grothe/UpperChaos"


def count_levels(n):
    return n * (n + 1) * (n + 2) // 3


def read_f64(archive, member, shape):
    raw = archive.read(member)
    if raw[:6] != b"\x93NUMPY" or raw[6:8] not in (b"\x01\x00", b"\x02\x00", b"\x03\x00"):
        raise ValueError(f"unsupported NPY header: {member}")
    header_size = 2 if raw[6] == 1 else 4
    n = int.from_bytes(raw[8:8 + header_size], "little")
    start = 8 + header_size
    header = ast.literal_eval(raw[start:start + n].decode("utf-8"))
    if header != {"descr": "<f8", "fortran_order": False, "shape": shape}:
        raise ValueError(f"unexpected binary64 layout: {member}: {header}")
    data = raw[start + n:]
    if len(data) != 8 * math.prod(shape):
        raise ValueError(f"unexpected binary64 byte count: {member}")
    values = []
    for (x,) in struct.iter_unpack("<d", data):
        if not math.isfinite(x):
            raise ValueError(f"nonfinite center: {member}")
        numerator, denominator = x.as_integer_ratio()
        exponent = denominator.bit_length() - 1
        if denominator != 2 ** exponent or abs(numerator) >= 2 ** 53:
            raise ValueError(f"invalid reduced binary64 dyadic: {member}")
        if exponent > COMMON_EXPONENT:
            raise ValueError(f"common exponent too small: {member}")
        values.append((numerator, exponent))
    return values


def scaled(values):
    return [m << (COMMON_EXPONENT - e) for m, e in values]


def packed_chunks(values):
    records = [f"{m}:{e}" for m, e in values]
    chunks = [",".join(records[i:i + CHUNK_SIZE]) for i in range(0, len(records), CHUNK_SIZE)]
    # Independent lexical round-trip, including zero, signs and both endpoints.
    unpacked = []
    for chunk in chunks:
        row = []
        for record in chunk.split(","):
            fields = record.split(":")
            if len(fields) != 2:
                raise ValueError("bad generated record")
            m, e = map(int, fields)
            if not 0 <= e <= COMMON_EXPONENT or abs(m) >= 2 ** 53:
                raise ValueError("bad generated dyadic")
            row.append((m, e))
        if not 1 <= len(row) <= CHUNK_SIZE:
            raise ValueError("bad chunk length")
        unpacked.extend(row)
    if unpacked != values:
        raise ValueError("packed format failed exact round-trip")
    return chunks


def data_module(name, values, source, source_count, retained_degree):
    chunks = packed_chunks(values)
    lines = [
        "import Grothe.UpperChaos.PackedDyadic", "",
        "/-! Generated by tools/gen_taylor_rounding_data.py; do not edit.",
        "Exact normalized Hermite centers; no Gaussian error assertion.",
        f"Source SHA256: {source['sha256']}",
        "Agent-ID: codex-2ca4 -/", "",
        "namespace Grothe.UpperChaos", "",
        f"def {name}CommonExponent : ℕ := {COMMON_EXPONENT}",
        f"def {name}Count : ℕ := {len(values)}", "",
        f"/-- Exact dyadic records in flat graded order; at most {CHUNK_SIZE} per chunk. -/",
        f"def {name}PackedChunks : Array String := #[",
    ]
    lines.extend('  "' + chunk + '"' + ("," if i + 1 < len(chunks) else "")
                 for i, chunk in enumerate(chunks))
    lines += ["]", "", "end Grothe.UpperChaos", ""]
    text = "\n".join(lines)
    info = {
        "source_file": source["path"], "source_sha256": source["sha256"],
        "source_coefficient_count": source_count,
        "retained_coefficient_count": len(values), "retained_degree": retained_degree,
        "source_max_denominator_exponent": max(e for _, e in values),
        "common_denominator_exponent": COMMON_EXPONENT,
        "chunk_count": len(chunks), "chunk_size": CHUNK_SIZE,
        "last_chunk_count": len(values) - CHUNK_SIZE * (len(chunks) - 1),
        "lean_bytes": len(text.encode()), "lean_sha256": hashlib.sha256(text.encode()).hexdigest(),
    }
    return text, info


def generated(repo):
    data = repo / "data/taylor-approximants"
    manifest = json.loads((data / "manifest.json").read_text())
    sources = {}
    for item in manifest["inputs"]:
        path = data / item["path"]
        raw = path.read_bytes()
        if len(raw) != item["size_bytes"] or hashlib.sha256(raw).hexdigest() != item["sha256"]:
            raise ValueError(f"source hash/size mismatch: {path.name}")
        sources[path.name] = item

    centers = {}
    original_counts = {}
    for power, filename, source_n, retained_n in [
        (1, "arb_first_phase_D181.npz", 91, 91),
        (2, "arb_phase_power2_D151.npz", 76, 46),
        (3, "arb_phase_power3_D51.npz", 26, 26),
    ]:
        with zipfile.ZipFile(data / sources[filename]["path"]) as archive:
            values = read_f64(archive, "center.npy", (count_levels(source_n),))
        original_counts[power] = len(values)
        centers[power] = values[:count_levels(retained_n)]

    vf = "frozen_taylor_correction_D201.npz"
    with zipfile.ZipFile(data / sources[vf]["path"]) as archive:
        frozen = [value for q in range(101)
                  for value in read_f64(archive, f"C{q}.npy", (q + 2, q + 1))]
    if len(frozen) != count_levels(101) or any(m != 0 for m, _ in frozen[count_levels(91):]):
        raise ValueError("frozen correction is not exactly zero above degree 181")
    frozen_retained = frozen[:count_levels(91)]
    arrays = {j: scaled(values) for j, values in centers.items()}
    frozen_ints = scaled(frozen_retained)
    at = lambda a, k: a[k] if k < len(a) else 0
    residual = [6 * arrays[1][k] + 3 * at(arrays[2], k) + at(arrays[3], k) - 6 * frozen_ints[k]
                for k in range(count_levels(91))]
    integer_sum = sum(x * x for x in residual)
    denominator = 6 * 2 ** COMMON_EXPONENT
    energy = Fraction(integer_sum, denominator * denominator)
    if not integer_sum * 10 ** 36 <= 36 * 2 ** (2 * COMMON_EXPONENT):
        raise ValueError("exact rounding norm exceeds 10^-18")

    # Verify the common-scale identity independently using Fraction at sensitive
    # support/chunk boundaries, not only the integer implementation itself.
    probe = set(range(100))
    for edge in [1024, count_levels(26), count_levels(46), count_levels(91)]:
        probe.update(k for k in range(edge - 2, edge + 2) if 0 <= k < len(residual))
    rational_at = lambda values, k: Fraction(*((values[k][0], 2 ** values[k][1]))) if k < len(values) else Fraction()
    for k in probe:
        direct = (rational_at(centers[1], k) + rational_at(centers[2], k) / 2
                  + rational_at(centers[3], k) / 6 - rational_at(frozen_retained, k))
        if direct != Fraction(residual[k], denominator):
            raise ValueError(f"scaling identity failed at {k}")

    # Bind the reused production c3 literal to this same complete source.
    third_data = (repo / "Grothe/UpperChaos/TaylorBandData.lean").read_text()
    import re
    block = third_data.split("def thirdCenterPacked : String :=", 1)[1].split("[", 1)[1].split("\n]", 1)[0]
    original_records = ",".join(re.findall(r'"([^"\\]*)"', block)).split(",")
    production_third = [tuple(map(int, rec.split(":"))) for rec in original_records]
    if production_third != centers[3]:
        raise ValueError("production thirdCenterPacked does not match recovered c3 source")

    outputs = {}
    module_info = {}
    for name, filename, values, source_name, source_count, degree in [
        ("firstCenter", "TaylorFirstData.lean", centers[1], "arb_first_phase_D181.npz", original_counts[1], 181),
        ("secondCenter", "TaylorSecondData.lean", centers[2], "arb_phase_power2_D151.npz", original_counts[2], 91),
        ("frozenCorrection", "TaylorFrozenData.lean", frozen_retained, vf, len(frozen), 181),
    ]:
        outputs[filename], module_info[name] = data_module(
            name, values, sources[source_name], source_count, degree)
    receipt = {
        "agent_id": "codex-2ca4", "scope": "Exact source arithmetic receipt; the Lean certificate checks the same concrete coefficient function",
        "common_exponent": COMMON_EXPONENT,
        "logical_source_counts": {"c1": len(centers[1]), "c2": len(centers[2]), "c3": len(centers[3]), "v": len(frozen)},
        "retained_level_counts": {"c1": 91, "c2": 46, "c3": 26, "v": 91},
        "frozen_zero_coefficients_above_181": len(frozen) - len(frozen_retained),
        "source3_reused": sources["arb_phase_power3_D51.npz"],
        "source3_production_literal_matches": True,
        "integer_residual": "6*A1[k] + 3*A2[k] + A3[k] - 6*V[k], all A at scale 2^206; zero beyond each retained support",
        "residual_integer_sum_squares": str(integer_sum),
        "rounding_energy": str(energy),
        "rounding_norm_decimal_for_orientation": math.sqrt(float(energy)),
        "integer_check": "sumSquares * 10^36 <= 36 * 2^412",
        "integer_check_passed": True,
        "integer_check_slack": str(36 * 2 ** 412 - integer_sum * 10 ** 36),
        "new_data_modules": module_info,
        "no_duplicate_residual_coefficients": True,
        "no_duplicate_c3_coefficients": True,
    }
    outputs["TaylorRoundingData.lean"] = "\n".join([
        "import Mathlib.Data.Int.Basic", "",
        "/-! Generated by tools/gen_taylor_rounding_data.py. Agent-ID: codex-2ca4. -/",
        "namespace Grothe.UpperChaos", "",
        "/-- Exact integer sum of squares of the scaled rounding coefficients. -/",
        f"def roundingIntegerEnergy : ℤ := {integer_sum}", "",
        "end Grothe.UpperChaos", "",
    ])
    outputs["rounding-audit.json"] = json.dumps(receipt, indent=2) + "\n"
    return outputs, receipt


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--repo", type=Path, default=REPO)
    p.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    outputs, receipt = generated(args.repo)
    if not args.check:
        args.output.mkdir(parents=True, exist_ok=True)
    for name, wanted in outputs.items():
        path = (args.repo / "data/taylor-approximants/rounding.json"
                if name == "rounding-audit.json" and args.output == DEFAULT_OUTPUT
                else args.output / name)
        if args.check:
            if not path.exists() or path.read_text() != wanted:
                raise SystemExit(f"stale generated rounding data: {path}")
        else:
            path.write_text(wanted)
    print(json.dumps({"agent_id": "codex-2ca4", "output": str(args.output),
                      "rounding_norm": receipt["rounding_norm_decimal_for_orientation"],
                      "integer_check_passed": receipt["integer_check_passed"],
                      "module_bytes": {k: v["lean_bytes"] for k, v in receipt["new_data_modules"].items()}}, indent=2))


if __name__ == "__main__":
    main()
