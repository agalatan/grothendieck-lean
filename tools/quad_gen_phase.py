#!/usr/bin/env python3
"""Inputs of the twisted node loop (`quadrun twist*`, docs/UPPER_CLOSURE.md §8.2).

    python3 tools/quad_gen_phase.py            # data/quad-checker/phase.txt from Grothe/Upper/Data.lean
    python3 tools/quad_gen_phase.py --centers  # handoff/quad-checker/center-{1,2,3}.txt from the npz centers

`phase.txt`: one line `i j k num den` per monomial `C U^i V^j W^k` of `phaseStrs` (exact).
`center-j.txt`: one line `q c d m e` per center coefficient, value `m * 2^-e` (the binary64 values
of `data/taylor-approximants/inputs/*.npz` are exact dyadics; the same numbers as the packed Lean
data `firstCenterAt`/`secondCenterAt`/`thirdCenterAt`).

Agent-ID: claude-b9ee. Refs #41, #313.
"""
import argparse
import os
import re
import sys
from fractions import Fraction

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CENTER_FILES = {1: ("arb_first_phase_D181.npz", 91), 2: ("arb_phase_power2_D151.npz", 46),
                3: ("arb_phase_power3_D51.npz", 26)}


def phase_terms(root):
    with open(os.path.join(root, "Grothe/Upper/Data.lean"), encoding="utf-8") as f:
        src = f.read()
    m = re.search(r"def phaseStrs : List String := \[(.*?)\]", src, re.S)
    out = []
    for i, j, k, num, den in re.findall(r'"(\d+),(\d+),(\d+):(-?\d+)/(\d+)"', m.group(1)):
        out.append((int(i), int(j), int(k), int(num), int(den)))
    return out


def write_phase(root):
    terms = phase_terms(root)
    path = os.path.join(root, "data/quad-checker/phase.txt")
    with open(path, "w", encoding="utf-8") as f:
        f.write("# i j k num den : the monomials C U^i V^j W^k of phaseStrs (Grothe/Upper/Data.lean); "
                "generated by tools/quad_gen_phase.py\n")
        for i, j, k, num, den in terms:
            f.write(f"{i} {j} {k} {num} {den}\n")
    print(f"wrote {path}: {len(terms)} terms, max degree {max(i + j + k for i, j, k, _, _ in terms)}")


def write_centers(root):
    import numpy as np
    outdir = os.path.join(root, "handoff/quad-checker")
    os.makedirs(outdir, exist_ok=True)
    for j, (name, Q) in CENTER_FILES.items():
        z = np.load(os.path.join(root, "data/taylor-approximants/inputs", name))
        flat = z["center"].astype(np.float64)
        path = os.path.join(outdir, f"center-{j}.txt")
        n = 0
        emax = 0
        with open(path, "w", encoding="utf-8") as f:
            off = 0
            for q in range(Q):
                for c in range(q + 2):
                    for d in range(q + 1):
                        x = float(flat[off])
                        off += 1
                        if x == 0.0:
                            continue
                        fr = Fraction(x)
                        den = fr.denominator
                        e = den.bit_length() - 1
                        assert den == 1 << e, (q, c, d, x)
                        emax = max(emax, e)
                        f.write(f"{q} {c} {d} {fr.numerator} {e}\n")
                        n += 1
        print(f"wrote {path}: {n} nonzero of {off} coefficients (grades < {Q}), max exponent {emax}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=ROOT)
    ap.add_argument("--centers", action="store_true")
    args = ap.parse_args()
    write_phase(args.root)
    if args.centers:
        write_centers(args.root)


if __name__ == "__main__":
    main()
