#!/usr/bin/env python3
"""Generate the root import files Grothe.lean, GrotheKernel.lean and GrotheCapsKernel.lean (one import per line, sorted).

Every module file under Grothe/ (resp. GrotheKernel/) is imported, except those listed in
data/root-imports-exclude.txt (modules of the separate target GrotheCaps, and a few kernel modules built through
Grothe.Upper). So a delivery never edits the root files by hand: a new module is picked up by rerunning
    python3 tools/gen_root_imports.py            # rewrite the root files
and CI runs
    python3 tools/gen_root_imports.py --check    # exit 1 if a root file is not the generated one
Without --check it also re-sorts and de-duplicates the union-merged list files (union merge may leave the two
sides' new lines out of order). So after any merge: rerun it, and a conflict in a root file is resolved too.

--check also checks the list files that git union-merges (.gitattributes): data/root-imports-exclude.txt,
data/axioms/native.txt, data/axioms/required.txt, data/axioms/modes/*.txt (sorted, no duplicates) and the `#print axioms` lines of
scratch/Axioms.lean and scratch/AxiomsCaps.lean (sorted, no duplicates, imports first).
"""
import glob, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXCLUDE = os.path.join(ROOT, "data", "root-imports-exclude.txt")
HEADER = "-- Root of the {lib} library: generated by tools/gen_root_imports.py; do not edit.\n"
SORTED_LISTS = ["data/root-imports-exclude.txt", "data/axioms/native.txt", "data/axioms/required.txt"] + sorted(
    os.path.relpath(path, ROOT) for path in glob.glob(os.path.join(ROOT, "data", "axioms", "modes", "*.txt")))
AXIOM_REPORTS = ["scratch/Axioms.lean", "scratch/AxiomsCaps.lean"]


def entries(path):
    """Non-comment, non-empty lines of a list file."""
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return [l.split("#", 1)[0].strip() for l in f if l.split("#", 1)[0].strip()]


def modules(lib):
    out = []
    for d, _, files in os.walk(os.path.join(ROOT, lib)):
        for f in files:
            if f.endswith(".lean"):
                rel = os.path.relpath(os.path.join(d, f), ROOT)[:-5]
                out.append(rel.replace(os.sep, "."))
    return out


def generated(lib, excluded):
    mods = sorted(m for m in modules(lib) if m not in excluded)
    return HEADER.format(lib=lib) + "".join(f"import {m}\n" for m in mods)


def list_problems():
    problems = []
    for path in SORTED_LISTS:
        if not os.path.exists(os.path.join(ROOT, path)):
            problems.append(f"{path}: missing")
            continue
        e = entries(path)
        if len(e) != len(set(e)):
            problems.append(f"{path}: duplicate entries {sorted({x for x in e if e.count(x) > 1})}")
        if e != sorted(e):
            problems.append(f"{path}: not sorted")
    for path in AXIOM_REPORTS:
        with open(os.path.join(ROOT, path), encoding="utf-8") as f:
            lines = [l.rstrip("\n") for l in f if l.strip()]
        imports = [l for l in lines if l.startswith("import ")]
        prints = [l for l in lines if l.startswith("#print axioms ")]
        other = [l for l in lines if l not in imports and l not in prints]
        if lines[:len(imports)] != imports:
            problems.append(f"{path}: imports must come first")
        if other:
            problems.append(f"{path}: unexpected lines {other[:3]}")
        if len(prints) != len(set(prints)):
            problems.append(f"{path}: duplicate #print axioms lines")
        if prints != sorted(prints):
            problems.append(f"{path}: #print axioms lines not sorted")
    return problems


def normalize_lists():
    """Sort and de-duplicate the list files in place (comments/header lines first, kept as they are)."""
    for path in SORTED_LISTS:
        full = os.path.join(ROOT, path)
        if not os.path.exists(full):
            continue
        with open(full, encoding="utf-8") as f:
            lines = [l.rstrip("\n") for l in f]
        head = [l for l in lines if l.strip().startswith("#") or not l.strip()]
        body = sorted({l.strip() for l in lines if l.strip() and not l.strip().startswith("#")})
        new = "\n".join([h for h in head if h.strip()] + body) + "\n"
        if new != "\n".join(lines) + "\n":
            with open(full, "w", encoding="utf-8") as f:
                f.write(new)
            print(f"sorted {path}")
    for path in AXIOM_REPORTS:
        full = os.path.join(ROOT, path)
        with open(full, encoding="utf-8") as f:
            lines = [l.rstrip("\n") for l in f if l.strip()]
        imports = sorted({l for l in lines if l.startswith("import ")})
        prints = sorted({l for l in lines if l.startswith("#print axioms ")})
        other = [l for l in lines if not l.startswith(("import ", "#print axioms "))]
        if other:
            continue  # leave unexpected content for --check to report
        new = "\n".join(imports) + "\n\n" + "\n".join(prints) + "\n"
        with open(full, encoding="utf-8") as f:
            old = f.read()
        if new != old:
            with open(full, "w", encoding="utf-8") as f:
                f.write(new)
            print(f"sorted {path}")


def main():
    check = "--check" in sys.argv[1:]
    if [a for a in sys.argv[1:] if a != "--check"]:
        print(f"usage: {sys.argv[0]} [--check]")
        return 2
    excluded = set(entries("data/root-imports-exclude.txt"))
    missing = sorted(m for m in excluded if not os.path.exists(os.path.join(ROOT, *m.split(".")) + ".lean"))
    bad = [f"data/root-imports-exclude.txt: no such module {m}" for m in missing]
    for lib in ["Grothe", "GrotheKernel", "GrotheCapsKernel"]:
        path = os.path.join(ROOT, f"{lib}.lean")
        want = generated(lib, excluded)
        have = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                have = f.read()
        if have != want:
            if check:
                bad.append(f"{lib}.lean is not the generated file: run python3 tools/gen_root_imports.py")
            else:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(want)
                print(f"wrote {lib}.lean ({want.count('import ')} imports)")
    if check:
        bad += list_problems()
    else:
        normalize_lists()
    for b in bad:
        print("FAIL:", b)
    if not bad:
        print("root import files and list files are up to date" if check else "done")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
