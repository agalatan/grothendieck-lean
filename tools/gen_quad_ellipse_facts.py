#!/usr/bin/env python3
"""Generate the native shard facts of the ellipse checker (claude-b9ee, #303):
Grothe/UpperQuad/QuadEllipseFacts/ShardNN.lean (one `native_decide` each, so Lake runs them in
parallel) and Grothe/UpperQuad/QuadEllipseFacts/All.lean (their combination).  The shard budgets are
equal shares of 1.04e-12 (the target of `quadRemainderHyp_of_panels` is 1.06e-12).
Usage: tools/gen_quad_ellipse_facts.py [--shards K]"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
N = 1289
K = int(sys.argv[sys.argv.index('--shards') + 1]) if '--shards' in sys.argv else 8
size = (N + K - 1) // K
shards = []
i = 0
while i < N:
    shards.append((i, min(size, N - i)))
    i += size
# budget per shard: 104/10^15 * 10 / K  ->  total 1.04e-12
bnum, bden = 104 * 10, K * 10 ** 15
d = os.path.join(ROOT, 'Grothe', 'UpperQuad', 'QuadEllipseFacts')
os.makedirs(d, exist_ok=True)
for k, (i0, ln) in enumerate(shards):
    open(os.path.join(d, 'Shard%02d.lean' % k), 'w').write(f'''import Grothe.UpperQuad.QuadEllipsePlans

/-!
# Ellipse checker, shard {k}: panels {i0}–{i0 + ln - 1} (generated by `tools/gen_quad_ellipse_facts.py`)

Agent-ID: claude-b9ee. Refs #303.
-/

namespace Grothe.UpperQuad.EllCheck

/-- The native check of the panels `[{i0}, {i0 + ln})` with their plans:
error sum `< {bnum}/{bden}`. -/
theorem shard{k:02d} : shardOK plans {i0} {ln} ({bnum} / {bden}) = true := by native_decide

end Grothe.UpperQuad.EllCheck
''')
imports = '\n'.join('import Grothe.UpperQuad.QuadEllipseFacts.Shard%02d' % k for k in range(len(shards)))
steps = []
acc_len = 0
lines = []
lines.append('theorem allShards : ∃ f : ℕ → ℝ, (∀ k, k < %d →' % N)
lines.append('    PanelGood (Grothe.UpperChaos.Q0GaussAddressScan.sourcePanels.getD (0 + k) default) (f k)) ∧')
lines.append('    ∑ k ∈ Finset.range %d, f k < ((%d : ℕ) : ℝ) * (((%d / %d : ℚ)) : ℝ) := by' % (N, len(shards), bnum, bden))
# chain merges
first = True
for k, (i0, ln) in enumerate(shards):
    if first:
        lines.append('  have h0 := shardOK_sound shard00')
        lines.append('  simp only [zero_add] at h0 ⊢')
        lines.append('  have m0 : ∃ f : ℕ → ℝ, (∀ k, k < %d → PanelGood' % ln)
        lines.append('      (Grothe.UpperChaos.Q0GaussAddressScan.sourcePanels.getD k default) (f k)) ∧')
        lines.append('      ∑ k ∈ Finset.range %d, f k < ((1 : ℕ) : ℝ) * (((%d / %d : ℚ)) : ℝ) := by' % (ln, bnum, bden))
        lines.append('    simpa using h0')
        acc_len = ln
        first = False
    else:
        lines.append('  have m%d := merge_shards %d %d (shardOK_sound shard%02d) m%d rfl' % (k, acc_len, ln, k, k - 1))
        acc_len += ln
lines.append('  simpa using m%d' % (len(shards) - 1))
TEMPLATE = '''{imports}
import Grothe.UpperQuad.QuadRemainderFinal

/-!
# The ellipse checker over all panels (generated by `tools/gen_quad_ellipse_facts.py`)

The {len(shards)} shard facts combine to `PanelGood` for all {N} source panels with total error
`< {len(shards)} · {bnum}/{bden} ≤ 1.06·10⁻¹²`, hence `QuadRemainderHyp`.

Agent-ID: claude-b9ee. Refs #303.
-/

namespace Grothe.UpperQuad.EllCheck

open Grothe.UpperQuad Grothe.UpperQuad.QuadRem

/-- Two consecutive shards merge. -/
lemma merge_shards (a b : ℕ) {B₁ B₂ : ℚ} {n₁ : ℕ}
    (h2 : ∃ g : ℕ → ℝ, (∀ k, k < b →
      PanelGood (Grothe.UpperChaos.Q0GaussAddressScan.sourcePanels.getD (a + k) default) (g k)) ∧
      ∑ k ∈ Finset.range b, g k < (B₂ : ℝ))
    (h1 : ∃ f : ℕ → ℝ, (∀ k, k < a →
      PanelGood (Grothe.UpperChaos.Q0GaussAddressScan.sourcePanels.getD k default) (f k)) ∧
      ∑ k ∈ Finset.range a, f k < (n₁ : ℝ) * (B₁ : ℝ)) (hB : B₂ = B₁) :
    ∃ h : ℕ → ℝ, (∀ k, k < a + b →
      PanelGood (Grothe.UpperChaos.Q0GaussAddressScan.sourcePanels.getD k default) (h k)) ∧
      ∑ k ∈ Finset.range (a + b), h k < ((n₁ + 1 : ℕ) : ℝ) * (B₁ : ℝ) := by
  obtain ⟨f, hf, hfs⟩ := h1
  obtain ⟨g, hg, hgs⟩ := h2
  refine ⟨fun k => if k < a then f k else g (k - a), fun k hk => ?_, ?_⟩
  · by_cases hka : k < a
    · simp only [hka, ite_true]; exact hf k hka
    · simp only [hka, ite_false]
      have := hg (k - a) (by omega)
      rwa [show a + (k - a) = k by omega] at this
  · rw [Finset.sum_range_add]
    have e1 : ∑ k ∈ Finset.range a, (if k < a then f k else g (k - a)) =
        ∑ k ∈ Finset.range a, f k :=
      Finset.sum_congr rfl fun k hk => by simp [Finset.mem_range.mp hk]
    have e2 : ∑ k ∈ Finset.range b, (if a + k < a then f (a + k) else g (a + k - a)) =
        ∑ k ∈ Finset.range b, g k :=
      Finset.sum_congr rfl fun k _ => by simp
    rw [e1, e2]
    subst hB
    push_cast
    linarith

{chr(10).join(lines)}

/-- **`QuadRemainderHyp`, proved** (the Gauss–Legendre remainders on the covered set). -/
theorem quadRemainderHyp : QuadRemainderHyp := by
  obtain ⟨f, hf, hs⟩ := allShards
  have hN : Grothe.UpperChaos.Q0GaussAddressScan.sourcePanels.length = {N} := by decide +kernel
  apply quadRemainderHyp_of_panels (fun p => f p.val)
  · intro p
    have := hf p.val (by rw [← hN]; exact p.isLt)
    rwa [List.getD_eq_getElem?_getD, List.getElem?_eq_getElem p.isLt, Option.getD_some] at this
  · rw [Fin.sum_univ_eq_sum_range (fun k => f k), hN]
    have : (({len(shards)} : ℕ) : ℝ) * ((({bnum} / {bden} : ℚ)) : ℝ) ≤ (106 : ℝ) / 10 ^ 14 := by
      norm_num
    push_cast at hs this
    linarith

end Grothe.UpperQuad.EllCheck
'''
text = (TEMPLATE.replace('{imports}', imports).replace('{N}', str(N))
        .replace('{len(shards)}', str(len(shards))).replace('{bnum}', str(bnum))
        .replace('{bden}', str(bden)).replace('{chr(10).join(lines)}', chr(10).join(lines)))
open(os.path.join(d, 'All.lean'), 'w').write(text)
print('wrote', len(shards), 'shards')
