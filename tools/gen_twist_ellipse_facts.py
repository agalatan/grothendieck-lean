#!/usr/bin/env python3
"""Generate native twisted-ellipse shard/total statements and registration manifest.

Agent-ID: codex-40e8. Refs #343.
Requires complete validated plans and their current generated Lean arrays. Budgets
come from the input's exact relaxed_radii minus tail_gap_reserve, never defaults in
this script. --budgets optionally checks that those recorded inputs equal the
caller's expected budgets. Generated native_decide statements still need Lean to
execute them; no analytic remainder theorem is generated. Shared axiom registries
are never edited. Root registers the reproducible facts-registration.json entries.
"""
from __future__ import annotations

import argparse
from fractions import Fraction as Q
import hashlib
import json
from pathlib import Path
import re
import sys

import gen_twist_ellipse_plans as plans

ROOT = Path(__file__).resolve().parents[1]
SHARD_SIZE = 64
NAMESPACE = "Grothe.UpperQuad.TwistEllCheck.Facts"
MODULE = "Grothe.UpperQuad.TwistEllipseFacts"
PLANS_MODULE = "Grothe.UpperQuad.TwistEllipsePlans"
NATIVE_SUFFIX = "._native.native_decide.ax_1_1"


def budgets_from_data(data, expected=None):
    radii = data.get("relaxed_radii")
    if not isinstance(radii, list) or len(radii) != 3 or "tail_gap_reserve" not in data:
        raise ValueError("input must record three relaxed_radii and exact tail_gap_reserve")
    radii = [plans.rational(q, f"relaxed_radii[{i}]") for i, q in enumerate(radii)]
    reserve = plans.rational(data["tail_gap_reserve"], "tail_gap_reserve")
    if reserve < 0 or any(radius <= reserve for radius in radii):
        raise ValueError("require nonnegative reserve and each relaxed radius > reserve")
    budgets = [radius-reserve for radius in radii]
    if expected is not None:
        values = expected.split(",")
        if len(values) != 3:
            raise ValueError("--budgets requires three exact expected budgets")
        if [plans.rational(q, "expected budget") for q in values] != budgets:
            raise ValueError("--budgets disagrees with the exact recorded radius-minus-reserve budgets")
    return radii, reserve, budgets


def ranges(count):
    plans.integer(count, "source panel count", 1)
    return [(first, min(first + SHARD_SIZE, count)) for first in range(0, count, SHARD_SIZE)]


def header(input_sha256):
    return [f"import {PLANS_MODULE}", "", "/-! Generated by tools/gen_twist_ellipse_facts.py.",
            f"Input plans SHA256: {input_sha256}",
            "Lean must execute this finite check; analytic identification remains separate.",
            "Agent-ID: codex-40e8. Refs #343. -/", "", "set_option maxRecDepth 8192", "",
            f"namespace {NAMESPACE}", "", "open Grothe.UpperQuad.TwistEllCheck", ""]


def render(rows, count, budgets, input_sha256):
    """Render only computational statements; never an analytic/aggregate All theorem."""
    expected = {(i, j) for i in range(count) for j in (1, 2, 3)}
    keys = [(row.panel, row.j) for row in rows]
    if len(keys) != len(expected) or set(keys) != expected:
        raise ValueError("facts require unique complete source-panel coverage for all three powers")
    if len(budgets) != 3 or any(type(q) is not Q or q <= 0 for q in budgets):
        raise ValueError("facts require three positive exact Fraction budgets")
    totals = [sum((row.error_cap for row in rows if row.j == j), Q(0)) for j in (1, 2, 3)]
    if any(total > budget for total, budget in zip(totals, budgets)):
        raise ValueError("exact errorCap total exceeds a recorded panel budget")
    files, entries = {}, []
    for j in (1, 2, 3):
        for shard, (first, stop) in enumerate(ranges(count)):
            stem, fact = f"J{j}Range{shard:02d}", f"j{j}Range{shard:02d}"
            lines = header(input_sha256) + [
                f"/-- Power {j}, source panels [{first}, {stop}); half-open endpoints. -/",
                f"theorem {fact} :",
                f"    shardOK ({j-1} : Power) {first} {stop} j{j}Certificates = true := by",
                "  native_decide", "", f"end {NAMESPACE}", ""]
            files[stem + ".lean"] = "\n".join(lines)
            entries.append({"kind": "range", "j": j, "first": first, "stop": stop,
                            "module": MODULE + "." + stem, "theorem": NAMESPACE + "." + fact})
        stem, fact = f"J{j}Total", f"j{j}Total"
        lines = header(input_sha256) + [
            "/-- Exact cap total against the recorded relaxed radius minus tail/gap reserve. -/",
            f"theorem {fact} :",
            f"    totalOK j{j}Certificates {plans.lean_q(budgets[j-1])} = true := by",
            "  native_decide", "", f"end {NAMESPACE}", ""]
        files[stem + ".lean"] = "\n".join(lines)
        entries.append({"kind": "total", "j": j, "budget": str(budgets[j-1]),
                        "module": MODULE + "." + stem, "theorem": NAMESPACE + "." + fact})
    files["Checks.lean"] = "\n".join(
        ["import " + entry["module"] for entry in entries] + ["",
         "/-! Imports all generated twisted-ellipse finite checks. No aggregate or analytic theorem.",
         f"Input plans SHA256: {input_sha256}", "Agent-ID: codex-40e8. Refs #343. -/", ""])
    for entry in entries:
        entry["native_axiom"] = entry["theorem"] + NATIVE_SUFFIX
    return files, entries, totals


def registration(files, entries, count, radii, reserve, budgets, totals, input_sha256, source_hashes):
    return {
        "agent": "codex-40e8", "task": 343,
        "status": "generated statements; native execution and axiom inventory require Lean verification",
        "input_sha256": input_sha256, "production_source_sha256": source_hashes,
        "panel_count": count, "shard_size": SHARD_SIZE,
        "relaxed_radii": [str(q) for q in radii], "tail_gap_reserve": str(reserve),
        "panel_budgets": [str(q) for q in budgets], "errorCap_sums": [str(q) for q in totals],
        "budget_source": "input relaxed_radii[j-1] - input tail_gap_reserve",
        "facts": entries,
        "native_txt_additions": sorted(entry["native_axiom"] for entry in entries),
        "axioms_lean_import": "import " + MODULE + ".Checks",
        "axioms_lean_additions": sorted("#print axioms " + entry["theorem"] for entry in entries),
        "generated_sha256": {name: hashlib.sha256(text.encode()).hexdigest()
                             for name, text in sorted(files.items())},
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--repo", type=Path, default=ROOT)
    ap.add_argument("--input", type=Path)
    ap.add_argument("--output", type=Path, help="directory for generated Lean fact modules")
    ap.add_argument("--registration", type=Path, help="output registration JSON; shared registries stay untouched")
    ap.add_argument("--plans-module", type=Path, help="current generated plans Lean file; checked byte-for-byte")
    ap.add_argument("--check", action="store_true", help="compare all outputs without writing")
    ap.add_argument("--require-source-hashes", action="store_true")
    ap.add_argument("--budgets", help="optional expected q1,q2,q3; must match the input's recorded budgets")
    args = ap.parse_args(argv)
    source = args.input or args.repo / "data/twist-ellipse/plans.json"
    output = args.output or args.repo / "Grothe/UpperQuad/TwistEllipseFacts"
    reg = args.registration or args.repo / "data/twist-ellipse/facts-registration.json"
    plan_file = args.plans_module or args.repo / "Grothe/UpperQuad/TwistEllipsePlans.lean"
    try:
        if not source.is_file():
            raise ValueError(f"missing plan input: {source}; final verified plans are required")
        raw = source.read_bytes()
        data = plans.parse_json(raw.decode("utf-8"))
        panels = plans.read_panels(args.repo)
        rows = plans.validate_plans(data, panels)
        if args.require_source_hashes:
            plans.check_provenance(data, args.repo)
        radii, reserve, budgets = budgets_from_data(data, args.budgets)
        input_hash = hashlib.sha256(raw).hexdigest()
        expected_plans = plans.render(rows, input_hash)
        if not plan_file.is_file() or plan_file.read_text() != expected_plans:
            raise ValueError("generated plans module is missing/stale; run gen_twist_ellipse_plans.py first")
        files, entries, totals = render(rows, len(panels), budgets, input_hash)
        hashes = {name: hashlib.sha256((args.repo / name).read_bytes()).hexdigest()
                  for name in (plans.ADDRESS, plans.SCAN)}
        manifest = registration(files, entries, len(panels), radii, reserve, budgets,
                                totals, input_hash, hashes)
        manifest["plans_module_sha256"] = hashlib.sha256(expected_plans.encode()).hexdigest()
        manifest["generator_source_sha256"] = {
            "tools/gen_twist_ellipse_facts.py": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            "tools/gen_twist_ellipse_plans.py": hashlib.sha256(Path(plans.__file__).read_bytes()).hexdigest(),
        }
        reg_text = json.dumps(manifest, sort_keys=True, indent=2) + "\n"
        targets = {output / name: text for name, text in files.items()}
        if reg.resolve() in {source.resolve(), plan_file.resolve()} or reg.resolve() in {p.resolve() for p in targets}:
            raise ValueError("registration output overlaps an input or a generated Lean file")
        protected = {source.resolve(), plan_file.resolve(),
                     (args.repo / "data/axioms/native.txt").resolve(),
                     (args.repo / "scratch/Axioms.lean").resolve()}
        if reg.resolve() in protected or any(path.resolve() in protected for path in targets):
            raise ValueError("output overlaps an input or protected shared registry")
        expected_names = set(files)
        if output.is_dir():
            existing = {path.name for path in output.iterdir()
                        if re.fullmatch(r"J[123](?:Range[0-9]+|Total)\.lean|Checks\.lean", path.name)}
            if existing - expected_names:
                raise ValueError(f"unexpected stale generated modules: {sorted(existing-expected_names)}")
        targets[reg] = reg_text
        if args.check:
            stale = [str(path) for path, text in targets.items() if not path.is_file() or path.read_text() != text]
            if stale:
                raise ValueError(f"generated facts missing/stale: {stale[:5]}")
        else:
            for path, text in targets.items():
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
        print(json.dumps({"status": "checked" if args.check else "generated", "panels": len(panels),
                          "range_facts": len(entries)-3, "total_facts": 3,
                          "panel_budgets": [str(q) for q in budgets],
                          "errorCap_sums": [str(q) for q in totals], "registration": str(reg)}))
        return 0
    except (OSError, ValueError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
