#!/usr/bin/env python3
"""Generate Grothe/Lower/ChordData.lean: lifted node caps and chord-domination certificates for
all 365 (source + imported) physical polynomials, aligned with `polyGroupsV2` (exact rationals)."""
import json
from fractions import Fraction as Q
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIFT = Q(1, 10**8)
src = json.load(open(ROOT / "handoff" / "data" / "lower-source-profiles.json"))["groups"]
extra = json.load(open(ROOT / "handoff" / "lower-import" / "combined-polynomials.json"))

def q(x) -> str:
    x = Q(x)
    return f"({x.numerator} : ℚ) / {x.denominator}" if x.denominator != 1 else f"({x.numerator} : ℚ)"
def qs(x) -> str:
    x = Q(x)
    return f"{x.numerator}/{x.denominator}" if x.denominator != 1 else f"{x.numerator}"

out = ["import Grothe.Lower.Chords\nimport Grothe.Lower.ProfileDataV2\n\n/-!\n# Chord-domination data (generated by `tools/gen_chord_data.py`; do not edit)\n\n"
       "`chordPts_g` are the lifted node caps `(r, cap + 10⁻⁸)` of source group `g`; `chordCerts_g`\n"
       "are the certificates aligned with `polyGroupV2_g` (cells encoded as `hi:idx;…`).\n-/\n\nnamespace Grothe.Lower\n\n"]
npts = []; ncerts = []
for gi, g in enumerate(src):
    pts = [(Q(p["r"]), Q(p["cap"]) + LIFT) for p in g["points"]]
    assert pts[0][0] == 0 and all(a[0] < b[0] for a, b in zip(pts, pts[1:]))
    out.append(f"/-- Lifted node caps of source group {gi} (`{g['profile']['id']}`). -/\ndef chordPts_{gi} : List (ℚ × ℚ) :=\n[" +
               ",\n".join(f"  ({q(r)}, {q(c)})" for r, c in pts) + "]\n\n")
    recs = g["polynomials"] + extra.get(g["profile"]["id"], [])
    certs = []
    for rec in recs:
        ph = rec["physical"]
        prev = Q(0); cells = []
        for lo, hi, idx in ph["cells"]:
            assert Q(lo) == prev; prev = Q(hi); cells.append(f"{qs(hi)}:{idx}")
        assert prev == Q(ph["tail_start"])
        certs.append(f"  ⟨{q(ph['tail_start'])}, {ph['tail_index']}, \"{';'.join(cells)}\"⟩")
    out.append(f"/-- Chord certificates of group {gi}, aligned with `polyGroupV2_{gi}`. -/\ndef chordCerts_{gi} : List PhysCert :=\n[" + ",\n".join(certs) + "]\n\n")
    npts.append(len(pts)); ncerts.append(len(certs))
out.append("/-- All node-cap lists. -/\ndef chordPts : List (List (ℚ × ℚ)) :=\n  [" + ", ".join(f"chordPts_{i}" for i in range(len(src))) + "]\n\n")
out.append("/-- All certificate lists. -/\ndef chordCerts : List (List PhysCert) :=\n  [" + ", ".join(f"chordCerts_{i}" for i in range(len(src))) + "]\n\nend Grothe.Lower\n")
(ROOT / "Grothe" / "Lower" / "ChordData.lean").write_text("".join(out))
print("ok pts", npts, "certs", ncerts, "total", sum(ncerts))
