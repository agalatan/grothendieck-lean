#!/usr/bin/env python3
"""Generate exact packed dyadic Taylor centers and finite band-norm targets.

All source bytes are pinned by the manifest. The generated data define finite
Hermite vectors; they do not certify Gaussian approximation error bounds.
"""

import argparse
import hashlib
import json
import math
from fractions import Fraction
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/taylor-approximants"
OUTPUT = ROOT / "Grothe/UpperChaos/TaylorBandData.lean"
CERTIFICATE = DATA / "third-center.json"
BANDS = [(0, 11), (11, 21), (21, 31), (31, 51)]


def count_through(degree):
    n = (degree + 1) // 2
    return n * (n + 1) * (n + 2) // 3


def norm_interval(energy):
    scale = 10 ** 30
    floor = math.isqrt(energy.numerator * scale * scale // energy.denominator)
    lower, upper = Fraction(floor, scale), Fraction(floor + 1, scale)
    assert 0 < lower and lower * lower <= energy < upper * upper
    return lower, upper


def literal(q):
    return f"({q.numerator} / {q.denominator})"


def generated():
    manifest = json.loads((DATA / "manifest.json").read_text())
    sources = {}
    for item in manifest["inputs"]:
        path = DATA / item["path"]
        raw = path.read_bytes()
        if len(raw) != item["size_bytes"] or hashlib.sha256(raw).hexdigest() != item["sha256"]:
            raise ValueError(f"source hash/size mismatch: {path.name}")
        sources[path.name] = item
    name = "arb_phase_power3_D51.npz"
    with np.load(DATA / sources[name]["path"], allow_pickle=False) as archive:
        center = archive["center"]
        if center.dtype != np.dtype("<f8") or center.shape != (count_through(51),):
            raise ValueError("unexpected third-center binary64 encoding or shape")
        if not np.isfinite(center).all():
            raise ValueError("nonfinite center coefficient")
        values = [Fraction.from_float(float(x)) for x in center]

    indices = [((q + 1 - c, q - d), (c, d))
               for q in range(26) for c in range(q + 2) for d in range(q + 1)]
    if len(indices) != len(values) or len(set(indices)) != 6552:
        raise ValueError("invalid third-center enumeration")
    records = []
    exponents = []
    for value in values:
        exponent = value.denominator.bit_length() - 1
        if value.denominator != 2 ** exponent or abs(value.numerator) >= 2 ** 53:
            raise ValueError("coefficient is not a binary64 dyadic")
        records.append(f"{value.numerator}:{exponent}")
        exponents.append(exponent)
    exponent = max(exponents)
    assert exponent == 105
    # Independent round-trip through the packed format and common denominator.
    decoded = [int(r.split(":")[0]) * 2 ** (exponent - int(r.split(":")[1])) for r in records]
    assert [Fraction(m, 2 ** exponent) for m in decoded] == values
    energy = sum((x * x for x in values), Fraction())
    band_data = []
    for lo, hi in BANDS:
        start, stop = count_through(lo), count_through(hi)
        e = sum((x * x for x in values[start:stop]), Fraction())
        lower, upper = norm_interval(e)
        band_data.append((lo, hi, start, stop, e, lower, upper))
    assert sum((b[4] for b in band_data), Fraction()) == energy

    lines = ["import Grothe.UpperChaos.PackedDyadic",
        "import Grothe.UpperChaos.TaylorThirdIntegerData", "",
        "/-! Generated by tools/gen_taylor_band_data.py from data/taylor-approximants/inputs.",
        "Exact binary64 centers in the normalized Hermite basis; no Gaussian error claim. -/", "",
        "namespace Grothe.UpperChaos", "",
        "/-- Common dyadic denominator exponent for the third approximant. -/",
        f"def thirdCenterExponent : ℕ := {exponent}", "",
        "/-- Packed exact coefficients, one string per grade, in row-major order. -/",
        "def thirdCenterPacked : String := String.intercalate \",\" ["]
    for q in range(26):
        start, stop = q * (q + 1) * (q + 2) // 3, (q + 1) * (q + 2) * (q + 3) // 3
        lines.append('  "' + ",".join(records[start:stop]) + '"' + ("," if q < 25 else ""))
    lines += ["]", "",
        "/-- Authoritative exact integer coefficients from the ordered named grade arrays. -/",
        "def thirdCenterInts : Array ℤ :=",
        "  thirdCenterIntegerValues.toArray", "",
        "/-- Direct graded lookup of the unscaled third approximant's exact coefficient. -/",
        "def thirdCenterCoeff (q c d : ℕ) : ℚ :=",
        "  PackedDyadic.coeff thirdCenterExponent thirdCenterInts",
        "    (q * (q + 1) * (q + 2) / 3 + c * (q + 1) + d)", "",
        "/-- Exact total rational energy target. -/",
        f"def thirdCenterEnergyQ : ℚ := {literal(energy)}", ""]
    for label, typ, pos, doc in [
        ("Lo", "ℕ", 0, "Lower (excluded) total degree of each captured band."),
        ("Hi", "ℕ", 1, "Upper (included) total degree of each captured band."),
        ("EnergyQ", "ℚ", 4, "Exact rational energy targets for the four captured bands."),
        ("LowerQ", "ℚ", 5, "Rational lower enclosures of the four band norms."),
        ("UpperQ", "ℚ", 6, "Rational upper enclosures of the four band norms."),
    ]:
        lines += [f"/-- {doc} -/", f"def thirdCenterBand{label} : Fin 4 → {typ}"]
        for k, b in enumerate(band_data):
            pattern = str(k) if k < 3 else "_"
            val = literal(b[pos]) if typ == "ℚ" else str(b[pos])
            lines.append(f"  | {pattern} => {val}")
        lines.append("")
    lines += ["end Grothe.UpperChaos", ""]
    certificate = {
        "source_file": sources[name]["path"], "source_sha256": sources[name]["sha256"],
        "source_degree": 51, "coefficient_count": len(values), "denominator_exponent": exponent,
        "index_convention": "Cq[c,d] -> ((q+1-c,q-d),(c,d)); q, then c, then d",
        "basis": "normalized tensor Hermite hvec2", "scaling": "unscaled c3, without division by 6",
        "energy": str(energy),
        "bands": [dict(lo=b[0], hi=b[1], start=b[2], stop=b[3], energy=str(b[4]),
                       norm_lower=str(b[5]), norm_upper=str(b[6])) for b in band_data],
    }
    return "\n".join(lines), json.dumps(certificate, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    lean, certificate = generated()
    for path, wanted in [(OUTPUT, lean), (CERTIFICATE, certificate)]:
        if args.check:
            if not path.exists() or path.read_text() != wanted:
                raise SystemExit(f"stale generated file: {path.relative_to(ROOT)}")
        else:
            path.write_text(wanted)
    print("Taylor center data match the pinned binary64 source" if args.check
          else "generated the exact third center and all four band targets")


if __name__ == "__main__":
    main()
