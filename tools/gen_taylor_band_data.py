#!/usr/bin/env python3
"""Decode the preserved binary64 Taylor centers as exact dyadic rationals.

The first certificate is the third approximant's degree <= 11 band. All source
bytes are pinned by the manifest. This generator does not certify that the
centers approximate Gaussian integrals; Lean checks the finite vector's norm.
"""

import argparse
import hashlib
import json
import math
from fractions import Fraction
from pathlib import Path

import numpy as np


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/taylor-approximants"
OUTPUT = ROOT / "Grothe/UpperChaos/TaylorBandData.lean"
CERTIFICATE = DATA / "third-band11.json"


def count_through(degree):
    n = (degree + 1) // 2
    return n * (n + 1) * (n + 2) // 3


def generated():
    manifest = json.loads((DATA / "manifest.json").read_text())
    sources = {}
    for item in manifest["inputs"]:
        path = DATA / item["path"]
        raw = path.read_bytes()
        if len(raw) != item["size_bytes"] or hashlib.sha256(raw).hexdigest() != item["sha256"]:
            raise ValueError(f"source hash/size mismatch: {path.name}")
        sources[path.name] = item
    name = "arb_phase_power3_D51.npz"
    with np.load(DATA / sources[name]["path"], allow_pickle=False) as archive:
        center = archive["center"]
        if center.dtype != np.dtype("<f8") or center.shape != (count_through(51),):
            raise ValueError("unexpected third-center binary64 encoding or shape")
        if not np.isfinite(center).all():
            raise ValueError("nonfinite center coefficient")
        values = [Fraction.from_float(float(x)) for x in center[:count_through(11)]]

    # The package flattens Cq[c,d] in row-major order, q first.
    indices = [((q + 1 - c, q - d), (c, d))
               for q in range(6) for c in range(q + 2) for d in range(q + 1)]
    if len(indices) != len(values) or len(set(indices)) != 112:
        raise ValueError("invalid third-band enumeration")
    energy = sum((x * x for x in values), Fraction())
    scale = 10 ** 30
    floor = math.isqrt(energy.numerator * scale * scale // energy.denominator)
    lower, upper = Fraction(floor, scale), Fraction(floor + 1, scale)
    assert 0 < lower and lower * lower <= energy < upper * upper

    def literal(q):
        return f"({q.numerator} / {q.denominator})"

    lines = [
        "import Mathlib.Data.Rat.Defs", "",
        "/-! Generated by tools/gen_taylor_band_data.py from data/taylor-approximants/inputs.",
        "Exact binary64 centers in the normalized Hermite basis; no Gaussian error claim. -/", "",
        "namespace Grothe.UpperChaos", "",
        "/-- The third approximant's coefficients in total degrees 1, 3, ..., 11. -/",
        "def thirdBand11Terms : List (((ℕ × ℕ) × (ℕ × ℕ)) × ℚ) := [",
    ]
    for k, (index, value) in enumerate(zip(indices, values)):
        (p, q), (r, s) = index
        comma = "," if k + 1 < len(indices) else ""
        lines.append(f"  ((({p}, {q}), ({r}, {s})), {literal(value)}){comma}")
    lines += ["]", "",
              "/-- Exact rational squared norm target. -/",
              f"def thirdBand11EnergyQ : ℚ := {literal(energy)}", "",
              "/-- Rational lower enclosure of the norm. -/",
              f"def thirdBand11LowerQ : ℚ := {literal(lower)}", "",
              "/-- Rational upper enclosure of the norm. -/",
              f"def thirdBand11UpperQ : ℚ := {literal(upper)}", "",
              "end Grothe.UpperChaos", ""]
    certificate = {
        "source_file": sources[name]["path"], "source_sha256": sources[name]["sha256"],
        "source_degree": 51, "band": {"lo": 0, "hi": 11}, "coefficient_count": len(values),
        "index_convention": "Cq[c,d] -> ((q+1-c,q-d),(c,d)); q, then c, then d",
        "basis": "normalized tensor Hermite hvec2", "energy": str(energy),
        "norm_lower": str(lower), "norm_upper": str(upper),
    }
    return "\n".join(lines), json.dumps(certificate, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    lean, certificate = generated()
    for path, wanted in [(OUTPUT, lean), (CERTIFICATE, certificate)]:
        if args.check:
            if not path.exists() or path.read_text() != wanted:
                raise SystemExit(f"stale generated file: {path.relative_to(ROOT)}")
        else:
            path.write_text(wanted)
    print("Taylor band data match the pinned binary64 centers" if args.check
          else "generated the exact third-approximant band data and target")


if __name__ == "__main__":
    main()
