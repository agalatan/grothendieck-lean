#!/usr/bin/env python3
"""Generate the authoritative frozen witness as exact typed integer grades.

The pinned binary64 input is decoded twice: by Python's exact float ratio and
independently by sign/exponent/significand bits. No numerical error assertion is
made here. Lean checks use the generated named arrays directly.
Agent-ID: codex-7c2e.
"""
import argparse
import ast
import hashlib
import json
from pathlib import Path
import struct
import zipfile

REPO = Path(__file__).resolve().parents[1]
EXPONENT = 206
GRADES = 91
PART_SIZE = 64


def read_grade(archive, q):
    raw = archive.read(f'C{q}.npy')
    if raw[:6] != b'\x93NUMPY' or raw[6:8] not in (b'\x01\x00', b'\x02\x00', b'\x03\x00'):
        raise ValueError('Unsupported NPY header')
    width = 2 if raw[6] == 1 else 4
    length = int.from_bytes(raw[8:8 + width], 'little')
    start = 8 + width
    header = ast.literal_eval(raw[start:start + length].decode())
    if header != {'descr': '<f8', 'fortran_order': False, 'shape': (q + 2, q + 1)}:
        raise ValueError(f'Unexpected frozen grade layout: {q}')
    payload = raw[start + length:]
    if len(payload) != 8 * (q + 2) * (q + 1):
        raise ValueError(f'Unexpected frozen grade length: {q}')
    result, records = [], []
    for (bits,) in struct.iter_unpack('<Q', payload):
        sign = -1 if bits >> 63 else 1
        exponent = (bits >> 52) & 2047
        fraction = bits & (2 ** 52 - 1)
        if exponent == 2047:
            raise ValueError('Nonfinite frozen coefficient')
        significand = fraction if exponent == 0 else 2 ** 52 + fraction
        shift = (1 if exponent == 0 else exponent) - 1023 - 52 + EXPONENT
        if shift >= 0:
            integer = sign * (significand << shift)
        else:
            divisor = 2 ** (-shift)
            if significand % divisor:
                raise ValueError('Frozen coefficient exceeds common denominator')
            integer = sign * (significand // divisor)
        x = struct.unpack('<d', struct.pack('<Q', bits))[0]
        m, d = x.as_integer_ratio()
        e = d.bit_length() - 1
        if d != 2 ** e or e > EXPONENT or abs(m) >= 2 ** 53:
            raise ValueError('Invalid exact binary64 ratio')
        if integer != m * 2 ** (EXPONENT - e):
            raise ValueError('Independent binary64 decoders disagree')
        result.append(integer)
        records.append(f'{m}:{e}')
    return result, records


def generate(repo=REPO):
    data = repo / 'data/taylor-approximants'
    manifest = json.loads((data / 'manifest.json').read_text())
    source = next(item for item in manifest['inputs']
                  if item['path'].endswith('/frozen_taylor_correction_D201.npz'))
    path = data / source['path']
    raw = path.read_bytes()
    if len(raw) != source['size_bytes'] or hashlib.sha256(raw).hexdigest() != source['sha256']:
        raise ValueError('Pinned frozen source hash/size mismatch')
    grades, records = [], []
    with zipfile.ZipFile(path) as archive:
        for q in range(101):
            values, texts = read_grade(archive, q)
            if q < GRADES:
                grades.append(values)
                records.extend(texts)
            elif any(values):
                raise ValueError('Frozen source is not zero above degree181')
    outputs = {}
    parts_count = 0
    for q, values in enumerate(grades):
        grade = f'frozenCorrectionGrade{q:03d}'
        names = []
        lines = ['import Init.Data.Array.Basic', '',
                 '/-! Generated by tools/gen_frozen_integer_data.py; do not edit.',
                 f'Exact frozen grade {q}; common denominator 2^{EXPONENT}.',
                 f'Pinned NPZ SHA256: {source["sha256"]}',
                 'Agent-ID: codex-7c2e -/', '', 'namespace Grothe.UpperChaos', '']
        for k in range(0, len(values), PART_SIZE):
            name = f'{grade}Part{k // PART_SIZE:03d}'
            names.append(name)
            lines += [f'def {name} : Array Int := #[',
                      '  ' + ', '.join(map(str, values[k:k + PART_SIZE])), ']', '']
        lines += [f'def {grade} : Array Int :=',
                  '  ' + ' ++ '.join(names), '',
                  'end Grothe.UpperChaos', '']
        outputs[f'FrozenSource/Grade{q:03d}Data.lean'] = '\n'.join(lines)
        parts_count += len(names)
    imports = [f'import Grothe.UpperChaos.FrozenSource.Grade{q:03d}Data' for q in range(GRADES)]
    outputs['TaylorFrozenData.lean'] = '\n'.join(imports + ['',
        '/-! Generated by tools/gen_frozen_integer_data.py; do not edit.',
        'The authoritative frozen witness consists of typed scaled integers.',
        'All grade and subchunk boundaries preserve the pinned coefficient order.',
        'No assertion equating obsolete text-parser definitions is needed or made.',
        'Agent-ID: codex-7c2e -/', '', 'namespace Grothe.UpperChaos', '',
        f'def frozenCorrectionCommonExponent : Nat := {EXPONENT}',
        f'def frozenCorrectionCount : Nat := {sum(map(len, grades))}', '',
        'def frozenCorrectionGrades : Array (Array Int) := #[',
        '  ' + ', '.join(f'frozenCorrectionGrade{q:03d}' for q in range(GRADES)), ']', '',
        'def frozenCorrectionData : Array Int :=',
        '  ' + ' ++ '.join(f'frozenCorrectionGrade{q:03d}' for q in range(GRADES)), '',
        'end Grothe.UpperChaos', ''])
    info = {'agent_id': 'codex-7c2e', 'source_file': source['path'],
            'source_sha256': source['sha256'], 'common_denominator_exponent': EXPONENT,
            'retained_coefficient_count': len(records), 'retained_degree': 181,
            'source_coefficient_count': 101 * 102 * 103 // 3,
            'source_max_denominator_exponent': max(int(s.split(':')[1]) for s in records),
            'grade_count': GRADES, 'subchunk_size': PART_SIZE, 'subchunk_count': parts_count,
            'canonical_records_sha256': hashlib.sha256(','.join(records).encode()).hexdigest(),
            'independent_binary64_replay': True,
            'lean_bytes': sum(len(s.encode()) for s in outputs.values()),
            'files': {name: hashlib.sha256(text.encode()).hexdigest()
                      for name, text in sorted(outputs.items())}}
    return outputs, info, grades


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', type=Path, default=REPO)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs, info, _ = generate(args.repo)
    target = args.output or args.repo / 'Grothe/UpperChaos'
    for name, text in outputs.items():
        path = target / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'Stale typed frozen source: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    receipt = (args.output / 'frozen-integers.json' if args.output
               else args.repo / 'data/taylor-approximants/frozen-integers.json')
    text = json.dumps(info, indent=2) + '\n'
    if args.check:
        if not receipt.exists() or receipt.read_text() != text:
            raise SystemExit('Stale typed frozen source receipt')
    else:
        receipt.write_text(text)
    print(json.dumps({k: info[k] for k in ['retained_coefficient_count', 'grade_count',
        'subchunk_count', 'lean_bytes', 'canonical_records_sha256', 'independent_binary64_replay']}))


if __name__ == '__main__':
    main()
