#!/usr/bin/env python3
"""Generate the inputs of `quadrun` (issue #303) from the Lean sources and committed data.

Writes, under data/quad-checker/ (or --check: compare byte for byte):
  panels.txt     the 1,289 panels of `Grothe/UpperChaos/Q0GaussAddress.lean` (`sourcePanels`:
                 lo, hi, order, offset);
  cutoffs.txt    the 21,577 per-node conditional cutoffs of
                 data/q0_quadrature/conditional_source/conditional_cutoffs.npy;
  profile.txt    the 12 profile coefficients `profileQ` and `aQ` of `Grothe/Upper/Data.lean`;
and, under handoff/quad-checker/ (git-ignored, 800 KB, regenerated from the Lean sources):
  rules.txt      the integer root brackets (denominator 2^640) of the 64 rules
                 `Q0LegendreRule01…64.lean` (`brackets`).

Agent-ID: claude-b9ee. Refs #303, #21.
"""
from __future__ import annotations

import hashlib
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "data", "quad-checker")
HANDOFF = os.path.join(ROOT, "handoff", "quad-checker")


def panels():
    src = open(os.path.join(ROOT, "Grothe/UpperChaos/Q0GaussAddress.lean"), encoding="utf-8").read()
    pat = r"⟨\(\((-?\d+) : ℚ\) / (\d+)\), \(\((-?\d+) : ℚ\) / (\d+)\), (\d+), (\d+)⟩"
    return [tuple(int(x) for x in m) for m in re.findall(pat, src)]


def brackets(order):
    src = open(os.path.join(ROOT, f"Grothe/UpperChaos/Q0LegendreRule{order:02d}.lean"), encoding="utf-8").read()
    m = re.search(r"def brackets : List \(ℤ × ℤ\) := \[(.*?)\]", src, re.S)
    pairs = re.findall(r"\(\s*(-?\d+)\s*,\s*(-?\d+)\s*\)", m.group(1))
    assert len(pairs) == order, (order, len(pairs))
    return [(int(a), int(b)) for a, b in pairs]


def cutoffs():
    raw = open(os.path.join(ROOT, "data/q0_quadrature/conditional_source/conditional_cutoffs.npy"), "rb").read()
    # minimal .npy reader (v1.0 header, '<i2', shape (21577,))
    assert raw[:6] == b"\x93NUMPY"
    hlen = struct.unpack("<H", raw[8:10])[0]
    header = raw[10:10 + hlen].decode()
    assert "'<i2'" in header, header
    data = raw[10 + hlen:]
    n = len(data) // 2
    return list(struct.unpack("<%dh" % n, data))


def profile():
    src = open(os.path.join(ROOT, "Grothe/Upper/Data.lean"), encoding="utf-8").read()
    m = re.search(r"def profileQ : List ℚ :=\s*\[(.*?)\]", src, re.S)
    cs = [(int(a), int(b)) for a, b in re.findall(r"\((-?\d+) : ℚ\) / (\d+)", m.group(1))]
    a = re.search(r"def aQ : ℚ := \((-?\d+) : ℚ\) / (\d+)", src)
    return cs, (int(a.group(1)), int(a.group(2)))


def main() -> int:
    check = "--check" in sys.argv[1:]
    out = {}
    lines = ["# panels of Q0GaussAddress.sourcePanels: index loN loD hiN hiD order offset;",
             "# generated by tools/quad_gen_partition.py (claude-b9ee, #303)"]
    total = 0
    for i, (loN, loD, hiN, hiD, order, offset) in enumerate(panels()):
        assert offset == total, (i, offset, total)
        lines.append(f"panel {i} {loN} {loD} {hiN} {hiD} {order} {offset}")
        total += order
    assert total == 21577, total
    out["panels.txt"] = "\n".join(lines) + "\n"
    rl = ["# root brackets of Q0LegendreRule01..64 (integers over 2^640): rule n, then n lines lo hi"]
    for order in range(1, 65):
        rl.append(f"rule {order}")
        for a, b in brackets(order):
            rl.append(f"bracket {a} {b}")
    rules_text = "\n".join(rl) + "\n"
    cs = cutoffs()
    assert len(cs) == 21577
    out["cutoffs.txt"] = "# ordinal cutoff (conditional_cutoffs.npy)\n" + "".join(f"{i} {c}\n" for i, c in enumerate(cs))
    coeffs, (aN, aD) = profile()
    assert len(coeffs) == 12
    out["profile.txt"] = ("# profileQ and aQ of Grothe/Upper/Data.lean\n" +
                          "".join(f"coeff {n} {d}\n" for n, d in coeffs) + f"a {aN} {aD}\n")
    bad = 0
    os.makedirs(HANDOFF, exist_ok=True)
    rules_path = os.path.join(HANDOFF, "rules.txt")
    with open(rules_path, "w", encoding="utf-8") as f:
        f.write(rules_text)
    print(f"wrote {rules_path} ({len(rules_text)} bytes) sha256 {hashlib.sha256(rules_text.encode()).hexdigest()}")
    for name, text in out.items():
        path = os.path.join(OUT, name)
        digest = hashlib.sha256(text.encode()).hexdigest()
        if check:
            have = open(path, encoding="utf-8").read() if os.path.exists(path) else None
            status = "OK" if have == text else "DIFFERS"
            bad += status != "OK"
            print(f"{name}: {status} sha256 {digest}")
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            print(f"wrote {name} ({len(text)} bytes) sha256 {digest}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
