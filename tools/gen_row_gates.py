#!/usr/bin/env python3
"""Generate the pure R-gate data and its exact soundness checks.

Usage: tools/gen_row_gates.py [INPUT.json] [--check]
The default input is the tracked data/row-gates.json, an exact snapshot of
cert-0745e's hash-checked row headers. It records the source file and manifest
hashes, and keeps every rational as a string. No handoff directory is needed.
With --check, verify both outputs byte for byte without writing any files.

Outputs:
  Grothe/Lower/RowGateData.lean (computable data only)
  Grothe/Lower/RowGates.lean (the unchanged exact consistency/gate checks)
"""
import argparse
import json
from fractions import Fraction as Q
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("input", nargs="?", type=Path, default=ROOT / "data" / "row-gates.json")
parser.add_argument("--check", action="store_true", help="check generated outputs without writing them")
args = parser.parse_args()
INPUT = args.input
OUT = ROOT / "Grothe" / "Lower" / "RowGates.lean"
DATA_OUT = ROOT / "Grothe" / "Lower" / "RowGateData.lean"

inputs = json.loads(INPUT.read_text())
SOURCE = inputs["source"]
EPS = Q(inputs["eps"])
assert EPS == Q(149, 200)
rows = inputs["rows"]
assert len(rows) == 19
assert [Q(r["t"]) for r in rows] == sorted(Q(r["t"]) for r in rows)

def q(x): return f"({x.numerator} : ℚ) / {x.denominator}" if x.denominator != 1 else f"({x.numerator} : ℚ)"

def ldl2(M, strict):
    a, b, c = M
    assert a > 0 and (a * c - b * b > 0 if strict else a * c - b * b >= 0)

entries = []
for R in rows:
    th = [Q(v) for v in R["theta"]]
    Rm = tuple(th[6:9]); delta = th[9]; b = th[10:13]; ell, beta = th[13], th[14]
    ldl2(Rm, True); ldl2((Rm[0] + 1, Rm[1], Rm[2] - EPS), False); ldl2((Rm[0] - EPS, Rm[1], Rm[2]), False)
    smax = Q(R["smax"])
    assert smax >= 2 * (abs(1 + b[0]) + Q(7358, 10000) * abs(b[1]) + Q(707107, 10**6) * abs(b[2]))
    entries.append(f"  ({q(ell)}, {q(beta)}, {q(delta)}, ⟨{q(Rm[0])}, {q(Rm[1])}, {q(Rm[2])}⟩)")

data_lean = f'''import Grothe.Lower.RowDataTypes

/-!
# The `R`-gates of the rows (generated by `tools/gen_row_gates.py` from `{SOURCE}`; do not edit)

For each row, in the order of `rowData`: `(ℓ, β, δ)` and the `2×2` gate matrix `R` of the fibre
potential (the block of `M = diag(E, E, R, R, ε I₂)` acting on the coefficients `ζ = (c_z, c_H)`).
`rowGates_consistent` ties the entries to `rowData`, `rowGates_ok` checks `R ≻ 0`, `R ⪰ diag(−1, ε)`,
`R ⪰ diag(ε, 0)`, and `rowData_smaxOK` checks the Lipschitz header of every row,
`smax ≥ 2(|1 + b₁| + 0.7358|b₂| + 0.707107|b₃|)` (with `2/e ≤ 0.7358`, `1/√2 ≤ 0.707107`).
-/

namespace Grothe.Lower

/-- `(ℓ, β, δ, R)` of the 19 rows. -/
def rowGates : List (ℚ × ℚ × ℚ × Sym2) := [
{(",\n").join(entries)}]

/-- The `R` gate of the `k`-th row. -/
def rowR (k : ℕ) : Sym2 := ((rowGates.getD k (0, 0, 0, ⟨0, 0, 0⟩)).2.2.2)

end Grothe.Lower
'''
lean = f'''import Grothe.Lower.RowReduction
import Grothe.Lower.RowGateData

/-!
# Exact checks of the row gates

Generated by `tools/gen_row_gates.py` from tracked `data/row-gates.json`
(original source `{SOURCE}`); do not edit. Computable data is in `RowGateData.lean`.
-/

namespace Grothe.Lower

/-- The entries of `rowGates` agree with `rowData`. -/
theorem rowGates_consistent :
    rowGates.length = rowData.length ∧
      (rowData.zip rowGates).all (fun p => decide (p.1.ell = p.2.1 ∧ p.1.beta = p.2.2.1 ∧
        p.1.delta = p.2.2.2.1)) = true := by
  decide +kernel

/-- **The `R`-gates of all rows**: `R ≻ 0`, `R ⪰ diag(−1, ε)`, `R ⪰ diag(ε, 0)`. -/
theorem rowGates_ok :
    rowGates.all (fun g => g.2.2.2.psdOK && (g.2.2.2.subDiag (-1) ε).psdOK &&
      (g.2.2.2.subDiag ε 0).psdOK) = true := by
  decide +kernel

/-- **The Lipschitz header of all rows**: `smax ≥ 2(|1 + b₁| + 0.7358|b₂| + 0.707107|b₃|)`. -/
theorem rowData_smaxOK :
    rowData.all (fun r => decide (2 * (|1 + r.b1| + 7358 / 10000 * |r.b2|
      + 707107 / 1000000 * |r.b3|) ≤ r.smax)) = true := by
  decide +kernel

end Grothe.Lower
'''
for target, text in [(DATA_OUT, data_lean), (OUT, lean)]:
    if args.check:
        if not target.exists() or target.read_bytes() != text.encode():
            parser.exit(1, f"generated output differs: {target}\n")
    else:
        target.write_text(text)
print("checked" if args.check else "wrote", DATA_OUT, "and", OUT, len(entries), "rows")
