#!/usr/bin/env python3
"""Generate the R-gate data module of the rows (exact rationals only):

  Grothe/Lower/RowGates.lean   for each of the 19 rows (in the order of `rowData`) the triple
                               `(ℓ, β, δ)` and the `2×2` gate matrix `R` of the fibre potential
                               (`rowGates`), with the exact checks `rowGates_consistent` (the triples
                               agree with `rowData`), `rowGates_ok` (`R ≻ 0`, `R ⪰ diag(−1, ε)`,
                               `R ⪰ diag(ε, 0)`) and `rowData_smaxOK` (the Lipschitz header
                               `smax ≥ 2(|1 + b₁| + 0.7358|b₂| + 0.707107|b₃|)`).

Usage: tools/gen_row_gates.py [SOURCE]   SOURCE = cert-0745e (default), a folder in handoff/lower-stein
(set GROTHE_HANDOFF when running from a worktree).  The row files are hash-checked against the manifest.
The profile vector `theta` of a row is `(E (6, upper triangle), R (3, upper triangle), δ, b (3), ℓ, β)`
(`tools/gen_lower_data.py`).
"""
import hashlib
import json
import os
import sys
from fractions import Fraction as Q
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HANDOFF = Path(os.environ.get("GROTHE_HANDOFF", ROOT / "handoff"))
SOURCE = sys.argv[1] if len(sys.argv) > 1 else "cert-0745e"
CERT = HANDOFF / "lower-stein" / SOURCE
OUT = ROOT / "Grothe" / "Lower" / "RowGates.lean"

man = json.load(open(CERT / "manifest.json"))
EPS = Q(man["eps"])
assert EPS == Q(149, 200)
for fn, h in man["files"].items():
    assert hashlib.sha256(open(CERT / fn, "rb").read()).hexdigest() == h, fn
rowfiles = sorted((f for f in man["files"] if f.startswith("row_")), key=lambda f: Q(json.load(open(CERT / f))["t"]))
assert len(rowfiles) == 19

def q(x): return f"({x.numerator} : ℚ) / {x.denominator}" if x.denominator != 1 else f"({x.numerator} : ℚ)"

def ldl2(M, strict):
    a, b, c = M
    assert a > 0 and (a * c - b * b > 0 if strict else a * c - b * b >= 0)

entries = []
for fn in rowfiles:
    R = json.load(open(CERT / fn))
    th = [Q(v) for v in R["theta"]]
    Rm = tuple(th[6:9]); delta = th[9]; b = th[10:13]; ell, beta = th[13], th[14]
    ldl2(Rm, True); ldl2((Rm[0] + 1, Rm[1], Rm[2] - EPS), False); ldl2((Rm[0] - EPS, Rm[1], Rm[2]), False)
    smax = Q(R["smax"])
    assert smax >= 2 * (abs(1 + b[0]) + Q(7358, 10000) * abs(b[1]) + Q(707107, 10**6) * abs(b[2]))
    entries.append(f"  ({q(ell)}, {q(beta)}, {q(delta)}, ⟨{q(Rm[0])}, {q(Rm[1])}, {q(Rm[2])}⟩)")

lean = f'''import Grothe.Lower.RowReduction

/-!
# The `R`-gates of the rows (generated by `tools/gen_row_gates.py` from `{SOURCE}`; do not edit)

For each row, in the order of `rowData`: `(ℓ, β, δ)` and the `2×2` gate matrix `R` of the fibre
potential (the block of `M = diag(E, E, R, R, ε I₂)` acting on the coefficients `ζ = (c_z, c_H)`).
`rowGates_consistent` ties the entries to `rowData`, `rowGates_ok` checks `R ≻ 0`, `R ⪰ diag(−1, ε)`,
`R ⪰ diag(ε, 0)`, and `rowData_smaxOK` checks the Lipschitz header of every row,
`smax ≥ 2(|1 + b₁| + 0.7358|b₂| + 0.707107|b₃|)` (with `2/e ≤ 0.7358`, `1/√2 ≤ 0.707107`).
-/

namespace Grothe.Lower

/-- `(ℓ, β, δ, R)` of the 19 rows. -/
def rowGates : List (ℚ × ℚ × ℚ × Sym2) := [
{(",\n").join(entries)}]

/-- The `R` gate of the `k`-th row. -/
def rowR (k : ℕ) : Sym2 := ((rowGates.getD k (0, 0, 0, ⟨0, 0, 0⟩)).2.2.2)

/-- The entries of `rowGates` agree with `rowData`. -/
theorem rowGates_consistent :
    rowGates.length = rowData.length ∧
      (rowData.zip rowGates).all (fun p => decide (p.1.ell = p.2.1 ∧ p.1.beta = p.2.2.1 ∧
        p.1.delta = p.2.2.2.1)) = true := by
  decide +kernel

/-- **The `R`-gates of all rows**: `R ≻ 0`, `R ⪰ diag(−1, ε)`, `R ⪰ diag(ε, 0)`. -/
theorem rowGates_ok :
    rowGates.all (fun g => g.2.2.2.psdOK && (g.2.2.2.subDiag (-1) ε).psdOK &&
      (g.2.2.2.subDiag ε 0).psdOK) = true := by
  decide +kernel

/-- **The Lipschitz header of all rows**: `smax ≥ 2(|1 + b₁| + 0.7358|b₂| + 0.707107|b₃|)`. -/
theorem rowData_smaxOK :
    rowData.all (fun r => decide (2 * (|1 + r.b1| + 7358 / 10000 * |r.b2|
      + 707107 / 1000000 * |r.b3|) ≤ r.smax)) = true := by
  decide +kernel

end Grothe.Lower
'''
OUT.write_text(lean)
print("wrote", OUT, len(entries), "rows")
