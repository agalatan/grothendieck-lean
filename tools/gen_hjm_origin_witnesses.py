#!/usr/bin/env python3
"""Generate the exact finite test vectors for HJM origin visible energy.

Agent-ID: codex-aa04. The input vectors are proposals: their provenance makes
no analytic claim. The emitted checks only certify finite rational arithmetic.
The Gaussian correlation estimates remain separate proof obligations.
"""
from __future__ import annotations
import argparse
from fractions import Fraction as Q
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'data/hjm/origin/visible-witnesses.json'
OUT = ROOT / 'Grothe/HJM/OriginWitnessData.lean'
EXPECTED = 'd7119d6ef8506506ddb62c0acc31a9045e185fac8778880fb34368783b1500a7'

def require(condition, message):
    if not condition:
        raise ValueError(message)

def rat(x):
    require(type(x) is str, 'rational must be a string')
    return Q(x)

def render_rat(x):
    q = Q(x)
    return str(q.numerator) if q.denominator == 1 else f'({q.numerator} / {q.denominator})'

def validate(doc):
    require(doc['schema_version'] == 1 and doc['count'] == 120, 'bad schema or mode count')
    require(doc['upstream_commit'] == '7139f4cb8d0f30c2eb4c1267c46732a9d5229c3f', 'wrong source revision')
    require(doc['panels_sha256'] == '76b2d5f3df4dd7c39d3202d12269650f8b9712158026232f6a1dcd80390ff35d', 'wrong phase proposal')
    target, err, weighted = (rat(doc[k]) for k in ('visible_target', 'correlation_error', 'weighted_mass_cap'))
    require(target == Q(23,2) and err == Q(1,10**8) and weighted == 10404, 'unexpected certificate targets')
    require(102 * Q(1001,10**15) <= err, 'spatial approximation allowance too small')
    for side in ('left','right'):
        row = doc['sides'][side]
        require(len(row['alpha']) == 120, 'bad witness length')
        alpha = [tuple(map(rat,p)) for p in row['alpha']]
        require(all(len(p)==2 for p in alpha), 'bad complex witness component')
        values = [(n+1)*(r*r+i*i) for n,(r,i) in enumerate(alpha)]
        mass, energy = sum(values), sum((2*n+1)**2*x for n,x in enumerate(values))
        B,L = rat(row['mass_cap']), rat(row['correlation_lower'])
        require(0 < B and 0 < L and mass <= B and energy <= weighted, f'{side}: witness norm rejected')
        require(B*target <= L*L, f'{side}: visible-energy arithmetic rejected')

def render(doc):
    lines = ['import Mathlib.Data.Rat.Defs', '',
             '/-! Generated by tools/gen_hjm_origin_witnesses.py; do not edit.',
             'Agent-ID: codex-aa04. Input SHA256: '+EXPECTED+'.',
             'The entries are arbitrary exact test vectors; finite checks do not',
             'assert any Gaussian integral enclosure. -/', '',
             'namespace Grothe.HJM.OriginWitnessData', '']
    for side in ('left','right'):
        row=doc['sides'][side]
        lines.append(f'def {side}Alpha : List (ℚ × ℚ) := [')
        lines.extend(f'  ({render_rat(r)}, {render_rat(i)})'+(',' if n<119 else '')
                     for n,(r,i) in enumerate(row['alpha']))
        lines.extend([']', f'def {side}MassCap : ℚ := {render_rat(row["mass_cap"])}',
                      f'def {side}CorrelationLower : ℚ := {render_rat(row["correlation_lower"])}', ''])
    lines.extend(['def visibleTarget : ℚ := 23 / 2', 'def weightedMassCap : ℚ := 10404',
                  'def correlationError : ℚ := 1 / 10 ^ 8', '',
                  '/-- Exact norm squared of the unweighted test coefficients. -/',
                  'def mass (xs : List (ℚ × ℚ)) : ℚ :=',
                  '  ((List.range 120).map fun n =>',
                  '    let a := xs.getD n (0, 0)',
                  '    (n + 1 : ℚ) * (a.1 ^ 2 + a.2 ^ 2)).sum', '',
                  '/-- Exact norm squared after multiplication by the chaos degree. -/',
                  'def weightedMass (xs : List (ℚ × ℚ)) : ℚ :=',
                  '  ((List.range 120).map fun n =>',
                  '    let a := xs.getD n (0, 0)',
                  '    (2 * (n : ℚ) + 1) ^ 2 * (n + 1 : ℚ) * (a.1 ^ 2 + a.2 ^ 2)).sum', '',
                  'set_option maxRecDepth 100000', 'set_option maxHeartbeats 16000000', ''])
    for side in ('left','right'):
        lines.extend([f'theorem {side}_mass_check : mass {side}Alpha ≤ {side}MassCap := by decide +kernel',
                      f'theorem {side}_weighted_mass_check : weightedMass {side}Alpha ≤ weightedMassCap := by decide +kernel',
                      f'theorem {side}_visible_arithmetic : {side}MassCap * visibleTarget ≤ {side}CorrelationLower ^ 2 := by decide +kernel', ''])
    lines.extend(['theorem spatial_error_arithmetic :',
                  '    (102 : ℚ) * (1001 / 10 ^ 15) ≤ correlationError := by decide +kernel', '',
                  'end Grothe.HJM.OriginWitnessData', ''])
    return '\n'.join(lines)

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check',action='store_true')
    ap.add_argument('--self-test',action='store_true')
    args=ap.parse_args()
    raw=DATA.read_bytes()
    require(hashlib.sha256(raw).hexdigest()==EXPECTED, 'witness input bytes changed')
    doc=json.loads(raw);validate(doc)
    if args.self_test:
        altered=json.loads(raw);altered['sides']['left']['alpha'][0]=['1000','1000']
        try: validate(altered)
        except ValueError: pass
        else: raise ValueError('oversized witness was not rejected')
        altered=json.loads(raw);altered['sides']['right']['correlation_lower']='1'
        try: validate(altered)
        except ValueError: pass
        else: raise ValueError('insufficient correlation was not rejected')
    result=render(doc)
    if args.check:
        require(OUT.exists() and OUT.read_text()==result, 'generated Lean output differs')
    else:
        OUT.write_text(result)
    print('witness inputs and finite exact comparisons verified')

if __name__=='__main__': main()
