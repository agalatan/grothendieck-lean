# tools/gen_lower_refinement_cover.py
"""Export the complete finite-mixture cover to Lean, with exact replay first."""
import argparse
from fractions import Fraction as Q
import json
import re

from lower_refinement import ROOT, DATA, RHO, poly, strings
from verify_lower_refinement import source_check, original_coverage, certificate_check


def quoted(value):
    return json.dumps(value, ensure_ascii=False)


def qterm(value):
    value = Q(value)
    return f'(({value.numerator} : ℚ) / {value.denominator})'


def mixture(components):
    parts = [(Q(w), source) for _, w, source in components if Q(w)]
    assert parts and all(w > 0 for w, _ in parts) and sum(w for w, _ in parts) == 1

    def tree(rest):
        w, source = rest[0]
        leaf = f'(.leaf (parseComp {quoted(source)}))'
        if len(rest) == 1:
            return leaf
        total = sum(v for v, _ in rest)
        return f'(.mix {qterm((total - w) / total)} {leaf} {tree(rest[1:])})'

    return tree(parts)


def render():
    source_check()
    original_coverage()
    doc = json.loads((DATA / 'cover.json').read_text())
    _, expected_count = certificate_check(doc, verbose=False)
    records = {r['parent']: r['tree'] for r in doc['records']}
    old_index = {poly(s.split('|')[1]): i for i, s in enumerate(strings)}
    source = (ROOT / 'Grothe/Research/RefinedCoverData.lean').read_text()
    tokens = '|'.join(re.findall(r'def refinedCuts\d+ : String :=\s*"([^"]*)"', source)).split('|')
    position = 0
    boxes, cuts = [], []

    def replacement(tr):
        if 'leaf' not in tr:
            cuts.append(str(tr['axis']) + ',' + tr['mid'])
            for child in tr['children']:
                replacement(child)
            return
        leaf = tr['leaf']
        cuts.append('.')
        if leaf['kind'] == 'cap':
            boxes.append(f'⟨parseBox {quoted(leaf["box"])}, none⟩')
        else:
            assert leaf['kind'] == 'multi'
            geometry = 'c|' + ','.join(leaf['bounds']) + '|0,0,0'
            boxes.append(f'⟨parseBox {quoted(geometry)}, some {mixture(leaf["components"])}⟩')

    def original(domain):
        nonlocal position
        token = tokens[position]
        position += 1
        if token == '.':
            index = old_index[tuple(domain)]
            if index in records:
                replacement(records[index])
            else:
                cuts.append('.')
                boxes.append(f'originalBox {index}')
            return
        axis, mid = token.split(',')
        axis, mid = int(axis), Q(mid)
        left, right = list(domain), list(domain)
        left[2 * axis + 1] = mid
        right[2 * axis] = mid
        cuts.append(token)
        original(left)
        original(right)

    original((Q(0), Q(9, 10), Q(0), RHO, Q(0), Q(31, 4)))
    assert position == len(tokens) and len(boxes) == expected_count == 14060
    bound = Q(doc['target'])
    endpoint = Q((1 / bound).numerator * 10**12 // (1 / bound).denominator, 10**12)
    assert endpoint * bound < 1
    out = [
        '-- Grothe/Research/LowerRefinementCoverData.lean\n'
        'import Grothe.Lower.FiniteMix\n'
        'import Grothe.Research.LowerRefinementData\n'
        'import Grothe.Research.RefinedCoverData\n\n'
        '/-! Generated by `tools/gen_lower_refinement_cover.py`; complete checked-cover input. -/\n\n'
        'namespace Grothe.Research.LowerRefinementCoverData\n\n'
        'open Grothe.Lower\n\n'
        f'def bound : ℚ := {qterm(bound)}\n'
        f'def endpoint : ℚ := {qterm(endpoint)}\n'
        'def chunkSize : ℕ := 3515\n\n'
        'def originalStrings : Array String := RefinedCoverData.refinedBoxes.toArray\n\n'
        '/-- Unchanged boxes reuse the pinned original certificate strings. -/\n'
        'def originalBox (i : ℕ) : MixBox :=\n'
        '  ⟨parseBox (originalStrings[i]?.getD ""), none⟩\n\n'
    ]
    names = []
    for start in range(0, len(boxes), 250):
        name = f'boxes{len(names):02d}'
        names.append(name)
        out.append(f'def {name} : List MixBox :=\n  [')
        out.append(',\n   '.join(boxes[start:start + 250]))
        out.append(']\n\n')
    out.append('def boxes : List MixBox :=\n  ' + ' ++ '.join(names) + '\n\n')
    out.append('def cutChunks : List String :=\n  [')
    out.append(',\n   '.join(quoted('|'.join(cuts[i:i + 400])) for i in range(0, len(cuts), 400)))
    out.append(']\n\n')
    out.append('def cuts : List String := cutChunks.flatMap (fun s => s.splitOn "|")\n\n')
    out.append('end Grothe.Research.LowerRefinementCoverData\n')
    return ''.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'Grothe/Research/LowerRefinementCoverData.lean'
    result = render()
    if args.check:
        if output.read_text() != result:
            raise ValueError('Generated lower-refinement cover differs')
    else:
        output.write_text(result)
    print('PASS exact Lean cover export: 14060 boxes, complete partition')


if __name__ == '__main__':
    main()
