#!/usr/bin/env python3
"""Generate the bisection tree certifying `φ² ≤ 3` (Grothe/UpperChaos/PhiCoverData.lean).

φ = D e^{−ε(U+V)} S(U,V,W) with D² = UV − W²; g = (UV − W²) e^{−2ε(U+V)} S² ≤ 3 is checked on the box
U, V ∈ [0, 64], W ∈ [−32, 32] (all points with U + V ≤ 60, W² ≤ UV); boxes with U_lo + V_lo ≥ 60 are left
to the analytic far-field bound.  Coordinates are integers in units of 2^-SC.  Leaf test (mirrors
`PhiCover.leafOK` exactly, integer arithmetic): Taylor shift of the integer polynomial
A0[i,j,k] = n_{ijk} 2^{SC(17−i−j−k)} (n = L·c) to the box centre, |S| ≤ Σ|B_α| R^α / (L 2^{17 SC}),
e^{−x} ≤ q^{⌊x⌋}/(1 + frac x) with q = 10^9/2718281828, D ≤ max(0, U_hi V_hi − w2lo).
Tree string: 'U','V','W' = split along that axis (left = lower half first), 'L' = checked leaf,
'F' = far leaf (U_lo + V_lo ≥ 60), 'X' = infeasible leaf (w2lo > U_hi V_hi).
Usage: python3 tools/gen_phi_cover.py PHASE_JSON OUT_LEAN"""
import json, sys, math
from fractions import Fraction as Q
SC = 16; DEG = 17; FAR = 60
EPS = None; Lden = None; A0 = None
QE = Q(10**9, 2718281828)

def load(path):
    global EPS, Lden, A0
    d = json.load(open(path))
    EPS = Q(d['epsilon'])
    terms = [(tuple(t['powers']), Q(t['coefficient'])) for t in d['monomial_coefficients']]
    Lden = 1
    for _, c in terms: Lden = Lden * c.denominator // math.gcd(Lden, c.denominator)
    A0 = {}
    for (i, j, k), c in terms:
        n = c * Lden; assert n.denominator == 1
        A0[(i, j, k)] = A0.get((i, j, k), 0) + int(n) * 2 ** (SC * (DEG - i - j - k))
    return d

def shift(P, axis, m):
    # P(…, m + y, …) as polynomial in y along axis; P dict -> dict
    out = {}
    lines = {}
    for e, c in P.items():
        key = e[:axis] + e[axis + 1:]
        lines.setdefault(key, {})[e[axis]] = c
    for key, line in lines.items():
        n = max(line)
        acc = []
        for i in range(n, -1, -1):
            # acc := acc*(m+Y) + a_i
            new = [0] * (len(acc) + 1)
            for t, a in enumerate(acc):
                new[t] += a * m; new[t + 1] += a
            new[0] += line.get(i, 0)
            acc = new
        for t, a in enumerate(acc):
            if a:
                e = key[:axis] + (t,) + key[axis:]
                out[e] = out.get(e, 0) + a
    return out

def leaf_bound(box):
    Ul, Uh, Vl, Vh, Wl, Wh = box
    mU, mV, mW = (Ul + Uh) // 2, (Vl + Vh) // 2, (Wl + Wh) // 2
    rU, rV, rW = (Uh - Ul) // 2, (Vh - Vl) // 2, (Wh - Wl) // 2
    B = shift(shift(shift(A0, 0, mU), 1, mV), 2, mW)
    b0 = abs(B.get((0, 0, 0), 0))
    rad = sum(abs(c) * rU ** e[0] * rV ** e[1] * rW ** e[2] for e, c in B.items() if e != (0, 0, 0))
    Smax = Q(b0 + rad, Lden * 2 ** (DEG * SC))
    w2lo = 0 if Wl <= 0 <= Wh else min(Wl * Wl, Wh * Wh)
    Dm = max(0, Uh * Vh - w2lo)
    D = Q(Dm, 2 ** (2 * SC))
    x = 2 * EPS * Q(Ul + Vl, 2 ** SC)
    n = x.numerator // x.denominator; f = x - n
    E = QE ** n / (1 + f)
    return D * E * Smax * Smax

def build(box, out, stats):
    Ul, Uh, Vl, Vh, Wl, Wh = box
    S = 2 ** SC
    if Ul + Vl >= FAR * S:
        out.append('F'); return
    w2lo = 0 if Wl <= 0 <= Wh else min(Wl * Wl, Wh * Wh)
    if w2lo > Uh * Vh:
        out.append('X'); return
    # cheap float pre-screen then exact
    if (Uh - Ul) <= 2 ** (SC - 1) * 4 or True:
        v = leaf_bound(box)
        if v <= 3:
            out.append('L'); stats[0] += 1; return
    w = [(Uh - Ul), (Vh - Vl), (Wh - Wl)]
    ax = max(range(3), key=lambda i: w[i])
    lo, hi = box[2 * ax], box[2 * ax + 1]
    assert hi - lo >= 2, "too deep"
    mid = (lo + hi) // 2
    out.append('UVW'[ax])
    b1 = list(box); b1[2 * ax + 1] = mid
    b2 = list(box); b2[2 * ax] = mid
    build(tuple(b1), out, stats); build(tuple(b2), out, stats)

def main():
    load(sys.argv[1])
    S = 2 ** SC
    box = (0, 64 * S, 0, 64 * S, -32 * S, 32 * S)
    out = []; stats = [0]
    sys.setrecursionlimit(100000)
    build(box, out, stats)
    tree = ''.join(out)
    print('nodes', len(tree), 'checked leaves', stats[0], 'L', Lden.bit_length())
    with open(sys.argv[2], 'w') as f:
        f.write('/-! Generated by `tools/gen_phi_cover.py`: the bisection tree of the phase cover. -/\n\n')
        f.write('namespace Grothe.UpperChaos\n\n')
        f.write('/-- The bisection tree (`U V W` split, `L` checked leaf, `F` far leaf, `X` empty leaf). -/\n')
        f.write('def phiTree : String :=\n')
        for i in range(0, len(tree), 96):
            f.write(('  "' if i == 0 else '  ++ "') + tree[i:i + 96] + '"\n')
        f.write('\nend Grothe.UpperChaos\n')

main()
