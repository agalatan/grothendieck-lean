#!/usr/bin/env python3
"""Generate the native-fact modules of the upper-closure port (docs/UPPER_CLOSURE.md §8.5: node ranges with committed partials).

    python3 tools/gen_port_facts.py            # all powers present in data/port-facts/
    python3 tools/gen_port_facts.py --check    # fail if a generated module differs from the file

Inputs: `data/port-facts/j<j>-tables.txt` (from `tools/port_facts_tables.py tables`), the centers'
dyadic numerators (`data/taylor-approximants/inputs/*.npz`, the same numbers as master's
`firstCenterInts`/`secondCenterInts`/`thirdCenterInts`).  Outputs, under `Grothe/UpperQuad/PortFacts/`:

* `J<j>Range<rr>.lean`: the table `j<j>Table<rr>` and the fact `j<j>Range<rr> : rangeFact j lo hi
  j<j>Table<rr> = true` (one `native_decide`: the kernel's node loop over `[lo, hi)`);
* `J<j>Tables.lean`: the fact `j<j>TablesValid : tablesFlags P0 (twistParams j) (tables j) = true`
  (the table-level flags, `TablesFlags.lean`);
* `J<j>Final.lean`: the boundaries, the list of tables, the threshold `θ_j` and the tolerance
  `eps_j`, the fact `j<j>Final : finalFact j … = true` (one `native_decide`: the tables' sum and the
  kernel's checks) and `j<j>RangeFacts` (every range fact, indexed).

`θ_j` is the exact lower end of the tables' `I`-sum rounded down to `10^{−20}` (`I_j ≥ θ_j`), `eps_j`
the exact low-band excursion bound of the tables' sum (`lowBandExcursionSq` at the scale `2^{1024}`)
rounded up to a power of two; both are computed here exactly from the tables, so the final fact holds
by construction once the tables are right.

Agent-ID: claude-b9ee.  Refs #41, #313.
"""
import argparse
import math
import os
import sys
from fractions import Fraction

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data/port-facts")
OUT = os.path.join(ROOT, "Grothe/UpperQuad/PortFacts")
KT, KOUT = 64, 256
NNODES = 21577
E = {1: 206, 2: 206, 3: 105}
QLOW = {1: 26, 2: 26, 3: 6}
CENTER_FILES = {1: ("arb_first_phase_D181.npz", 91), 2: ("arb_phase_power2_D151.npz", 46),
                3: ("arb_phase_power3_D51.npz", 26)}
CHUNK = 2000   # characters per string literal


def read_tables(j):
    path = os.path.join(DATA, f"j{j}-tables.txt")
    if not os.path.exists(path):
        return None
    rows = []
    with open(path, encoding="utf-8") as f:
        lines = [ln.rstrip("\n") for ln in f if not ln.startswith("#")]
    for k in range(0, len(lines), 2):
        p = lines[k].split()
        assert p[0] == "range" and int(p[1]) == k // 2, lines[k][:80]
        rows.append(dict(lo=int(p[2]), hi=int(p[3]), iMid=int(p[4]), iRad=int(p[5]), lowRad=int(p[6]),
                         low=lines[k + 1]))
    return rows


def center_low(j):
    """The center's low-band numerators at the exponent E[j], flat graded order (q < QLOW)."""
    import numpy as np
    name, _ = CENTER_FILES[j]
    flat = np.load(os.path.join(ROOT, "data/taylor-approximants/inputs", name))["center"].astype(np.float64)
    out = []
    n = sum((q + 2) * (q + 1) for q in range(QLOW[j]))
    for x in flat[:n]:
        fr = Fraction(float(x)) * (1 << E[j])
        assert fr.denominator == 1
        out.append(int(fr))
    return out


def chunks(s):
    parts, cur = [], []
    n = 0
    for tok in s.split(","):
        if cur and n + len(tok) + 1 > CHUNK:
            parts.append(",".join(cur))
            cur, n = [], 0
        cur.append(tok)
        n += len(tok) + 1
    if cur:
        parts.append(",".join(cur))
    return parts


HEADER = "-- Generated by tools/gen_port_facts.py from data/port-facts/j{j}-tables.txt; do not edit.\n"


def range_module(j, r, row):
    name = f"j{j}Table{r:02d}"
    lit = ",\n    ".join('"' + c + '"' for c in chunks(row["low"]))
    return (HEADER.format(j=j) + "import Grothe.UpperQuad.PortFacts.Common\n\n"
            f"/-!\n# Native fact: power {j}, nodes `[{row['lo']}, {row['hi']})` of the partition\n\n"
            f"`rangeFact {j} {row['lo']} {row['hi']} {name}`: the profile flags, the kernel's twisted node loop "
            f"over the nodes\n`[{row['lo']}, {row['hi']})` of `partitionSpecs` for the power `{j}`, and its accumulator "
            f"inside the committed table\n`{name}` (midpoints at the scale `2^64`, radii {row['iRad']} and "
            f"{row['lowRad']}).  One `native_decide`; consumed by\n`j{j}RangeFacts` (`J{j}Final.lean`).\n\n"
            "Agent-ID: claude-b9ee. Refs #41, #313.\n-/\n\n"
            "namespace Grothe.UpperQuad.PortFacts\n\n"
            f"/-- The committed partial table of the nodes `[{row['lo']}, {row['hi']})`, power {j}. -/\n"
            f"def {name} : PartialTable :=\n  ⟨{row['iMid']}, {row['iRad']}, {row['lowRad']}, #[\n    {lit}]⟩\n\n"
            f"theorem j{j}Range{r:02d} : rangeFact {j} {row['lo']} {row['hi']} {name} = true := by native_decide\n\n"
            "end Grothe.UpperQuad.PortFacts\n")


def tables_module(j):
    return ("-- Generated by tools/gen_port_facts.py; do not edit.\n"
            "import Grothe.UpperQuad.PortFacts.TablesFlags\n\n"
            f"/-!\n# Native fact: the table-level flags of the power {j}\n\n"
            f"`tablesFlags P0 (twistParams {j}) (tables {j})`: the positivity of `λ_{j}`, `√λ_{j}`, `√n` "
            "(`n < D' + 2`) and of the\nenclosures `√(c! d!)` of the per-process tables (`TablesFlags.lean`). "
            "One `native_decide` (seconds).\n\n"
            "Agent-ID: claude-b9ee. Refs #41, #313.\n-/\n\n"
            "namespace Grothe.UpperQuad.PortFacts\n\n"
            f"theorem j{j}TablesValid : tablesFlags P0 (twistParams {j}) (tables {j}) = true := by\n"
            "  native_decide\n\n"
            "end Grothe.UpperQuad.PortFacts\n")


def final_values(j, rows):
    """θ (num, den) and eps exactly as the final fact computes them from the tables."""
    sh = 2 * KOUT - KT
    ilo = sum((t["iMid"] - t["iRad"]) << sh for t in rows)
    den = 10 ** 20
    num = (ilo * den) >> (2 * KOUT)          # floor(ilo / 2^512 * 10^20)
    assert num * (1 << (2 * KOUT)) <= ilo * den
    mids = [list(map(int, t["low"].split(","))) for t in rows]
    cen = center_low(j)
    ex2 = 0
    for n, c in enumerate(cen):
        lo = sum((m[n] - t["lowRad"]) << sh for m, t in zip(mids, rows))
        hi = sum((m[n] + t["lowRad"]) << sh for m, t in zip(mids, rows))
        tc = c << (2 * KOUT - E[j])
        ex = max(hi - tc, tc - lo, 0)
        ex2 += ex * ex
    k = max(ex2.bit_length(), 1)
    eps = 1 << k                              # 2^k ≥ ex2
    return num, den, eps, k, Fraction(ilo, 1 << (2 * KOUT)), ex2


def final_module(j, rows):
    num, den, eps, k, ilo, ex2 = final_values(j, rows)
    bounds = [rows[0]["lo"]] + [t["hi"] for t in rows]
    n = len(rows)
    imports = "import Grothe.UpperQuad.PortFacts.Thresholds\n" + "".join(
        f"import Grothe.UpperQuad.PortFacts.J{j}Range{r:02d}\n" for r in range(n))
    tabs = ", ".join(f"j{j}Table{r:02d}" for r in range(n))
    facts = ", ".join(f"j{j}Range{r:02d}" for r in range(n))
    rt_eps = math.sqrt(eps) / 2 ** (2 * KOUT)
    return (HEADER.format(j=j) + imports + "\n"
            f"/-!\n# The final fact of the power {j}\n\n"
            f"The {n} node ranges `j{j}Bounds` tile the partition; `j{j}Final` adds their committed tables and "
            f"runs the\nkernel's checks on the sum: the lower end of the `I_{j}`-sum is at least "
            f"`θ = {num}/10^20`\n(the tables' exact lower end is `{float(ilo):.17e}`), and the squared "
            f"low-band excursions from the\ncenter's coefficients add up to at most `eps / 2^1024`, "
            f"`eps = 2^{k}` (`√eps / 2^512 = {rt_eps:.3e}`).\n\n"
            "Agent-ID: claude-b9ee. Refs #41, #313.\n-/\n\n"
            "namespace Grothe.UpperQuad.PortFacts\n\n"
            f"/-- The boundaries of the node ranges of the power {j}. -/\n"
            f"def j{j}Bounds : List ℕ := {bounds}\n\n"
            f"/-- The committed tables of the power {j}, one per range. -/\n"
            f"def j{j}Tables : List PartialTable := [{tabs}]\n\n"
            f"theorem j{j}Final : finalFact {j} j{j}Bounds j{j}Tables j{j}ThetaNum (10 ^ 20) j{j}Eps = true := by\n"
            "  native_decide\n\n"
            f"/-- Every range fact of the power {j}, indexed by the range. -/\n"
            f"theorem j{j}RangeFacts : ∀ r, r < {n} →\n"
            f"    rangeFact {j} (j{j}Bounds.getD r 0) (j{j}Bounds.getD (r + 1) 0) (j{j}Tables.getD r default) = true := by\n"
            "  intro r hr\n  interval_cases r\n"
            f"  exacts [{facts}]\n\n"
            "end Grothe.UpperQuad.PortFacts\n")


def thresholds_module(vals):
    body = ""
    for j, (num, k) in sorted(vals.items()):
        body += (f"/-- The numerator of the threshold `θ_{j} = j{j}ThetaNum / 10^20` of the final fact of the power {j}. -/\n"
                 f"def j{j}ThetaNum : ℤ := {num}\n\n"
                 f"/-- The low-band tolerance of the power {j} at the scale `2^1024`. -/\n"
                 f"def j{j}Eps : ℤ := 2 ^ {k}\n\n")
    return ("-- Generated by tools/gen_port_facts.py from data/port-facts/; do not edit.\n"
            "import Mathlib.Data.Rat.Defs\n\n"
            "/-!\n# The thresholds of the final facts\n\n"
            "`θ_j` is the exact lower end of the committed tables' `I_j`-sum rounded down to `10^{-20}`, `eps_j` the "
            "exact low-band\nexcursion bound of their sum rounded up to a power of two (`tools/gen_port_facts.py`). "
            "Kept apart from the\nfacts so that the margins (`Margins.lean`) do not import them.\n\n"
            "Agent-ID: claude-b9ee. Refs #41, #313.\n-/\n\n"
            "namespace Grothe.UpperQuad.PortFacts\n\n" + body + "end Grothe.UpperQuad.PortFacts\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    files = {}
    vals = {}
    for j in (1, 2, 3):
        rows = read_tables(j)
        if rows is None:
            continue
        assert rows[0]["lo"] == 0 and rows[-1]["hi"] == NNODES
        assert all(a["hi"] == b["lo"] for a, b in zip(rows, rows[1:]))
        for r, row in enumerate(rows):
            files[f"J{j}Range{r:02d}.lean"] = range_module(j, r, row)
        files[f"J{j}Final.lean"] = final_module(j, rows)
        files[f"J{j}Tables.lean"] = tables_module(j)
        num, den, eps, k, ilo, ex2 = final_values(j, rows)
        vals[j] = (num, k)
        print(f"j={j}: {len(rows)} ranges, I_lo(tables) = {float(ilo):.17e}, theta = {num}/10^20, "
              f"sqrt(excursion^2) = {math.isqrt(ex2) / 2 ** 512:.3e}, eps = 2^{k}")
    files["Thresholds.lean"] = thresholds_module(vals)
    bad = 0
    for name, text in sorted(files.items()):
        path = os.path.join(OUT, name)
        if args.check:
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
                print(f"differs: {path}")
                bad += 1
        else:
            os.makedirs(OUT, exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
    if args.check:
        sys.exit(1 if bad else 0)
    print(f"wrote {len(files)} modules under {OUT}")


if __name__ == "__main__":
    main()
