#!/usr/bin/env python3
"""Generate Grothe/HJM/Data.lean from the Heilman-Jones-Malavolta canonical certificate.

Input: data/hjm/audit_sparse6_altgroups.py, a verbatim copy of `audit_sparse6_altgroups.py` from
https://github.com/sheilman77/grothendieck_cx at commit 7139f4cb8d0f30c2eb4c1267c46732a9d5229c3f
(SHA-256 checked below). The five scalar preprocessors rho_r(t) = sum_m c_{r,m} t^{2m+1} and the six signed weights
w_1..w_6 are exact terminating decimals there. In Lean, P_r(x) = sum_m c_{r,m} x^m is a dense coefficient list
(`ofListQ`), so rho_r(t) = t P_r(t^2).

Usage: python3 tools/gen_hjm_data.py [--check]
"""
import ast, hashlib, sys
from fractions import Fraction as Q
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data/hjm/audit_sparse6_altgroups.py"
OUT = ROOT / "Grothe/HJM/Data.lean"
SHA = "d554af0d26e218a4fc2f2795e99a9ef39eb5077ceecf55a0daac46909e14dca1"


def literal_rows(tree):
    rows, weights = {}, None
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
            if name.startswith("RHO_") and name[4:].isdigit():
                entries = node.value.args[0].elts
                rows[int(name[4:])] = [(e.elts[0].value, Q(e.elts[1].value)) for e in entries]
            if name == "WEIGHTS":
                weights = [Q(e.value) for e in node.value.args[0].args[1].elts]
    return rows, weights


def lean_q(q):
    return f"({q.numerator} : ℚ) / {q.denominator}" if q.denominator != 1 else f"({q.numerator} : ℚ)"


def generate():
    data = SRC.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA:
        sys.exit(f"source hash mismatch: {digest}")
    rows, weights = literal_rows(ast.parse(data.decode()))
    assert sorted(rows) == [1, 2, 3, 4, 5] and len(weights) == 6
    out = ["/-! Generated by tools/gen_hjm_data.py from data/hjm/audit_sparse6_altgroups.py",
           f"(HJM canonical certificate, commit 7139f4cb8d0f30c2eb4c1267c46732a9d5229c3f, sha256 {digest}); do not edit. -/",
           "", "import Grothe.Upper.Head", "", "namespace Grothe.HJM", ""]
    for r in range(1, 6):
        deg = max(m for m, _ in rows[r])
        dense = [Q(0)] * (deg + 1)
        for m, c in rows[r]:
            dense[m] = c
        assert sum(abs(c) for c in dense) <= 1
        out.append(f"/-- The coefficients of `P_{r}` (`ρ_{r}(t) = t P_{r}(t²)`). -/")
        out.append(f"def pList{r} : List ℚ := [" + ", ".join(lean_q(c) for c in dense) + "]")
        out.append("")
    out.append("/-- The signed weights `w₁, …, w₆` (branch 6 is the asymmetric origin branch). -/")
    out.append("def weights : List ℚ := [" + ", ".join(lean_q(w) for w in weights) + "]")
    out += ["", "end Grothe.HJM", ""]
    return "\n".join(out), digest


if __name__ == "__main__":
    text, digest = generate()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else "Grothe/HJM/Data.lean is stale")
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} (source sha256 {digest})")
