#!/usr/bin/env python3
"""Generate bounded Lean checks of the actual typed frozen witness.
Agent-ID: codex-7c2e. All arithmetic targets are untrusted until Lean checks them.
"""
import argparse
from pathlib import Path
from gen_frozen_integer_data import generate, GRADES, PART_SIZE

ROOT = Path(__file__).resolve().parents[1]


def guard(names):
    lines = ['run_cmd do',
        '  let allowed : Array Lean.Name := #[``propext, ``Classical.choice, ``Quot.sound]']
    for name in names:
        lines += [f'  let unexpected := (← Lean.collectAxioms ``{name}).filter fun n => !allowed.contains n',
                  '  unless unexpected.isEmpty do',
                  f'    throwError "Unexpected axioms in {name}: {{unexpected}}"']
    return lines + [f'#print axioms {name}' for name in names] + ['']


def header(imports, ns):
    return [*['import ' + i for i in imports], 'import Lean.Util.CollectAxioms', '',
        '/-! Generated by tools/gen_frozen_integer_checks.py; do not edit.',
        'Statements refer to the actual named source arrays. Agent-ID: codex-7c2e. -/', '',
        f'namespace {ns}', 'open Grothe.UpperChaos', 'open ArraySquareEnergy', '',
        'set_option maxRecDepth 4096', 'set_option maxHeartbeats 400000', '']


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--grades', default='0,90')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    def write(path, text):
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'Stale actual frozen certificate: {path}')
        else:
            path.write_text(text)
    selected = list(range(GRADES)) if args.grades == 'all' else [int(x) for x in args.grades.split(',')]
    if any(not 0 <= q < GRADES for q in selected):
        parser.error('grade outside actual support')
    _, _, grades = generate()
    dest = ROOT / 'Grothe/UpperChaos/FrozenSource'
    for q, values in enumerate(grades):
        grade = f'frozenCorrectionGrade{q:03d}'
        ns = f'Grothe.UpperChaos.FrozenSource.Grade{q:03d}'
        parts = [(f'{grade}Part{k // PART_SIZE:03d}', values[k:k + PART_SIZE])
                 for k in range(0, len(values), PART_SIZE)]
        lines = header([f'Grothe.UpperChaos.FrozenSource.Grade{q:03d}Data',
                        'Grothe.UpperChaos.ArraySquareEnergy'], ns)
        for i, (part, items) in enumerate(parts):
            lines += [f'theorem part{i:03d}_size : {part}.size = {len(items)} := by rfl', '']
        size_rules = [grade] + (['Array.size_append'] if len(parts) > 1 else []) + [f'part{i:03d}_size' for i in range(len(parts))]
        lines += [f'theorem grade_size : {grade}.size = {len(values)} := by']
        if len(parts) == 1:
            lines += ['  exact part000_size']
        else:
            lines += ['  calc',
                      '    _ = (' + ' + '.join(str(len(items)) for _, items in parts) + ' : Nat) := by',
                      '      simp only [' + ', '.join(size_rules) + ']',
                      '    _ = _ := by decide +kernel']
        lines += ['', f'end {ns}', '']
        lines += guard([ns + '.grade_size'])
        write(dest / f'Grade{q:03d}Sizes.lean', '\n'.join(lines))
        if q not in selected:
            continue
        lines = header([f'Grothe.UpperChaos.FrozenSource.Grade{q:03d}Sizes'], ns)
        for i, (part, items) in enumerate(parts):
            target = sum(x * x for x in items)
            lines += [f'theorem part{i:03d}_energy : energy {part} = {target} := by',
                      '  decide +kernel', '']
        total = sum(x * x for x in values)
        energy_rules = [grade] + (['energy_append'] if len(parts) > 1 else []) + [f'part{i:03d}_energy' for i in range(len(parts))]
        lines += [f'theorem grade_energy : energy {grade} = {total} := by']
        if len(parts) == 1:
            lines += ['  exact part000_energy']
        else:
            lines += ['  calc',
                      '    _ = (' + ' + '.join(str(sum(x*x for x in items)) for _, items in parts) + ' : Int) := by',
                      '      simp only [' + ', '.join(energy_rules) + ']',
                      '    _ = _ := by decide +kernel']
        lines += ['', f'end {ns}', '']
        lines += guard([ns + '.grade_energy'])
        write(dest / f'Grade{q:03d}Check.lean', '\n'.join(lines))
        binding_ns = f'Grothe.UpperChaos.FrozenSource.Grade{q:03d}Production'
        lines = header(['Grothe.UpperChaos.TaylorFrozenCoefficients',
                        'Grothe.UpperChaos.FrozenSource.Sizes',
                        f'Grothe.UpperChaos.FrozenSource.Grade{q:03d}Check',
                        'Grothe.UpperChaos.ThirdFoldRectangle',
                        'Mathlib.Algebra.BigOperators.Ring.Finset',
                        'Mathlib.Data.Rat.Cast.Order',
                        'Mathlib.Tactic.NormNum'], binding_ns)
        lines += ['open scoped BigOperators', '']
        prefix = [f'frozenCorrectionGrade{r:03d}' for r in range(q)]
        suffix = [f'frozenCorrectionGrade{r:03d}' for r in range(q + 1, GRADES)]
        offset = sum(len(g) for g in grades[:q])
        split_rules = ['frozenCorrectionData', 'preData', 'postData', 'Array.append_assoc']
        if not prefix:
            split_rules.append('Array.empty_append')
        if not suffix:
            split_rules.append('Array.append_empty')
        lines += ['private def preData : Array Int := ' + (' ++ '.join(prefix) or '#[]'), '',
                  'private def postData : Array Int := ' + (' ++ '.join(suffix) or '#[]'), '',
                  f'private theorem source_split : frozenCorrectionData = preData ++ {grade} ++ postData := by',
                  '  simp only [' + ', '.join(split_rules) + ']', '',
                  f'private theorem prefix_size : preData.size = {offset} := by']
        if q == 0:
            lines += ['  rfl']
        elif q == 1:
            lines += ['  exact Grade000.grade_size']
        else:
            lines += ['  calc',
                      '    _ = (' + ' + '.join(str(len(g)) for g in grades[:q]) + ' : Nat) := by',
                      '      simp only [preData, Array.size_append, ' +
                      ', '.join(f'Grade{r:03d}.grade_size' for r in range(q)) + ']',
                      '    _ = _ := by decide +kernel']
        lines += ['', f'theorem at_eq (c d : Nat) (hc : c < {q + 2}) (hd : d < {q + 1}) :',
                  f'    frozenCorrectionAt {q} c d = {grade}[c * {q + 1} + d]?.getD 0 := by',
                  f'  have hk : c * {q + 1} + d < {grade}.size := by',
                  f'    rw [Grade{q:03d}.grade_size]', '    omega',
                  f'  have hoff : gradedFlatIndex {q} c d = preData.size + (c * {q + 1} + d) := by',
                  '    rw [prefix_size]', '    simp only [gradedFlatIndex]', '    omega',
                  f'  change frozenCorrectionData[gradedFlatIndex {q} c d]?.getD 0 = _',
                  '  rw [source_split, hoff, Array.append_assoc,',
                  '    Array.getElem?_append_right (Nat.le_add_right _ _), Nat.add_sub_cancel_left,',
                  '    Array.getElem?_append_left hk]', '',
                  'theorem integer_energy :',
                  f'    (∑ c ∈ Finset.range {q + 2}, ∑ d ∈ Finset.range {q + 1},',
                  f'      frozenCorrectionAt {q} c d ^ 2) = {total} := by',
                  '  calc',
                  f'    _ = ∑ c ∈ Finset.range {q + 2}, ∑ d ∈ Finset.range {q + 1},',
                  f'        ({grade}[c * {q + 1} + d]?.getD 0) ^ 2 := by',
                  '      apply Finset.sum_congr rfl', '      intro c hc',
                  '      apply Finset.sum_congr rfl', '      intro d hd',
                  '      rw [at_eq c d (Finset.mem_range.mp hc) (Finset.mem_range.mp hd)]',
                  f'    _ = ArraySquareEnergy.energy {grade} :=',
                  f'      ThirdFoldRectangle.grade_rectangle_fold _ {q + 2} {q + 1} Grade{q:03d}.grade_size',
                  f'    _ = _ := Grade{q:03d}.grade_energy', '',
                  'theorem coefficient_energy :',
                  f'    (∑ c ∈ Finset.range {q + 2}, ∑ d ∈ Finset.range {q + 1},',
                  f'      frozenCorrectionCoeff {q} c d ^ 2) =',
                  f'      ({total} : ℚ) / (2 : ℚ) ^ 412 := by',
                  '  unfold frozenCorrectionCoeff',
                  '  simp only [div_pow]',
                  '  simp only [div_eq_mul_inv, ← Finset.sum_mul, ← Int.cast_pow, ← Int.cast_sum]',
                  '  rw [integer_energy, ← pow_mul]',
                  '  norm_num only [Int.cast_ofNat]', '',
                  f'end {binding_ns}', '']
        lines += guard([binding_ns + '.' + name for name in
                        ['at_eq', 'integer_energy', 'coefficient_energy']])
        write(dest / f'Grade{q:03d}Production.lean', '\n'.join(lines))
    ns = 'Grothe.UpperChaos.FrozenSource'
    lines = header(['Grothe.UpperChaos.TaylorFrozenData'] +
                   [f'Grothe.UpperChaos.FrozenSource.Grade{q:03d}Sizes' for q in range(GRADES)], ns)
    lines += ['theorem source_grade_count : frozenCorrectionGrades.size = 91 := by rfl', '',
              'theorem source_size : frozenCorrectionData.size = 259532 := by',
              '  calc',
              '    _ = (' + ' + '.join(str(len(g)) for g in grades) + ' : Nat) := by',
              '      simp only [frozenCorrectionData, Array.size_append, ' +
              ', '.join(f'Grade{q:03d}.grade_size' for q in range(GRADES)) + ']',
              '    _ = _ := by decide +kernel',
              '', f'end {ns}', '']
    lines += guard([ns + '.source_size'])
    write(dest / 'Sizes.lean', '\n'.join(lines))
    ns = 'Grothe.UpperChaos.FrozenSourceBinding'
    lines = header(['Grothe.UpperChaos.TaylorFrozenCoefficients',
                    'Grothe.UpperChaos.FrozenSource.Sizes',
                    'Mathlib.Tactic.NormNum'], ns)
    lines += ['theorem source_array : frozenCorrectionInts = frozenCorrectionData := rfl', '',
              'theorem source_size : frozenCorrectionInts.size = 259532 := FrozenSource.source_size', '']
    for k, label in [(0, 'first'), (1, 'second')]:
        value = grades[0][k]
        lines += [f'theorem data_{label} : frozenCorrectionData[{k}]? = some ({value} : Int) := by',
                  '  simp only [frozenCorrectionData, Array.append_assoc]',
                  '  rw [',
                  f'    Array.getElem?_append_left (xs := frozenCorrectionGrade000) (i := {k})',
                  '      (by rw [FrozenSource.Grade000.grade_size]; decide)]',
                  '  rfl', '',
                  f'theorem at_{label} : frozenCorrectionAt 0 {k} 0 = {value} := by',
                  f'  change frozenCorrectionData[{k}]?.getD 0 = _',
                  f'  rw [data_{label}]', '  rfl', '']
    for label, c, m, d in [('first', 0, -8482657366253297, 73786976294838206464),
                            ('second', 1, 3578247007894465, 9223372036854775808)]:
        lines += [f'theorem coefficient_{label} : frozenCorrectionCoeff 0 {c} 0 = ({m} / {d} : ℚ) := by',
                  '  unfold frozenCorrectionCoeff', f'  rw [at_{label}]', '  norm_num', '']
    lines += [f'end {ns}', '']
    lines += guard([ns + '.' + name for name in
                    ['source_array', 'source_size', 'coefficient_first', 'coefficient_second']])
    write(ROOT / 'Grothe/UpperChaos/FrozenSourceBinding.lean', '\n'.join(lines))
    print(f'Generated all {GRADES} actual grade sizes and energy checks for grades {selected}.')


if __name__ == '__main__':
    main()
