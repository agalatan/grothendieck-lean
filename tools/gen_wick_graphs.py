"""Generate Grothe/LowerAnalytic/WickGraphData.lean: edge-step certificates for E F^2, E F^4, E F^6.

A partial graph on N vertices (each vertex a copy of the cubic chaos F) is a canonical edge list
(normalised pairs, sorted).  From the empty graph, repeatedly pick the vertex v0 of largest degree
< 3 and apply the edge step  k * val(es) = sum_{t != v0, deg t < 3} val(es + [(v0, t)])  (k = 3 - deg v0),
canonicalising each successor by brute force over vertex relabellings (the relabelling is the
certificate checked by decide).  The flow mu (coefficient of each state reached from the root)
gives the linear combination closing the proof.

Usage:  python3 tools/gen_wick_graphs.py Grothe/LowerAnalytic/WickGraphData.lean
"""
import itertools, sys
from fractions import Fraction as Fr
def norm(es): return tuple(sorted((min(a,b),max(a,b)) for a,b in es))
def canon(es,N):
    best=None;bp=None
    for p in itertools.permutations(range(N)):
        k=norm([(p[a],p[b]) for a,b in es])
        if best is None or k<best: best=k;bp=p
    return best,bp
def deg(es,N):
    d=[0]*N
    for a,b in es: d[a]+=1;d[b]+=1
    return d
def run(N,rule):
    root=()
    states={}; order=[]
    stack=[root]
    while stack:
        s=stack.pop()
        if s in states: continue
        d=deg(s,N)
        if all(x==3 for x in d): states[s]=None; continue
        cands=[v for v in range(N) if d[v]<3]
        if rule=='max': v0=max(cands,key=lambda v:(d[v],-v))
        else: v0=min(cands,key=lambda v:(d[v],v))
        succ=[]
        for t in range(N):
            if t==v0 or d[t]>=3: continue
            c,p=canon(list(s)+[(v0,t)],N)
            succ.append((t,c,p))
            stack.append(c)
        states[s]=(v0,3-d[v0],succ)
    return states
def lean_list(es): return '[' + ', '.join('(%d, %d)'%e for e in es) + ']'
def lean_frac(q):
    q=Fr(q)
    if q.denominator==1: return '(%d : ℝ)'%q.numerator
    return '(%d / %d : ℝ)'%(q.numerator,q.denominator)
def gen(N, name, out):
    st=run(N,'max')
    # names
    keys=sorted(st.keys(), key=lambda s:(len(s),s))
    nm={s:'%s_%d'%(name,i) for i,s in enumerate(keys)}
    # mu flow: topological by edge count
    mu={s:Fr(0) for s in keys}; mu[()] = Fr(1)
    for s in keys:
        if st[s] is None: continue
        v0,k,succ=st[s]
        for t,c,p in succ: mu[c]+=mu[s]/k
    for s in keys:
        out.append('/-- A partial graph on %d vertices. -/\ndef %s : List (Fin %d × Fin %d) := %s\n'%(N,nm[s],N,N,lean_list(s)))
    full=[s for s in keys if st[s] is None]
    lines=[]
    lines.append('theorem %s_moment : E (F ^ %d) = %s := by'%(name,N,
        ' + '.join('%s * gval E F %s'%(lean_frac(mu[s]),nm[s]) for s in full if mu[s]!=0)))
    lines.append('  rw [← gval_empty E F (N := %d)]'%N)
    lines.append('  change gval E F %s = _'%nm[()])
    lc=[]
    for s in keys:
        if st[s] is None: continue
        v0,k,succ=st[s]
        if mu[s]==0: continue
        sl='['+', '.join('(%d, ![%s], %s)'%(t,', '.join(str(x) for x in p),nm[c]) for t,c,p in succ)+']'
        lines.append('  have h%s : ((%d : ℕ) : ℝ) * gval E F %s = _ :='%(nm[s].split('_')[-1],k,nm[s]))
        lines.append('    gval_step_cert hE hF (v₀ := %d) (succ := %s) (by decide +kernel)'%(v0,sl))
        lc.append('%s * h%s'%(lean_frac(mu[s]/k), nm[s].split('_')[-1]))
    lines.append('  simp only [List.map_cons, List.map_nil, List.sum_cons, List.sum_nil, Nat.cast_ofNat, Nat.cast_one] at *')
    lines.append('  linear_combination ' + ' + '.join(lc))
    return full, mu, nm, '\n'.join(lines)
out=[]
res={}
thms=[]
for N,name in [(2,'wg2'),(4,'wg4'),(6,'wg6')]:
    full,mu,nm,th=gen(N,name,out)
    res[N]=(full,mu,nm); thms.append(th)
    print(N,[(nm[s],str(mu[s]),s) for s in full], file=sys.stderr)
hdr='''import Grothe.LowerAnalytic.WickGraph

/-!
# The second, fourth and sixth moments of a cubic chaos as multigraph sums

Generated by `tools/gen_wick_graphs.py`: the edge-step certificates (`gval_step_cert`) of the
moments `E F²`, `E F⁴`, `E F⁶` of a cubic chaos, ending in the closed (cubic) multigraphs.
Each partial graph is stored in a canonical form (normalised sorted edge list).
-/

namespace Grothe.LowerAnalytic

noncomputable section

'''
body='\n'.join(out)
sec='''
section moments

variable {ι : Type*} [Fintype ι] [DecidableEq ι] {E : MvPolynomial ι ℝ →ₗ[ℝ] ℝ}
  (hE : IsGaussianExpectation E) {F : MvPolynomial ι ℝ} (hF : Chaos3 F)
include hE hF

'''+'\n\n'.join(thms)+'\n\nend moments\n\nend\n\nend Grothe.LowerAnalytic\n'
open(sys.argv[1],'w').write(hdr+body+sec)
