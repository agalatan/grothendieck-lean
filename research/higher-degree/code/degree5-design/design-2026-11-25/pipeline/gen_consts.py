# Generate glconsts.h: outward-rounded double enclosures (hex) of Gauss-Legendre nodes/weights on [-1,1],
# 1/pi and ln 2, all computed with Arb (python-flint).  claude-b9ee d5cert worker, 16 Nov 2026.  [C-input]
import sys
from flint import arb, ctx
ctx.prec = 256
def enclose(a):
    """doubles lo <= a <= hi (lo, hi exact binary64), from an arb ball."""
    import math
    L = a.lower(); U = a.upper()          # exact endpoints (radius 0)
    lo = float(L); hi = float(U)
    while arb(lo) > L: lo = math.nextafter(lo, -math.inf)
    while arb(hi) < U: hi = math.nextafter(hi, math.inf)
    assert arb(lo) <= L and arb(hi) >= U
    return lo, hi
NS = [4, 6, 8, 10, 12, 16, 20, 24, 32]
out = ['// generated by gen_consts.py (python-flint %s, prec 256); do not edit' % __import__('flint').__version__]
pi = arb.pi(); lo, hi = enclose(1 / pi); out.append('static const double INVPI_LO = %s, INVPI_HI = %s;' % (lo.hex(), hi.hex()))
l2 = arb(2).log(); lo, hi = enclose(l2); out.append('static const double LN2_LO = %s, LN2_HI = %s;' % (lo.hex(), hi.hex()))
out.append('static const int GL_NS[%d] = {%s};' % (len(NS), ','.join(map(str, NS))))
for n in NS:
    xs = []; ws = []
    for k in range(n):
        r, w = arb.legendre_p_root(n, k, weight=True)
        xs.append(enclose(r)); ws.append(enclose(w))
    # sanity: weights sum to 2, nodes symmetric
    s = sum((arb(w[0]) for w in ws), arb(0)); assert abs(float(s) - 2) < 1e-12
    out.append('static const double GLX%d[%d][2] = {%s};' % (n, n, ','.join('{%s,%s}' % (a.hex(), b.hex()) for a, b in xs)))
    out.append('static const double GLW%d[%d][2] = {%s};' % (n, n, ','.join('{%s,%s}' % (a.hex(), b.hex()) for a, b in ws)))
out.append('static const double* GLX_[%d] = {%s};' % (len(NS), ','.join('&GLX%d[0][0]' % n for n in NS)))
out.append('static const double* GLW_[%d] = {%s};' % (len(NS), ','.join('&GLW%d[0][0]' % n for n in NS)))
open(sys.argv[1] if len(sys.argv) > 1 else 'glconsts.h', 'w').write('\n'.join(out) + '\n')
print('ok', NS)
