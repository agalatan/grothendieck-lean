#!/usr/bin/env python3
"""codex-6e2b: regenerate certified radial beta0 data for the secant checker.

The output is not a trusted cache. Default execution replays the profile
Hessian certificate supplying |Fraw second derivative|<=1; callers that
already replayed that dependency can use --skip-dependency-replay.
All values are recomputed by the audited signed-density Arb quadrature.
"""
import argparse
from fractions import Fraction
import importlib.util
import json
from pathlib import Path
import time

ROOT = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('content_next_bound', ROOT/'content_next_bound.py')
source = importlib.util.module_from_spec(spec)
spec.loader.exec_module(source)
arb = source.arb
SCALE = 100000000


def integer_endpoint(value, upper):
    endpoint = value.upper() if upper else value.lower()
    rounded = endpoint.ceil() if upper else endpoint.floor()
    integer = rounded.unique_fmpz()
    assert integer is not None, (str(value), str(rounded))
    result = int(integer)
    assert arb(result) >= value.upper() if upper else arb(result) <= value.lower()
    return result


def generate(tolerance):
    nodes = [Fraction(0)]+[Fraction(2*j+1,200) for j in range(600)]+[Fraction(6)]
    assert len(nodes)==602 and nodes[0]==0 and nodes[-1]==6
    assert all(0<r-l<=Fraction(1,100) for l,r in zip(nodes,nodes[1:]))
    rows=[]
    started=time.time()
    for j,R in enumerate(nodes):
        if R==0:
            raw=arb(0); cells=0
        else:
            # Radius <= tolerance for Fraw=R(c0+h(R^2)).  At small R,
            # max(R,.05) keeps h quadrature reasonably tight as well.
            htol=arb(str(tolerance))/arb(str(max(R,Fraction(1,20))))
            h,cells=source.field_point(R,tolerance=htol)
            raw=arb(str(R))*(source.pr.c0+h)
            assert raw.rad() < arb(str(tolerance)), (str(R),str(raw))
        low=integer_endpoint(raw*SCALE,False)
        high=integer_endpoint(raw*SCALE,True)
        assert low<=high
        ri=R*SCALE
        assert ri.denominator==1
        rows.append((j,ri.numerator,low,high))
        if (j+1)%25==0 or j+1==len(nodes):
            print(json.dumps({'progress':j+1,'total':len(nodes),'R':str(R),
                              'raw':str(raw),'cells':cells,
                              'seconds':time.time()-started}),flush=True)
    assert rows[0]==(0,0,0,0)
    assert rows[-1][1]==6*SCALE
    assert all(l[1]<r[1] and r[1]-l[1]<=SCALE//100 for l,r in zip(rows,rows[1:]))
    return rows


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--skip-dependency-replay',action='store_true')
    parser.add_argument('--raw-tolerance',default='1/20000')
    args=parser.parse_args()
    tolerance=Fraction(args.raw_tolerance)
    assert 0<tolerance<=Fraction(1,20000)
    start=time.time()
    if args.skip_dependency_replay:
        print('CONDITIONAL RUN: N_Phi<1/3 must already be certified by the calling chain.',flush=True)
    else:
        result=source.base.certify_global(emit=False)
        print(json.dumps({'dependency':result}),flush=True)
    rows=generate(tolerance)
    contents=['# Agent-ID: codex-6e2b',
              '# C: outward Arb enclosures regenerated by secant_profile_table.py.',
              '# Fraw(R)=R*(c0+h_(3/5)(R^2)); Fraw(0)=0.',
              '# Linear interpolation error <= (R_hi-R_lo)^2/8 from certified |Fraw second derivative|<=1.',
              '# count denominator',f'{len(rows)} {SCALE}',
              '# index R_integer Fraw_lower_integer Fraw_upper_integer']
    contents.extend(' '.join(map(str,row)) for row in rows)
    output=ROOT/'secant_profile_table.txt'
    output.write_text('\n'.join(contents)+'\n')
    print(json.dumps({'claim':'certified secant beta0 radial table',
                      'nodes':len(rows),'scale':SCALE,'raw_radius_tolerance':str(tolerance),
                      'dependency_replayed_here':not args.skip_dependency_replay,
                      'path':str(output),'seconds':time.time()-start,'passed':True}),flush=True)


if __name__=='__main__':
    main()
