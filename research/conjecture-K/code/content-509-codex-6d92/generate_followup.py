#!/usr/bin/env python3
"""Numerical discovery only. Exact acceptance is in verify_staircase.py."""
from pathlib import Path
import importlib.util
import sys,json,time,warnings
from fractions import Fraction as Q
import numpy as np
warnings.filterwarnings('ignore')
sys.dont_write_bytecode=True
source=Path(sys.argv[1])/'research/conjecture-K/code/raw-content-2026-11-17-gemini-5331/generate_stein_duals.py'
spec=importlib.util.spec_from_file_location('gen',source)
g=importlib.util.module_from_spec(spec)
spec.loader.exec_module(g)
knots_q,knots,starts,coeff=g.load_base_inputs()
caps=g.cs.load_caps()
energies=[Q(j,1000) for j in range(35,47)]+[Q('.0463')]
models=[]
now=time.monotonic()
for u in energies:
    uf=float(u)
    trial_grid=np.unique(np.r_[np.linspace(0,12,481),np.linspace(12,40,113),np.geomspace(40,256,65),knots,starts/uf])
    val_grid=np.unique(np.r_[np.linspace(0,12,4001),np.linspace(12,40,1401),np.linspace(40,256,4001),knots, starts/uf])
    for chi in map(Q,('.36','.85','1.5','2.2')):
        grid=trial_grid.copy()
        for i in range(3):
            sol=g.solve_socp(uf,float(chi),knots,starts,coeff,grid)
            gap=g.candidate_gap(uf,sol,knots,val_grid,starts,coeff)
            bad=np.flatnonzero(gap < -1e-7)
            if not len(bad):
                break
            grid=np.unique(np.r_[grid,val_grid[bad[np.argsort(gap[bad])[:120]]]])
        for bump in map(Q,('1e-8','3e-8','1e-7','3e-7','1e-6','3e-6','1e-5')):
            row=g.convert_row(u,knots_q,sol,bump)
            ok,test=g.check_node_any_u(row,caps,depth=20)
            if ok:
                del row['knots']
                row['chi_anchor']=str(chi)
                row['P0_slack']=str(bump)
                models.append(row)
                break
        else:
            print('SKIPPED',u,chi,test,flush=True)
    out={'provenance':'Generated by generate_followup.py using #518 spectral Stein template. Coefficients checked exactly.',
         'agent_id':'codex-6d92','knots':knots_q,'energies':[str(u) for u in energies],'models':models}
    (Path(__file__).resolve().parent/'stein-supplement.json').write_text(json.dumps(out,separators=(',',':'))+'\n')
    print('u',str(u),len(models),round(time.monotonic()-now,2),flush=True)
