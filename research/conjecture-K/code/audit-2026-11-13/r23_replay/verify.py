Ahi=[Q(row['A'][1],data['value_denominator']) for row in data['rows']]
Hhi=[Q(row['H'][1],data['value_denominator']) for row in data['rows']]
D=2**40

def ceilq(x):return (x.p+x.q-1)//x.q

class Linear:
 def __init__(self,xs,left,right):
  self.xs=xs;self.xf=[float(x) for x in xs];self.left=left
  self.slope=[(b-a)/(r-l) for a,b,l,r in zip(left,right,xs,xs[1:])]
  self.f0=[Q(0)];self.f1=[Q(0)]
  for x,r,c,m in zip(xs,xs[1:],left,self.slope):
   d=r-x
   f=c*d+m*d*d/2
   self.f0.append(self.f0[-1]+f)
   self.f1.append(self.f1[-1]+x*f+c*d*d/2+m*d**3/3)
 def idx(self,x):
  # Float supplies only an initial guess; exact comparisons validate it.
  i=min(len(self.left)-1,max(0,bisect.bisect_right(self.xf,float(x))-1))
  while i>0 and x<self.xs[i]:i-=1
  while i<len(self.left)-1 and x>self.xs[i+1]:i+=1
  assert self.xs[i]<=x<=self.xs[i+1]
  return i
 def at(self,x):
  i=self.idx(x);return self.left[i]+self.slope[i]*(x-self.xs[i])
 def prim(self,x):
  i=self.idx(x);s=self.xs[i];d=x-s;c=self.left[i];m=self.slope[i]
  f=c*d+m*d*d/2
  return self.f0[i]+f,self.f1[i]+s*f+c*d*d/2+m*d**3/3

left=[];right=[]
for i in range(len(xs)-2):
 h=xs[i+1]-xs[i];c=Alo[i];s=(Alo[i+1]-c)/h
 if i==0:eps=Ahi[0]-Alo[1]
 else:
  sl=(Alo[i]-Ahi[i-1])/(xs[i]-xs[i-1])
  sr=(Ahi[i+2]-Alo[i+1])/(xs[i+2]-xs[i+1])
  dl=s-sl;dr=sr-s
  eps=Q(0) if dl<=0 or dr<=0 else h*dl*dr/(dl+dr)
 eps=Q(ceilq(eps*D),D)
 left.append(Alo[i]-eps);right.append(Alo[i+1]-eps)
 assert left[-1]>0 and right[-1]>0
AA=Linear(xs[:-1],left,right)
HH=Linear(xs[:-1],Hhi[:-2],Hhi[1:-1])

def havg(u,y):
 v=u*y;d=v-u
 if not d:return HH.at(u)
 return (HH.prim(v)[0]-HH.prim(u)[0])/d

def aavg(u,y):
 v=u*y;d=v-u
 if not d:return AA.at(u)/2
 f,g=AA.prim(v);f0,g0=AA.prim(u)
 return (v*(f-f0)-(g-g0))/(d*d)


def poly_lower(cs,l,r):
 c0,c1,c2,c3=cs;d=r-l
 cc=[c0+c1*l+c2*l*l+c3*l**3,d*(c1+2*c2*l+3*c3*l*l),d*d*(c2+3*c3*l),d**3*c3]
 return min(sum((cc[j]*Q(math.comb(k,j),math.comb(3,j)) for j in range(k+1)),Q(0)) for k in range(4))

ap=data['profile']['a'];bp=data['profile']['b']
a=arb(ap[0])/ap[1];b=arb(bp[0])/bp[1]
I=arb.pi()/(2*(a*b).sqrt())*(a/b).exp()*(a/b).sqrt().erfc()
j0=arb.pi().sqrt()/b-2*(1+a/b)*I
assert j0<0 and j0>-arb(17)/10
assert AA.at(Q(1463,10000))>1
# d_u(v) >= (v-u-1/10)/10 for v >= 70u, using A(u+1/10)>1.
