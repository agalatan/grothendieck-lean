class Linear:
 def __init__(self,xs,left,right):
  self.xs=xs;self.xf=[float(x) for x in xs];self.left=left
  self.slope=[(b-a)/(r-l) for a,b,l,r in zip(left,right,xs,xs[1:])]
  self.f0=[Q(0)];self.f1=[Q(0)]
  for x,r,c,m in zip(xs,xs[1:],left,self.slope):
   d=r-x
   f=c*d+m*d*d/2
   self.f0.append(self.f0[-1]+f)
   self.f1.append(self.f1[-1]+x*f+c*d*d/2+m*d**3/3)
 def idx(self,x):
  # Float supplies only an initial guess; exact comparisons validate it.
  i=min(len(self.left)-1,max(0,bisect.bisect_right(self.xf,float(x))-1))
  while i>0 and x<self.xs[i]:i-=1
  while i<len(self.left)-1 and x>self.xs[i+1]:i+=1
  assert self.xs[i]<=x<=self.xs[i+1]
  return i
 def at(self,x):
  i=self.idx(x);return self.left[i]+self.slope[i]*(x-self.xs[i])
 def prim(self,x):
  i=self.idx(x);s=self.xs[i];d=x-s;c=self.left[i];m=self.slope[i]
  f=c*d+m*d*d/2
  return self.f0[i]+f,self.f1[i]+s*f+c*d*d/2+m*d**3/3

