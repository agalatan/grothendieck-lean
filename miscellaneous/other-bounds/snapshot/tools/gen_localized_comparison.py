#!/usr/bin/env python3
"""Generate finite-band comparison data from inherited coefficient-error bounds.

No Gaussian integral or optimizer is trusted here. The source bounds remain
explicit inputs. The new norm radii use only the stored finite energy table
and its existing l1 error. A separate native Lean check verifies the masses.
"""
from fractions import Fraction as Q
import hashlib
import json
from math import factorial, isqrt
from pathlib import Path
import sys
sys.path.insert(0,str(Path(__file__).resolve().parent))
from head_weights import Weights
from gen_upper_data import verify_linear_refinement

ROOT=Path(__file__).resolve().parents[1]

def ceil_grid(x,scale):return Q(-((-x.numerator*scale)//x.denominator),scale)

def sqrt_up(x,scale=10**12):
    n=isqrt(x.numerator*scale**2//x.denominator)
    if n*n*x.denominator<x.numerator*scale**2:n+=1
    assert Q(n,scale)**2>=x
    return Q(n,scale)

def main(check=False):
    if not __debug__:raise RuntimeError('Run without -O: assertions are certificate checks')
    src=ROOT/'data/localized-comparison/inputs/taylor_comparison_result.json'
    assert hashlib.sha256(src.read_bytes()).hexdigest()=='5619546626b7588ce64a2229aa58b0d161bde613dbf9a5eaad94a3ef93461915'
    j=json.loads(src.read_text());p=ROOT/'data/upper-preprocess/certificate.json'
    d=json.loads(p.read_text());entries=[(n,m,Q(v)) for n,m,v in d['energies']]
    raw={k:d[k] for k in ['profileQ','aQ','bQ','etaQ','phaseEpsQ','phase']}
    raw_hash=hashlib.sha256(json.dumps(raw,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    assert raw_hash=='420f677e6cf18e8c74fb7fce89c74b58f64676031f8c788ce36543e116753af7'
    weights=Weights(d['pList'],d['qList']);bands=[];rounding=Q(j['rounding_error']);assert rounding<Q(1,10**18)
    def add(lo,hi,eps,origin):
        mass=sum(v*weights(n,m)**2 for n,m,v in entries if lo<n+m and (hi==0 or n+m<=hi))
        cap=sqrt_up(mass+Q(d['energyErrQ']))
        bands.append(dict(lo=lo,hi=hi,error=str(ceil_grid(eps,10**18)),norm=str(cap),origin=origin))
    add(0,0,Q(1,10**18),'frozen-vector rounding')
    for row in j['details']:
        power=row['power'];fac=factorial(power);cursor=0
        for band in row['bands']:
            assert band['lo']==cursor;cursor=band['hi']
            add(band['lo'],band['hi'],Q(band['coefficient_error_cap'])/fac,f'Taylor power {power}, finite band')
        assert cursor==row['cutoff']
        add(row['cutoff'],0,Q(row['tail_cap'])/fac,f'Taylor power {power}, high tail')
    cross=sum(Q(b['norm'])*Q(b['error']) for b in bands)
    radius=sum(Q(b['error']) for b in bands)
    triangle_cap=ceil_grid(2*cross+radius**2,10**15)
    def overlap(a,b):
        return not ((a['hi'] != 0 and a['hi'] <= b['lo']) or
                    (b['hi'] != 0 and b['hi'] <= a['lo']))
    quadratic=sum(Q(a['error'])*Q(b['error']) for a in bands for b in bands if overlap(a,b))
    cap=ceil_grid(2*cross+quadratic,10**15)
    assert cap<Q(1065637497,10**15)
    delta=cap+sum(Q(d[k]) for k in ['headCapQ','energyErrQ','hardy_tail'])
    score=Q(d['slopeQ'])-delta;bound=1/score;headline=ceil_grid(bound,10**12)
    recipe=dict(bands=bands,comparison_cap=str(cap),error_radius=str(radius),cross=str(cross),
                triangle_cap=str(triangle_cap),overlap_quadratic=str(quadratic),
                delta=str(delta),score=str(score),bound=str(bound),headline=f'{float(headline):.12f}',
                source_sha256=hashlib.sha256(src.read_bytes()).hexdigest(),
                rounder_source_sha256=raw_hash,
                weight_method='128-bit outward interval costs, 21 unshifted coefficients; unit cost otherwise',
                weight_script_sha256=hashlib.sha256((ROOT/'tools/head_weights.py').read_bytes()).hexdigest(),
                energy_source_sha256=hashlib.sha256(json.dumps({'energies':d['energies'],
                    'pList':d['pList'],'qList':d['qList'],
                    'energyErrQ':d['energyErrQ']},sort_keys=True,separators=(',',':')).encode()).hexdigest(),
                scope='Weighted finite selected-block comparison; unchanged inherited Gaussian component-error inputs.')
    recipe_path=ROOT/'data/localized-comparison/recipe.json'
    recipe_text=json.dumps(recipe,indent=2)+'\n'
    if check:assert recipe_path.read_text()==recipe_text
    else:recipe_path.write_text(recipe_text)
    def rat(x):
        q=Q(x);return f'({q.numerator} : ℚ) / {q.denominator}'
    lines=['import GrotheKernel.BandMass\nimport Mathlib.Data.Rat.Init\n',
           '/-! Generated by tools/gen_localized_comparison.py; do not edit. -/\n',
           'namespace Grothe.Upper\nopen GrotheKernel\n',
           'def comparisonBands : List ComparisonBand := [']
    lines.append(',\n'.join(f'  ⟨{b["lo"]}, {b["hi"]}, {rat(b["error"])}, {rat(b["norm"])}⟩' for b in bands)+']\n')
    lines.append(f'def comparisonTriangleQ : ℚ := {rat(triangle_cap)}\n')
    lines.append(f'def compareQ : ℚ := {rat(cap)}\n')
    lines.append('end Grothe.Upper\n')
    lean_path=ROOT/'Grothe/Upper/ComparisonData.lean'
    if check:
        assert lean_path.read_text()=='\n'.join(lines)
        for key,value in dict(compare=str(cap),delta=str(delta),incumbent_score=str(score),
                exact_bound=str(bound),headline_upper=str(headline),headline_decimal=recipe['headline'],
                localized_recipe_sha256=hashlib.sha256(recipe_text.encode()).hexdigest()).items():
            assert d[key]==value,(key,d[key],value)
    else:
        lean_path.write_text('\n'.join(lines))
        d.update(compare=str(cap),delta=str(delta),incumbent_score=str(score),
                 exact_bound=str(bound),headline_upper=str(headline),headline_decimal=recipe['headline'],
                 localized_recipe_sha256=hashlib.sha256(recipe_text.encode()).hexdigest())
        if 'linear_budget_refinement' in d:
            refined=d['linear_budget_refinement']
            head_residual=cap+Q(d['headCapQ'])+Q(d['energyErrQ'])
            linear_lower=Q(d['slopeQ'])-head_residual
            refined_delta=head_residual+Q(refined['hardy_tail'])
            refined_score=Q(d['slopeQ'])-refined_delta
            refined.update(head_residual=str(head_residual),linear_lower=str(linear_lower),
                delta=str(refined_delta),incumbent_score=str(refined_score),
                exact_bound=str(1/refined_score),
                headline_decimal=f'{float(ceil_grid(1/refined_score,10**12)):.12f}')
            verify_linear_refinement(d)
        p.write_text(json.dumps(d,indent=2)+'\n')
    print('Comparison',float(cap),'pieces',len(bands),'upper',recipe['headline'],flush=True)
    return recipe

if __name__=='__main__':
    import argparse
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true')
    main(check=parser.parse_args().check)
