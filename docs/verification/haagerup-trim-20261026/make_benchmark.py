#!/usr/bin/env python3
"""Generate a Mathlib-free benchmark from the current exact Lean data only."""
from pathlib import Path
from hashlib import sha256

root = Path(__file__).resolve().parents[3]
source = root / 'Grothe/Haagerup/PowerCheck.lean'
text = source.read_text()
start = text.index('def pl :')
end = text.index('def checks : Bool :=')
defs = text[start:end].replace('ℚ', 'Rat').replace('ℕ', 'Nat')
assert 'native_decide' not in defs and 'Mathlib' not in defs
body = '''
structure Inputs where
  primary : List Rat
  inverse : List Rat

-- Inputs are fetched from an IO.Ref inside each iteration; neither wrapper is
-- a closed constant. Both P and R are runtime arguments, so seedNormOK also
-- recomputes its unchanged P^17 work on every timed call.
@[noinline] def checkDefect (input : Inputs) : Bool :=
  resolventNormOK input.primary input.inverse defectCap

@[noinline] def checkSeed (input : Inputs) : Bool :=
  seedNormOK input.primary input.inverse seedPower seedCap

def warmup (check : Inputs → Bool) (inputRef : IO.Ref Inputs) : IO Unit := do
  let input ← inputRef.get
  unless check input do
    throw (IO.userError "warmup check returned false")

def runBatch (kind : String) (check : Inputs → Bool) (inputRef : IO.Ref Inputs)
    (variant : String) (batch position loops : Nat) : IO Unit := do
  let start ← IO.monoNanosNow
  for _ in [:loops] do
    let input ← inputRef.get
    unless check input do
      throw (IO.userError s!"{kind} {variant}: check returned false")
  let finish ← IO.monoNanosNow
  let elapsed := finish - start
  IO.println s!"{kind},{batch},{position},{variant},{loops},{elapsed},{elapsed / loops},true"

def runKind (kind : String) (check : Inputs → Bool)
    (beforeRef afterRef : IO.Ref Inputs) (loops : Nat) : IO Unit := do
  warmup check beforeRef
  warmup check afterRef
  for batch in [:5] do
    if batch % 2 == 0 then
      runBatch kind check beforeRef "before" batch 0 loops
      runBatch kind check afterRef "after" batch 1 loops
    else
      runBatch kind check afterRef "after" batch 0 loops
      runBatch kind check beforeRef "before" batch 1 loops

def run (loops : Nat) : IO Unit := do
  unless pl.length == 15 && rl.length == 65 do
    throw (IO.userError "expected P length 15 and trimmed R length 65")
  let beforeRef ← IO.mkRef (Inputs.mk pl (rl ++ List.replicate 64 (0 : Rat)))
  let afterRef ← IO.mkRef (Inputs.mk pl rl)
  IO.println "kind,batch,position,variant,loops,total_ns,ns_per_call,accepted"
  runKind "defect" checkDefect beforeRef afterRef loops
  runKind "seed" checkSeed beforeRef afterRef loops

end HaagerupPaddingBench

def main (args : List String) : IO Unit := do
  let loops : Nat ← match args with
    | [] => pure 10
    | [s] => match s.toNat? with
      | some n => pure n
      | none => throw (IO.userError "loops must be a natural number")
    | _ => throw (IO.userError "usage: benchmark [loops-per-batch; default 10]")
  unless 0 < loops && loops ≤ 100 do
    throw (IO.userError "loops must be between 1 and 100")
  HaagerupPaddingBench.run loops
'''
header = f'''import GrotheKernel.ResolventTail

/-! Generated by handoff/lean-audit/make_haagerup_bench.py.
Exact data copied from Grothe/Haagerup/PowerCheck.lean, SHA256:
{sha256(source.read_bytes()).hexdigest()}

Only the two affected actual kernel checks are benchmarked. No finite Haagerup
head, native theorem, Mathlib module, floating arithmetic or parallelism is used.
The old inverse is reconstructed as the trimmed inverse plus 64 exact zero entries.
Compile this harness to native code before interpreting timings as native runtime.
Default: five alternating before/after batches, ten calls each; use argument 1 for
an initial short run. Timing excludes setup/list construction and output printing.
-/
set_option maxRecDepth 100000
namespace HaagerupPaddingBench
open GrotheKernel

'''
output = root / 'handoff/lean-audit/HaagerupPaddingBench.lean'
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text(header + defs + body)
print(f'Wrote {output} ({len((header + defs + body).splitlines())} lines)')
